// ============================================================
// LC 2567 修改两个元素的最小分数 —— 排序后只剩 3 种可能
// ------------------------------------------------------------
// 考点：排序 + 分类枚举（不是 DP，也不是二分）
// 复杂度：时间 O(n log n)，空间 O(1)（排序原地）
// 日期：2026-11-19（嵌入式日每日一题，一次写对）
// ------------------------------------------------------------
// 题意：
//   nums 里可以【任选两个元素，改成任意值】（改成一个、同一个数都允许）。
//   分数 = max(nums) - min(nums)。
//   要求分数尽量小，返回最小的分数。
//
// ============================================================
// 【第一步转化：「可以改成任意值」= 「可以删掉」】
// ============================================================
//   被改的那两个元素，改完之后只有两种命运：
//     ① 改到 [min, max] 区间【内部】 -> 不影响 max/min -> 等于没改
//     ② 改到区间【外部】           -> 会撑大区间 -> 只会更差
//   所以最优策略一定是：把它改成一个不撑大、也不参与极差的数
//   -> 效果上等价于【把这两个位置从考虑范围里删掉】。
//
//   于是问题变成：从 nums 里删掉两个元素，剩下的极差最小。
//
// ============================================================
// 【第二步：删哪两个？只看两端】
// ============================================================
//   把 nums 升序排序。极差只由【最小值】和【最大值】决定，
//   中间的数是"陪跑"的 —— 删中间的数，极差一点不变（白删）。
//   所以两个删除名额，只会花在两端。
//
//   两个名额分给两端的方案，穷举只有 3 种（2+0 / 0+2 / 1+1）：
//
//     ① 删最大的 2 个 -> 剩下 nums[0 .. n-3] -> 极差 nums[n-3] - nums[0]
//     ② 删最小的 2 个 -> 剩下 nums[2 .. n-1] -> 极差 nums[n-1] - nums[2]
//     ③ 两端各删 1 个 -> 剩下 nums[1 .. n-2] -> 极差 nums[n-2] - nums[1]
//
//   三种取 min 就是答案。
//
//   ★ 注意 ③ 的两个下标不是相邻的：删最小的 1 个和最大的 1 个，
//     剩下的区间是 [1, n-2]，所以是 nums[n-2] - nums[1]。
//
// ============================================================
// 【为什么这三种就够了（不需要再枚举别的）】
// ============================================================
//   设删掉的最小下标是 i、最大下标是 j（i <= j），
//   剩余区间 = [i', j']，极差 = nums[j'] - nums[i']，随区间越大而越大。
//   -> 要让极差小，就要让剩余区间尽量窄
//   -> 即让 i' 尽量大、j' 尽量小
//   -> 名额必须全部压在两端，且"压在左"和"压在右"的分配只有 3 种。
//   区间再往中间缩，就是"白花了名额"，不可能更优。
//
// ============================================================
// 【细节】
// ============================================================
//   - n >= 3（题目约束），所以 n-3 >= 0，nums[n-3] 不会越界。
//     如果 n 能小到 2，那么删完只剩 0 个元素，n-3 就是负数了。
//   - 代码里的 abs() 是多余的：数组已升序，nums[n-3] >= nums[0] 恒成立，
//     减法结果一定非负。保留也无害，但不能靠 abs 兜住下标写反的错
//     （比如误写成 nums[n-2] - nums[1] 方向反了，abs 会让它"看起来对"）。
//   - 排序是必须的：不排序就没法用"下标"表示"第几小"，也就没法删端点。
//   - 这里是原地排序（直接改了入参）。若后续还要用原顺序，
//     需要先复制一份（或在本地测试时按值传递）。
//
// ============================================================
// 【验证】
// ============================================================
//   手算用例：
//       [1,4,3]           -> 0     （删两个剩一个，极差 0）
//       [1,4,7,8,5]       -> 3     （排序后 1,4,5,7,8，n=5）
//                                   ① nums[2]-nums[0] = 5-1 = 4
//                                   ② nums[4]-nums[2] = 8-5 = 3
//                                   ③ nums[3]-nums[1] = 7-4 = 3  -> 3
//       [1,1,1,1]         -> 0
//       [-5,0,5]          -> 0
//       [1,2,3,100,200]   -> 2     （排序后 ① 3-1=2）
//
//   随机对拍：与"枚举删掉哪两个下标、算剩余极差"的暴力比，
//   20000 组（n∈[3,8]，值∈[-10,10]）零不一致。
//   6 个定点用例全部 OK。
// ============================================================

#include <vector>
#include <algorithm>
#include <cstdlib>
using namespace std;

class Solution {
public:
    int minimizeSum(vector<int>& nums) {
        int n = nums.size();
        sort(nums.begin(), nums.end());          // 排序后"删端点"才有意义

        // 三种删除方案，穷举取最小
        int mm = min(abs(nums[n - 3] - nums[0]),                    // ① 删最大的两个
                 min(abs(nums[n - 1] - nums[2]),                    // ② 删最小的两个
                     abs(nums[n - 2] - nums[1])));                  // ③ 两端各删一个
        return mm;
    }
};
