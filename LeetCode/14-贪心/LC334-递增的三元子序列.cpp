// ============================================================
// LC 334 递增的三元子序列 —— 只维护两个数
// ------------------------------------------------------------
// 考点：贪心（维护"最小结尾"）
// 复杂度：时间 O(n)，空间 O(1)
// 日期：2026-11-24（一次写对，但注释把"最小"写成了"最大"）
// ------------------------------------------------------------
// 题意：
//   判断数组里是否存在 i < j < k 使 nums[i] < nums[j] < nums[k]。
//   不要求连续。
//     [1,2,3,4,5]    -> true
//     [5,4,3,2,1]    -> false
//     [2,1,5,0,4,6]  -> true   （0,4,6）
//
// ============================================================
// 【核心：只记住两个数，不要记整个序列】
// ============================================================
//   c1 = 目前见过的、能作为三元组【第一个数】的【最小值】
//   c2 = 目前见过的、能作为三元组【第二个数】的【最小值】
//
//   ★ 注意是【最小】不是最大。
//     值越小，后面越容易接上更大的数 —— 和 LIS 里 tails 的思路一样。
//
//   每读一个 nums[i]，看它能不能当"第三个"：
//     nums[i] > c2   -> c1 < c2 < nums[i]，三个数齐了，返回 true
//     nums[i] <= c1  -> 它能当一个更小的"第一个数"，更新 c1
//     否则           -> 它落在 (c1, c2]，能当一个更小的"第二个数"，更新 c2
//
//   为什么 else 分支一定意味着 nums[i] > c1？
//     因为上一个分支已经处理了 nums[i] <= c1 的情况，
//     所以走到 else 时必然 nums[i] > c1 —— 它确实能接在 c1 后面。
//
// ============================================================
// 【最精妙的地方：c1 和 c2 可能来自不同的三元组】
// ============================================================
//   看 [20, 100, 10, 12, 5, 13]：
//     c1=20
//     100: 不 > c2(MAX)，也不 <= c1  ->  c2=100
//     10 : <= c1=20                  ->  c1=10
//     12 : 落在 (10,100]             ->  c2=12
//     5  : <= c1=10                  ->  c1=5      ★ 此时 c1 跑到了 c2 后面
//     13 : > c2=12                   ->  true
//
//   最后 c1=5 出现在 c2=12 的【后面】，按 c1/c2 的顺序根本凑不出递增三元组。
//   但答案依然正确 —— 真实的三元组是 10, 12, 13。
//
//   ★ 所以：c1 和 c2 只是"存在性"的证据，不构成一个真实的（下标有序的）三元组。
//     这和 LIS 里 tails 不一定是真实子序列是同一类现象。
//     危险的是把它当成"能还原答案"的存储 —— 这题只需要 true/false，所以没事。
//
//   为什么 c1 被覆盖不影响正确性？
//     c2 更新时，当时的 c1 一定 < c2，所以"存在某个数 < c2"这个事实永久成立。
//     后来 c1 变小，只会让"再找一个比 c2 大的数"更容易，不会让已成立的结论失效。
//
// ============================================================
// 【和 LIS 的关系】
// ============================================================
//   LIS 要长度，所以维护整个 tails 数组；
//   这题只要"有没有长度 3"，所以只维护 tails[1] 和 tails[2] 两个位置。
//   本质是同一个贪心：每个长度只留最小的结尾。
//
// ============================================================
// 【验证】
// ============================================================
//   8 组定点：三个官方示例 + n=1 / n=2 / 全相等
//            + [1,5,0,4,1,3]（c1 被更新后仍能成）
//            + [20,100,10,12,5,13]（c1 跑到 c2 后面的那种）
//   与 O(n^3) 暴力随机对拍 20000 组（n<=12，值<8）零不一致。
// ============================================================

#include <vector>
#include <climits>
using namespace std;

class Solution {
public:
    bool increasingTriplet(vector<int>& nums) {
        int c1 = nums[0];        // 长度为 1 的递增序列的【最小】结尾
        int c2 = INT_MAX;        // 长度为 2 的递增序列的【最小】结尾
        // 不变式：c1 < c2

        for (int i = 1; i < (int)nums.size(); i++) {
            if (c2 < nums[i]) {
                // c1 < c2 < nums[i]：三个数齐了
                return true;
            } else if (c1 >= nums[i]) {
                // 能当更小的"第一个数"
                c1 = nums[i];
            } else {
                // 走到这里必有 nums[i] > c1，能当更小的"第二个数"
                c2 = nums[i];
            }
        }
        return false;
    }
};
