// ============================================================
// LC 503 下一个更大元素 II（循环数组）
// ------------------------------------------------------------
// 考点：单调栈 + **循环数组的处理**
// 复杂度：时间 O(n)，空间 O(n)
// 日期：2026-10-08（Week 5 第 3 题，一次通过）
// ------------------------------------------------------------
// 题意：
//   给一个【循环数组】nums（最后一个元素的下一个又是第一个），
//   对每个元素找它下一个更大的数；绕一圈也没有则填 -1。
//     [1,2,1]      ->  [2,-1,2]
//     [1,2,3,4,3]  ->  [2,3,4,-1,4]
//     [5,4,3,2,1]  ->  [-1,5,5,5,5]
//     [1,1,1]      ->  [-1,-1,-1]        ← 相等不算"更大"
// ------------------------------------------------------------
// 思路：
//   ① 把数组【接长一倍】：tmp = nums + nums（长度 2n）
//        —— 这样"绕回开头"就变成了"继续往后看"，环形问题化为线性问题。
//   ② 在 tmp 上跑 739 的单调栈（while 弹 + 无条件 push）
//   ③ 只要【前 n 个】位置的答案（后面那半只是为了给前面当"右边的候选"）
//
//   为什么接长一倍就够：位置 j（0 <= j < n）最多需要看它后面的 n-1 个位置，
//   即虚拟下标最大到 j + n - 1 <= 2n - 2，落在 tmp 范围内 ✓
//
//   ※ 另一种等价写法：不复制数组，用 `nums[i % n]` 取数（省 O(n) 空间）。
//     两种都是标准写法 —— 复制更直观，取模更省内存。
//
//   与前面两题的对照（"栈里存什么"取决于要什么）：
//     739：存【下标】，记"距离"（i - j）
//     496：存【值】，记"答案值"
//     503：存【下标】（要写 ret[st.top()]），记"答案值" + 循环处理
// ------------------------------------------------------------
// 易错点：
//   ① 相等不算"更大" —— 判断必须是严格的 `>`（`[1,1,1]` 答案全 -1）
//   ② 最大值元素自己也得 -1（它绕一圈也遇不到更大的）
//   ③ 第二轮的下标（n..2n-1）也会进栈、也会被算答案 —— 无害，
//      最后截取前 n 个丢掉即可；也可以只把 i < n 的压栈，更干净
//   ④ 别忘记截取：直接把 2n 长的结果返回就错了
// ------------------------------------------------------------
// 实测：5 个验证用例全对；20000 组随机对拍 vs 暴力（沿环走 n-1 步）零不一致；
//      递增/递减/全相等三种极端（n=2000）与暴力一致；n = 200000 通过；-Wall 无警告
// ============================================================

class Solution {
public:
    vector<int> nextGreaterElements(vector<int>& nums) {
        int n = nums.size();

        // ① 接长一倍：环形 -> 线性
        vector<int> tmp(nums.begin(), nums.end());
        for (int i = 0; i < n; i++) {
            tmp.push_back(nums[i]);
        }

        vector<int> ret(2 * n);
        stack<int> st;

        // ② 在 tmp 上跑单调栈（与 739 相同的两步结构）
        for (int i = 0; i < 2 * n; i++) {
            while (st.size() && tmp[i] > tmp[st.top()]) {
                ret[st.top()] = tmp[i];
                st.pop();
            }
            st.push(i);
        }
        while (st.size()) {
            ret[st.top()] = -1;
            st.pop();
        }

        // ③ 只有前 n 个是答案
        return vector<int>(ret.begin(), ret.begin() + n);
    }
};
