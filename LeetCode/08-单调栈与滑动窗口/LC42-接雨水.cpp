// ============================================================
// LC 42 接雨水（困难）
// ------------------------------------------------------------
// 考点：双指针（两侧夹逼）+ 「前缀/后缀最大值」的思想
// 复杂度：时间 O(n)，空间 **O(1)**（这是本题的空间最优解）
// 日期：2026-10-09（Week 5 第 5 题；与同日 LC 84 形成"能不能用双指针"的对照）
// ------------------------------------------------------------
// 题意：
//   给 n 个非负整数表示宽度为 1 的柱子高度，问下雨后能接住多少水。
//     [0,1,0,2,1,0,1,3,2,1,2,1] -> 6
//     [4,2,0,3,2,5]             -> 9
//
// 单个位置 i 的积水 = min(左侧最大值, 右侧最大值) - height[i]
//   （水面高度由左右两边较矮的那堵"墙"决定）
// ------------------------------------------------------------
// 双重指针做法的核心：
//   维护 lm = max(height[0..left])、rm = max(height[right..n-1])
//
//   每轮比较 height[left] 与 height[right]，**处理较矮的那一侧**：
//     height[right] >= height[left]  ->  处理 left：积水量 = lm - height[left]，left++
//     否则                            ->  处理 right：积水量 = rm - height[right]，right--
//
//   为什么"较矮那一侧"可以当场结算？
//     那一侧的水位由"那一侧的最大值"决定 —— 因为另一侧更高，永远挡得住，
//     不会成为更矮的"墙"。所以水位 = 本侧最大值 ✓
//
// ------------------------------------------------------------
// ★ 与 LC 84（柱状图中最大的矩形）的对照 —— 同一天实测
//
//   | | LC 42 接雨水 | LC 84 柱状图 |
//   |---|---|---|
//   | 每个位置的答案依赖 | min(左max, 右max) | 「左右第一个【更矮】的位置」 |
//   | 这个量能增量维护吗 | **能**（一个 max 变量） | **不能**（"第一个"要记住候选） |
//   | 双指针 | ✅ O(n) / O(1) 空间 | ❌ 退化 O(n²)（实测 n=40000 时 274ms） |
//
//   判据：**答案只依赖"可增量维护的量"（前缀 max/min、累加和…）→ 双指针可行；
//         依赖"某个特定位置"（第一个更矮/更大）→ 需要栈。**
//
// ------------------------------------------------------------
// 易错点：
//   ① 判断用 `>=` 还是 `>`：`height[right] >= height[left]` 时处理 left
//      —— 相等时处理哪边都行，但必须有一边能走，否则死循环
//   ② 两个 max 必须在【处理对应侧之前】更新
//   ③ 循环条件是 `left < right`（相遇即停，最后那根柱子接不到水）
//   ④ 本题也可用「前缀/后缀最大值」两数组做（O(n) 空间），或单调栈横向分块
//      —— 双指针是其中空间最优的
// ------------------------------------------------------------
// 实测：9 个用例（含空数组 / 单元素 / 递增 / 递减 / 两等 / 简单盆地）全对；
//      30000 组随机对拍 vs 暴力零不一致，且与前缀后缀版三方互证；
//      特殊形状（n=3000）全对；n=200000 为 0.0 ms
// ============================================================

class Solution {
public:
    int trap(vector<int>& height) {
        int left = 0, right = height.size() - 1;
        int lm = 0, rm = 0;          // lm = 左侧最大，rm = 右侧最大
        int ret = 0;
        while (left < right) {
            lm = lm > height[left] ? lm : height[left];
            rm = rm > height[right] ? rm : height[right];

            if (height[right] >= height[left]) {
                // 左边更矮 -> 左边的水位由 lm 决定，可以当场结算
                ret += lm - height[left++];
            } else {
                // 右边更矮 -> 右边的水位由 rm 决定
                ret += rm - height[right--];
            }
        }
        return ret;
    }
};

// ============================================================
// 【解法二】单调栈（横向按层结算）—— 与 LC 84 同构
// ------------------------------------------------------------
// 与解法一（双指针）的取舍：
//   双指针：O(n) 时间、**O(1) 空间**   ← 空间最优
//   单调栈：O(n) 时间、O(n) 空间
//   两者结果实测完全一致（30000 组三方对拍零不一致）
//
// 和 LC 84 的对照（骨架完全一样，只有"弹出时算什么"不同）：
//   | | LC 84 柱状图 | LC 42 栈版 |
//   |---|---|---|
//   | 弹出条件 | h[i] < h[栈顶]（找更矮） | **h[i] > h[栈顶]**（找更高，方向反过来） |
//   | 弹出 mid 后算 | 矩形面积 = h[mid] × 宽度 | 这一层的水 = (水位 - h[mid]) × 宽度 |
//   | "高"由谁决定 | h[mid] 自己 | **min(h[left], h[i])**（两边墙的较矮者） |
//   | 宽度 | i - left - 1 | i - left - 1（**一样**） |
//
// ★ "分层"的含义：
//   弹出 mid 时算的是「mid 头顶那一层」——水深 = min(h[left], h[i]) - h[mid]。
//   而 **h[mid] 恰好等于「上一层的水位」**，所以这个差就是"这一层的厚度"，
//   在宽度 i-left-1 内每一格厚度相同 → 直接乘，不用逐个位置循环。
//
// ★ 42 栈版特有的一步：**弹出后如果栈空 → 左边没墙 → 接不到水**（跳过）。
//   （84 里没有这一步 —— 那里"没有左边界"用 -1 表示，是一种合法情况）
//
// 实测：11 个用例全对；30000 组三方对拍（vs 双指针 vs 暴力）零不一致；
//      n=200000 为 1.0 ms；-Wall 无警告
// ============================================================

class SolutionStack {
public:
    int trap(vector<int>& height) {
        int n = height.size();
        int ret = 0;
        stack<int> st; // 存下标
        for (int i = 0; i < n; i++) {
            //每次进入right是i
            while (st.size() && height[i] > height[st.top()]) {
                int mid = st.top();
                st.pop();
                if (st.empty()) //左边没墙
                    break;
                int left = st.top();
                int morlow = min(height[left], height[i]);
                ret += (morlow - height[mid]) * (i - left - 1);
            }
            // 只要右边小一直压入
            st.push(i);
        }
        return ret;
    }
};
