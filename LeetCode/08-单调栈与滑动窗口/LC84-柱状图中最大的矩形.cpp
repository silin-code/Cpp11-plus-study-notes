// ============================================================
// LC 84 柱状图中最大的矩形（困难）
// ------------------------------------------------------------
// 考点：单调栈的【反向用法】—— 找右边第一个【更小】的 + 面积计算
// 复杂度：时间 O(n)（每根柱子进栈一次、出栈一次），空间 O(n)
// 日期：2026-10-09（Week 5 第 4 题；同日先答了"能不能用双指针"）
// ------------------------------------------------------------
// 题意：
//   给 n 个非负整数 heights（柱状图每根柱子高度，宽度都是 1），求能画出的最大矩形面积。
//     [2,1,5,6,2,3] -> 10      [2,4] -> 4      [1,1] -> 2
// ------------------------------------------------------------
// 思路（三个台阶）：
//
//   台阶一：最大矩形一定【以某根柱子的高度为高】
//       —— 若矩形高比所有柱子都矮，它还能往上长。所以只需枚举"高 = 某根柱子的高度"。
//
//   台阶二：把"高定成 heights[i]"时能覆盖的宽度，换算成"左右边界"
//       left[i]  = 左边第一个比 heights[i] 矮的柱子的下标（没有则 -1）
//       right[i] = 右边第一个比 heights[i] 矮的柱子的下标（没有则 n）
//       宽度 = right[i] - left[i] - 1
//       （左边界和右边界这两根柱子本身太矮、不能用，所以是 -1）
//
//   台阶三：用【递增栈】一趟求出所有边界，边弹边结算
//       栈里存下标，栈内高度递增。
//       遇到一根更矮的柱子 i 时，栈顶 j 的右边界就确定了（= i），可以弹出结算：
//           右边界 = i
//           左边界 = 弹出【之后】的新栈顶（= 左边第一个比 j 矮的）
//           面积   = heights[j] × (右边界 - 左边界 - 1)
//
//   ★ 为什么"弹出后的新栈顶"就是左边界：
//       ① 栈内高度递增 → j 下面那个一定比 j 矮 ✓
//       ② j 和它之间原有的柱子都已被弹掉 → 它们挡不住 j 的左边 ✓
//
//   哨兵技巧：在数组两头各加一根高度 0 的柱子
//       → 最后那根 0 会把栈里剩下的全部弹出来（省掉"收尾处理"）
//       → 0 号哨兵永远垫在栈底，"栈空"分支用不到
//
//   与前面三题的对照：
//       739/496/503 找右边第一个【更大】→ 弹出条件是 `>`
//       本题        找两边第一个【更小】→ 弹出条件是 `<`
//       骨架完全一样，只是方向反过来。
// ------------------------------------------------------------
// 易错点：
//   ① 【只 pop 不结算】—— 半成品最常见的样子：弹出后什么也不算，答案恒为 0
//   ② 【左边界必须"先 pop 再读栈顶"】—— 顺序反了就读到 j 自己
//   ③ 宽度公式是 `right - left - 1`（两根边界柱子本身不能用）
//   ④ 收尾：扫完后栈里剩下的柱子右边界要按 n 算（或用哨兵省掉这一步）
//   ⑤ 【别用双指针】—— 中心扩展版逻辑能算对，但退化 O(n²)：
//        实测 n=40000 时 274 ms，外推 n=100000 ≈ 1.7 秒（考场必超）。
//        根因：LC 11 那种"移动较矮一侧可安全排除"的单调性，本题不存在
//        （一根矮柱子可能是"墙"，保护中间的高柱）。LC 11 能双指针 O(n)，本题不能。
// ------------------------------------------------------------
// 实测：8 个验证用例全对；30000 组随机对拍 vs 暴力（中心扩展）零不一致；
//      递增/递减/全相等/全零（n=3000）全对；n=100000 上限 0.0 ms；-Wall 无警告
// ============================================================

class Solution {
public:
    int largestRectangleArea(vector<int>& height) {
        // 两头加哨兵 0
        vector<int> heights;
        heights.push_back(0);
        for (auto e : height) {
            heights.push_back(e);
        }
        heights.push_back(0);

        int n = heights.size();
        int ret = 0;
        stack<int> st; // 存可能出现的最矮的下标
        for (int i = 0; i < n; i++) {
            while (st.size() && heights[st.top()] > heights[i]) {
                int mid = st.top(); // 当前中心
                st.pop();
                int right = i;                         // 右
                int left = st.empty() ? -1 : st.top(); // 左
                ret = max(ret, heights[mid] * (right - left - 1));
            }
            st.push(i);
        }
        return ret;
    }
};
