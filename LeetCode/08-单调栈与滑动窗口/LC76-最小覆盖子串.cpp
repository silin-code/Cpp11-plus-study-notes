// ============================================================
// LC 76 最小覆盖子串（困难）—— Week 5 收官
// ------------------------------------------------------------
// 考点：滑动窗口（**求最短**）+ 三个账本维护"覆盖"性质
// 复杂度：时间 O(m + n)，空间 O(字符集)
// 日期：2026-10-12（Week 5 第 8 题，模块收官）
// ------------------------------------------------------------
// 题意：
//   在 s 里找【最短】的连续子串，使它包含 t 的所有字符（**重复的也要满足个数**）。
//   不存在返回 ""。
//     s="ADOBECODEBANC", t="ABC"  ->  "BANC"
//     s="a",   t="aa"             ->  ""      （t 需要两个 a，s 只有一个）
//
// 与 LC 3 的关系（同一骨架，两处反转）：
//   | | LC 3 | LC 76 |
//   | 窗口求什么 | 最长 | 最短 |
//   | 合法时 | 不动，继续往右扩 | 【记录答案】→ 然后【尽力缩左边】 |
//   | 合法判据 | 窗口内无重复（简单） | 窗口覆盖 t（需要计数） |
//
// 三个账本：
//   need[c]     t 里字符 c 需要几个
//   window[c]   【当前窗口】里字符 c 有几个
//   flag        【还没达标】的字符种类数
//               （初始 = t 的不同字符种类数；全部达标时 flag == 0）
//
// 两个计数的维护（注意顺序）：
//   加入：if (++window[s[right]] == need[s[right]])  flag--;        ← 刚好达标
//   移出：if (--window[s[left]] < need[s[left]] && need[s[left]])  flag++;   ← 刚好不达标
//   （移出时那个 `need[c] != 0` 是必要的：t 里没有的字符，window 减成负数会误判）
//
// 每轮（对每个 right）：
//   ① 扩：把 s[right] 纳入窗口
//   ② while (left < right && flag == 0) {        ← 窗口合法
//          先【记录答案】（比当前最优短就更新 l / len）
//          再【缩】：移出 s[left]，left++
//      }
//   "记录"写在"缩"之前：每次进入 while 时窗口都是合法的（第一次刚好合法，
//   之后是缩完仍合法）→ 这就是"以当前 right 结尾的最短合法窗口"。
//
// ------------------------------------------------------------
// 易错点（本人都踩过）
// ------------------------------------------------------------
//   ① 【自增混在表达式里】`++window[s[right++]] == need[s[right]]`
//      —— s[right++] 与同一表达式中的 s[right] 既读又写 right，是【未定义行为】；
//         g++ 表现为"右侧的 s[right] 看到自增后的值" → 比较的是【下一个字符】的需求
//      → **判据：`++` / `--` 永远单独一行，不要挤在表达式里**
//   ② 【continue 跳过 while】刚加入一个字符就达标时，恰恰要立刻检查（记录 + 缩）；
//      写 continue 会把这一轮整个跳过（s="a", t="a" 就死在这里）
//   ③ 【长度约定】加入后就 right++ → right 指向"下一个待加入位置" → 窗口是 [left, right-1]
//      → 长度 = `right - left`（**不是** right - left + 1）
//   ④ `for (char c : t) need[c]++` 会有 -Wchar-subscripts 警告：
//      若 char 是 signed 且字符值 > 127 → c 为负 → need[负数] 越界。
//      严格写 `need[(unsigned char)c]`（本题限英文字母，但值得知道）
//
//   ⑤ 「能过≠对」又一例：`"ADOBECODEBANC"/"ABC"` 在①的错法下**恰好答对**（flag 凑巧减到 0）。
//      这种"错得刚好"的用例最容易让人以为代码没问题 —— 这也是坚持随机对拍的理由。
// ------------------------------------------------------------
// 实测：9 个用例全对；20000 组随机对拍 vs 暴力零不一致
// ============================================================

class Solution {
public:
    string minWindow(string s, string t) {
        int m = s.size(), n = t.size();
        if (n > m)
            return "";
        int need[128] = {0};   // 需要的
        int window[128] = {0}; // 窗口里的
        int flag = 0;          // 还没达标的种类数
        for (char c : t)
            need[c]++;
        for (auto e : need) {
            if (e != 0)
                flag++;
        }
        int left = 0, right = 0, len = 500001;
        int l = 0;
        while (right < m) {
            // 加入窗口
            if (++window[s[right]] == need[s[right]]) {
                flag--;
            }
            right++;
            // 更新窗口
            while (left < right && flag == 0) {
                // 凑齐了 -> 先记录
                if (len > right - left) {
                    l = left;
                    len = right - left;
                }
                // 出窗口
                if (--window[s[left]] < need[s[left]] && need[s[left]] != 0) {
                    flag++;
                }
                left++;
            }
        }
        if (len == 500001) return "";
        return s.substr(l, len);
    }
};
