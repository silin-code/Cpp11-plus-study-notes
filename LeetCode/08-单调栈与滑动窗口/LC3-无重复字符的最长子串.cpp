// ============================================================
// LC 3 无重复字符的最长子串（滑动窗口入门题）
// ------------------------------------------------------------
// 考点：**滑动窗口**（变长窗口，两个指针都只增不减）
// 复杂度：时间 O(n)（left 与 right 各走 n 步），空间 O(字符集大小)
// 日期：2026-10-10（Week 5 第 6 题；嵌入式日的「每日一题」）
// ------------------------------------------------------------
// 题意：
//   给字符串 s，返回其中不含重复字符的最长子串的长度。
//     "abcabcbb" -> 3 ("abc")     "bbbbb" -> 1     "pwwkew" -> 3 ("wke")
//
// 思路：
//   维护窗口 [left, right]，保证【窗口内没有重复字符】。两个动作：
//     ① 右指针【扩】：right 右移，把 s[right] 纳入窗口
//     ② 左指针【缩】：一旦 s[right] 已在窗口里，就不断 left 右移，直到不冲突
//   每轮用 right - left 更新答案。
//
//   ★ 本写法用 `while (right < n)` + `if/else` 实现"缩到不冲突为止"：
//       冲突  -> 只缩一格（left++），下一轮继续检查
//       不冲突 -> 扩一格（right++）
//     两种动作都只让指针前进，所以总步数 O(n)。
//
//   ★ 与单调栈的姐妹关系（Week 5 的主线问题）：
//       单调栈  ：什么时候【扔掉】栈里的候选？
//       滑动窗口：什么时候【缩减】窗口的左边？
//     都是"什么时候，那些候选可以被排除掉"。
//
//   另一种常见写法（跳位法）：用 last[c] 记录字符最近出现的位置，
//     冲突时直接 left = last[c] + 1，一步跳到该字符的下一位（常数更小）。
//     本写法逐格缩，等价且更直观。
// ------------------------------------------------------------
// 易错点：
//   ① 缩窗口要"缩到不冲突为止" —— 不是缩一次就够
//      （如 "abbbbbbc"：right 遇到重复的 b 时，要连缩多次）
//      本写法靠 while 循环反复进入 + 每轮缩一格实现，效果一样 ✓
//   ② 更新答案的时机：要在【每轮结尾】都更新（扩完或缩完之后）
//   ③ `hash` 只当"在不在窗口里"用（值只有 0/1）—— 所以判断写 `== 1` 是对的；
//      若改成"计数"语义就要写 `> 0`
//   ④ `unordered_map` 每步操作常数较大：n=200000 实测 2.0 ms，
//      换成 `int cnt[256]` 或"最近位置"数组为 0.0 ms（本题数据不大，都可）
// ------------------------------------------------------------
// 实测：10 个用例（含经典坑 "dvdf"=3 / "abba"=2 / "tmmzuxt"=5）全对；
//      30000 组三方对拍（本解 / 暴力 / 另一种实现）零不一致；
//      全同字符与 a-z 循环（n=20000）正确；n=200000 为 2.0 ms；-Wall 无警告
// ============================================================

class Solution {
public:
    int lengthOfLongestSubstring(string s) {
        unordered_map<char, int> hash;   // 只当"在不在窗口里"用（0/1）
        int left = 0, right = 0;
        int n = s.size();
        int ret = 0;
        while (right < n) {
            if (hash[s[right]] == 1) {
                // s[right] 已在窗口里 -> 缩一格（下一轮继续检查）
                hash[s[left++]] = 0;
            } else {
                // 不冲突 -> 扩一格
                hash[s[right++]]++;
            }
            // 每轮都更新（扩完或缩完之后的窗口长度）
            ret = max(ret, right - left);
        }
        return ret;
    }
};
