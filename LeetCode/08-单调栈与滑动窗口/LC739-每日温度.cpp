// ============================================================
// LC 739 每日温度（Week 5 单调栈 · 母题）
// ------------------------------------------------------------
// 考点：单调栈 —— 「对每个 i，找右边第一个比它大的位置」
// 复杂度：时间 O(n)（每个下标进栈一次、出栈一次），空间 O(n)
// 日期：2026-10-07（休假归来第二天；Week 5 开篇）
// ------------------------------------------------------------
// 题意：
//   给数组 temperatures，返回 answer，其中 answer[i] = 从第 i 天起要等几天
//   才会出现一个【更高】的温度；之后都不会更高则记 0。
//     [73,74,75,71,69,72,76,73]  ->  [1,1,4,2,1,1,0,0]
// ------------------------------------------------------------
// 思路（两步结构）：
//   维护一个栈，存【还没等到答案的那些天的下标】，栈内温度从底到顶递减。
//
//   遍历到 i 时：
//     ① while：只要栈顶那天的温度 < 今天，栈顶那位的答案就是 i（弹出并结算 i - j）
//              —— 可能连弹好几个，所以要 while 不是 if
//     ② push i：不管怎样，i 自己都要进栈（它也在等答案）
//
//   ★ 核心判据（Week 5 的主线问题）：
//       「什么时候，栈里那些候选可以被扔掉？」
//       —— 本题：新来的比栈顶热，栈顶那位的答案就定了，它以后再也没用。
//
//   暴力的浪费在重复扫描（O(n²)）；单调栈让每个下标只进出一次 → O(n)。
// ------------------------------------------------------------
// 易错点：
//   ① `st.top() < temperatures[i]` —— **左边是下标、右边是温度**，
//      类型/语义都混了（`0 < 73` 恒成立 → 每轮弹空整个栈 → 答案全 0）。
//      必须写 `temperatures[st.top()] < temperatures[i]`
//   ② `while (st.size())` 少条件 —— 会把【整个栈】弹空，
//      而不是"弹到栈顶温度不小于当前为止"
//   ③ 三段式（`if 栈空 push` / `if 比较` / `else if push`）有两个 push 点：
//      同一个 i 可能被 push 两次；且"相等"时两分支都不走 → i 会丢失。
//      正确结构里 **push 只有一处，且无条件**（"栈空则 push"是它的特例）
//   ④ ★【能过≠对】第 5 种形态：若输入是**单调不增**（如 [90,80,70]）或
//      **全相等**（如 [30,30,30]），正确答案本来就是全 0 ——
//      上面①那种写错的版本（恒输出全 0）**会通过这些用例**。
// ------------------------------------------------------------
// 实测：9 个用例（4 官方 + 5 自造边界，含 [1] / [5,5] / [100]）全对；
//      20000 组随机对拍 vs 暴力零不一致；n = 200000 规模测试通过
// ============================================================

class Solution {
public:
    vector<int> dailyTemperatures(vector<int>& temperatures) {
        int n = temperatures.size();
        stack<int> st;
        vector<int> ret(n, 0);
        for (int i = 0; i < n; i++) {
            // ① 新来的比栈顶热 -> 栈顶那位的答案就是 i（可能连弹好几个）
            while (st.size() && temperatures[i] > temperatures[st.top()]) {
                ret[st.top()] = i - st.top();
                st.pop();
            }
            // ② 无论如何，i 自己进栈（它也在等答案）
            st.push(i);
        }
        return ret;
    }
};
