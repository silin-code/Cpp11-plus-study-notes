// ============================================================
// LC 496 下一个更大元素 I
// ------------------------------------------------------------
// 考点：单调栈（739 的变形）+ 哈希表
// 复杂度：时间 O(n + m)，空间 O(n)
// 日期：2026-10-08（Week 5 第 2 题）
// ------------------------------------------------------------
// 题意：
//   给两个数组 nums1、nums2（nums1 是 nums2 的子集，且 nums2 中元素互不相同）。
//   对 nums1 里的每个元素 x，找它在 nums2 中【右边第一个比它大的数】，没有则 -1。
//     nums1=[4,1,2] nums2=[1,3,4,2]  ->  [-1,3,-1]
//     nums1=[2,4]   nums2=[1,2,3,4]  ->  [3,-1]
// ------------------------------------------------------------
// 思路：
//   ① 在 nums2 上跑一遍【739 的单调栈】（while 弹 + 无条件 push）
//        区别只在"弹出时记什么"：
//          739 记 距离  answer[j] = i - j
//          本题 记 数值  hash[栈顶值] = nums2[i]
//   ② 栈里最后剩下的那些值：右边没有更大的 → 全部记 -1
//   ③ 按 nums1 的顺序查表输出
//
//   ★ 本解的两个设计要点：
//     ① 栈里【存值】而不是下标 —— 因为本题要的答案就是"那个更大的数本身"，
//        不需要位置信息（739 要"等了几天"，所以那时必须存下标）。
//        判据：栈里存什么，取决于"题目最后要的是什么"。
//     ② hash 里直接存【值 → 答案值】，省掉了"值 → 位置"的中间映射：
//        弹出时 st.top() 本身就是那个值，一步就能记录答案。
// ------------------------------------------------------------
// 易错点：
//   ① 栈里剩的最后一批必须补 -1（不补会漏，hash 里没有这些 key）
//   ② `unordered_map::operator[]` 查不到 key 时会【插入默认值 0】——
//      若 nums1 不是 nums2 的子集，会得到 0 而不是 -1。
//      只读查询用 count() / find() 更安全。
//       （本题题目保证是子集，所以直接用 [] 没问题）
//   ③ `for (int i = 0; i < nums1.size(); i++)` 有 -Wsign-compare 警告，写 (int) 更干净
// ------------------------------------------------------------
// 实测：6 个用例（含降序 / 单元素 / nums1==nums2）全对；
//      20000 组随机对拍 vs 暴力零不一致；n = 200000 通过
// ============================================================

class Solution {
public:
    vector<int> nextGreaterElement(vector<int>& nums1, vector<int>& nums2) {
        int n = nums2.size();
        stack<int> st;                       // 存【值】（本题不需要位置信息）
        unordered_map<int, int> hash;        // 值 -> 右边第一个比它大的数

        for (int i = 0; i < n; i++) {
            while (st.size() && nums2[i] > st.top()) {
                hash[st.top()] = nums2[i];
                st.pop();
            }
            st.push(nums2[i]);
        }

        // 栈里剩下的：右边没有更大的
        while (st.size()) {
            hash[st.top()] = -1;
            st.pop();
        }

        vector<int> ret(nums1.size());
        for (int i = 0; i < (int)nums1.size(); i++) {
            ret[i] = hash[nums1[i]];
        }
        return ret;
    }
};
