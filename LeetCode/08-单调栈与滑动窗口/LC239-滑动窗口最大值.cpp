// ============================================================
// LC 239 滑动窗口最大值（困难）
// ------------------------------------------------------------
// 考点：**单调队列**（deque，两端都要动的第一个结构）
// 复杂度：时间 O(n)，空间 O(k)
// 日期：2026-10-11（Week 5 第 7 题；周日算法日）
// ------------------------------------------------------------
// 题意：
//   给数组 nums 和窗口大小 k，窗口从最左滑到最右（每次右移一格），
//   返回每个窗口里的最大值。
//     nums=[1,3,-1,-3,5,3,6,7], k=3  ->  [3,3,5,5,6,7]
//
// ============================================================
// 【思路复盘】
// ============================================================
//
// 一、这题在问什么
//     滑动窗口 + 求极值。窗口每滑一格，都要马上知道"当前窗口的最大值"。
//     暴力：每个窗口扫一遍 → O(nk)。n=200000、k=1000 时约 2×10^8 次 → 会超时。
//     所以核心问题变成：**窗口滑动时，信息怎么复用？**
//
// 二、核心洞察（本题的全部）
//     「新元素进来时，哪些【旧候选】可以被永久扔掉？」
//
//         如果新来的 nums[i] 比前面某个元素【大】，那么前面那个元素
//         在离开窗口之前，永远不可能成为最大值了 —— 因为：
//             ① nums[i] 比它大
//             ② nums[i] 比它晚离开窗口（位置更靠右）
//
//     所以：**只要队列保持递减，队首就永远是当前窗口的最大值。**
//
// 三、为什么队列里必须存【下标】（不能存值）
//     因为要回答最关键的一问：「这个最大值，什么时候过期？」
//         窗口范围是 [i-k+1, i]
//         队首下标 <= i-k  →  它已经滑出窗口  →  弹掉
//     存值的话，你知道"队首是 3"，但不知道"这个 3 在数组的哪个位置" → 判断不了。
//
// 四、每一轮 i 做四件事（顺序不能乱）
//     ① 队尾清理：while (队列非空 && nums[队尾] < nums[i])  →  从队尾弹出
//            理由：它们被 nums[i] "盖住"了，以后永远当不了最大值
//     ② 入队：把 i 从队尾压入
//            理由：i 自己也是候选（它还在窗口里）
//     ③ 队首过期：if (队首下标 <= i - k)  →  从队首弹出
//            理由：它滑出窗口了
//            用 if 不是 while：每轮只滑一格，最多只会过期一个
//     ④ 记录答案：if (i >= k - 1)  →  ret.push_back(nums[队首])
//            理由：前 k-1 轮窗口还没成形（长度不到 k），此时答案无效
//
// 五、为什么是 O(n)
//     每个下标最多【进队一次】（②）、最多【出队一次】（①或③）
//     → 总操作 ≤ 2n → O(n)
//
// 六、和单调栈的关系（同一主线的第二种形态）
//     | | 单调栈（739/84/42） | 单调队列（本题） |
//     |---|---|---|
//     | 问的问题 | 什么时候扔掉候选 | 什么时候扔掉候选 |
//     | 出口个数 | 1 个（栈顶） | **2 个**（队尾比大小 + 队首判过期） |
//     | 保证 | 栈内单调 | 队内单调（本题递减，队首最大） |
//     | 数据结构 | stack | **deque** |
//     唯一的新东西：窗口是【滑动】的 → 元素会【从左边过期】→ 于是需要第二个出口。
//
// ============================================================
// 易错点（本人都踩过）
// ============================================================
//   ① 循环起点：`i` 必须从 0 开始（前 k 个元素也要在循环里入队）
//      写成 `int right = k` 会让下标 0..k-1 从未进队 → 第一个窗口的队列是空的
//      （`if (i >= k-1)` 这个条件已经负责"前 k-1 轮不记答案"，两者不要叠加）
//   ② 结果数组长度：答案只有 n-k+1 个
//      用 `push_back` 边算边加（长度自动对），或者 `ret(n)` + 返回时截取 [k-1, n)
//   ③ ③ 用 `if` 不是 `while`（每轮只滑一格，最多过期一个）
//   ④ 判断过期用【下标】比较，不能用"值相等"（值可能重复）
//   ⑤ `deque` 的 pop_back/pop_front 不返回被删的值 —— 要先 back()/front() 读
// ============================================================
// 实测：5 个验证用例全对；30000 组随机对拍 vs 暴力零不一致
//      （含负数值、k=1、k=n）；n=200000 k=1000 为 1.0 ms
// ============================================================

class Solution {
public:
    vector<int> maxSlidingWindow(vector<int>& nums, int k) {
        int n = nums.size();
        vector<int> ret(n);
        deque<int> q;                    // 存【下标】，队内按 nums 值递减
        int right = 0;
        while (right < n) {
            // ① 队尾清理：被 nums[right] 盖住的候选，永远当不了最大值了
            while (q.size() && nums[q.back()] < nums[right]) {
                q.pop_back();
            }
            // ② 入队
            q.push_back(right);
            // ③ 队首过期（窗口是 [right-k+1, right]）
            if (q.front() <= right - k) {
                q.pop_front();
            }
            // ④ 窗口成形后才记录答案
            if (right >= k - 1) {
                ret[right] = nums[q.front()];
            }
            right++;
        }
        // 答案填在下标 k-1..n-1，共 n-k+1 个
        return vector<int>(ret.begin() + k - 1, ret.end());
    }
};
