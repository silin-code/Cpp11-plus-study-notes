// ============================================================
// LeetCode 1684. 统计一致字符串的数目
// 考点：**位掩码表示"字符集合"**（26 个小写字母 -> 26 位）
// 复杂度：时间 O(L)（L = allowed + 所有单词的字符总数），空间 O(1)
// 日期：2026-09-30（一次通过）
// ============================================================
//
// 【题意】
// allowed 是一个由【互不相同】小写字母组成的字符串。
// 如果某个单词里的【所有字符】都在 allowed 里，就称这个单词"一致"。
// 返回 words 里一致单词的数目。
//
//     allowed = "ab",  words = ["ad","bd","aaab","baa","badab"]  ->  2
//     allowed = "abc", words = ["a","b","c","ab","ac","bc","abc"] ->  7
//     allowed = "cad", words = ["cc","acd","b","ba","bac","bad","ac","d"] -> 4
//
// ============================================================
// 【核心：一个字符串 -> 一个 mask】
// ============================================================
//     字符只有 26 种（小写字母），正好放 26 位。约定：
//         c - 'a'  就是它的位号      （'a'->bit0, 'b'->bit1, ...）
//
//     把一个字符串压成 mask：
//         for (char c : s) m |= 1 << (c - 'a');
//
//     这个 mask【完全等价于"这个字符串用了哪些字母"】——
//     字母出现多少次、什么顺序，全都不影响 mask。
//
//   ★ 这和 LC 464 是同一个思想：**用一个整数表示一个集合**。
//       464 表示的是"哪些数字被拿走了"，这里表示的是"哪些字母出现过"。
//
// ============================================================
// 【两种判"一致"的写法 —— 各有各的适用场景】
// ============================================================
//
// 【写法一】逐字符检查 + 早退出（**本题的最优选择**）
//     for (auto& w : words) {
//         bool ok = true;
//         for (char c : w)
//             if (!(amask & (1 << (c - 'a')))) { ok = false; break; }
//         if (ok) ret++;
//     }
//   优点：**一发现不在 allowed 里的字符就 break**，不用看完整个单词。
//
// 【写法二】子集判据
//     for (auto& w : words) {
//         int wm = 0;
//         for (char c : w) wm |= 1 << (c - 'a');
//         if ((wm & amask) == wm) ret++;       // wm 是 amask 的子集
//     }
//   判据：**A 是 B 的子集 ⟺ (A & B) == A**
//         （`&` 会把 A 里"B 没有的位"清掉；清完没变说明 A 每一位 B 都有。
//           等价写法：(A | B) == B）
//
//   ⚠️ 写法二在本题【没有优势】—— 它必须把整个单词压完才能判，没法早退出。
//
// ============================================================
// 【那子集判据什么时候才非用不可？】
// ============================================================
//   当"集合"需要【预先存起来、反复两两比较】的时候。
//
//   例：LC 318 最大单词长度乘积 —— 要比较【所有单词两两之间有没有公共字母】：
//       · 逐字符比：O(n^2 × 26)
//       · 预压成 mask：每对只要一次 `(mi & mj) == 0` → O(n^2 + L)
//
//   **判据：比较次数多到"不能每次重算集合"时，就用 mask 预存。**
//
// ============================================================
// 【易错点】
// ============================================================
//   ① 【别用 `-` 之外的偏移】位号必须是 `c - 'a'`（不是 `c` 本身、也不是 `c - 'A'`）。
//      用 `c` 本身会移 97~122 位，直接溢出/UB。
//
//   ② 【本题没有成员容器，所以没有"复位"问题】——
//      但如果把 `ret` 或 mask 改成成员变量，就要在入口复位。
//      （LC 78 / LC 486 都栽在这上面；这条已经是第四次提醒。）
//
//   ③ 【空字符串是"一致"的】空串没有任何字符 —— 所有字符都在 allowed 里（空真）。
//      实测 `allowed="a", words={"a","aa","b",""}` -> 3。
//
// ============================================================
// 【408 标注】"用位向量表示集合"是 408 里的常见手法（位示图 / 位向量）。
//   这类题练的就是"集合运算 → 位运算"的翻译：
//       并集 A|B　交集 A&B　差集 A&~B　子集 (A&B)==A　不相交 (A&B)==0
// ============================================================

// ============================================================
// 【用户自己的写法（收录原样，一次通过）】
// 逐字符检查 + 早退出 —— 本题的最优写法
// 实测：3 个官方示例全对；3000 组随机对拍与另两份独立实现零不一致；
//       边角（空字符串、words 为空）也对。
// ============================================================

class Solution {
public:
int countConsistentStrings(string allowed, vector<string>& words) {
int ret = 0;

// ① 把 allowed 的字母压成一个 mask
int mask = 0;
for (auto e : allowed)
{
mask = mask | (1 << (e - 'a'));       // 置位：把字母 e 对应的那一位置 1
}

// ② 逐个单词检查
for (auto& e : words)
{
int flag = 1;
for (auto w : e)
{
if (mask & (1 << (w - 'a')))      // w 这个字母在 allowed 里
{
continue;
}
else
{
flag = 0;
break;                        // ★ 早退出：一个字符不在就不用再看后面的
}
}
if (flag)
{
ret++;
}
}
return ret;
}
};

