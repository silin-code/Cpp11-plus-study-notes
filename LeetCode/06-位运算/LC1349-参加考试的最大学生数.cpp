// ============================================================
// LeetCode 1349. 参加考试的最大学生数（Maximum Students Taking Exam）
// 考点：**状压 DP** —— 状态 =（行号，这一行的坐法）
// 复杂度：时间 O(m × 2^n × 2^n)，空间 O(m × 2^n)
// 日期：2026-10-01（**第一道独立写出来的 hard 状压 DP**）
// ============================================================
//
// 【题意】
// 一个 m × n 的教室座位图：'.' 是好椅子，'#' 是坏椅子。
// 学生只能坐在好椅子上，且**任意两个学生不能互相看见**。
// 问最多能坐多少人。
//
// 【"谁能看见谁"——这条规则有个坑】
// 题目原文：学生能看见【左、右、左上、右上】的人；
//          看不见【正前方、正后方】的人。
//
//           左上 ✗    正上 ✓    右上 ✗
//           左   ✗    自己      右   ✗
//           左下 ?    正下 ?    右下 ?
//       （下排的三个由"下排那个学生"的规则覆盖，所以等价）
//
//   ⚠️ **正上方（同一列相邻两行）是允许的！** 这是最容易搞错的地方 ——
//      很多人第一反应会把正上方也禁掉，那答案就全错了。
//      → 行与行之间**只需要判两条对角线**。
//
// ============================================================
// 【核心一：状态怎么定】（本题的难点）
// ============================================================
//   一行一行往下安排。问一句："**排第 r 行时，我必须知道什么？**"
//
//   答案：**只需要知道第 r-1 行是怎么坐的。**
//      · 更上面的行（r-2、r-3…）碰不到第 r 行 —— 隔着一行，不在可见范围里
//      · 第 r 行自己的椅子坏不坏，是题目给的（不用"记"，直接查）
//
//   "一行怎么坐"就是一个 mask。所以：
//
//        dp[r][mask] = 第 r 行坐成 mask 时，前 r 行最多坐了几个人
//
//   ★ 这和前面几道题的 mask 有一个重要区别：
//         LC 464 的 mask = "选了哪些数"（选项的集合）
//         LC 1349 的 mask = "一排位置分别坐没坐人"（一排的状态）
//     —— mask 的**语义换了**，但"用整数表示一排东西"这个用法是一样的。
//
// ============================================================
// 【核心二：三条位运算判据】（全部是"移位 → & → 看是不是 0"）
// ============================================================
//   【判据 1】行内：mask 里不能有两个相邻的 1
//        (mask & (mask << 1)) == 0
//      读法：把 mask 左移一位再和自己与 —— 有相邻的 1 就会撞上。
//
//   【判据 2】这一行的坐法不能落在坏椅子上
//        (mask & bad[r]) == 0
//      就是判"两个集合有没有交集"—— 和 LC 318 的 (m[i] & m[j]) == 0 同一个形状。
//
//   【判据 3】行间：上一行的 prev 和这一行的 mask 能不能共存
//        (mask & ((prev << 1) | (prev >> 1))) == 0
//      读法：prev 的每一位 c，管到下一行的 c-1 和 c+1 位
//            （prev<<1 得 c+1，prev>>1 得 c-1，并起来就是"所有被管到的位置"）
//            再和 mask 求交 —— 非 0 就是被看见了。
//      ★ 判据 1 和判据 3 是**同一个套路**：移位 → & → 看是不是 0。
//
// ============================================================
// 【递推】
// ============================================================
//   ① 预处理每行的坏椅子 mask：bad[r]
//   ② dp[r][mask]：第 r 行坐成 mask 时，前 r 行最多几个人
//   ③ 第 0 行单独处理（它没有"上一行"）：
//        合法就 dp[0][mask] = popcount(mask)
//   ④ 第 1 行起：
//        dp[r][mask] = popcount(mask) + max{ dp[r-1][k] }
//        （k 遍历上一行的坐法，只取满足判据 3 的）
//        前置条件：mask 满足判据 1 和判据 2（针对第 r 行）
//   ⑤ 答案 = max over mask of dp[m-1][mask]
//
//   ★ **不需要哨兵**：`k = 0`（上一行没人）永远满足判据 3，
//     所以每个合法 mask 都是可达的，不用 -1 标记"到不了"。
//
// 【复杂度】状态 m × 2^n ≤ 8 × 256 = 2048，每个状态遍历 2^n 个 k
//          → 约 5 × 10⁵，非常宽裕。
//
// ============================================================
// 【易错点（本题实际踩过的）】
// ============================================================
//   ① 【转移里写 `bad[0]`】循环变量是 i，却用了 bad[0]。
//      只有"每行坏椅子分布完全相同"时才对。
//
//   ② 【`for (auto e : dp[i-1])` —— e 是【值】不是【下标】】★最致命
//      `e` 拿到的是 `dp[i-1][k]` 的**值**（人数，0/1/2/3…），
//      而你需要的**上一行的 mask** 是 `k`。
//      于是把"人数"当 mask 用、又当索引去查表 → 语义全错。
//      修正：用下标循环，`k` 才是 mask；取人数用 `dp[i-1][k]`。
//
//   ③ 【括号少一层】`((e << 1) | (e >> 1) & mask) == 0`
//      `&` 的优先级**高于** `|` → 被解析成 `(e<<1) | ((e>>1) & mask)`。
//      正确：`(((e << 1) | (e >> 1)) & mask) == 0`。
//      （和 LC 318 那个优先级坑是同一个。）
//
//   ④ 【变量名】本题里同时有"mask"和"人数"两种 int，长得一样但含义完全不同。
//      `e` 这种名字看不出是哪种 → 一定会搞混。
//      **变量名要能看出它是什么**：`prevMask` / `cnt`。
//
// 【408 标注】状压 DP 是把"集合/一排的状态"编码进整数的二进制位，
//   本质是"用位向量表示集合"（408 里的位示图 / 位向量是同一个思想）。
// ============================================================

class Solution {
int n, m;
vector<int> bad;                    // bad[r] = 第 r 行坏椅子的 mask
public:
int maxStudents(vector<vector<char>>& seats) {
n = seats.size(), m = seats[0].size();

// ① 预处理：每行的坏椅子压成一个 mask
//    （约定：bit j 对应 seats[r][j]，左右方向不影响答案 —— 本题左右对称）
bad.resize(n);
for (int i = 0; i < n; i++) {
int mask = 0;
for (int j = seats[i].size() - 1; j >= 0; j--) {
if (seats[i][j] == '#') {
mask |= (1 << j);
}
}
bad[i] = mask;
}

// ② dp[r][mask]：第 r 行坐成 mask 时，前 r 行最多坐几个人
vector<vector<int>> dp(n, vector<int>(pow(2, m), 0));

// ③ 第 0 行：没有"上一行"的约束
for (int i = 0; i < pow(2, m); i++) {
int mask = i;
// 判据 1（行内不相邻）+ 判据 2（不坐坏椅子）
if (((mask & bad[0]) == 0) && (((mask << 1) & mask) == 0)) {
int count = 0;
while (mask) {
if (mask & 1)
count++;
mask >>= 1;
}
dp[0][i] = count;
}
}

// ④ 第 1 行起：要同时看"上一行怎么坐的"
for (int i = 1; i < n; i++) {
for (int j = 0; j < pow(2, m); j++) {
int mask = j;
// 判据 1 + 判据 2 —— 注意是 bad[i]，不是 bad[0]
if (((mask & bad[i]) == 0) && (((mask << 1) & mask) == 0)) {
// k 是【上一行的坐法】（不是上一行的值！）
for (int k = 0; k < (int)dp[i - 1].size(); k++) {
// 判据 3：两条对角线不冲突（正上方允许）
if ((((k << 1) | (k >> 1)) & mask) == 0)
dp[i][mask] = max(dp[i][mask], dp[i - 1][k] + getnum(mask));
}
}
}
}

// ⑤ 答案：最后一行的最大值
int ret = 0;
for (int i = 0; i < pow(2, m); i++) {
ret = max(ret, dp[n - 1][i]);
}
return ret;
}

int getnum(int mask) {                 // 数 mask 里有几个 1
int count = 0;
while (mask) {
if (mask & 1)
count++;
mask >>= 1;
}
return count;
}
};

