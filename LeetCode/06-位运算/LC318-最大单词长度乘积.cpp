//
//   LC 464   状压 DP：状态就是一个集合（哪些数被拿走了）+ 博弈
//   LC 78    枚举所有子集：mask 就是子集本身
//   LC 1684  mask 表示字符集合，**只用一次** -> 逐字符检查更优
//   LC 318   mask 表示字符集合，**反复两两比较** -> 预压才划算  ← 本文件
//
// 一句话总括：
//     集合 -> 一个整数；集合运算 -> 一次位运算；
//     **要反复比较 -> 预存成 mask。**
// ============================================================
