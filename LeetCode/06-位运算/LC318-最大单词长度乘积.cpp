// ============================================================
// LeetCode 318. 最大单词长度乘积
// 考点：**mask 表示字符集合**，而且是"**预先存起来、反复两两比较**"的那种用法
// 复杂度：时间 O(L + n^2)（L = 所有字符总数），空间 O(n)
// 日期：2026-09-30（一轮修正后通过）
// ============================================================
//
// 【题意】
// 给一个字符串数组 words，找【两个不同的单词】，它们【没有公共字母】，
// 使它们【长度之积】最大。返回这个最大乘积；没有这样的两个单词就返回 0。
//
//     ["abcw","baz","foo","bar","xtfn","abcdef"]      -> 16  （"abcw" × "xtfn" = 4×4）
//     ["a","ab","abc","d","cd","bcd","abcd"]           -> 4   （"ab" × "cd" = 2×2）
//     ["a","aa","aaa","aaaa"]                          -> 0   （都含 'a'，两两都有公共字母）
//
// ============================================================
// 【核心一：为什么要把 mask "预存起来"】
// ============================================================
//   朴素做法：每比较一对 (i,j)，就去扫一遍 words[i] 和 words[j] 看有没有公共字母
//       -> 每对 O(|wi| + |wj|)，总共 O(n^2 × 平均长度)
//
//   mask 做法：**先把每个单词压成一个 mask 存进数组**，然后每对只要一次位运算
//       -> 预压 O(L)，之后每对 O(1)，总共 O(L + n^2)
//
//   ★ 这就是"**用 mask 表示集合**"从"用一次"升级到"**反复用**"的那一级台阶。
//      判据：**当集合需要被反复比较时，就值得先存成 mask。**
//      （对照 LC 1684：那里每个单词只比一次，用"逐字符检查 + 早退出"反而更好。）
//
// ============================================================
// 【核心二：交集判据 —— "没有公共字母"】
// ============================================================
//     if ((m[i] & m[j]) == 0)
//
//   为什么：`&` 求交集。交集为 0 就是"一个共同字母都没有"。
//
//   集合运算对照（背下来）：
//       并集 A|B    交集 A&B    差集 A&~B
//       A 是 B 的子集 (A&B)==A      A、B 不相交 (A&B)==0      A 为空 A==0
//
// ============================================================
// 【核心三：长度直接取 size()，不要去数 mask 里的 1】
// ============================================================
//   ⚠️ **mask 里 1 的个数 = "出现了几种字母"，不是"单词长度"**：
//
//        单词      长度    mask      mask 里 1 的个数
//        "aaa"      3      0b001          1        ← 不等！
//        "aaab"     4      0b011          2        ← 不等！
//
//   重复字母只占一位。所以长度必须用 `words[i].size()`。
//   （"数 1 的个数"只在【单词内字母互不相同】时才等于长度，而题目没这个保证。）
//
// ============================================================
// 【易错点（本题踩过的）】
// ============================================================
//   ① 【`|` 和 `&` 用反】"没有公共字母"是**交集**为空 -> 要用 `&`。
//      写成 `|` 就成了"并集为空"，那只在两集合【都空】时成立 —— 完全不是这个意思。
//
//   ② 【优先级坑（必须背）】
//          `&`、`|`、`^` 的优先级都【低于】`==`、`!=`、`<`、`>`。
//
//          写成 `m[i] | m[j] == 0`  会被解析成  `m[i] | (m[j] == 0)`  —— 全错。
//          正确：`(m[i] & m[j]) == 0`   **位运算必须自己加括号。**
//
//   ③ 【想用"数 1 的个数"当长度】见核心三，重复字母会丢。
//      加了那两段 while 不但多余，还会因为下面的 ④ 直接死循环。
//
//   ④ 【`cur1 >> 1;` 没接住 -> 死循环】
//          `x >> 1` 单独成句 = **算了一下就扔掉**，x 一点没变。
//          必须有 `=`（`cur1 >>= 1`），或者把结果用掉。
//          ⚠️ 这是**第二次**栽在 `>> 1;` 上（第一次是 `printBinary` 里的 `x >> 1;`）。
//          编译器用 `-Wall` 会报 `statement has no effect`，开警告就能提前抓。
//
//   ⑤ 【内层循环从 j = i 开始】会把自己和自己配一次。
//      标准是 `j = i + 1`（两个**不同**的单词）。
//      本题里自己配自己不会算出错答案（`mask & 自己 != 0` 会被排除），
//      但多跑 n 次、意图不清。
//
//   ⑥ 【签名/返回值的类型】`words[i].size()` 是 `size_t`，两个相乘还是 `size_t`；
//      `max(int, size_t)` 会有类型推导问题 -> 显式转 `(int)` 最稳。
//
// 【408 标注】"用位向量表示集合"是 408 常见手法（位示图 / 位向量）。
//   本题练的就是"集合运算 -> 位运算"的翻译。
// ============================================================

class Solution {
public:
int maxProduct(vector<string>& words) {
int n = words.size();

// ① 预压：把每个单词压成一个 26 位的 mask（bit c-'a' 表示字母 c 出现过）
//    —— 预存下来，后面每次比较就不用重扫字符串了
vector<int> m(n, 0);
for (int i = 0; i < n; i++) {
for (auto w : words[i])
m[i] |= 1 << (w - 'a');
}

int ret = 0;
for (int i = 0; i < n; i++) {
for (int j = i + 1; j < n; j++)          // j 从 i+1 起：两个【不同】的单词
{
if ((m[i] & m[j]) == 0)              // 交集为空 = 没有公共字母（括号一定要包住位运算）
{
// 长度直接取 size()，不要数 mask 里的 1
ret = max(ret, (int)(words[i].size() * words[j].size()));
}
}
}
return ret;
}
};

