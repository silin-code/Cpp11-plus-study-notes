// ============================================================
// LeetCode 1870. 准时到达的列车最小时速
// 考点：二分答案（浮点 check + 最后一趟不取整）
// 复杂度：时间 O(n log 10^7)，空间 O(1)
// 日期：2026-09-14
// ============================================================
//
// 【题意】
// 依次乘 n 趟列车。第 i 趟在第 i-1 小时**准点发车**，路上耗时 dist[i]/speed 小时。
// 必须在 hour 小时内到达（hour 可为小数）。求最小的整数速度。
//
// 【核心：只有最后一趟不取整】
// 除最后一趟外，每趟都必须等到整点才能坐上下一趟，
// 所以前 n-1 趟的时间要**向上取整**，最后一趟到了就结束、保留小数。
//
// 【无解判断】
// 前 n-1 趟每趟至少 1 小时，加上最后一趟的正时间，总时间严格大于 n-1。
// 所以 hour <= n-1 时必然无解 → 返回 -1。（注意是 <=，不是 <）
//
// 【上下界】
//   lo = 1
//   hi = 10^7（题目给出的速度范围上界）
//
// 【易错：强制转换的位置】
//   (double)a / b      先转再除 → 浮点除法，保留小数 ✅
//   a / (double)b      同上 ✅
//   (double)(a / b)    括号里已经整数除完，小数早丢了 ❌
// 想要小数，必须在**做除法之前**把其中一个操作数变成浮点。
//
// 【易错：浮点比较】
// time <= hour 可能有精度误差，写成 time <= hour + 1e-9 更稳。
//
// 【可简化处】
// 上面那段"浮点除 + 判断是否整除"的向上取整，可以直接用整数写法：
//     time += (dist[i] + mid - 1) / mid;
// 更短，而且没有浮点比较的不确定性。
// 另外 hi = 1e7 是 double 字面量，写成 10000000 更明确。
// ============================================================

class Solution {
public:
    int minSpeedOnTime(vector<int>& dist, double hour) {
        if (hour <= dist.size() - 1) return -1;    // 时间不够，无解

        int n = dist.size();
        int lo = 1, hi = 1e7;

        while (lo < hi) {
            int mid = lo + (hi - lo) / 2;          // 速度

            double time = 0.0;
            for (int i = 0; i < n; i++) {
                if (i != n - 1) {
                    // 前 n-1 趟：要等整点 → 向上取整
                    double flag1 = (double)dist[i] / mid;
                    int flag2 = (int)dist[i] / mid;
                    if (flag1 - flag2 != 0) {
                        time += (flag2 + 1);       // 有小数 → 进位
                    } else {
                        time += flag1;             // 整除，直接用
                    }
                } else {
                    // 最后一趟：到了就结束 → 不取整，保留小数
                    time += (double)dist[i] / mid;
                }
            }

            if (hour >= time) hi = mid;            // 时间够 → 往小逼
            else              lo = mid + 1;        // 时间不够 → 往大逼
        }
        return lo;
    }
};
