// ============================================================
// LeetCode 410. 分割数组的最大值
// 考点：二分答案 · 最大值最小化（check = 最少段数）
// 复杂度：时间 O(n log(sum(nums)))，空间 O(1)
// 日期：2026-09-14 初版 / 2026-09-17 不看代码重写，2'08" 一次通过
// ============================================================
//
// 【题意】
// 把数组切成 k 段连续的非空子数组，使「各段和的最大值」尽可能小，
// 返回这个最小值。
//
// 【信号词】
// "让最大的那个尽量小" = 最大值最小化 = 二分答案。
// 二分对象是「段和的上限 mid」：问在每段和都不超过 mid 的前提下，
// 最少能切成几段。
//
// 【为什么 cur <= k 就代表可行】
// 贪心算出的 cur 是"最少需要几段"。题目要恰好 k 段：
//   cur <= k → 把某些段再锯开（锯开后每段和只会更小，仍 <= mid）
//              就能凑到 k 段 → 可行
//   cur >  k → 连最少段数都超过 k → 不可行
// （能把段锯开的前提是每段至少 2 个元素，题目保证 k <= n，总锯得出来。）
//
// 【上下界】
//   lo = max(nums)：单个元素就超过 mid 的话，它所在段必然超标
//   hi = sum(nums)：全部合成一段
//
// 【为什么 int 够用 —— 算过才敢用】
//   约束：n ≤ 1000，0 ≤ nums[i] ≤ 10^6
//   hi 最大 = 1000 × 10^6 = 10^9
//   int 上限 = 2.147×10^9  → 余量 2.15 倍，安全
//   （比 LC 304 / 560 薄：那两道余量分别是 5.37 倍 / 21 倍）
//   实测 n=1000 全 10^6、k=1 → 返回 10^9，正确。
//
// 【易错（09-15 小测两个坑，重写已全部修掉）】
// 1. lo 的起手值：求最大值要用 lo = 0 配 max()，
//    写成 lo = INT_MAX 配 max() 会恒等于 INT_MAX（循环跑完什么都没变）。
// 2. if 里写了 sum = 0，外面的 sum += e 要保留；
//    写成 if { sum = e; } 时，外面的 sum += e 就必须挪进 else。
//    两处只能有一个地方给 sum 加 e。
// ============================================================

class Solution {
public:
    int splitArray(vector<int>& nums, int k) {
        int lo = 0, hi = 0;
        for (auto e : nums) {
            lo = max(e, lo);                   // 下界：至少要能装下最大的元素
            hi += e;                           // 上界：全部合成一段
        }

        while (lo < hi) {
            int mid = lo + (hi - lo) / 2;

            // check：以 mid 为段和上限，最少需要切几段
            int cur = 1;                       // 至少一段
            int sum = 0;                       // 当前段的和
            for (auto e : nums) {
                if (sum + e > mid) {           // 装不下 → 新开一段
                    cur++;
                    sum = 0;
                }
                sum += e;                      // 当前元素总是要装进去
            }

            if (cur > k) lo = mid + 1;         // 段数太多 → 上限要更大
            else         hi = mid;             // 段数够少 → 试试更小的上限
        }
        return lo;
    }
};
