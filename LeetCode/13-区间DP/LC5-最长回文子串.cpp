// ============================================================
// LC 5 最长回文子串 —— 区间 DP 巩固（形态 A：看两端）
// ------------------------------------------------------------
// 考点：区间 DP + 【连续】子串判断
// 复杂度：时间 O(n²)，空间 O(n²)
// 日期：2026-11-07（周六嵌入式日，巩固 516/1039 的骨架）
// 定位：**练骨架，不是练最优解**（更优解见文末）
// ------------------------------------------------------------
// 题意：
//   给字符串 s，找出最长的【回文子串】（必须是【连续】的一段）并返回它。
//
//     "babad" -> "bab"（"aba" 也对，长度相同都算对）
//     "cbbd"  -> "bb"
//
// ------------------------------------------------------------
// 【和 LC 516 的关系：同一个骨架，改三处】
// ------------------------------------------------------------
//                  LC 516 子序列            LC 5 子串
//   连续性          可以不连续               必须连续
//   dp[l][r] 存     最长长度（int）          是否回文（bool）
//   转移            取 max                   只是 true/false 判断
//   遍历顺序        i 递减 + j 递增          完全一样
//   答案            dp[0][n-1]               要在填表时记录 max
//
// ------------------------------------------------------------
// 【状态定义】
// ------------------------------------------------------------
//   dp[l][r] = s[l..r] 这一段是不是回文（bool）
//
//   本文件用 1-based：dp[i][j] 对应 s[i-1..j-1]，i/j 取 1..n。
//
// ------------------------------------------------------------
// 【转移】
// ------------------------------------------------------------
//   s[i-1] != s[j-1]  ->  false（两端不一样，肯定不是回文；保持初始 false 即可）
//
//   s[i-1] == s[j-1]  ->  再看里面：
//        j - i <= 2  ->  true     ★ 长度 1 / 2 / 3 的特判
//        j - i >  2  ->  dp[i+1][j-1]
//
//   ★ 为什么 j-i <= 2 要单独判：
//        长度 1（i==j）：单字符，回文
//        长度 2（j=i+1）：两字符相同，回文
//        长度 3（j=i+2）：X ? X，中间是什么都无所谓，回文
//        这三种情况 dp[i+1][j-1] 都是"左 > 右"的空区间，
//        没有意义（值是初始 false），不能直接用。
//
// ------------------------------------------------------------
// 【★ 遍历顺序（本次又踩了一次，记牢）】
// ------------------------------------------------------------
//   dp[i][j] 依赖 dp[i+1][j-1]  ——  在【右下】方向
//
//   =>  i 必须【递减】（保证 i+1 那一行先算完）
//   =>  j 必须【递增】（保证 j-1 那一列先算完）
//
//   口诀：**区间 DP：外层 i 从右往左，内层 j 从左往右。**
//   原因：所有区间 DP 都依赖"更短的区间"，
//         而更短的区间一定在当前格的【下一行】或【左边】。
//
//   写成 i 递增的后果：dp[i+1][j-1] 还是初始值，
//   实测所有用例都返回空串 ""。
//
// ------------------------------------------------------------
// 【答案怎么记（★ 和 516 最大的区别）】
// ------------------------------------------------------------
//   516 问"整个串的最长回文子序列长度" -> 答案就是 dp[0][n-1]
//   5   问"所有回文子串里最长的那个"   -> 答案不在固定位置
//
//   所以要两个变量：
//        left  、right  = 当前找到的最长回文子串的【1-based 区间】
//   每发现一个 dp[i][j] == true，就比较长度：
//        if (dp[i][j] && (right - left < j - i))
//            left = i, right = j;
//
//   初始 left = 1, right = 0（一个空区间，长度 0）
//   -> right - left = -1 < j - i（j >= i，所以 j-i >= 0）恒成立
//   -> 第一个真回文一定能更新进去 ✓
//
// ------------------------------------------------------------
// 【substr 的两个参数（★ 本次踩的坑，很常见）】
// ------------------------------------------------------------
//   string::substr(pos, len)
//                   ↑    ↑
//                起始位置  长度（不是结束下标！）
//
//   本文件 left/right 是 1-based 的区间 [left, right]：
//        起始位置 = left - 1      （转成 0-based）
//        长度     = right - left + 1
//
//   -> return s.substr(left - 1, right - left + 1);
//
//   写错成 s.substr(left, right) 会得到空串或无意义的结果。
//
// ------------------------------------------------------------
// 【本次踩的 4 个坑】
// ------------------------------------------------------------
//   ① i 递增（应递减）              -> dp[i+1][j-1] 还没算，全 false
//   ② 缺 j-i<=2 特判                -> 长度 2 的 "bb" 被判成非回文
//   ③ j 从 i 开始 + 无条件覆盖       -> dp[i][i] 被覆盖成 false，单字符都检测不到
//      （加了 ② 之后这个覆盖自然无害，因为 j-i=0 也走 true 分支）
//   ④ s.substr(left, right)         -> 第二个参数是长度，且 1-based 要减 1
//
// ------------------------------------------------------------
// 【更优解（今天不用，但要知道）】
// ------------------------------------------------------------
//   中心扩展：枚举中心（奇数 2n-1 个 + 偶数 n-1 个），向两边扩
//            时间 O(n²)，空间 O(1)   ← 空间比区间 DP 好
//   Manacher：时间 O(n)，空间 O(n)   ← 面试/竞赛的"最优解"
//
//   今天用区间 DP 写，目的是把 516/1039 的骨架变成肌肉记忆，
//   不是因为这题的最优解是区间 DP。
//
// ------------------------------------------------------------
// 实测：10 个固定用例 + 3000 组随机对拍（与暴力比长度）零不一致
// ============================================================

#include <string>
#include <vector>
using namespace std;

class Solution {
public:
    string longestPalindrome(string s) {
        int n = s.size();

        // dp[i][j] = s[i-1..j-1] 是不是回文（1-based）
        // 多开两行两列，是为了 i+1 / j-1 不越界
        vector<vector<bool>> dp(n + 2, vector<bool>(n + 2, false));

        int left = 1, right = 0;      // 当前最长回文子串的 1-based 区间（初始为空）

        // ★ i 递减（从右往左），j 递增（从左往右）
        for (int i = n; i >= 1; i--) {
            dp[i][i] = true;          // 单字符一定是回文

            for (int j = i; j <= n; j++) {
                if (s[i - 1] == s[j - 1]) {
                    if (j - i <= 2) {
                        dp[i][j] = true;          // 长度 1/2/3：两端相同即回文
                    } else {
                        dp[i][j] = dp[i + 1][j - 1];   // 长度 >= 4：看里面
                    }
                }
                // 两端不同时保持初始值 false，不用显式赋值

                // 更新最长（right-left 是当前长度-1，j-i 是新区间长度-1，直接比即可）
                if (dp[i][j] && (right - left < j - i)) {
                    left = i;
                    right = j;
                }
            }
        }

        // substr(起始位置, 长度)：1-based -> 0-based
        return s.substr(left - 1, right - left + 1);
    }
};
