// ============================================================
// LC 516 最长回文子序列 —— 区间 DP 入门
// ------------------------------------------------------------
// 考点：区间 DP（状态是 [l, r]，不是"前 i 个"）
// 复杂度：时间 O(n²)，空间 O(n²)
// 日期：2026-11-06（改了 2 版：① 1-based 版遍历顺序错 ② 0-based 简化 + j 方向）
// ------------------------------------------------------------
// 题意：
//   给字符串 s，求最长回文子序列的长度（可不连续，顺序保持）。
//
//     "bbbab" -> 4   （"bbbb"）
//     "cbbd"  -> 2   （"bb"）
//
// ------------------------------------------------------------
// 【状态定义】
// ------------------------------------------------------------
//   dp[l][r] = s 的下标区间 [l, r] 里，最长回文子序列的长度
//
//   和前四类 DP 的区别：
//     背包 / LIS / LCS / 打家劫舍：状态都是"前缀视角"（前 i 个）
//     区间 DP：左右两端都是变量 -> dp[l][r]
//
//   为什么必须这样：回文是"两头往中间收缩"的结构，
//   "前 i 个的最长回文"这个定义根本推不出转移。
//
// ------------------------------------------------------------
// 【转移：只看两端 s[l]、s[r]】
// ------------------------------------------------------------
//   s[l] == s[r]：这两个字符可以同时放进回文两端
//        dp[l][r] = dp[l+1][r-1] + 2      ← 两头剥掉，看里面
//
//   s[l] != s[r]：至少一个不能进回文
//        dp[l][r] = max(dp[l+1][r],      ← 丢掉左端
//                       dp[l][r-1])      ← 丢掉右端
//
// ------------------------------------------------------------
// 【★ 遍历顺序：区间 DP 唯一的新东西】
// ------------------------------------------------------------
//   dp[l][r] 依赖两格：
//       dp[l+1][r]   下一行，同一列      -> 要求 i 递减（下面那行先填完）
//       dp[l][r-1]   本行，左边一格      -> 要求 j 递增（左边那格先填完）
//
//   => 外层 i 从 n-1 递减到 0，内层 j 从 i+1 递增到 n-1   （本文件采用）
//
//   等价写法：按区间长度 len 从 2 到 n（"按对角线填表"）
//       for (len = 2; len <= n; len++)
//           for (l = 0; l + len - 1 < n; l++) { r = l + len - 1; ... }
//
//   两种都能满足依赖，只是"走法"不同：一个横着扫、一个斜着扫。
//   本文件的写法少一个 len 变量。
//
// ------------------------------------------------------------
// 【边界】
// ------------------------------------------------------------
//   dp[i][i] = 1                 单字符本身就是长度 1 的回文
//   j 从 i+1 开始                ★ 若从 i 开始，j==i 会把 dp[i][i] 覆盖成 2
//   dp 初始化为 0                ★ len=2 时 dp[l+1][l]（左>右的空区间）必须是 0
//
// ------------------------------------------------------------
// 【本次踩的坑】
// ------------------------------------------------------------
//   第 1 版（1-based，dp 开 n+2）：
//       · 遍历写成 i 递增 + j 递增  -> dp[i+1][j] 还没算，读到初始值
//       · dp 初始化为 1             -> 空区间贡献 1 而不是 0，len=2 变成 3
//       · else 分支多了 +1           -> 丢一个端点，长度不会凭空 +1
//       · return dp[0][n]            -> i/j 从 1 起，整串是 dp[1][n]
//       · i==j 没单独处理
//       => 官方样例全错，恒返回 1
//
//   第 2 版（0-based，用户自己简化）：
//       · 遍历写成 i 递减 + j 递减  -> dp[i][j-1] 还没算
//       · i 从 n 起、j 到 n         -> 越界
//       · j 从 i 起                 -> 覆盖 dp[i][i]
//       => "a" 返回 2
//
//   第 3 版（本文件）：i 递减 + j 递增 + j 从 i+1 起，全对 ✓
//
// ------------------------------------------------------------
// 实测：8 个用例全过；与"按 len"版随机对拍 3000 组零不一致
// （C++ exe 被 Device Guard 拦，用 Python 等价逻辑对拍）
// ============================================================

#include <string>
#include <vector>
#include <algorithm>
using namespace std;

class Solution {
public:
    int longestPalindromeSubseq(string s) {
        int n = s.size();
        vector<vector<int>> dp(n, vector<int>(n, 0));   // n×n，不用 +2

        for (int i = 0; i < n; i++)
            dp[i][i] = 1;                               // 单字符 = 1

        for (int i = n - 1; i >= 0; i--) {              // ★ i 递减：下面那行先填完
            for (int j = i + 1; j < n; j++) {           // ★ j 递增，且跳过 j==i
                if (s[i] == s[j]) {
                    dp[i][j] = dp[i + 1][j - 1] + 2;    // 两头相同：剥掉 +2
                } else {
                    dp[i][j] = max(dp[i + 1][j], dp[i][j - 1]);  // 丢一端
                }
            }
        }
        return dp[0][n - 1];                            // 整个串
    }
};

