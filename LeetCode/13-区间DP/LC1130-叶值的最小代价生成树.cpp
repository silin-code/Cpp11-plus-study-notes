// ============================================================
// LC 1130 叶值的最小代价生成树 —— 区间 DP 与贪心两种解法
// ------------------------------------------------------------
// 考点：区间 DP（枚举切分线） / 贪心（每次合并相邻最小乘积）
// 复杂度：解一 O(n³) / 解二 O(n²)（n ≤ 40，都够）
// 日期：2026-11-17
// ------------------------------------------------------------
// 题意：
//   给正整数数组 arr，构造一棵满二叉树（每节点 0 或 2 个子节点）：
//       · 叶子按【中序】顺序对应 arr[0..n-1]
//       · 每个非叶节点的值 = 左子树叶子最大值 × 右子树叶子最大值
//   求所有非叶节点值之和的最小值。
//
//     [6,2,4]  ->  32
//     [4,11]   ->  44
//
// ============================================================
// 【一、先解决一个概念：中序遍历】
// ============================================================
//       1
//      / \
//     2   3
//    / \
//   4   5
//
//   前序（根左右）：1 2 4 5 3
//   中序（左根右）：4 2 5 1 3
//   后序（左右根）：4 5 2 3 1
//
//   ★ 名字里的"前/中/后"，指的是【根】排在第几位。
//
//   ★ 注意："BST 的中序是升序"是 BST 的性质，不是中序的定义。
//     本题的树不是 BST，不能用"升序"去想。
//
//   ★ "叶子按中序 = arr" 的意思是：
//       叶子没有子节点，遍历它们时退化成"就访问自己"
//       -> 中序遍历会从左到右把叶子逐个走一遍
//       -> 即：叶子从左到右依次是 arr[0], arr[1], ...
//
// ============================================================
// 【二、解一：区间 DP —— 状态是推出来的】
// ============================================================
//   起点是这句话：**根节点把叶子序列切成连续的两段。**
//
//       arr = [a, b, c, d] 时，根只有三种切法：
//           k=0: [a] | [b,c,d]
//           k=1: [a,b] | [c,d]
//           k=2: [a,b,c] | [d]
//
//       因为叶子顺序固定，左子树只能拿【前缀】，右子树只能拿【后缀】，
//       不可能交叉 -> 所以"整棵树"拆成"两个更短的区间"。
//
//   状态：
//       dp[i][j] = 用 arr[i..j] 这段叶子构成一棵子树的最小总代价
//
//   转移：
//       dp[i][j] = min over k ∈ [i, j-1] of
//                  dp[i][k] + dp[k+1][j] + mval[i][k] * mval[k+1][j]
//                  左子树      右子树        根的值
//
//   为什么还要 mval：
//       根的值 = 左子树叶子最大值 × 右子树叶子最大值
//       dp 只存"最小代价"，不知道最大值 -> 需要一张辅助表
//       mval[i][j] = max(arr[i..j])
//
//       ★ 这不是"多一个状态"，而是"转移时要查的表"。
//
//   与 1039/312 的唯一差别（最容易写错的一行）：
//       1039/312：dp[i][k] + dp[k][j]       k 是【公共端点】
//       1130    ：dp[i][k] + dp[k+1][j]     k 是【切分线】
//
//   遍历顺序（第三种写法）：
//       j 递增，i 在 j 内部递减
//       依赖验证：
//           dp[i][k]   右端点 k<j  -> 之前的 j 轮（j 递增保证）
//           dp[k+1][j] 左端点 >i  -> 本轮 i 更大时（i 递减保证）
//
//       （已知三种等价写法：
//            A. i 递减 + j 递增        —— 516 / 1039 / 312
//            B. len 递增 + l 递增      —— 通用对角线
//            C. j 递增 + i 递减        —— 本题）
//
//   mval 的递推技巧：
//       mval[i][j] = max(arr[i], mval[i+1][j])
//       （i 递减，所以 mval[i+1][j] 刚算过；省掉单独的 O(n²) 预处理）
//
// ============================================================
// 【三、解二：贪心 —— 每次合并"相邻最小乘积"】
// ============================================================
//   思路：
//       反复执行：
//           找相邻两数乘积最小的那一对
//           累加这个乘积
//           删掉其中【较小的那个数】
//       直到只剩一个元素。
//
//   为什么能这样贪（直觉）：
//       每个非叶节点贡献一次"左max × 右max"。
//       一个数如果两边都有比它大的，那它迟早是"被乘掉的那一方"
//       （它只会作为较小值出现在某个乘积里，而不是作为 max）。
//       所以让它尽早和"更小的那个邻居"配对，代价最小。
//
//       ★ 严格证明要用到"局部最小值可以先消除"的交换论证，
//         竞赛里记住结论即可（和 Huffman 的贪心思路同源）。
//
//   正确性验证（不在理论上纠结，直接对拍）：
//       与解一随机对拍 3000 组，零不一致。
//
//   复杂度：
//       每次扫描 O(n) + erase O(n) -> O(n²)
//       （还有 O(n) 的单调栈写法，本题 n≤40 用不上）
//
// ============================================================
// 【四、为什么"叶子的顺序不能变"】
// ============================================================
//   如果允许排序，那答案就是"每次拿最小的两个相乘"，会简单得多。
//   但题目保证"叶子按中序 = arr"，顺序固定，所以只能用"相邻合并"。
//
//   这也是贪心版每轮只比较【相邻】元素的原因。
//
// ============================================================
// 实测：
//   [6,2,4] -> 32   [4,11] -> 44   [6,2,4,3] -> 44   [1] -> 0
//   [5,5] -> 25     [3,7,2,9,4] -> 134
//   两个解法随机对拍 3000 组零不一致
// ============================================================

#include <vector>
#include <algorithm>
#include <climits>
using namespace std;

// ------------------------------------------------------------
// 解一：区间 DP（O(n³)）—— 用来理解"状态怎么来的"
// ------------------------------------------------------------
class Solution {
public:
    int mctFromLeafValues(vector<int>& arr) {
        int n = arr.size();

        vector<vector<int>> dp(n, vector<int>(n, INT_MAX));  // 最小代价
        vector<vector<int>> mval(n, vector<int>(n));         // 区间最大值

        for (int j = 0; j < n; j++) {
            mval[j][j] = arr[j];
            dp[j][j] = 0;                    // 单个叶子，不用合并

            for (int i = j - 1; i >= 0; i--) {
                // 区间 [i,j] 的最大值 = max(第一个, 区间 [i+1,j] 的最大值)
                mval[i][j] = max(arr[i], mval[i + 1][j]);

                // 枚举根的位置 k：左拿 [i,k]，右拿 [k+1,j]
                for (int k = i; k < j; k++) {
                    dp[i][j] = min(dp[i][j],
                        dp[i][k] + dp[k + 1][j] + mval[i][k] * mval[k + 1][j]);
                }
            }
        }
        return dp[0][n - 1];
    }
};

// ------------------------------------------------------------
// 解二：贪心（O(n²)）—— 代码短，但要接受"这个贪心是对的"
// ------------------------------------------------------------
class Solution2 {
public:
    int mctFromLeafValues(vector<int>& arr) {
        vector<int> a = arr;         // 拷贝一份，不破坏入参
        int res = 0;

        while (a.size() > 1) {
            // 找相邻乘积最小的一对
            int best = INT_MAX, idx = -1;
            for (int i = 0; i < (int)a.size() - 1; i++) {
                if (a[i] * a[i + 1] < best) {
                    best = a[i] * a[i + 1];
                    idx = (a[i] < a[i + 1]) ? i : i + 1;   // 删较小的那个
                }
            }
            res += best;
            a.erase(a.begin() + idx);
        }
        return res;
    }
};
