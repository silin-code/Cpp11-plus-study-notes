// ============================================================
// LC 1039 多边形三角剖分的最低得分
// ------------------------------------------------------------
// 考点：区间 DP 的第二种转移形态 —— 【枚举分割点 k】
//       （516 是"看两端"，这题是"从中间切"，两者合起来就是区间 DP 全貌）
// 复杂度：时间 O(n³)，空间 O(n²)
// 日期：2026-11-06（同日与 LC516 一起做完；转移写对，卡在初始化）
// 标签：**不熟练，需要回顾**
// ============================================================
//
// ============================================================
// 一、题意（先把它画出来）
// ============================================================
//
//   给一个【凸多边形】，顶点值 values[0..n-1]，按顺序围成一圈。
//   用 n-3 条【不相交的对角线】把它剖分成 n-2 个三角形。
//   每个三角形的得分 = 三个顶点值的乘积。
//   求所有剖分方案里最小的总得分。
//
//   values = [3, 7, 4, 5]   →   144
//
//   画成四边形（顶点按 0→1→2→3→0 围一圈）：
//
//         0(值3) --------- 1(值7)
//            |                 |
//            |                 |
//         3(值5) --------- 2(值4)
//
//   四边形只有 2 种剖分（往里加 1 条对角线）：
//
//     剖分 A：加对角线 (0,2)
//         三角形 (0,1,2)  得分 3×7×4 = 84
//         三角形 (0,2,3)  得分 3×4×5 = 60
//         合计 144   ← 答案
//
//     剖分 B：加对角线 (1,3)
//         三角形 (1,2,3)  得分 7×4×5 = 140
//         三角形 (0,1,3)  得分 3×7×5 = 105
//         合计 245
//
//   min(144, 245) = 144 ✓
//
// ============================================================
// 二、状态定义（★ 这题最容易卡的地方，逐字读）
// ============================================================
//
//   dp[i][j] = 从【编号 i】到【编号 j】这一串【连续顶点】
//              （即 i, i+1, ..., j）
//              + 封口的弦 (i, j)
//              围出来的那块多边形，
//              把它全部剖分成三角形所需的最小总得分。
//
//   ------------------------------------------------------------
//   【三个必须搞清楚的点】
//   ------------------------------------------------------------
//
//   ① i、j 是【顶点编号】（下标），不是顶点的值
//         values = [3, 7, 4, 5]
//                    ↑  ↑  ↑  ↑
//         编号：      0  1  2  3
//
//        dp[0][3] 里的 0 和 3 是"第 0 号顶点""第 3 号顶点"，
//        不是值 3 和 5。
//
//   ② "连续顶点" = 沿多边形边界从 i 走到 j 经过的那一串
//         dp[0][2]  →  顶点 0,1,2
//         dp[1][3]  →  顶点 1,2,3
//         dp[0][3]  →  顶点 0,1,2,3（全部，也就是原多边形）
//
//      为什么必须连续？因为对角线只会在"连续的一段顶点"内部切，
//      不可能跳着切。
//
//   ③ 弦 (i,j) 是"封口的那条边"
//         在多边形 [i..j] 里，边界由两部分组成：
//             · 原来的边：(i,i+1), (i+1,i+2), ..., (j-1,j)
//             · 封口的弦：(i,j)      ← 它是人为"补"上去的
//         当 j - i == 1 时，(i,j) 本身就是原多边形的一条边。
//
//   ------------------------------------------------------------
//   【j - i 决定它是几边形】
//   ------------------------------------------------------------
//         j - i = 1  →  2 个点  →  只是一条线段，围不成面  →  dp = 0
//         j - i = 2  →  3 个点  →  三角形（唯一，不用剖分）→  三角之积
//         j - i = 3  →  4 个点  →  四边形（2 种剖分）
//         j - i = 4  →  5 个点  →  五边形（5 种剖分）
//
//       即：j - i + 1 = 这块多边形有几个顶点
//
//   ------------------------------------------------------------
//   【n = 4 时，逐格列举（每一格对应一个看得见的图形）】
//   ------------------------------------------------------------
//       格子       包含顶点      围成什么              值
//       dp[0][1]   0,1          一条边                0
//       dp[1][2]   1,2          一条边                0
//       dp[2][3]   2,3          一条边                0
//       dp[0][2]   0,1,2        三角形（左上块）      3×7×4 = 84
//       dp[1][3]   1,2,3        三角形（右下块）      7×4×5 = 140
//       dp[0][3]   0,1,2,3      整个四边形            待求 = 144
//
// ============================================================
// 三、转移怎么推出来的（★ 全题的核心逻辑）
// ============================================================
//
//   【关键事实】
//       在最终的剖分里，边 (i, j) 一定属于【某一个】三角形。
//       （因为 (i,j) 是多边形 [i..j] 的边界，边界不可能被切开）
//
//   【那么这个三角形的第三个顶点是谁？】
//       它只能是 i 和 j 之间的某个点，记作 k（i < k < j）。
//       → 枚举 k，就是在枚举"这条边跟谁组成三角形"
//       → 也就是在枚举"第一刀往哪切"
//
//   【选定 k 之后，多边形被分成三块】
//       ① 三角形 (i, k, j) 自己             得分 values[i]*values[k]*values[j]
//       ② 弦 (i,k) 左边剩下的多边形 [i..k]  代价 dp[i][k]
//       ③ 弦 (k,j) 右边剩下的多边形 [k..j]  代价 dp[k][j]
//
//       画出来（k=2，四边形）：
//
//            0 --------- 1
//            | ╲         |
//            |   ╲       |  ← 弦 (0,2)
//            |     ╲     |
//            |       ╲   |
//            3 --------- 2
//             ╲_________╱
//              ↑ 三角形 (0,2,3) 在两条弦之间
//              [0,2] 这块在左上，[2,3] 这块退化成一个点集
//
//       三块加起来：
//           dp[i][j] = dp[i][k] + dp[k][j] + values[i]*values[k]*values[j]
//
//   【为什么是"取最小"】
//       不同的 k 对应不同的第一刀，每种切法的总代价不同，
//       题目要求最小 → 对所有 k 取 min。
//
// ============================================================
// 四、手算 [3, 7, 4, 5]（每个数字都对上）
// ============================================================
//
//   长度 2（三个点，三角形）：
//       dp[0][2]：k 只能 = 1
//           = dp[0][1] + dp[1][2] + 3×7×4
//           =    0     +    0     +   84        = 84
//       dp[1][3]：k 只能 = 2
//           = dp[1][2] + dp[2][3] + 7×4×5
//           =    0     +    0     +  140        = 140
//
//   长度 3（四个点，四边形）：
//       dp[0][3]：k 可取 1、2
//           k=1：dp[0][1] + dp[1][3] + 3×7×5 = 0 + 140 + 105 = 245
//           k=2：dp[0][2] + dp[2][3] + 3×4×5 = 84 + 0 + 60  = 144
//           dp[0][3] = min(245, 144) = 144 ✓
//
// ============================================================
// 五、遍历顺序（和 LC516 完全一样）
// ============================================================
//
//   dp[i][j] 依赖两格：
//       dp[i][k]   k < j  →  本行，左边      →  要求 j 递增
//       dp[k][j]   k > i  →  下面某一行      →  要求 i 递减
//
//   => for (i = n-1 递减到 0)
//          for (j = i+2 递增到 n-1)     ← 从 i+2 起：j-i<2 不算多边形
//              for (k = i+1 到 j-1)     ← k 的方向无所谓（只读不写）
//
//   为什么 j 从 i+2 开始：
//       j = i   →  1 个点，不是多边形
//       j = i+1 →  2 个点，不是多边形
//       j = i+2 →  3 个点，最小三角形  ← 第一个要算的
//
// ============================================================
// 六、初始化（★ 本次踩的坑，必须记住）
// ============================================================
//
//   【需求】两种格子的初值不一样：
//       j - i <  2  →  必须是 0   （不是多边形，剖分代价 0）
//       j - i >= 2  →  必须是 INF （等着被 min 更新）
//
//   【错法】整张表都初始化成 0x3f3f3f：
//       dp[0][1]、dp[1][2] 这些"不是多边形"的格子也变成 INF，
//       而转移里 k=i+1 时会用到 dp[i][i+1]，k=j-1 时会用到 dp[j-1][j]，
//       → INF + INF + 得分 → 溢出 / 结果恒为 INF
//       → 实测返回 4144959（正好是 0x3f3f3f 本身），全错
//
//   【正确写法】先全 0，进入循环时再设 INF：
//       vector<vector<int>> dp(n + 1, vector<int>(n + 1, 0));
//       ...
//       for (int j = i + 2; j < n; j++) {
//           dp[i][j] = 0x3f3f3f;          // ★ 只有"是多边形"的格子才设大数
//           for (int k = i + 1; k < j; k++) ...
//       }
//
//   【通用判据】
//       求 min 的 DP：初值 = 大数，但【只有需要求值的格子】才设大数。
//       "退化情况"（不是合法问题）的格子要单独设成它真实的边界值（这里是 0）。
//
// ============================================================
// 七、★ 题解里常见的"哈希表"写法是什么（等价，不是另一种算法）
// ============================================================
//
//   有些题解写成这样（记忆化搜索 + unordered_map）：
//
//       unordered_map<int,int> memo;
//       int dfs(int i, int j) {
//           if (j - i < 2) return 0;
//           int key = i * n + j;                    // 把 (i,j) 编码成一个 int
//           if (memo.count(key)) return memo[key];
//           int res = INT_MAX;
//           for (int k = i + 1; k < j; k++)
//               res = min(res, values[i]*values[k]*values[j] + dfs(i,k) + dfs(k,j));
//           return memo[key] = res;
//       }
//
//   这是【同一件事的另一种写法】：
//
//       递推版（本文件）：从小区间往大区间算，答案存二维数组
//       记忆化版（题解）：从大区间递归下去，答案存哈希表
//
//   为什么题解用哈希表？
//       · 递归的访问顺序不确定，用 map 不用操心下标范围
//       · 也有人直接开 dp[50][50] 初始化为 -1，一样对，而且更快
//       · n <= 50 时，二维数组（2500 个 int）比 unordered_map 快得多
//
//   【为什么两者结果一定相同】
//       状态定义相同（[i,j] 这块多边形）、转移相同、边界相同
//       → 只是"谁来驱动计算"不同
//       实测：两者在 2000 组随机数据上零不一致
//
//   【什么时候用哪种】
//       状态好枚举、依赖方向清楚  →  递推（快、无递归开销）
//       状态稀疏 / 依赖方向难确定  →  记忆化搜索（写得快）
//
// ============================================================
// 八、常见错误清单（本次踩的 + 容易踩的）
// ============================================================
//
//   ① 整张表初始化成 INF              → "不是多边形"的格子也变 INF，结果恒为 INF
//   ② j 从 i+1 开始（而不是 i+2）      → j-i=1 的格子被当成多边形，k 循环一次都不执行，
//                                       dp[i][i+1] 被设成 INF 后又没更新
//   ③ 忘记设 dp[i][j] = INF 就直接 min  → 初值 0，min 永远是 0
//   ④ 外层 i 递增                       → dp[k][j]（k>i）还没算
//   ⑤ 内层 j 递减                       → dp[i][k]（k<j）还没算
//   ⑥ 转移里写成 dp[i][j] 而不是 min     → 用最后一个 k 覆盖前面所有结果
//   ⑦ 多打一个右大括号                   → return 跑到函数外，编译不过
//
// ============================================================
// 九、区间 DP 骨架总结（516 / 1039 / 312 / 5 都是这个壳）
// ============================================================
//
//   ① 状态：dp[i][j] = 区间 [i, j] 的答案
//   ② 转移：两种形态
//         形态 A（看两端）：dp[i][j] 由 dp[i+1][j-1] / dp[i+1][j] / dp[i][j-1] 推出
//                          → 例：LC 516 最长回文子序列、LC 5 最长回文子串
//         形态 B（枚举 k）：dp[i][j] = min/max over k of
//                            dp[i][k] + dp[k][j] + 代价(i,k,j)
//                          → 例：LC 1039 三角剖分、LC 312 戳气球、
//                                矩阵链乘法、石子合并、能量项链
//   ③ 顺序：i 递减 + j 递增（等价于按区间长度 len 递增）
//
// ============================================================
// 十、408 视角（顺带记一笔）
// ------------------------------------------------------------
//   本题的"枚举分割点"结构，和 408 里【矩阵链乘法】求最少乘法次数
//   是同一个模型（最优二叉搜索树也是），只是代价函数不同：
//
//       矩阵链：dp[i][j] = min over k of dp[i][k] + dp[k+1][j] + p[i-1]*p[k]*p[j]
//       本题  ：dp[i][j] = min over k of dp[i][k] + dp[k][j]   + v[i]*v[k]*v[j]
//
//   差别只在"右半块的起点"（k+1 还是 k）和"代价怎么算"。
//   会了这题，矩阵链乘法就是换个式子。
// ============================================================
// 实测：3 个官方用例全过；递推版 vs 记忆化版 2000 组随机对拍零不一致
// ============================================================

#include <vector>
#include <algorithm>
using namespace std;

class Solution {
public:
    int minScoreTriangulation(vector<int>& values) {
        int n = values.size();

        // dp[i][j] = 顶点 i..j 这块多边形的最小剖分得分
        // 注意：初始全 0 是【故意】的 —— j-i<2 的格子本来就该是 0
        vector<vector<int>> dp(n + 1, vector<int>(n + 1, 0));

        // 从下往上（i 递减）、从左往右（j 递增）
        for (int i = n - 1; i >= 0; i--) {
            // j 从 i+2 起：j-i<2 时不是多边形，保持 0
            for (int j = i + 2; j < n; j++) {
                dp[i][j] = 0x3f3f3f;                 // ★ 只对"是多边形"的格子设大数

                // 枚举"边 (i,j) 所属三角形的第三个顶点 k"
                for (int k = i + 1; k < j; k++) {
                    // 左块 dp[i][k] + 右块 dp[k][j] + 三角形 (i,k,j) 的得分
                    dp[i][j] = min(dp[i][j],
                        values[i] * values[k] * values[j] + dp[i][k] + dp[k][j]);
                }
            }
        }
        return dp[0][n - 1];      // 整个多边形
    }
};
