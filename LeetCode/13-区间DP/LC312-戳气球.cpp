// ============================================================
// LC 312 戳气球（Burst Balloons）—— 区间 DP · 枚举分割点（困难）
// ------------------------------------------------------------
// 考点：区间 DP 的「反向思考」——不看"先戳谁"，看"最后戳谁"
// 复杂度：时间 O(n³)，空间 O(n²)
// 日期：2026-11-13
// 自我评价：**难以想出，但是看得懂**（反向思考这一步是最大的门槛）
// ------------------------------------------------------------
// 题意：
//   n 个气球排成一行，nums[i] 是第 i 个气球上的数字。
//   戳破气球 i 能得到 nums[i-1] * nums[i] * nums[i+1] 个硬币。
//   越界时按 1 计算（左右两端各补一个虚拟的 1）。
//   求戳破所有气球能获得的最大硬币数。
//
//     [3,1,5,8]  ->  167
//     [1,5]      ->  10
//
// ============================================================
// 【一、为什么"先戳哪个"这条思路走不通（这是本题的核心难点）】
// ============================================================
//   假设 nums = [3,1,5,8]，先戳 1（下标 1）：
//       得分 = 3 × 1 × 5 = 15
//       剩 [3, 5, 8]        ← 注意：3 和 5 现在【成了邻居】
//
//   接下来戳 3：
//       得分 = 1 × 3 × 5 = 15
//       这个"5"是谁？是刚变成邻居的那个 5
//
//   ★ 问题：每戳一个，邻居关系就变了。
//     "戳 3 得多少分"取决于"之前戳了谁" —— 状态无法只用区间 [i,j] 表示。
//
//   ★ 如果硬要正向做，状态必须记录"当前还剩哪些气球" = bitmask(2^n)。
//     实测：正向记忆化（mask 状态）和本解法的答案完全一致，
//           但正向是 O(2^n · n)，反向是 O(n³) —— 这就是"反向"的全部价值。
//
// ============================================================
// 【二、反向思考：不看"先戳谁"，看"区间内【最后】戳谁"】
// ============================================================
//   设区间 (i, j) 内最后戳破的是 k。
//
//   戳 k 的那一刻发生了什么？
//       区间 (i,j) 里除 k 以外的气球【全都已经戳完了】
//       -> k 的左边邻居一定是 i，右边邻居一定是 j
//       -> 得分 = tmp[i] * tmp[k] * tmp[j]
//                  ↑ 只依赖边界，和"中间怎么戳的"完全无关
//
//   ★ 这一步把"过程"消掉了：不管中间怎么戳，最后一下的得分是固定的。
//
//   更关键的：k 是一个【屏障】
//       k 还没戳的时候：
//           左块 (i,k) 里的气球戳破时，右邻居是 k（不是 (k,j) 里的东西）
//           右块 (k,j) 里的气球戳破时，左邻居是 k
//       -> 两块【互不干扰】，可以各自独立求解
//
//   ★ 这就是"最优子结构"。正向想的时候，这个性质根本不存在。
//
// ============================================================
// 【三、状态定义】
// ============================================================
//   先给 nums 补上两端的虚拟球：
//       tmp[0] = 1, tmp[1..n] = nums, tmp[n+1] = 1
//       （长度 n+2，下标 0..n+1）
//
//   dp[i][j] = 戳破【开区间 (i, j) 内所有气球】能获得的最大硬币数
//              i、j 本身【不戳】，它们只是边界（保证最后戳的时候两边有邻居）
//
//   注意是【开区间】：dp[i][i] 和 dp[i][i+1] 都表示"里面没有气球"，值为 0。
//
// ============================================================
// 【四、转移】
// ============================================================
//   dp[i][j] = max over k in (i, j) of
//              dp[i][k]  +  dp[k][j]  +  tmp[i] * tmp[k] * tmp[j]
//              左块         右块            最后戳 k 这一下
//
//   三块加起来：
//       · 先把 (i,k) 里的戳完       —— dp[i][k]
//       · 再把 (k,j) 里的戳完       —— dp[k][j]
//       （两块顺序无所谓，因为 k 一直没戳，把两边隔开了）
//       · 最后戳 k                  —— tmp[i]*tmp[k]*tmp[j]
//
// ============================================================
// 【五、遍历顺序（和 LC 1039 完全一样）】
// ============================================================
//   dp[i][j] 依赖 dp[i][k]（k < j，本行左边）和 dp[k][j]（k > i，下面某行）
//   -> i 递减、j 递增
//
//   边界：
//       j 从 i+2 开始（中间至少要有 1 个气球 k 可枚举）
//       j 最大 n+1
//       i 从 n-1 开始就够（i = n+1 时 j 会超过 n+1，循环体不执行）
//
//   答案：dp[0][n+1]（整个区间，两端是虚拟的 1）
//
// ============================================================
// 【六、和 LC 1039 三角剖分的对照（同一个骨架，换个说法）】
// ============================================================
//                     LC 1039 三角剖分            LC 312 戳气球
//   状态 dp[i][j]     顶点 i..j 的多边形          开区间 (i,j) 内的气球
//   枚举 k            三角形 (i,k,j) 的第三点     区间内【最后戳破】的那个
//   代价              v[i]*v[k]*v[j]              tmp[i]*tmp[k]*tmp[j]
//   三块              左块 + 右块 + 三角形         左块 + 右块 + 最后一下
//   答案              dp[0][n-1]                  dp[0][n+1]
//
//   ★ 式子一模一样，只是：
//       · 1039 的边界是"顶点"（存在）
//       · 312  的边界是"虚拟的 1"（补出来的）
//
// ============================================================
// 【七、一句话记住这题】
// ============================================================
//   正向戳，邻居会变，状态爆炸；
//   反向戳（最后戳谁），邻居固定，左右独立。
//
//   ★ 凡是"操作会改变局面结构"的题，先想【最后一步】。
//     （同类：LC 1039 三角剖分、矩阵链乘法、石子合并）
//
// ============================================================
// 实测：
//   [3,1,5,8] -> 167 ✓   [1,5] -> 10 ✓   [1] -> 1 ✓   [2,4] -> 12 ✓
//   [1,2,3] -> 12 ✓      [8,2,3,4,5] -> 352 ✓
//   与"正向 bitmask 暴力"随机对拍 1500 组零不一致
// ============================================================

#include <vector>
#include <algorithm>
using namespace std;

class Solution {
public:
    int maxCoins(vector<int>& nums) {
        int n = nums.size();

        // 两端补虚拟球 1（越界时按 1 计算）
        // tmp 长度 n+2，下标 0 .. n+1
        vector<int> tmp;
        tmp.push_back(1);
        for (auto e : nums) tmp.push_back(e);
        tmp.push_back(1);

        // dp[i][j] = 戳破开区间 (i, j) 内所有气球的最大收益
        // i、j 不戳，只作为边界。初始全 0（空区间收益 0）
        vector<vector<int>> dp(n + 2, vector<int>(n + 2, 0));

        // i 递减、j 递增（依赖"下面一行"和"本行左边"）
        for (int i = n + 1; i >= 0; i--) {
            // j 从 i+2 起：中间至少要有 1 个气球 k 可以枚举
            for (int j = i + 2; j <= n + 1; j++) {
                // 枚举"区间内【最后】戳破的那个气球" k
                for (int k = i + 1; k < j; k++) {
                    // 左块 dp[i][k] + 右块 dp[k][j] + 最后戳 k 的得分
                    dp[i][j] = max(dp[i][j],
                                   dp[i][k] + dp[k][j] + tmp[i] * tmp[k] * tmp[j]);
                }
            }
        }
        return dp[0][n + 1];      // 整个区间（两端是虚拟的 1）
    }
};
