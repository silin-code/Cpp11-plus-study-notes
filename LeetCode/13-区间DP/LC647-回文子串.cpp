// ============================================================
// LC 647 回文子串（计数）—— 区间 DP 最轻的一道
// ------------------------------------------------------------
// 考点：区间 DP（形态 A：看两端），和 LC 5 同一个骨架
// 复杂度：时间 O(n²)，空间 O(n²)
// 日期：2026-11-08（5 分钟写完，巩固题）
// ------------------------------------------------------------
// 题意：
//   统计字符串 s 中【回文子串】的个数（位置不同算不同，内容相同也算两个）。
//
//     "abc" -> 3    （"a" "b" "c"）
//     "aaa" -> 6    （"a"×3 + "aa"×2 + "aaa"×1）
//     "aaaa"-> 10   （4+3+2+1）
//
// ------------------------------------------------------------
// 【和 LC 5 的对照：骨架一模一样，只有答案取法不同】
// ------------------------------------------------------------
//                   LC 5（最长回文子串）        LC 647（本题）
//   dp[i][j]        s[i-1..j-1] 是否回文        完全一样
//   转移            两端相同 + 长度特判          完全一样
//   遍历            i 递减 + j 递增              完全一样
//   答案            记录最长的区间               统计 true 的个数
//
//   LC 5 ：if (dp[i][j] && 更长) { left=i; right=j; }
//   647  ：if (dp[i][j]) ans++;
//
//   所以这题只需在昨天的代码上"把最后一步改掉"。
//
// ------------------------------------------------------------
// 【状态 / 转移 / 遍历（三件套，和前两题一致）】
// ------------------------------------------------------------
//   状态：dp[i][j] = s[i-1..j-1] 是不是回文（bool，1-based）
//
//   转移：
//        s[i-1] != s[j-1]           ->  false
//        s[i-1] == s[j-1] 且 j-i<=2 ->  true    （长度 1/2/3）
//        s[i-1] == s[j-1] 且 j-i> 2 ->  dp[i+1][j-1]
//
//   遍历：i 从 n 递减到 1，j 从 i 递增到 n
//        （dp[i][j] 依赖右下的 dp[i+1][j-1]，所以 i 逆序、j 正序）
//
// ------------------------------------------------------------
// 【一处可以更简洁】
// ------------------------------------------------------------
//   本文件的两个分支里各写了一次 s[i-1] == s[j-1] 判断，可以合并成：
//
//       if (s[i - 1] != s[j - 1])      dp[i][j] = false;
//       else if (j - i <= 2)           dp[i][j] = true;
//       else                           dp[i][j] = dp[i + 1][j - 1];
//
//   逻辑等价，少一层嵌套。
//
// ------------------------------------------------------------
// 【一处可选优化】
// ------------------------------------------------------------
//   本文件最后单独扫了一遍 dp 统计 true 的个数（多一次 O(n²)）。
//   可以把 ret++ 直接写在填 dp[i][j] 之后，省掉最后一轮双重循环。
//   （总复杂度仍是 O(n²)，只是常数更小）
//
// ------------------------------------------------------------
// 实测：9 个固定用例 + 3000 组随机对拍（与暴力枚举比）零不一致
// ============================================================

#include <string>
#include <vector>
using namespace std;

class Solution {
public:
    int countSubstrings(string s) {
        int n = s.size();

        // dp[i][j] = s[i-1..j-1] 是否回文（1-based，多开两格防越界）
        vector<vector<bool>> dp(n + 2, vector<bool>(n + 2, false));

        // i 递减、j 递增
        for (int i = n; i > 0; i--) {
            dp[i][i] = true;                       // 单字符

            for (int j = i; j <= n; j++) {
                if (j - i <= 2) {
                    // 长度 1 / 2 / 3：两端相同即回文
                    if (s[i - 1] == s[j - 1])
                        dp[i][j] = true;
                    else
                        dp[i][j] = false;
                } else {
                    // 长度 >= 4：看里面那段
                    if (s[i - 1] == s[j - 1])
                        dp[i][j] = dp[i + 1][j - 1];
                    else
                        dp[i][j] = false;
                }
            }
        }

        // 统计所有 true 的个数
        int ret = 0;
        for (int i = 1; i <= n; i++) {
            for (int j = i; j <= n; j++) {
                if (dp[i][j]) ret++;
            }
        }
        return ret;
    }
};
