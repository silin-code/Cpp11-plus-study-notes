// ============================================================
// LC 1049 最后一块石头的重量 II（中等）—— 01 背包 · 尽量平分
// ------------------------------------------------------------
// 考点：01 背包 + 问题转化（"碰撞抵消" → "分成两堆，差最小"）
// 日期：2026-10-23（二维一次写对；一维压缩一次写对）
// ------------------------------------------------------------
// 题意：
//   每块石头重量 stones[i]。每次选两块粉碎：
//     · 重量相同 → 两块都碎掉
//     · 重量不同 → 留下差值
//   求最后剩下石头的【最小重量】。
//   样例：[2,7,4,1,8,1] → 1 ； [31,26,33,21,40] → 5
//
// ------------------------------------------------------------
// ★ 转化（这题的关键一步）
// ------------------------------------------------------------
//   "每次抵消两块" 等价于：把石头分成两堆 A、B，让 |B - A| 最小
//       A + B = sum
//       B - A = (sum - A) - A = sum - 2A
//   → 要让差最小，就要让 A 【尽量大】但不能超过 sum/2
//   → A = "容量为 sum/2 的背包能装出的最大重量和"
//   → 答案 = sum - 2 * dp[sum/2]
//
//   ★ 这题的特殊之处：价值 = 重量（v[i] == w[i] == stones[i]）
//     所以转移里"加的是 stones[i]"这个值，既是重量也是价值。
//
// ------------------------------------------------------------
// 状态与转移
// ------------------------------------------------------------
//   状态：dp[j] = 容量为 j 时能装出的最大重量和
//   边界：全 0（"不装"也是合法方案 —— 求 max，0 正好是合法下界）
//   转移：dp[j] = max(dp[j], dp[j - stones[i]] + stones[i])
//         j 必须【倒序】（01 背包：每个石头只能用一次）
//
//   二维版对照：dp[i][j] = max(dp[i-1][j], dp[i-1][j-stones[i-1]] + stones[i-1])
//               i 从 1 开始 + stones[i-1]；压成一维后 i 从 0 开始 + stones[i]
//
// 实测：LeetCode 通过（用户报告，二维版 + 一维版均通过）
// ============================================================

class Solution {
public:
    int lastStoneWeightII(vector<int>& stones) {
        int n = stones.size();
        int sum = 0;
        for (auto e : stones)
            sum += e;

        vector<int> dp(sum / 2 + 1, 0);
        // dp[j] 表示容量为 j 时，能装出的最大重量和
        for (int i = 1; i <= n; i++) {
            for (int j = sum / 2; j >= stones[i - 1]; j--) {      // ★ 倒序（01 背包）
                dp[j] = max(dp[j], dp[j - stones[i - 1]] + stones[i - 1]);
            }
        }
        return sum - 2 * dp[sum / 2];
    }
};
