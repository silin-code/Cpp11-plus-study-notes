// ============================================================
// 卡码网 56 携带矿石资源 —— 多重背包（朴素质疑：枚举用几个）
// ------------------------------------------------------------
// 考点：多重背包（每种物品有 k[i] 个上限）
// 复杂度：时间 O(N × C × k)，空间 O(N × C)
// 日期：2026-10-31（一次提交 AC，未做二进制拆分优化）
// ------------------------------------------------------------
// 题意：
//   宇航舱容量 C，N 种矿石。
//   每种：重量 w[i]、价值 v[i]、最多 k[i] 个。
//   求不超过容量时的最大总价值。
//
//   输入格式（注意：分行给数组，不是每行给一个物品的三元组）
//       第一行：C N
//       第二行：w[1] w[2] ... w[N]
//       第三行：v[1] v[2] ... v[N]
//       第四行：k[1] k[2] ... k[N]
//
//   样例：
//       10 3
//       1 3 4
//       15 20 30
//       2 3 2
//       -> 90   （2 个物品1 + 2 个物品3 = 10 重、90 价）
//
// ------------------------------------------------------------
// 【三种背包的唯一区别：每种能选几个】
// ------------------------------------------------------------
//   01 背包   ：1 个           -> dp[i-1][j-v]
//   完全背包  ：无限个         -> dp[i][j-v]（本行）
//   多重背包  ：k[i] 个        -> 枚举"选 a 个"，从 dp[i-1][j-a*v] 来
//
// ------------------------------------------------------------
// 【两种等价写法】
// ------------------------------------------------------------
//   写法 A（拆成 k[i] 份，一维 01 背包）：
//       for (i) for (a = 1..k[i]) for (j = C..w[i])
//           dp[j] = max(dp[j], dp[j-w[i]] + v[i]);
//
//   写法 B（本文件，三维枚举用几个）：
//       dp[i][j] = dp[i-1][j];                       // 不选
//       for (a = 1; a <= k[i] && a*w[i] <= j; a++)
//           dp[i][j] = max(dp[i][j], dp[i-1][j-a*w[i]] + a*v[i]);
//
//   两者结果完全一样。写法 A 更好写（复用 01 背包肌肉记忆），
//   写法 B 更能说明"枚举用几个"这个本质。
//
// ------------------------------------------------------------
// 【为什么这里不需要二进制拆分】
// ------------------------------------------------------------
//   本题数据：N ≤ 100，C ≤ 2000，k ≤ 1000
//   朴素复杂度 = 100 × 2000 × 1000 = 2×10^8 —— 卡在边缘，实测 AC。
//
//   如果 k 的上限再大（比如 10^5），朴素必 TLE，就要用【二进制拆分】：
//       把 k 个物品拆成 1, 2, 4, 8, ..., 余数 这样 10 组"打包物品"
//       -> 复杂度降到 O(N × C × log k)
//   本文件暂不实现（用户明确说"不优化了"），留作下一步。
//
// ------------------------------------------------------------
// 【本次踩的坑】
// ------------------------------------------------------------
//   ① 用 `long double` 存 dp -> 输出带小数，而且没必要（全整数）
//   ② `dp[i][j] = dp[i-1][j]` 放在了数量循环【里面】-> 每圈重置，结果被覆盖
//   ③ 转移写成 `dp[i][j - w[i]]`（本行）-> 变成完全背包
//      每种只有 k[i] 个，必须从 dp[i-1] 来
//
// ------------------------------------------------------------
// 实测：卡码网提交 AC（用户报告）
// ============================================================

#include <bits/stdc++.h>
using namespace std;
using ll = long long;

int main() {
    ll C, N;
    cin >> C >> N;

    vector<ll> w(N + 1), v(N + 1), k(N + 1);
    for (ll i = 1; i <= N; i++) cin >> w[i];      // 先给重量
    for (ll i = 1; i <= N; i++) cin >> v[i];      // 再给价值
    for (ll i = 1; i <= N; i++) cin >> k[i];      // 最后给数量

    // dp[i][j] = 从前 i 种物品里选、容量不超过 j 的最大价值
    vector<vector<ll>> dp(N + 1, vector<ll>(C + 1, 0));

    for (int i = 1; i <= N; i++) {
        for (int j = 0; j <= C; j++) {
            dp[i][j] = dp[i - 1][j];                              // 不选第 i 种

            // 枚举"选 a 个第 i 种"
            for (int a = 1; a <= k[i] && (ll)a * w[i] <= j; a++) {
                dp[i][j] = max(dp[i][j],
                               dp[i - 1][j - (ll)a * w[i]] + (ll)a * v[i]);
            }
        }
    }

    cout << dp[N][C];
    return 0;
}
