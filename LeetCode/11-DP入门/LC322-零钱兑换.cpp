// ============================================================
// LC 322 零钱兑换（中等）—— 完全背包 · 求最少个数
// ------------------------------------------------------------
// 考点：完全背包（每种硬币无限个）+ 哨兵值的选择
// 日期：2026-10-22（01 背包 → 完全背包 的衔接题）
// ------------------------------------------------------------
// 题意：
//   给硬币面额 coins 和金额 amount，求凑出 amount 的最少硬币数；凑不出返回 -1。
//     coins=[1,2,5], amount=11  →  3   （5+5+1）
//     coins=[2],     amount=3   →  -1
//     coins=[1],     amount=0   →  0
//
// ------------------------------------------------------------
// 完全背包 vs 01 背包（只差一个下标）
// ------------------------------------------------------------
//   01 背包：   dp[i][j] = max/min(dp[i-1][j], dp[i-1][j-v] + w)
//   完全背包：  dp[i][j] = max/min(dp[i-1][j], dp[i][j-v] + w)
//                                                  ↑ 本行：可以重复选
//
//   一维数组版（"j 的方向"决定能不能重复选）：
//   01 背包：  for (j = V; j >= v; j--)      倒序 → dp[j-v] 还是上一行
//   完全背包： for (j = v; j <= V; j++)      正序 → dp[j-v] 已被本行更新
//
// ------------------------------------------------------------
// ★ 本题最大的坑：哨兵值选反了（首版 3/6 用例错）
// ------------------------------------------------------------
//   首版把 `-1` 当"不可达"：
//     ① `-1` 是【最小】的数 → 在 min() 里永远赢
//        例：min(dp[0][2] = -1, dp[1][0] + 1 = 1) = -1     ✗ 应为 1
//     ② `-1 + 1 = 0` → 不可达的格子 +1 变成了"0 个硬币"，假装合法 ✗
//
//   ★ 判据：哨兵值必须是「在 max/min 比较里永远输」的那个值
//       求 max  →  -INF（比任何合法值小）
//       求 min  →  +INF（比任何合法值大）★ 本题
//       求 bool →  false      ｜  求方案数 →  0
//   一句话："哨兵要站在你不想选的那一边。"
//
// ------------------------------------------------------------
// 实测：6 个用例全对
//   [1,2,5],11 → 3 ｜ [2],3 → -1 ｜ [1],0 → 0 ｜ [2,5],11 → 4 ｜ [5],5 → 1
// ============================================================

class Solution {
    const int INF = 1e9;
public:
    int coinChange(vector<int>& coins, int amount) {
        int n = coins.size();
        // dp[i][j] 表示用 i 以及之前的硬币刚好凑出 j 的最小数量
        vector<vector<int>> dp(n + 1, vector<int>(amount + 1, INF));
        dp[0][0] = 0;

        for (int i = 1; i <= n; i++) {
            dp[i][0] = 0;
            for (int j = 0; j <= amount; j++) {
                dp[i][j] = dp[i - 1][j];                          // 不用第 i 种硬币
                if (j >= coins[i - 1]) {
                    dp[i][j] = min(dp[i][j],
                                   dp[i][j - coins[i - 1]] + 1);  // dp[i] 可以重复使用
                }
            }
        }
        return dp[n][amount] == INF ? -1 : dp[n][amount];
    }
};
