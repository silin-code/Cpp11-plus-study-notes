// ============================================================
// LC 474 一和零（中等）—— 01 背包 · 二维费用
// ------------------------------------------------------------
// 考点：01 背包 + **两个容量限制**（0 的个数 ≤ m，1 的个数 ≤ n）
// 复杂度：时间 O(size × m × n)，空间 O(m × n)
// 日期：2026-10-28
// ------------------------------------------------------------
// 题意：
//   给字符串数组 strs 和两个整数 m、n。
//   找出 strs 的【最大子集】，使其中 '0' 的总数 ≤ m、'1' 的总数 ≤ n。
//   返回这个子集的大小。
//
//     strs = ["10","0001","111001","1","0"], m=5, n=3  ->  4
//     strs = ["10","0","1"],                 m=1, n=1  ->  2
//
// ------------------------------------------------------------
// 【核心：什么叫"二维费用"】
// ------------------------------------------------------------
//   普通 01 背包：一个容量（体积 j）          -> dp[j]
//   二维费用背包：两个容量（0 的个数 j、1 的个数 k）-> dp[j][k]
//
//   物品的"费用"也变成两个：这个字符串有几个 '0'、几个 '1'
//   物品的"价值"：1（选一个串，答案 +1）
//
//   所以：
//       dp[j][k] = 用 0 不超过 j 个、1 不超过 k 个时，最多能选几个字符串
//       转移：dp[j][k] = max(dp[j][k], dp[j - c0][k - c1] + 1)
//       遍历：j 从 m 倒序、k 从 n 倒序（★ 每个串只能用一次）
//
// ------------------------------------------------------------
// 【三维原型（先看这个，最直观）】
// ------------------------------------------------------------
//   dp[i][j][k] = 用【前 i 个字符串】，0 不超过 j、1 不超过 k 时的最大子集大小
//
//   dp[i][j][k] = max(
//       dp[i-1][j][k],                          // 不选第 i 个
//       dp[i-1][j-c0[i]][k-c1[i]] + 1           // 选（来自上一行）
//   )
//
//   压成二维：省掉 i（和 01 背包的一维压缩同理），j、k 都倒序
//
// ------------------------------------------------------------
// ★ 本题踩过的三个坑（都是"维度语义"没对齐）
// ------------------------------------------------------------
//   ① 统计 0/1 个数时，内层循环写成了 `for (auto e : strs)`
//      应该是 `for (char c : s)` —— 遍历当前这个串的字符，不是又遍历一遍数组。
//      而且 `e == '0'` 里 e 是 string，比较的是"整个串是否等于字符串 '0'"。
//
//   ② 三维版 dp 的第一维写成 `n + 1`（1 的个数上限），应该是 `size + 1`（字符串个数）
//      → size > n 时 dp[i] 越界。
//      ⚠️ 开数组前先把三个维度的范围写下来：
//         i: 0..size   j: 0..m   k: 0..n
//
//   ③ 压成二维后，`j` 从 n 开始、`k` 从 m 开始 —— 两个变量反了
//      → k 最大到 m(5)，但 dp 第二维只有 n+1(4) 个 → 越界。
//
//   ★ 记忆口诀：**下标顺序 = 参数顺序**
//       声明 dp[m][n]  ->  循环必须 j 对 m、k 对 n
//
// ------------------------------------------------------------
// 实测：本机 PowerShell 拒绝调用 g++（"无法在管道中间运行文档"，与之前的
//       "应用程序控制策略"同类），本次未能本机实测；以下为逻辑审查通过 + 用户自测。
// ============================================================

#include <vector>
#include <string>
using namespace std;

class Solution {
public:
    int findMaxForm(vector<string>& strs, int m, int n) {
        int size = strs.size();

        // ① 预处理：每个字符串里 '0' 和 '1' 的个数
        vector<pair<int, int>> nums;          // nums[i] = {count0, count1}
        for (auto& s : strs) {
            int count0 = 0, count1 = 0;
            for (char c : s) {                // ★ 遍历这个串的字符
                if (c == '0') count0++;
                else          count1++;
            }
            nums.push_back(make_pair(count0, count1));
        }

        // ② dp[j][k]：0 不超过 j 个、1 不超过 k 个时，最多能选几个字符串
        vector<vector<int>> dp(m + 1, vector<int>(n + 1, 0));

        for (int i = 1; i <= size; i++) {
            int c0 = nums[i - 1].first;
            int c1 = nums[i - 1].second;

            for (int j = m; j >= c0; j--) {           // ★ 倒序（01 背包）
                for (int k = n; k >= c1; k--) {       // ★ 倒序
                    dp[j][k] = max(dp[j][k], dp[j - c0][k - c1] + 1);
                }
            }
        }
        return dp[m][n];
    }
};
