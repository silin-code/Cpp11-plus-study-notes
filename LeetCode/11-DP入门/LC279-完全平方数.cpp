// ============================================================
// LC 279 完全平方数（中等）—— 完全背包 · 求最少个数
// ------------------------------------------------------------
// 考点：完全背包（每个平方数可用无限次）+ 求 min + 哨兵值
// 日期：2026-10-26（复习完全背包当天，一次写对）
// ------------------------------------------------------------
// 题意：
//   给正整数 n，求【最少】用几个完全平方数（1,4,9,16,...）之和等于 n。
//   样例：n=12 → 3（4+4+4）；n=13 → 2（4+9）
//
// ------------------------------------------------------------
// 建模
// ------------------------------------------------------------
//   物品：1², 2², 3², ... （每个可以无限次用）→ 完全背包
//   容量：n
//   价值：不用价值，问"最少用几个" → 转移用 min，每次 +1
//
//   状态：dp[i][j] = 用前 i 个平方数凑出 j 的最少个数
//   转移：dp[i][j] = min(dp[i-1][j],              // 不用第 i 个平方数
//                        dp[i][j - nums[i]] + 1)   // ★ 用本行（可重复用）
//   边界：dp[i][0] = 0（凑 0 不需要任何数）
//        其余初值 = 大数（求 min 的哨兵）
//
// ★ 哨兵值：求 min → 用【极大】(0x3f3f3f / 1e9)，它在 min 里永远输
//   （反过来求 max 就用 -1 / -INF，见 DP41、DP42）
//
// ------------------------------------------------------------
// 与 LC 322 零钱兑换的关系
// ------------------------------------------------------------
//   322：给定硬币面额，求凑出 amount 的最少硬币数
//   279：面额是"完全平方数"，求凑出 n 的最少个数
//   → 同一个模型，只是"物品"是自动生成的
//
// ------------------------------------------------------------
// 实测：9 个用例（n=12/13/1/4/100/9999/0/2/43），与一维版、BFS 三方一致
// ============================================================

#include <vector>
#include <cmath>
using namespace std;

class Solution {
public:
    int numSquares(int n) {
        vector<int> nums;
        nums.push_back(0);
        // 完全平方数作为"物品"：1, 4, 9, 16, ...
        for (int i = 1; i * i <= n; i++) {      // 只生成不超过 n 的
            nums.push_back(i * i);
        }
        int size = nums.size();

        vector<vector<int>> dp(size, vector<int>(n + 1, 0x3f3f3f));
        // dp[i][j] 从前 i 个数里面选可以凑出 j 的最小次数
        for (int i = 1; i < size; i++) {
            dp[i][0] = 0;
            for (int j = 1; j <= n; j++) {
                dp[i][j] = dp[i - 1][j];                        // 不用第 i 个平方数
                if (j - nums[i] >= 0) {
                    dp[i][j] = min(dp[i][j],
                                   dp[i][j - nums[i]] + 1);     // ★ 本行（可重复）
                }
            }
        }
        return dp[size - 1][n];
    }
};

