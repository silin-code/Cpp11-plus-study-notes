// ============================================================
// LC 416 分割等和子集（中等）—— 01 背包 · 布尔可达性
// ------------------------------------------------------------
// 考点：01 背包的"可行性"变体（状态从"最大价值"变成"能否"）
// 复杂度：O(n × sum/2) 时间，O(n × sum/2) 空间（可优化到一维）
// 日期：2026-10-18（用户第 2 次改对，是本周第一道 DP 题）
// ------------------------------------------------------------
// 题意：
//   给正整数数组 nums，判断能否分成两个子集，使两个子集的元素和相等。
//     [1,5,11,5] → true（[1,5,5] 和 [11]）
//     [1,2,3,5]  → false
//
// 转化（这题的关键一步）：
//   总和 sum；两个子集和相等 → 各为 sum/2
//   ① sum 为奇数 → 直接 false
//   ② 否则：问题变成「能否从 nums 里选一些数，和恰好 = sum/2」
//
// 三段式：
//   状态：dp[i][j] = 用前 i 个数，能否凑出和 j（bool）
//   边界：dp[i][0] = true       （什么都不选就凑出 0）
//         dp[0][j] = false     （一个都不选，凑不出 j > 0）
//   转移：dp[i][j] = dp[i-1][j]                                  // 不选第 i 个
//         if (j >= nums[i-1]) dp[i][j] |= dp[i-1][j - nums[i-1]]  // 选第 i 个
//
// ------------------------------------------------------------
// 与 DP41「01 背包 · 恰好装满」的对照（同一个骨架，换"值"还是"能否"）
// ------------------------------------------------------------
//   | | DP41 恰好装满 | LC 416 |
//   |---|---|---|
//   | 状态含义 | 体积恰好 j 的【最大价值】 | 能否凑出 j（【bool】） |
//   | j=0 边界 | dp[0][0] = 0 | dp[i][0] = true |
//   | 不可达表示 | -INF | false |
//   | 转移 | dp[i-1][j-v] + w | dp[i-1][j-v] |
//   | 输出 | dp[n][V]（-INF→0） | dp[n][sum/2] |
//
// ------------------------------------------------------------
// 易错点（本次踩了 2 个）
// ------------------------------------------------------------
//   ① 【边界：dp[i][0] 必须是 true】
//      循环通常从 j=1 开始（因为 j-v 要求 j≥v），导致 dp[i][0] 从未被赋值、
//      保持初始 false → 转移 dp[i-1][j-v] 在 j==v 时拿到 false → 整个 DP 全 false。
//      ★ 通用规律：dp[i][0] = "用前 i 个、容量 0" = 只能什么都不选 = 【空方案的值】
//                  最大价值 → 0    恰好装满 → 0    布尔可达 → true
//
//   ② 【01 背包写成完全背包：dp[i][j-v] 应为 dp[i-1][j-v]】
//      dp[i][j-v] 表示"在前 i 个里凑出 j-v"，可能已经选了第 i 个 → 同一个数可重复用。
//      ★ 判据："选第 i 个"时，来源必须是 dp[i-1] —— 因为选了它之后就不能再选它了。
//      （这个坑 2026-10-18 一天内踩了两次：DP41 第一版、本题）
// ------------------------------------------------------------
// 实测：10 个用例（含 [2,2]/[1,1]/单元素/sum 奇偶/凑不出）全对；
//      3000 组随机对拍 vs 暴力枚举子集零不一致
// ============================================================

class Solution {
public:
    bool canPartition(vector<int>& nums) {
        int sum = 0;
        int n = nums.size();
        for (auto e : nums)
            sum += e;
        if (sum % 2 == 1)
            return false;
        sum /= 2;

        vector<vector<bool>> dp(n + 1, vector<bool>(sum + 1, 0));
        // dp[i][j]表示能否刚好凑出
        // dp[0][j]表示用0个凑出j的大小，需要初始化为0
        for (int i = 1; i <= sum; i++) {
            dp[0][i] = false;
        }
        for (int i = 0; i <= n; i++) {
            dp[i][0] = true;
        }

        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= sum; j++) {
                dp[i][j] = dp[i - 1][j] == false ? false : true;
                if (j >= nums[i - 1] && dp[i - 1][j - nums[i - 1]] != false) {
                    dp[i][j] = true;
                }
            }
        }
        return dp[n][sum];
    }
};
