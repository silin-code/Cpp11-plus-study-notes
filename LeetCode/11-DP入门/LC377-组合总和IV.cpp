// ============================================================
// LC 377 组合总和 IV（中等）—— 这是【走法计数】，不是背包！
// ------------------------------------------------------------
// 日期：2026-10-25
// ★ 模型由用户自己识别（"这题不是背包，是爬楼梯"）—— 这一步定对了，后面全通
// ------------------------------------------------------------
// 题意：
//   给 nums（不同的正整数）和 target，从 0 开始，每一步从 nums 里挑一个"步伐"，
//   问走到 target 有多少条【不同的路】。顺序不同 = 不同的路。
//   样例：nums=[1,2,3], target=4 → 7
//         (1,1,1,1) (1,1,2) (1,2,1) (1,3) (2,1,1) (2,2) (3,1)
//
// ------------------------------------------------------------
// ★ 模型识别（最重要的一步）
// ------------------------------------------------------------
//   题目问的是「怎么走过去」，不是「选哪些东西」。
//
//   和 LC 70 爬楼梯【完全同构】：
//       爬楼梯：每次走 1 或 2 级      → dp[j] = dp[j-1] + dp[j-2]
//       本题  ：每次走 nums[i] 级     → dp[j] = Σ_i dp[j - nums[i]]
//
//   | | 背包（518 / 416 / 494） | 本题（377） |
//   | 问什么 | 选哪些东西 | 怎么走过去 |
//   | 状态 | dp[i][j]：前 i 件 | dp[j]：走到 j |
//   | 顺序 | 无关 → 组合数 | 有关 → 排列数 |
//   | 典型 | 零钱兑换 II | 爬楼梯、组合总和 IV |
//
//   ⚠️ 套错模型的后果：把"走法"硬解释成"选法"，会数出组合（4）而不是排列（9），
//      而且怎么调循环顺序都很别扭。
//
// ------------------------------------------------------------
// ★ 二维写法：i = "最后一步走的是哪种步伐"
// ------------------------------------------------------------
//   dp[i][j] = 走到 j、且【最后一步是 nums[i]】的路径数
//
//   dp[i][j] = Σ_k dp[k][j - nums[i]]        （前面那段走到 j-nums[i]，怎么走来都行）
//   （j == nums[i] 时额外 +1：整条路只有这一脚）
//
//   答案 = Σ_i dp[i][target]
//
//   nums = [1,2,5] 的表：
//   | j | 末步=1 | 末步=2 | 末步=5 | 合计 |
//   | 0 |   0   |   0   |   0   |  0   |
//   | 1 |   1   |   0   |   0   |  1   |
//   | 2 |   1   |   1   |   0   |  2   |
//   | 3 |   2   |   1   |   0   |  3   |
//   | 4 |   3   |   2   |   0   |  5   |
//   | 5 |   5   |   3   |   1   |  9   |   ← 排列 9（组合只有 4）
//
//   对比 518 的二维：那里 i 是"前 i 种"，累加是【横向】（上一行 + 本行左边）；
//   这里 i 是"最后一步"，累加是【纵向】（同一列的所有行）。
//
// ------------------------------------------------------------
// ★ 一维压缩（dp[j] 就是上表"合计"那一列）
// ------------------------------------------------------------
//   dp[0] = 1
//   for (int j = 1; j <= target; j++)      // 外层：金额（台阶）
//       for (int x : nums)                  // 内层：枚举所有步伐
//           if (j >= x) dp[j] += dp[j - x];
//
//   为什么外层是金额就是排列：dp[j] 在计算时，dp[j-x] 已经包含了「走到 j-x 的
//   所有路（含各种顺序）」，末尾再走一步 x —— 这步 x 可以接在任意一条路的后面。
//
// ------------------------------------------------------------
// 实测：6 个用例全对（二维版 / 一维版 / 暴力 DFS 三方一致）
//   [1,2,3],4→7 ｜ [9],3→0 ｜ [1,2],3→3 ｜ [1],1→1 ｜ [1,2,5],5→9 ｜ [1,2],5→8
// ============================================================

#include <vector>
using namespace std;
using ull = unsigned long long;

class Solution {
public:
    int combinationSum4(vector<int>& nums, int target) {
        // dp[j] 表示刚好凑出（走到）j 的方案数
        vector<ull> dp(target + 1, 0);
        dp[0] = 1;                                    // 起点：什么都不走算 1 条路
        for (int j = 1; j <= target; j++) {           // 外层：台阶
            for (int num : nums) {                    // 内层：枚举所有步伐
                if (num <= j) {
                    dp[j] += dp[j - num];
                }
            }
        }
        return dp[target];
    }
};
