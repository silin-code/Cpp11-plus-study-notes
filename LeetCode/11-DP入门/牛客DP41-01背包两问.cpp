// ============================================================
// 牛客 DP41 · 01 背包（两问）—— 01 背包的【二维标准式】
// ------------------------------------------------------------
// 考点：01 背包 + 两种边界的对比
// 日期：2026-10-23（第三次重写；二维版一次成功）
// ------------------------------------------------------------
// 题意：
//   给 n 个物品（体积 v[i]、价值 w[i]）和背包容量 V。
//   第一问：不要求装满，求能获得的最大总价值。
//   第二问：要求【恰好装满】，求最大总价值；若不存在则输出 0。
//
// ------------------------------------------------------------
// ★ 两问的唯一差别：边界
// ------------------------------------------------------------
//   第一问（不要求装满）：
//       dp1[0][j] = 0           ← 任何容量都"可达成"（什么都不装也是合法方案）
//
//   第二问（恰好装满）：
//       dp2[0][0] = 0
//       dp2[0][j>0] = -1        ← 只有体积 0 可达成，其余"不可达"
//       转移时要判 dp2[i-1][j-v] != -1
//
//   ★ 哨兵值：本题求 max，所以用【-1】—— 它比任何合法价值都小，在 max 里永远输 ✓
//      （反过来：求 min 就要用 +INF。见 LC322 零钱兑换）
//
// ------------------------------------------------------------
// 踩过的坑（第 4 次在 dp[i-1] / dp[i] 上出事）
// ------------------------------------------------------------
//   ① 【检查条件与赋值必须用同一个 i-1】
//        错：if (dp2[i-1][j-v[i]] != -1)
//                dp2[i][j] = max(dp2[i][j], dp2[i][j-v[i]] + w[i]);   ← 赋值用了 i
//        对：两处都是 dp2[i-1]
//      首版"检查用 i-1、赋值用 i"—— 恰好被检查拦住所以没出错，但前后自相矛盾：
//      一旦有人放松检查条件，立刻变成「完全背包」。
//
//   ② 【无解时输出 0，不是 -1】（题面明确："答案记为 0"）
//
// ------------------------------------------------------------
// 实测：6 个用例全对
//   {3,5,(2,3)(3,4)(4,5)} → 7 / 7
//   {2,5,(2,3)(4,4)}      → 4 / 0   （恰好装满无解）
//   {1,3,(3,10)}          → 10 / 10
//   {1,3,(2,10)}          → 10 / 0  （装不满）
//   {3,4,(1,2)(2,3)(2,3)} → 6 / 6
//   {1,3,(1,10)}          → 10 / 0  （01 只能选 1 个，凑不满 3）
// ============================================================

#include <iostream>
#include <vector>
using namespace std;

int main() {
    int n, V;
    cin >> n >> V;
    vector<int> v(n + 1);   // 体积
    vector<int> w(n + 1);   // 价值
    for (int i = 1; i <= n; i++) {
        cin >> v[i] >> w[i];
    }

    // ---------- 第一问：不要求装满 ----------
    vector<vector<int>> dp1(n + 1, vector<int>(V + 1, 0));
    // dp1[i][j] 表示从前 i 个物品里面选，最大容量为 j 时的最大价值
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= V; j++) {
            dp1[i][j] = dp1[i - 1][j];          // 不选 i，直接继承前 i-1 个的最优
            if (j >= v[i]) {                     // 当前容量装得下
                dp1[i][j] = max(dp1[i][j], dp1[i - 1][j - v[i]] + w[i]);
            }
        }
    }

    // ---------- 第二问：恰好装满 ----------
    vector<vector<int>> dp2(n + 1, vector<int>(V + 1, -1));
    // dp2[i][j] 表示从前 i 个物品里面选，恰好凑出 j 的最大价值；-1 表示凑不出
    dp2[0][0] = 0;
    for (int i = 1; i <= n; i++) {
        dp2[i][0] = 0;                          // 凑出 0 体积：不选，价值 0
        for (int j = 1; j <= V; j++) {
            dp2[i][j] = dp2[i - 1][j];          // 不用 i，直接继承
            if (j >= v[i] && dp2[i - 1][j - v[i]] != -1) {   // 装得下 且 来源可达
                dp2[i][j] = max(dp2[i][j], dp2[i - 1][j - v[i]] + w[i]);
            }
        }
    }

    cout << dp1[n][V] << '\n' << (dp2[n][V] == -1 ? 0 : dp2[n][V]);
    return 0;
}
