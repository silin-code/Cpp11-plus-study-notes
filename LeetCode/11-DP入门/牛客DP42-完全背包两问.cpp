// ============================================================
// 牛客 DP42 【模板】完全背包（两问）—— 二维 + 一维
// ------------------------------------------------------------
// 考点：完全背包（每种物品无限个）+ 两问的边界差异
// 日期：2026-10-26（复习；二维、一维都是一次写对）
// ------------------------------------------------------------
// 题意：
//   n 个物品（体积 vi[i]、价值 wi[i]，每种可用【无数次】），背包体积 V。
//   第一问：不要求装满，求最大价值。
//   第二问：恰好装满，求最大价值；无解输出 0。
//
//   样例1：2 6 / (5,10) (3,1)        → 10 / 2
//   样例2：3 8 / (3,10) (9,1) (10,1) → 20 / 0（无法恰好装满）
//
// ------------------------------------------------------------
// 完全背包 vs 01 背包：只差一个下标 / 一个方向
// ------------------------------------------------------------
//   二维：  01 → dp[i-1][j-v]        完全 → dp[i][j-v]  （★ 本行）
//   一维：  01 → j 倒序              完全 → j 正序
//
//   为什么"本行 / 正序"= 可以重复选：
//     一维正序时，dp[j-v] 已经被【本轮（同一个物品）】更新过
//       → 它里面可能已经装了这个物品 → 现在还能再装一个
//     一维倒序时，dp[j-v] 还是【上一轮】的值 → 这个物品只能用一次
//
//   一句话：正序 = 允许重复选，倒序 = 只准选一次。
//
// ------------------------------------------------------------
// 两问的唯一差别：边界
// ------------------------------------------------------------
//   第一问（不要求装满）：dp[0] = 0，其余 0      ← 任何体积都"可达成"
//   第二问（恰好装满）：  dp[0] = 0，其余 -1     ← 只有体积 0 可达成
//                        转移时判 dp[j-v] != -1
//
//   ★ 哨兵值：本题求 max，所以用 -1（比任何合法价值都小 → 在 max 里永远输）
//     （反过来求 min 就要用 +INF，见 LC 322）
//
// ------------------------------------------------------------
// 实测：4 个用例（样例 1、2 + 两个自测），二维版与一维版结果完全一致
// ============================================================

#include <iostream>
#include <vector>
using namespace std;

int main() {
    int n, V;
    cin >> n >> V;
    vector<int> vi(n + 1);
    vector<int> wi(n + 1);
    for (int i = 1; i <= n; i++)
        cin >> vi[i] >> wi[i];

    // ============ 第一问：不要求装满 ============
    vector<int> dp1(V + 1, 0);
    // dp1[j] 表示容量上限为 j 时的最大价值
    for (int i = 1; i <= n; i++) {
        for (int j = vi[i]; j <= V; j++) {                  // ★ 正序（完全背包）
            dp1[j] = max(dp1[j], dp1[j - vi[i]] + wi[i]);
        }
    }

    // ============ 第二问：恰好装满 ============
    vector<int> dp2(V + 1, -1);
    // dp2[j] 表示恰好凑出体积 j 的最大价值；-1 表示凑不出
    dp2[0] = 0;
    for (int i = 1; i <= n; i++) {
        for (int j = vi[i]; j <= V; j++) {                  // ★ 正序（端点与第一问相同）
            if (dp2[j - vi[i]] != -1) {
                dp2[j] = max(dp2[j], dp2[j - vi[i]] + wi[i]);
            }
        }
    }

    cout << dp1[V] << '\n' << (dp2[V] == -1 ? 0 : dp2[V]);
    return 0;
}
