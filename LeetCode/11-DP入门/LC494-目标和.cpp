// ============================================================
// LC 494 目标和（中等）—— 01 背包 · 求方案数
// ------------------------------------------------------------
// 考点：01 背包（计数型）+ 问题转化
// 日期：2026-10-21（第一道自己完成"转化"的 DP）
// ------------------------------------------------------------
// 题意：
//   给整数数组 nums 和目标 target，给每个数前面加 '+' 或 '-'，
//   求有多少种方式让表达式结果等于 target。
//   样例：[1,1,1,1,1], 3 → 5
//
// ★ 关键转化（这题最难的一步）：
//   设加号部分的和为 P、减号部分（绝对值）的和为 N
//       P - N = target
//       P + N = sum（所有数的和）
//   两式相加 → 2P = sum + target → P = (sum + target) / 2
//
//   于是问题变成：从 nums 里选一些数，和为 P，有多少种选法？ → 01 背包计数
//
//   无解的情况：
//       · sum + target 为奇数（除不尽）
//       · P < 0（target 太负）
//       · P > sum（target 太大）—— 本实现由 dp 数组越界自然排除（t ≤ sum 时安全）
//
// ------------------------------------------------------------
// 01 背包的「三张脸」（同一个骨架，换问法）
// ------------------------------------------------------------
//   | 题 | 问什么 | dp[j] 含义 | 转移 |
//   | 牛客 DP41 | 恰好装满的最大价值 | 价值 | max |
//   | LC 416 | 能不能凑出 | bool | \|= |
//   | LC 494 | 凑出的【方案数】 | 计数 | += |
//
// ------------------------------------------------------------
// 状态与转移
// ------------------------------------------------------------
//   状态：dp[i][j] = 用前 i 个数，凑出和为 j 的方案数
//   边界：dp[0][0] = 1（空集算一种方案）；其余 dp[0][j] = 0
//   转移：dp[i][j] = dp[i-1][j]                     // 不选第 i 个
//                  + dp[i-1][j - nums[i-1]]          // 选第 i 个（注意是 i-1）
//
// ★ 两个易错点（本次都踩了）
//   ① 【i 的起点与 nums 下标必须配对】
//        dp[i] 表示"前 i 个" → i 从 1 开始，nums 用 i-1
//        若 i 从 0 开始，则 dp[i-1] 会取到 dp[-1]（越界，读到垃圾/崩溃）
//   ② 【"改了一半"】
//        `if (j - nums[i-1] >= 0) dp[i][j] += dp[i-1][j - nums[i]];`
//        左边改了 i-1、右边忘改 → i == n 时 nums[n] 越界。
//        习惯：同一个条件里出现多次 nums[...] 时，改完一处要扫全行。
// ------------------------------------------------------------
// 实测：7 个用例全对（含 [1,1,1,1,1],3 → 5；[0],0 → 2；多个 0 → 16；target 为负 → 0）
// ============================================================

class Solution {
public:
    int findTargetSumWays(vector<int>& nums, int target) {
        // 在数组中选择一些数 = (target + sum) / 2
        int n = nums.size();
        int sum = accumulate(nums.begin(), nums.end(), 0);
        int t = (target + sum) / 2;
        if (t < 0 || (target + sum) % 2) return 0;

        vector<vector<int>> dp(n + 1, vector<int>(t + 1, 0));
        // dp[i][j] 从前 i 个数里面选，总和正好为 j，一共有多少种选法
        dp[0][0] = 1;

        for (int i = 1; i <= n; i++) {
            for (int j = 0; j <= t; j++) {
                dp[i][j] = dp[i - 1][j];
                if (j - nums[i - 1] >= 0)
                    dp[i][j] += dp[i - 1][j - nums[i - 1]];
            }
        }
        return dp[n][t];
    }
};
