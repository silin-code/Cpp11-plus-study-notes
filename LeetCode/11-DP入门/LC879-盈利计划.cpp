// ============================================================
// LC 879 盈利计划（困难）—— 01 背包 · 二维费用 + 「至少」型
// ------------------------------------------------------------
// 考点：01 背包 + 两个费用（人数、利润）+ 「至少」的状态定义 + 取模
// 复杂度：时间 O(size × n × minProfit)，空间 O(size × n × minProfit)（可压成二维）
// 日期：2026-10-29
// ------------------------------------------------------------
// 题意：
//   n 个成员，minProfit 最小利润。
//   group[i] = 第 i 个工作需要的成员数；profit[i] = 它产生的利润。
//   求选择工作的方案数：总人数 ≤ n，总利润 ≥ minProfit。答案对 1e9+7 取模。
//
//     n=5,  minProfit=3, group=[2,2],   profit=[2,3]     -> 2
//     n=10, minProfit=5, group=[2,3,5], profit=[6,7,8]   -> 7
//
// ------------------------------------------------------------
// 【与 LC 474 一字之差】
// ------------------------------------------------------------
//   LC 474：0 的个数【不超过】m、1 的个数【不超过】n     -> 两个都是上界
//   LC 879：人数【不超过】n、利润【至少】minProfit        -> 一个是下界 ★
//
// ------------------------------------------------------------
// 【核心：为什么用 max(0, k - profit[i])】
// ------------------------------------------------------------
//   dp[i][j][k] = 前 i 个工作里选，人数 ≤ j、利润【至少】k 的方案数
//
//   选了第 i 个工作（利润 p）后，剩下的部分要凑「至少 k - p」的利润。
//   但如果 p > k（这份工作自己就够），k - p 就是负数 —— 而利润不可能为负。
//       「利润 ≥ 负数」 等价于 「利润 ≥ 0」
//   → 所以下标取 max(0, k - p)。
//
//   ★ 不加 max 会怎样：k - p 为负 -> 数组负下标 -> 越界。
//
//   用数字看：minProfit = 5，某个工作 profit = 10
//       选它 -> 它自己就满足「至少 5」-> 剩下随便什么方案都行 -> dp[j-g][0]
//
// ------------------------------------------------------------
// 【初始化：dp[i][j][0] = 1（所有 i、所有 j）】
// ------------------------------------------------------------
//   「利润至少 0」= 任何方案都满足 -> 只有空集 1 种
//
//   注意是【所有 j】都是 1，不只是 dp[0][0] —— 因为人数限制不影响到"空集"。
//
//   忘了这一步会怎样：整张表第 0 列全是 0 -> 所有"选了工作"的转移都加 0
//   -> 最终答案 0。
//
// ------------------------------------------------------------
// 【必须每步取模】
// ------------------------------------------------------------
//   size ≤ 100 -> 方案数最多 2^100 ≈ 1.3×10^30
//   long long / unsigned long long 上限 ≈ 1.8×10^19
//   -> 中间值早就溢出，最后的 % 只是对垃圾取模。
//
//   所以：每次加法后立刻 %= MOD。
//
// ------------------------------------------------------------
// 【本次踩到的四个坑】
// ------------------------------------------------------------
//   ① k 循环写成 `k <= minProfit + 1` -> 越界（dp 第三维只有 minProfit+1 个）
//   ② 转移写成 dp[i][...] -> 变成完全背包（每个工作能选多次）
//      正确是 dp[i-1][...]（01 背包）
//   ③ 初始化只写了全 0 -> dp[*][*][0] 应该是 1
//   ④ 取模只写在 return -> 中间溢出
//
// ------------------------------------------------------------
// 实测：本机 exe 无法执行（编译成功但 Permission denied / 应用控制策略），
//       本次为逻辑审查 + 用户自测；算法与 LC 474 同构，只多「至少」的截断。
// ============================================================

#include <vector>
using namespace std;

class Solution {
public:
    int profitableSchemes(int n, int minProfit, vector<int>& group, vector<int>& profit) {
        const unsigned long long MOD = 1000000007ULL;
        int size = group.size();

        // dp[i][j][k] = 前 i 个工作里选，人数 ≤ j、利润【至少】k 的方案数
        vector<vector<vector<unsigned long long>>> dp(
            size + 1,
            vector<vector<unsigned long long>>(
                n + 1, vector<unsigned long long>(minProfit + 1, 0)));

        // 初始化：利润至少 0 -> 任何方案都满足 -> 1
        for (int i = 0; i <= size; i++)
            for (int j = 0; j <= n; j++)
                dp[i][j][0] = 1;

        for (int i = 1; i <= size; i++) {
            int g = group[i - 1];
            int p = profit[i - 1];
            for (int j = 0; j <= n; j++) {                 // j 从 0 开始（更规范）
                for (int k = 0; k <= minProfit; k++) {     // ★ 到 minProfit
                    dp[i][j][k] = dp[i - 1][j][k];         // 不选第 i 个
                    if (j >= g) {                          // 选第 i 个（从上一行来）
                        dp[i][j][k] = (dp[i][j][k]
                            + dp[i - 1][j - g][max(0, k - p)]) % MOD;
                    }                                      // ★ 每步取模
                }
            }
        }
        return (int)dp[size][n][minProfit];
    }
};

