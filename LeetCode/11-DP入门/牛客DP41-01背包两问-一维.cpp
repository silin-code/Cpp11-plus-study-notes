// ============================================================
// 牛客 DP41 · 01 背包（两问）—— 【一维压缩版】
// ------------------------------------------------------------
// 与二维版的唯一区别：把 dp[i][j] 压成 dp[j]（省掉 i 这一维）
//
// ★ 为什么能压缩：
//     二维的 dp[i][*] 只依赖 dp[i-1][*]（上一行）；
//     第 i 行算完，第 i-1 行就再也用不到了
//     → 可以用一个数组"原地滚动"
//
// ★ 为什么必须【倒序】遍历 j：
//     倒序：dp[j-v] 还没被本轮改过 → 它是"上一行"的值 → 物品只能用一次 ✓（01 背包）
//     正序：dp[j-v] 已被本轮改过   → 它变成"本行"的值   → 可以重复选（完全背包）✗
//
// ★ 二维里的 `dp[i-1][j-v]` 和一维里的"倒序"是同一件事的两种写法。
// ------------------------------------------------------------
// ★ 两问的 for 循环【完全一样】，只有循环体不同：
//          for (int j = V; j >= v[i]; j--)
//   这句是本次踩坑的地方：
//     · 写成 `j = V; j >= V`     → 只执行 1 次
//     · 写成 `j = 1; j >= v[i]`  → 一次都不执行（v[i] > 1 时）
//   判据：写完问自己"这个循环会执行几次？"
//         0 次 / 1 次 → 端点一定写错了。
// ------------------------------------------------------------
// 实测：6 个用例与二维版【完全一致】
//   {3,5,(2,3)(3,4)(4,5)} → 7 / 7      {2,5,(2,3)(4,4)} → 4 / 0
//   {1,3,(3,10)} → 10 / 10             {1,3,(2,10)}     → 10 / 0
//   {3,4,(1,2)(2,3)(2,3)} → 6 / 6      {1,3,(1,10)}     → 10 / 0
// ============================================================

#include <iostream>
#include <vector>
using namespace std;

int main() {
    int n, V;
    cin >> n >> V;
    vector<int> v(n + 1);   // 体积
    vector<int> w(n + 1);   // 价值
    for (int i = 1; i <= n; i++) {
        cin >> v[i] >> w[i];
    }

    // ---------- 第一问：不要求装满 ----------
    vector<int> dp1(V + 1, 0);
    // dp1[j] 表示容量上限为 j 时的最大价值
    for (int i = 1; i <= n; i++) {
        for (int j = V; j >= v[i]; j--) {           // ★ 倒序
            dp1[j] = max(dp1[j], dp1[j - v[i]] + w[i]);
        }
    }

    // ---------- 第二问：恰好装满 ----------
    vector<int> dp2(V + 1, -1);
    // dp2[j] 表示恰好凑出体积 j 的最大价值；-1 表示凑不出
    dp2[0] = 0;
    for (int i = 1; i <= n; i++) {
        for (int j = V; j >= v[i]; j--) {           // ★ 倒序（端点与第一问完全相同）
            if (dp2[j - v[i]] != -1) {
                dp2[j] = max(dp2[j], dp2[j - v[i]] + w[i]);
            }
        }
    }

    cout << dp1[V] << '\n' << (dp2[V] == -1 ? 0 : dp2[V]);
    return 0;
}
