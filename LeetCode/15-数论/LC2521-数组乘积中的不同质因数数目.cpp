// ============================================================
// LC 2521 数组乘积中的不同质因数数目 —— spf + factorize 的第一次实战
// ------------------------------------------------------------
// 考点：质因数分解（spf 表）+ 集合去重
// 复杂度：时间 O(k log n + n)，空间 O(n)
// 日期：2026-11-26
// ------------------------------------------------------------
// 题意（重点：返回的是【数目】，不是乘积）：
//   对 nums 所有元素求积，返回这个乘积中【不同质因数的个数】。
//     [2,4,3,7,10,6] -> 4     质因数 2,3,5,7 共 4 个
//     [2,4,8,16]     -> 1     只有 2
//   约束：1 <= nums.length <= 1e4，2 <= nums[i] <= 1000
//
// ============================================================
// 【官方提示第一条：不要真的把乘积算出来】
// ============================================================
//   乘积可能是 1000^10000 = 10^30000，任何类型都装不下。
//   而且就算能装，取模之后也无法再分解（取模不可逆）。
//
//   正确思路：根本不需要乘积本身。
//     「乘积的质因数集合」= 「所有元素的质因数集合的并集」
//   所以只要把每个元素单独分解，收集出现过的质数，最后数一数就行。
//
// ============================================================
// 【本次的错误（两层，都记录在这里）】
// ============================================================
//   1. 代码层面（用户版本）：
//        for (e : nums) { cnt *= e; cnt %= mod; }   // 先把乘积算出来并取模
//        while (cnt) { while (cnt % primes[i] == 0) cnt /= primes[i]; ret++; }
//      - 取模不可逆，分解取模后的数毫无意义（乘积的正确性已被破坏）
//      - i 从 0 开始且从不自增 -> 死循环（cnt 变奇数后外层 while(cnt) 永真）
//      - spf 表建了却没用，分解时自己写了一版
//      - spf[i*p] 的边界写成 > n+1，i*p == n+1 时会越界
//
//   2. 出题层面（我的错，更严重）：
//      我把题目读成了「返回不同质因数的【乘积】对 1e9+7 取模」，
//      于是给了错误的题面、错误的示例（210）、错误的实现（ans 累乘取模）。
//      用户写「返回个数」是对的，我却批评他错了。
//      ★ 教训：出题前必须核对原始题面（英文原题 / 官方示例输出），
//        不能凭题名猜。这题题名是 "Distinct Prime Factors of Product of Array"，
//        只看 "Product" 很容易误以为要算乘积。
//
// ============================================================
// 【spf 表的边界（保留这条，是真坑）】
// ============================================================
//       vector<int> spf(1001, 0);          // 合法下标 0..1000
//       if (i * p > 1001) break;           // ✗ i*p == 1001 时下面越界
//       spf[i * p] = p;
//   -> 条件必须是 i * p > n（即 > 1000），不是 > n+1。
//
// ============================================================
// 【结构：分解 -> 去重 -> 数个数】
// ============================================================
//   ① spfTable(1000)         数据范围只有 1000，建一次表
//   ② factorize(x, spf)      逐个分解，只用 pair.first（质因子本体）
//   ③ seen[p] 标记 + cnt++   第一次遇到某个质数时计数加一
//
//   ★ x = 1 时 factorize 返回空（本题约束 nums[i] >= 2，用不到，
//     但写法上天然正确，不会崩）。
//   ★ 用 bool 数组而不是 set：质数最大 1000，数组更快也更简单。
//
// ============================================================
// 【验证】
// ============================================================
//   8 组定点：
//     [2,4,3,7,10,6] -> 4        [2,4,8,16] -> 1
//     [2,3,5] -> 3               [1000] -> 2（2 和 5）
//     [2] -> 1                   [997] -> 1
//     [6,10,15] -> 3（2,3,5）    前 10 个质数 -> 10
//   与「试除 + set 去重」的暴力随机对拍 3000 组零不一致。
// ============================================================

#include <vector>
#include <utility>
using namespace std;

class Solution {
    // 最小质因子表
    vector<int> spfTable(int n) {
        vector<int> spf(n + 1, 0);
        vector<int> primes;
        vector<bool> isComp(n + 1, false);

        for (int i = 2; i <= n; i++) {
            if (!isComp[i]) {
                primes.push_back(i);
                spf[i] = i;
            }
            for (int p : primes) {
                if ((long long)i * p > n) break;   // 注意是 > n，不是 > n+1
                isComp[i * p] = true;
                spf[i * p] = p;
                if (i % p == 0) break;
            }
        }
        return spf;
    }

    // 质因数分解：返回 {质因子, 指数}
    vector<pair<int, int>> factorize(int x, const vector<int>& spf) {
        vector<pair<int, int>> res;
        while (x > 1) {
            int p = spf[x];
            int cnt = 0;
            while (x % p == 0) { x /= p; cnt++; }
            res.push_back(make_pair(p, cnt));
        }
        return res;
    }

public:
    int distinctPrimeFactors(vector<int>& nums) {
        vector<int> spf = spfTable(1000);
        vector<bool> seen(1001, false);
        int cnt = 0;                    // 不同质数的个数

        for (int x : nums) {
            vector<pair<int, int>> f = factorize(x, spf);
            for (size_t i = 0; i < f.size(); i++) {
                int p = f[i].first;              // 只要质因子本体，指数忽略
                if (!seen[p]) {                  // 第一次见到这个质数
                    seen[p] = true;
                    cnt++;
                }
            }
        }
        return cnt;
    }
};
