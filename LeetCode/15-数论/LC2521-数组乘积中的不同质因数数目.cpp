// ============================================================
// LC 2521 数组乘积中的不同质因数数目 —— spf + factorize 的第一次实战
// ------------------------------------------------------------
// 考点：质因数分解（spf 表）+ 去重 + 边乘边取模
// 复杂度：时间 O(k log n + n)，空间 O(n)
// 日期：2026-11-26
// ------------------------------------------------------------
// 题意：
//   对 nums 里每个元素做质因数分解，把所有【出现过的不重复质数】乘起来，
//   对 1e9+7 取模。
//     [2,4,3,7,10,6] -> 210     {2,3,5,7}
//     [2,4,8,16]     -> 2       只有 2
//   约束：1 <= nums[i] <= 1000，1 <= nums.length <= 1000
//
// ============================================================
// 【本题唯一的核心：顺序不能反】
// ============================================================
//   正确顺序：
//       分解每个数  ->  收进集合  ->  乘起来  ->  最后取模
//
//   ★ 一旦先乘起来再取模，就再也分解不出来了。
//     原乘积可能是 10^400 级别的数，取模后变成一个随机的 30 位数，
//     它的质因子和原数组毫无关系。
//
// ============================================================
// 【本次的错误版本（思路性错误，不是笔误）】
// ============================================================
//   错法：先把所有数乘起来并取模，再去分解这个取模后的数。
//       for (e : nums) { cnt *= e; cnt %= mod; }
//       while (cnt) { while (cnt % primes[i] == 0) cnt /= primes[i]; ret++; }
//
//   三个问题：
//   1. 顺序反了 —— 取模后信息已丢失，分解无意义（最致命）
//   2. 死循环 —— i 从不自增，cnt 变成奇数后外层 while(cnt) 永真
//   3. 返回的是质数【个数】而不是【乘积】
//
//   另外建了 spf 表却没用，分解时自己写了一遍试除。
//
// ============================================================
// 【spf 表的一个边界】
// ============================================================
//       vector<int> spf(1001, 0);          // 合法下标 0..1000
//       if (i * p > 1001) break;           // ✗ i*p == 1001 时后面会越界
//       spf[i * p] = p;
//   -> 条件必须是 i * p > 1000（即 > n），不是 > n+1。
//
// ============================================================
// 【三块结构】
// ============================================================
//   ① spfTable(1000)      数据范围只有 1000，建一次表
//   ② factorize(x, spf)   逐个分解，只看 pair.first（质因子本体），
//                         pair.second（指数）这题用不上
//   ③ seen[p] 标记 -> 从 2 到 1000 扫一遍，标记过的乘起来并取模
//
//   ★ x = 1 时 factorize 返回空，内层循环不执行，天然正确。
//   ★ ans 初值 1：一个质数都没有时（如 [1]），空集乘积按 1 算。
//
// ============================================================
// 【验证】
// ============================================================
//   6 组定点：[2,4,3,7,10,6]->210、[2,4,8,16]->2、[1]->1、[37]->37、
//             [1000]->10（1000=2³·5³）、前 10 个质数->469693188
//   与「试除分解 + bool 数组去重」的暴力随机对拍 3000 组零不一致。
// ============================================================

#include <vector>
#include <utility>
using namespace std;

class Solution {
    const int mod = 1000000007;

    // 最小质因子表
    vector<int> spfTable(int n) {
        vector<int> spf(n + 1, 0);
        vector<int> primes;
        vector<bool> isComp(n + 1, false);

        for (int i = 2; i <= n; i++) {
            if (!isComp[i]) {
                primes.push_back(i);
                spf[i] = i;
            }
            for (int p : primes) {
                if ((long long)i * p > n) break;   // 注意是 > n
                isComp[i * p] = true;
                spf[i * p] = p;
                if (i % p == 0) break;
            }
        }
        return spf;
    }

    // 质因数分解：返回 {质因子, 指数}
    vector<pair<int, int>> factorize(int x, const vector<int>& spf) {
        vector<pair<int, int>> res;
        while (x > 1) {
            int p = spf[x];
            int cnt = 0;
            while (x % p == 0) { x /= p; cnt++; }
            res.push_back(make_pair(p, cnt));
        }
        return res;
    }

public:
    int distinctPrimeFactors(vector<int>& nums) {
        vector<int> spf = spfTable(1000);
        vector<bool> seen(1001, false);

        // ① 分解每个元素，把出现过的质数打勾（指数忽略）
        for (int x : nums) {
            vector<pair<int, int>> f = factorize(x, spf);
            for (size_t i = 0; i < f.size(); i++) {
                seen[f[i].first] = true;
            }
        }

        // ② 乘起来，边乘边取模
        long long ans = 1;
        for (int p = 2; p <= 1000; p++) {
            if (seen[p]) ans = ans * p % mod;
        }
        return (int)ans;
    }
};
