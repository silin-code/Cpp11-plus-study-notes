// ============================================================
// LC 372 超级次方 —— 指数太大，换一种进制拆
// ------------------------------------------------------------
// 考点：快速幂的"指数拆分"思想，从二进制推广到十进制
// 复杂度：时间 O(len(b) × log 10)，空间 O(1)
// 日期：2026-11-23（同一天刚学完 qpow）
// ------------------------------------------------------------
// 题意：
//   a 是正整数，b 是一个【用数组表示的十进制大数】（每一位一个元素），
//   求 a^b mod 1337。
//   a = 2, b = [1,0] -> 1024（即 2^10）
//   b 的长度可达 2000 位，即 b 本身远超 long long。
//
// ============================================================
// 【难点：qpow 收不到指数】
// ============================================================
//   昨天写的 qpow(a, b, mod) 里 b 是 long long，最大约 9.2e18（19 位）。
//   本题 b 有 2000 位，根本传不进去。
//
//   所以不能"先算出 b 再调 qpow"，必须【边读位边算】。
//
// ============================================================
// 【核心：十进制天然适合拆——每次"升 10 次方"】
// ============================================================
//   设前 k-1 位组成的数是 N，读到第 k 位数字 d 后，新数是 10N + d。
//
//   用【律 1】把指数拆开：
//       a^(10N + d) = a^(10N) × a^d
//
//   用【律 2】把前一项换成幂的幂：
//       a^(10N) = (a^N)^10
//
//   合起来：
//       a^(10N+d) = (a^N)^10 × a^d
//
//   而 a^N 正是"处理完前 k-1 位后得到的结果 res"。于是：
//
//       res_new = res_old^10 × a^d
//
//   ★ 这一步是整道题的全部。剩下都是调用 qpow。
//
// ============================================================
// 【和普通快速幂的关系（同一个思想的两个用法）】
// ============================================================
//   普通 qpow：指数 b 是 long long  ->  拆成【二进制】的 2 的幂之和
//   本题     ：指数 b 是 2000 位数组 ->  拆成【十进制】的每一位
//
//   共同点：指数太大就换进制拆，每拆一层，指数规模就降一个量级。
//
// ============================================================
// 【为什么每一步的指数都很小】
// ============================================================
//   本题只需要两种幂：
//     res^10       指数固定是 10   ->  qpow 里 4 轮
//     a^d          指数是 0..9     ->  qpow 里最多 4 轮
//   所以 2000 位总共才几千次操作，不会超时。
//
// ============================================================
// 【本次踩的坑】
// ============================================================
//   qpow 的 return 写成了 `return ret;`
//   ret 是 superPow 的局部变量，qpow 里只有 res -> 编译报
//       error: 'ret' was not declared in this scope
//   改成 `return res;` 才通。
//   ★ 教训：变量名跨函数复用（ret / res 只差一个字母）非常容易看错，
//     建议两个函数用完全不同的名字，比如外层 ans、内层 res。
//
// ============================================================
// 【验证】
// ============================================================
//   a=2,          b=[3]                     -> 8
//   a=2,          b=[1,0]                   -> 1024
//   a=1,          b=[4,3,3,8,5,5,3,8,1,3]   -> 1
//   a=2147483647, b=[2,0,0]                 -> 1198   （a 大于 mod，测取模）
//   a=2,          b=[1,2,3]                 -> 1191   （即 2^123）
//   a=1337,       b=[1]                     -> 0
//   a=0,          b=[0]                     -> 1      （0^0 定义为 1）
//   a=2,          b=2000 位全 9             -> 589    （压力组）
//
//   全部与 Python pow(a, int(b), 1337) 一致。
// ============================================================

#include <vector>
using namespace std;

class Solution {
    const int mod = 1337;

    int qpow(int a, int b) {
        int res = 1;
        a %= mod;
        while (b) {
            if (b & 1) res = res * a % mod;
            a = a * a % mod;
            b >>= 1;
        }
        return res;                 // ★ 这里原本误写成 return ret;
    }

public:
    int superPow(int a, vector<int>& b) {
        long long ret = 1;
        a %= mod;                   // a 可能大于 1337（示例 4 就是）

        for (auto e : b) {
            ret = qpow(ret, 10);            // 律 2：整体升 10 次方（指数左移一位）
            ret = ret * qpow(a, e);         // 律 1：再乘 a^这一位
        }

        return ret % mod;           // ret 最大 1336*1336，long long 装得下，这里统一取模
    }
};
