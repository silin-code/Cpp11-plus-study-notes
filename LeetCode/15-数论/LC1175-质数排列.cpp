// ============================================================
// LC 1175 质数排列 —— 数质数 + 两个阶乘
// ------------------------------------------------------------
// 考点：埃氏筛（复用）+ 阶乘取模
// 复杂度：时间 O(n log log n)，空间 O(n/8)
// 日期：2026-11-24（周二嵌入式日，15 分钟题；sieve 重写错了一轮）
// ------------------------------------------------------------
// 题意：
//   把 1..n 排成一列，要求所有【质数】都排在【编号是质数的位置】上
//   （位置从 1 开始编号）。求方案数 mod 1e9+7。
//
// ============================================================
// 【思路：两个独立的排列】
// ============================================================
//   设 1..n 里有 p 个质数，则非质数有 n-p 个。
//   位置 1..n 里，编号是质数的位置也正好 p 个（同一个判断标准）。
//
//   质数只能进质数位置：p 个质数在 p 个格子里全排列 -> p!
//   非质数只能进非质数位置：n-p 个在 n-p 个格子里全排列 -> (n-p)!
//   两类互不干扰 -> 答案 = p! × (n-p)!
//
//   n = 5：质数 2,3,5 共 3 个 -> 3! × 2! = 6 × 2 = 12
//
//   ★ 边界：p = 0 或 n-p = 0 时，循环一次不进，ret 保持 1 —— 正好是 0! = 1。
//     所以 while(i) 这种写法在 0 时天然正确，不用特判。
//
// ============================================================
// 【sieve 这一版踩的四个坑（第一版全中）】
// ============================================================
//   坑 1：vector<bool> tmp(n, true)
//        合法下标只有 0..n-1，而 k 可能取到 n -> 越界。必须 n+1。
//
//   坑 2：tmp[0] = tmp[1] = false
//        n = 1 时 size = 2，下标 1 恰好合法；
//        但如果 n = 0，size = 1，tmp[1] 就越界了。
//        本题 n >= 1，所以安全；通用模板里应加 if (n >= 1) 保护。
//
//   坑 3：内层条件写成 k * i <= n（★ 同一个错误犯了第二次）
//        k 本身就是要划掉的数，范围是 [i*i, n]，条件只能是 k <= n。
//        k*i <= n 相当于要求 k <= n/i，只划到一小段就停了。
//        （11-21 默写时写的是 k*k <= n，也是同类错误）
//
//   坑 4：在外层循环里 ret++
//        外层 i 只走到 sqrt(n)，n=100 时 i 最多到 10，
//        质数 11,13,...,97 根本没被访问过 -> 统计结果 5（真实 25）。
//        ★ 筛法和计数必须分成两个循环：先筛干净，再数一遍。
//
// ============================================================
// 【验证】
// ============================================================
//   n = 1   -> 1
//   n = 2   -> 1
//   n = 3   -> 2
//   n = 4   -> 4
//   n = 5   -> 12
//   n = 100 -> 682289015      （25 个质数：25! × 75!）
//
//   全量对拍 n = 1..1000：与「暴力判断质数 + 两个阶乘」的参考实现零不一致。
// ============================================================

#include <vector>
using namespace std;

class Solution {
    const int mod = 1000000007;

    // 返回 1..n 里有多少个质数
    int sieve(int n) {
        vector<bool> tmp(n + 1, true);    // 坑 1：必须是 n+1
        tmp[0] = tmp[1] = false;          // 本题 n>=1，安全

        for (int i = 2; i * i <= n; i++) {
            if (tmp[i]) {
                for (int k = i * i; k <= n; k += i) {   // 坑 3：k <= n，不是 k*i
                    tmp[k] = false;
                }
            }
        }

        // 坑 4：计数必须单独一遍，不能塞在外层循环里
        int ret = 0;
        for (auto e : tmp) {
            if (e) ret++;
        }
        return ret;
    }

public:
    int numPrimeArrangements(int n) {
        long long ret = 1;
        int i = sieve(n);      // 质数个数 p
        int j = n - i;         // 非质数个数 n-p

        // p! —— i 递减到 0，i=0 时循环不进，ret 保持 1（即 0! = 1）
        while (i) {
            ret = (ret * i) % mod;
            ret %= mod;
            i--;
        }
        // (n-p)!
        while (j) {
            ret = (ret * j) % mod;
            ret %= mod;
            j--;
        }
        return ret % mod;
    }
};
