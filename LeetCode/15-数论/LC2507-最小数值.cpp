// ============================================================
// LC 2507 最小数值 —— 反复把 n 换成"质因数之和"
// ------------------------------------------------------------
// 考点：质因数分解（带重数求和）+ 循环不变式
// 复杂度：时间 O(k·√n)，k 是替换轮数（很小），空间 O(1)
// 日期：2026-11-27（三版才过：前两版把"收尾"写进了循环体）
// ------------------------------------------------------------
// 题意：
//   如果 n 是质数，返回 n。
//   否则把 n 换成【它所有质因数之和（按重数计）】，重复直到 n 是质数。
//     15 -> 3+5=8 -> 2+2+2=6 -> 2+3=5 -> 返回 5
//     12 -> 2+2+3=7  -> 返回 7
//     4  -> 2+2=4    -> 不动，返回 4
//
// ============================================================
// 【核心：质因数之和 = Σ(p × c)】
// ============================================================
//   和 divisorCount 共用同一个"数指数"的动作，只是加工方式不同：
//       divisorCount：ans *= (c+1)      乘
//       本题         ：sum += p * c       加（等价于把 p 写 c 遍）
//
//   例：360 = 2³ × 3² × 5
//       divisorCount -> (3+1)(2+1)(1+1) = 24
//       质因数之和   -> 2×3 + 3×2 + 5×1 = 17
//
// ============================================================
// 【为什么不需要质数表、不需要单独的 isPrime】
// ============================================================
//   质数 n 分解后，循环里一个因子都找不到，剩下的就是 n 本身，
//   于是 sum = n。所以 `if (sum == n) return n;` 这一句同时覆盖：
//       - n 是质数        （sum 等于自己）
//       - n = 4 这个固定点（2+2 还是 4）
//
// ============================================================
// 【两版错误：都出在"收尾动作的位置"】
// ============================================================
//   错误一：把 `if (n > 1) sum += n;` 写在 for 循环【里面】
//       n = 15 时，i=2 一轮什么都没找到，就直接 sum += 15 -> 返回 15（应为 5）
//       n = 100 时，i=2、3、4 各加一次剩余部分 -> 结果 89
//       ★ 「处理剩余」这类动作，永远在循环结束之后做。
//
//   错误二：`if (sum == n) return sum;` 也写在循环里
//       每转一圈就判断一次，判断的是半成品。
//
// ============================================================
// 【现在的版本能过，但逻辑是脆弱的】
// ============================================================
//   原写法直接在 n 上做除法（n /= i），所以循环结束后 n 已经是被除小的值，
//   `sum == n` 比较的其实是 sum 和"残留的 n"，不是原数。
//   它能正确，靠的是三件事凑在一起：
//       ① 质数时 n 没被除过  -> sum == n 天然成立
//       ② 合数时 sum 通常远大于残留的 n -> 不会误判
//       ③ n = 4 单独特判（因为 4 除完变 1，sum=4 != 1，会无限递归）
//
//   ★ 推荐写法：多开一个副本 x，特判就可以删掉，逻辑也自洽：
//       int sum = 0, x = n;
//       for (int i = 2; i * i <= x; i++)
//           while (x % i == 0) { sum += i; x /= i; }
//       if (x > 1) sum += x;
//       if (sum == n) return n;      // 质数 / 固定点，一眼可见
//       return smallestValue(sum);   // 或 n = sum; 用 while 循环
//
// ============================================================
// 【验证】
// ============================================================
//   13 组定点：15->5、12->7、4->4、8->5、9->5、100->5、5->5、
//              97->97、3->3、2->2、1->0、1000->7、65536->7
//   与「副本写法 + while 循环」的参考实现全量对拍 n = 2..20000，
//   零不一致。
//   （题目约束 n >= 2，n = 1 返回 0 不在考察范围）
// ============================================================

class Solution {
public:
    int smallestValue(int n) {
        if (n == 4)               // 固定点：4 -> 2+2 -> 4，不特判会无限递归
            return 4;

        int sum = 0;

        for (int i = 2; i * i <= n; i++) {
            while (n % i == 0) {
                n /= i;
                sum += i;         // 质因子按重数逐个加：2³ 就是 +2 三次
            }
        }

        if (n > 1)                // 循环结束后的残留：一个大质数
            sum += n;

        if (sum == n)             // 质数（sum 等于自己）
            return sum;

        return smallestValue(sum); // 递归处理下一轮
    }
};
