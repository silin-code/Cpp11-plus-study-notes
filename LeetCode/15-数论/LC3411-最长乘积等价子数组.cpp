// ============================================================
// LC 3411 最长乘积等价子数组 —— 暴力双指针，本题不需要优化
// ------------------------------------------------------------
// 考点：gcd / lcm 的维护（不是滑动窗口）
// 复杂度：时间 O(n²)，空间 O(1)
// 日期：2026-11-24
// ------------------------------------------------------------
// 题意：
//   子数组 arr 满足 prod(arr) == lcm(arr) * gcd(arr) 时叫"乘积等价"。
//   求 nums 的最长乘积等价子数组长度。
//
//   约束：2 <= n <= 100，1 <= nums[i] <= 10
//   难度：LeetCode 标注为【简单】
//
// ============================================================
// 【第一个结论：本题的 O(n²) 就是正解，不要想滑窗】
// ============================================================
//   n <= 100 -> 双重循环 10000 次，比任何常数优化都便宜。
//   这题在 LeetCode 上标"简单"，考察点是"会不会维护 gcd/lcm"，
//   根本不是复杂度优化题。
//
// ============================================================
// 【第二个结论：滑动窗口在这里不可行（即使 n 很大也不行）】
// ============================================================
//   滑动窗口成立的前提：右端点扩张后，能从左边收缩把它救回来，
//   而且收缩时状态能 O(1) 撤销。
//
//   prod 可以撤销：prod /= nums[left]（除法）
//   gcd  不能撤销：删掉一个元素，gcd 可能变大，但无法从当前值反推
//   lcm  不能撤销：同理
//
//   ★ 所以任何"维护 gcd/lcm 的区间问题"，标准滑窗都做不了。
//     要么枚举左端点向右扩（本题），要么用稀疏表 / 分块。
//
// ============================================================
// 【如果 n 真的很大，正确的方向是什么（本题用不到）】
// ============================================================
//   不是滑窗，而是【利用乘积增长极快】：
//     prod <= 1e18 时，窗口里的非 1 元素最多约 60 个（2^60 ≈ 1e18）
//     1 不改变 prod / gcd / lcm，只贡献长度
//   -> 枚举左端点，向右最多扩展 60 个非 1 元素即可，复杂度 O(60n)
//
//   本题 nums[i] <= 10 且 n <= 100，乘积根本长不起来，用不上。
//
// ============================================================
// 【代码里两个值得注意的地方】
// ============================================================
//   1. 两个元素的子数组【一定】满足
//         a * b == gcd(a,b) * lcm(a,b)   恒等式
//      所以任何 n >= 2 的输入，答案至少是 2。
//      本例 res 初值 0 也能对，因为第一个 j = i+1 就会命中。
//
//   2. break 的条件 `prodVal > gcdVal * lcmVal` 是对的
//      窗口继续右扩时：prod 乘 x，gcd*lcm 最多乘 x
//        若已有 prod > gl，则 prod*x > gl*x >= gl_new，
//        不可能再回到相等 -> 可以安全退出本层
//      这也是本题不会溢出 long long 的原因：一超过就 break 了。
//
//   3. std::gcd / std::lcm 是 C++17 才有的
//      蓝桥杯考场是 C++11，没有这两个函数，必须自己写（见 number_theory.hpp）。
//      LeetCode 默认 C++17 所以这里能直接调用。
//
// ============================================================
// 【验证】
// ============================================================
//   官方示例：
//     [1,2,1,2,1,1,1]  -> 5
//     [2,3,4,5,6]      -> 3
//     [1,2,3,1,4,5,1]  -> 5
//   边界：
//     [1,1]            -> 2
//     [10,10]          -> 2
//     [1,1,1,1,1]      -> 5
//   压力：
//     100 个 1         -> 100
//     100 个 10        -> 2
//
//   与「__int128 暴力枚举所有子数组」的实现逐组对比，结果一致。
// ============================================================

#include <vector>
#include <algorithm>
#include <numeric>
using namespace std;

class Solution {
public:
    int maxLength(vector<int>& nums) {
        int res = 0;

        for (int i = 0; i < (int)nums.size(); i++) {
            long long prodVal = nums[i];
            long long gcdVal = nums[i];
            long long lcmVal = nums[i];

            for (int j = i + 1; j < (int)nums.size(); j++) {
                prodVal = prodVal * nums[j];
                gcdVal = gcd(gcdVal, (long long)nums[j]);
                lcmVal = lcm(lcmVal, (long long)nums[j]);

                // prod 已经超过 gcd*lcm，再往右扩只会更超 -> 本层可以停
                if (prodVal > gcdVal * lcmVal) {
                    break;
                }
                if (prodVal == gcdVal * lcmVal) {
                    res = max(res, j - i + 1);
                }
            }
        }
        return res;
    }
};
