// ============================================================
// LC 3411 最长乘积等价子数组 —— 两种解法
// ------------------------------------------------------------
// 考点：gcd / lcm 的质因子分析 + 滑动窗口
// 难度：LeetCode 标注【简单】（约束 n<=100、nums[i]<=10，
//       所以 O(n^2) 的暴力就是大多数人的正解）
// 日期：2026-11-24
// ------------------------------------------------------------
// 题意：
//   子数组 arr 满足 prod(arr) == lcm(arr) * gcd(arr) 时叫"乘积等价"。
//   求最长乘积等价子数组的长度。
//
// ============================================================
// 【基础：长度 2 恒成立】
// ============================================================
//   对任意两个正整数 a、b：
//       a * b = gcd(a,b) * lcm(a,b)
//   所以长度为 2 的子数组【天然满足】，答案至少是 2。
//   下面只讨论长度 >= 3 的情况。
//
// ============================================================
// 【核心结论：长度 >= 3 时，等价于"两两互质"】
// ============================================================
//   按质因子逐个看。取任意一个质数 p，设它在子数组 k 个元素里的指数分别是
//       x1, x2, ..., xk        （x_i >= 0）
//
//   那么 p 在三个量里的指数分别是：
//       prod : x1 + x2 + ... + xk          （乘积是指数相加）
//       gcd  : min(xi)                     （公因数取最小指数）
//       lcm  : max(xi)                     （公倍数取最大指数）
//
//   prod == gcd*lcm 要求两边【每个质因子的指数都相等】，于是：
//       x1 + x2 + ... + xk = min(xi) + max(xi)
//
//   把指数排序：x1' <= x2' <= ... <= xk'，则 min = x1'、max = xk'，代入：
//       x1' + x2' + ... + xk' = x1' + xk'
//   =>  x2' + x3' + ... + x(k-1)' = 0
//   因为每项都 >= 0，所以中间各项全为 0：
//       x2' = x3' = ... = x(k-1)' = 0
//   又因为 x1' <= x2' = 0 且 x1' >= 0，所以 x1' = 0。
//   => 只有 xk' 可能大于 0。
//
//   结论：**质数 p 只能出现在子数组的【一个】元素里。**
//   对每个质数都成立 => 任意两个元素不共享质因子 => 两两互质。
//
//   反过来也成立：两两互质时每个质因子只出现一次，
//   于是 min = 0、max = 该指数，Σ = max = min + max，条件满足。
//
//   ★ 所以：
//       长度 2  ->  恒成立
//       长度 >=3 ->  充要条件是窗口内元素两两互质
//     答案 = max(2, 最长两两互质子数组长度)
//
// ============================================================
// 【方法一：暴力枚举 O(n^2)（本题 n <= 100，够用）】
// ============================================================
//   枚举左端点，向右扩展，维护 prod / gcd / lcm。
//   若 prod > gcd*lcm 就 break（右扩只会更超，见下方单调性说明）。
//   复杂度 100^2 = 1e4，本题正解之一。
//
//   单调性证明（break 的依据）：
//     窗口右扩一个 x：prod_new = prod * x，而 gcd 只减不增、lcm 至多乘 x，
//     所以 gl_new <= gl * x。
//     若已有 prod > gl，则 prod*x > gl*x >= gl_new，
//     不可能再回到相等 -> 可以安全退出本层。
//   这也保证了 prod 不会无限增长到溢出（一超过就 break）。
//
// ============================================================
// 【方法二：转化 + 滑动窗口 O(n log M)（官方正解）】
// ============================================================
//   既然长度 >=3 等价于"两两互质"，问题就变成：
//       求最长的、内部两两互质的子数组。
//
//   滑窗维护：
//     prodVal = 窗口内所有元素的乘积
//     新元素 x 进来时，判断 gcd(prodVal, x)：
//       == 1  -> x 与窗口内所有元素互质，直接加入
//       >  1  -> x 与窗口内某个元素有公因子，左端点不断右移
//                （prodVal /= nums[start]）直到 gcd(prodVal, x) == 1
//     每成功加入一个元素，窗口长度就是一个合法答案。
//
//   ★ 为什么这里 prod 可以除回去，而 gcd/lcm 不行？
//     因为窗口内两两互质，prodVal 的各质因子互不重叠，
//     prodVal / nums[start] 一定能整除、且不丢失其他元素的信息。
//     而如果直接维护 gcd/lcm，删除元素后无法反推（gcd 可能变大、lcm 可能变小）。
//     -> 关键不在"能不能撤销 gcd"，而在【先把条件转化为只需要 prod】。
//
//   ★ gcd(prodVal, x) > 1 等价于"x 与窗口中某个元素有公共质因子"：
//     prodVal 是所有元素的乘积，某个质数 p 整除 prodVal
//     <=> p 整除其中某个元素。所以只要看 prodVal 整体即可。
//
// ============================================================
// 【方法二的一个实现细节：prodVal 用 int 够吗】
// ============================================================
//   窗口内两两互质 + nums[i] <= 10，窗口乘积的最大值出现在
//   最长的两两互质子集 {1,8,9,5,7} 上：8*9*5*7 = 2520。
//   1 可以无限重复（与任何数互质），但不影响乘积。
//   所以本题 int 完全够。
//   ★ 如果 nums[i] 范围放大，就必须换 long long 并防溢出。
//
// ============================================================
// 【验证】
// ============================================================
//   官方示例：
//     [1,2,1,2,1,1,1]  -> 5
//     [2,3,4,5,6]      -> 3
//     [1,2,3,1,4,5,1]  -> 5
//   边界：
//     [1,1] / [10,10] / [2,4,8,16] -> 2
//   压力：
//     100 个 1  -> 100      （1 与任何数互质，全窗口合法）
//     100 个 10 -> 2        （10 之间不互质，只能取 2 个）
//
//   方法二与「__int128 暴力枚举所有子数组」随机对拍 30000 组零不一致。
// ============================================================

#include <vector>
#include <algorithm>
#include <numeric>
using namespace std;

class Solution {
public:
    // ---------- 方法二：滑动窗口（推荐） ----------
    int maxLength(vector<int>& nums) {
        int res = 2;              // 长度 2 恒成立
        int prodVal = 1;          // 窗口内元素的乘积
        int n = (int)nums.size();
        int start = 0, end = 0;

        while (end < n) {
            // x 与窗口内某元素有公因子 -> 不断移出左端点
            while (gcd(prodVal, nums[end]) > 1) {
                prodVal /= nums[start];    // 两两互质，除法一定整除
                start++;
            }
            prodVal *= nums[end];
            res = max(res, end - start + 1);
            end++;
        }
        return res;
    }

    // ---------- 方法一：暴力 O(n^2)（本题 n<=100 也够） ----------
    int maxLengthBrute(vector<int>& nums) {
        int res = 0;
        for (int i = 0; i < (int)nums.size(); i++) {
            long long prodVal = nums[i];
            long long gcdVal = nums[i];
            long long lcmVal = nums[i];

            for (int j = i + 1; j < (int)nums.size(); j++) {
                prodVal = prodVal * nums[j];
                gcdVal = gcd(gcdVal, (long long)nums[j]);
                lcmVal = lcm(lcmVal, (long long)nums[j]);

                if (prodVal > gcdVal * lcmVal) break;   // 右扩只会更超
                if (prodVal == gcdVal * lcmVal) {
                    res = max(res, j - i + 1);
                }
            }
        }
        return res;
    }
};
