// ============================================================
// LC 2523 范围内最接近的两个质数 —— 一次筛 + 一遍扫描
// ------------------------------------------------------------
// 考点：埃氏筛 + 单遍扫描（线性）
// 复杂度：时间 O(R log log R)，空间 O(R/8)
// 日期：2026-11-21（周六每日一题；连超时两版才改对）
// ------------------------------------------------------------
// 题意：
//   给定 left、right，在闭区间 [left, right] 内找两个质数，使差值最小。
//   差值相同取第一个质数更小的那组；质数不足两个返回 [-1, -1]。
//
// ============================================================
// 【这一题真正的考点不是筛法，是「别把昂贵的东西放进内层」】
// ============================================================
// 同一份筛法，后面结算写错，就是从 3ms 变成 70 秒。
// 三个版本的演进过程（都实测过）：
//
//   版本 1（原版，TLE）
//     for (i in [left, right]) if (isprime[i])
//         for (j = i+1; j <= right; j++) ...   // 每个质数都往后扫整段
//     -> 1..1e6 有 78498 个质数，每个扫 1e6 -> 7.8e10 次
//     -> 实测 right=1e5: 641ms / 2e5: 2336ms / 3e5: 6327ms（平方增长）
//     -> 外推 1e6 约 70 秒
//
//   版本 2（收集到 tmp 再双层遍历，仍 TLE）
//     先把质数 push 进 tmp（这步是对的），但结算还是双层：
//         for (i = 0; i < tmp.size(); i++)
//             for (j = i+1; j < tmp.size(); j++)
//     -> 78498^2 / 2 ≈ 3.1e9 次
//     -> 实测 right=1e6: 702ms（单次就要 0.7 秒，多测试点累计必超）
//
//   版本 3（只比相邻，AC）
//         for (i = 0; i + 1 < tmp.size(); i++) 比 tmp[i] 和 tmp[i+1]
//     -> 78498 次
//     -> 实测 right=1e6: 3ms
//
// ============================================================
// 【为什么只比相邻就够（这一句是版本 3 的全部依据）】
// ============================================================
//   反证：设最小的一对是 tmp[a] 和 tmp[b]，且 b > a+1（中间夹着 tmp[a+1]）。
//         那么 tmp[a+1] < tmp[b]，所以
//             tmp[a+1] - tmp[a]  <  tmp[b] - tmp[a]
//         即存在一对差值更小 —— 与「tmp[b]-tmp[a] 是最小差」矛盾。
//   => b 只能等于 a+1，最优对必然相邻。
//
//   直观版：11 13 17 19
//           相邻 2, 4, 2  -> 最小 2（11,13）
//           隔一个 6, 8, 6 -> 全更大
//
// ============================================================
// 【实现上的三个点】
// ============================================================
//   1. isprime.assign(right + 1, true)
//      用 assign 而不是 resize + 手动清空：assign 会同时重设大小和值，
//      类成员在多次调用之间复用也不会残留上一组数据。
//      ★ 对比 LC 1584 那次 p.resize(n, -1) 的教训：resize 不会覆盖已有元素。
//
//   2. isprime[0] = isprime[1] = false
//      本题 right >= 1，assign(right+1) 之后至少有下标 0、1，安全。
//      （如果 n 可能为 0，就要加 if 保护 —— 见 number_theory.hpp 里的写法）
//
//   3. 差值相同取第一组
//      因为 i 从小到大扫，用严格 `ret > d`（不是 >=），
//      第一次遇到的就是 l 最小的那组，后面的相同差值自动被忽略。
//
// ============================================================
// 【验证】
// ============================================================
//   定点 10 组，含全部边界：
//       [10,19] -> [11,13]
//       [4,6] / [1,2] / [8,10] / [14,16] / [1,1] / [2,2] -> [-1,-1]
//       [2,3] -> [2,3]
//       [1,1000] -> [2,3]
//       [999983,1000000] -> [-1,-1]（该段只有一个质数 999983）
//
//   随机对拍：与「枚举区间内所有质数、枚举所有对取最小差」的暴力比，
//   20000 组（left∈[1,300], right∈[left,left+300]）零不一致。
//
//   性能：left=1 right=1e6 -> 3ms；left=999000 right=1e6 -> 1ms
// ============================================================

#include <vector>
using namespace std;

class Solution {
private:
    vector<bool> isprime;
public:
    vector<int> closestPrimes(int left, int right) {
        // ① 筛出 [0, right] 的质数表
        isprime.assign(right + 1, true);   // assign 同时重设大小和值，多次调用不残留
        isprime[0] = isprime[1] = false;

        for (int i = 2; i * i <= right; i++) {
            if (isprime[i]) {
                for (int k = i * i; k <= right; k += i) {   // 从 i*i 起，划到 right
                    isprime[k] = false;
                }
            }
        }

        // ② 把区间内的质数收集起来
        int ret = 0x3f3f3f;
        int r = -1, l = -1;
        vector<int> tmp;
        for (int i = left; i <= right; i++) {
            if (isprime[i])
                tmp.push_back(i);
        }

        if (tmp.size() < 2)
            return vector<int>{-1, -1};

        // ③ 只比相邻的两个（最优对必然相邻，证明见文件头）
        for (int i = 0; i + 1 < (int)tmp.size(); i++) {
            int d = tmp[i + 1] - tmp[i];
            if (ret > d) {          // 严格大于 -> 差值相同时保留第一组
                ret = d;
                r = tmp[i + 1];
                l = tmp[i];
            }
        }

        return vector<int>{l, r};
    }
};
