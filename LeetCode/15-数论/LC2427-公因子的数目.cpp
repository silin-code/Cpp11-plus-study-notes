// ============================================================
// LC 2427 公因子的数目 —— gcd + 根号枚举
// ------------------------------------------------------------
// 考点：gcd 的转化 + 「约数成对出现」的枚举技巧
// 复杂度：时间 O(log min(a,b) + sqrt(g))，空间 O(1)
// 日期：2026-11-22（周日轻量题；两处错：gcd 返回值 + 只数一半）
// ------------------------------------------------------------
// 题意：
//   给两个正整数 a、b，返回同时整除 a 和 b 的正整数个数。
//   a = 12, b = 6  ->  4（1 2 3 6）
//   a = 25, b = 30 ->  2（1 5）
//
// ============================================================
// 【第一步转化：公因子 <-> gcd 的约数】
// ============================================================
//   设 g = gcd(a, b)。
//
//   方向一：若 d | a 且 d | b，则 d 整除 a、b 的任意整系数组合，
//           特别地整除 gcd(a,b) = g。-> d 是 g 的约数。
//   方向二：若 d | g，因为 g | a 且 g | b，由传递性 d | a 且 d | b。
//
//   两个方向合起来：{a,b 的公因子} = {g 的约数}。
//   于是问题变成「求 g 有多少个约数」，a、b 本身不再参与。
//
// ============================================================
// 【第二步：约数是成对出现的（这题唯一的新技巧）】
// ============================================================
//   以 g = 12 为例，约数从小到大：1 2 3 4 6 12
//   配对：1*12、2*6、3*4 —— 每对的乘积都是 g。
//
//   配对里的两个数，一个 <= sqrt(g)，一个 >= sqrt(g)。
//   所以只枚举 i = 1 .. sqrt(g)：
//       只要 g % i == 0，就同时拿到 i 和 g/i 两个约数。
//
//   g = 12，枚举 i = 1,2,3 -> 3 对 -> 6 个约数。
//
//   ★ 完全平方的特例：g = 16，sqrt(16) = 4
//       i = 1 -> 1,16    i = 2 -> 2,8    i = 4 -> 4,4（同一个数！）
//       所以 i*i == g 时只能算 1 个，否则会把 4 数两次（得到 6 而不是 5）。
//
//   实现上推荐【分两行写】，不要合并成一句：
//       ret += 2;
//       if (i * i == g) ret--;
//   先无条件按"一对两个"加，再把重复的那一个减掉，逻辑不会绕。
//
// ============================================================
// 【本次踩的两个坑】
// ============================================================
//   1. gcd 里写了 return y;
//      循环条件是 while (y)，退出瞬间 y 必然为 0，
//      所以函数恒返回 0 -> tmp = 0 -> 循环一次不进 -> 所有用例返回 0。
//      必须是 return x;（退出时 x 才是最后一个非零余数）
//
//   2. 只数了一半
//      if (g % i == 0) ret++;   只会得到 "<= sqrt(g) 的约数个数"。
//      g = 12 时得 3，而正确答案是 6 —— 每一对的两个都要算。
//
// ============================================================
// 【验证】
// ============================================================
//   定点 9 组：
//       (12,6)=4  (25,30)=2  (1,1)=1  (1,12)=1  (12,12)=6
//       (16,16)=5        <- 完全平方，扣掉重复的那个 4
//       (6,9)=2          <- gcd=3，约数 1,3
//       (2,3)=1
//       (1e9,1e9)=100    <- 1e9 = 2^9 * 5^9，约数个数 (9+1)^2 = 100
//
//   随机对拍：与「枚举 1..min(a,b) 逐个判整除」的暴力比，
//   5000 组（a,b ∈ [1,1000]）零不一致。
//
//   性能：(1e9, 1e9) 耗时 0.07 ms（枚举到 sqrt(1e9) ≈ 31623 次）
// ============================================================

#include <algorithm>
using namespace std;

class Solution {
    int gcd(int x, int y) {
        while (y) {
            int t = x % y;
            x = y;
            y = t;
        }
        return x;              // 退出时 y == 0，x 才是答案
    }
public:
    int commonFactors(int a, int b) {
        int ret = 0;
        int tmp = gcd(a, b);   // 转化：只需求和 gcd 的约数个数

        // 只枚举到 sqrt(tmp)：每找到一个 i，g/i 也同时拿到
        for (int i = 1; i * i <= tmp; i++) {
            if (tmp % i == 0) {
                ret += 2;              // 先按"一对两个"加
                if (i * i == tmp)      // 完全平方：i 和 g/i 是同一个数
                    ret--;             // 扣掉重复的
            }
        }
        return ret;
    }
};
