// ============================================================
// LC 1390 四因数 —— 根号枚举成对约数
// ------------------------------------------------------------
// 考点：约数的成对枚举（与 LC 2427 同一套）
// 复杂度：时间 O(k·√n)，空间 O(1)
// 日期：2026-11-26（周四轻量题；两处 bug：去重 + 完全平方）
// ------------------------------------------------------------
// 题意：
//   "四因数"= 恰好有 4 个约数的正整数。
//   把所有四因数的【约数之和】加起来返回；没有则返回 0。
//   同一个数出现几次就算几次。
//
//     [21,4,7]   -> 32    21 的约数 1,3,7,21，和 32
//     [21,21,7]  -> 64    21 出现两次，32×2
//     [1,2,3,4]  -> 0
//
// ============================================================
// 【核心：根号枚举，i 和 n/i 是一对】
// ============================================================
//   i 从 1 到 √n，只要 n % i == 0，就同时拿到两个约数 i 和 n/i。
//   个数 +2，和 + i + n/i。
//
//   ★ 唯一例外：i * i == n 时，i 和 n/i 是同一个数，只能算一次。
//     例：n = 4，i = 2 时 2 和 2 是同一个，
//         不判断就会把 4 算成 4 个约数（实际只有 1,2,4 三个）。
//
// ============================================================
// 【本次两个 bug】
// ============================================================
//   1. 用 unordered_map 去重了
//      题目要求「每个出现都算」，[21,21,7] 应返回 64。
//      去重后只算一次，得 32。
//      （代码里虽然 hash[e]++ 统计了次数，但 count 一次都没用到）
//
//   2. 完全平方没判断
//      cnt += 2 无条件执行 -> n = 4 时得到 4 个约数 -> 被误判为四因数。
//      ★ 11-22 的 LC 2427 已经踩过这个坑（那里写的是 if (i*i==g) cnt--）。
//
// ============================================================
// 【还能更快吗 —— 两个方向，本题都用不上】
// ============================================================
//   方向一：数学结构。四因数只有两种形态。
//       设 n = p1^a1 · p2^a2 · ... ，约数个数 = (a1+1)(a2+1)...
//       要它等于 4，乘法拆分只有两种：
//           4 = 4        -> 单个质因子，指数 3  -> n = p³
//           4 = 2 × 2    -> 两个质因子，各指数 1 -> n = p × q
//       验证：p³ 的约数是 1,p,p²,p³（4 个）；
//             p×q 的约数是 1,p,q,pq（4 个）。
//       于是判断变成：n 是不是 p³，或者分歧成两个不同质数。
//       配合 spf 表可在 O(log n) 内判定，但实现比根号枚举复杂。
//
//   方向二：预筛表。若数组极长（1e6 以上），可以一次性算出
//       1..N 每个数的约数个数与约数和：
//           for (i = 1; i <= N; i++)
//               for (j = i; j <= N; j += i) { cnt[j]++; sum[j] += i; }
//       复杂度 O(N log N)，之后每个元素 O(1) 查询。
//       ★ 只有「查询次数远大于 N」时划算。本题 k ≤ 1e4、N ≤ 1e5，
//         逐个根号枚举 3×10^6 次已经足够，预筛反而更重。
//
//   => 本题当前写法就是合适解法，不必优化。
//
// ============================================================
// 【验证】
// ============================================================
//   8 组定点：三个官方示例 + [8]->15 + [16]->0 + [4]->0 + [1]->0 + 混合
//   与「枚举 1..n 全部约数」的暴力随机对拍 5000 组零不一致。
// ============================================================

#include <vector>
using namespace std;

class Solution {
public:
    int sumFourDivisors(vector<int>& nums) {
        int ret = 0;

        for (auto e : nums) {          // 不去重：每个出现都要算
            int n = e;
            int cnt = 0;
            int flag = 0;              // 名字叫 flag，实际是"约数之和"

            for (int i = 1; i * i <= n; i++) {
                if (n % i == 0) {
                    if (i * i == n) {          // 完全平方：两个约数是同一个
                        cnt += 1;
                        flag += i;
                    } else {
                        cnt += 2;
                        flag += i + n / i;
                    }
                }
                if (cnt > 4) break;            // 超过 4 个就没必要继续了
            }

            if (cnt == 4) ret += flag;
        }
        return ret;
    }
};
