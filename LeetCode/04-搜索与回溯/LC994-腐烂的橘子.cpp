// ============================================================
// LeetCode 994. 腐烂的橘子
// 考点：多源 BFS（多个起点同时扩散）+ 按层切分计时
// 复杂度：时间 O(n*m)，空间 O(n*m)
// 日期：2026-09-22
// ============================================================
//
// 【题意】
// 网格里 0 = 空格，1 = 新鲜橘子，2 = 腐烂橘子。每分钟，每个腐烂橘子让
// 上下左右相邻的【新鲜】橘子变腐烂。求让所有新鲜橘子都腐烂所需的最少分钟数；
// 若有新鲜橘子永远烂不到（被 0 隔开）→ 返回 -1。
//
// ============================================================
// 【核心一：多源 BFS —— 队列开局塞进【所有】腐烂橘子】
// ============================================================
// 单源 BFS：队列里一开始只有一个起点，一圈一圈往外扩。
// 多源 BFS：队列里一开始就有【一批】起点，它们【同时】往外扩。
//
// 为什么不能逐个烂橘子当起点各跑一次 BFS？
//   因为各起点的扩散是【并行】的，答案取决于"最晚被覆盖的那一层"；
//   分开跑再合并很麻烦。把全部源一次入队，BFS 天然就按"同时"推进。
//
// ============================================================
// 【核心二：层 = 时间，但第 0 层不算】
// ============================================================
// BFS 的每一"层"就是"过了一分钟"，所以用两层 while：
//   外层 while (!q.empty())    —— 一轮 = 处理一整层
//   内层 while (size--)        —— size 先取 q.size()，只处理当前这一层；
//                                 内层新推入的节点留到下一轮（下一分钟）
//
// 关键：开局那一层（初始腐烂橘子）是【第 0 分钟】，不算时间。
// 所以不能无毒地 ret++，要【本层真的扩散了才 +1】：
//     bool flag = false;
//     ... 每成功腐烂一个邻居 → flag = true;
//     if (flag) ret++;
//
// 反例（实测）：[[2,1,1],[1,1,0],[0,1,1]] 应 4，
//   若在 while 里无条件 ret++，会得 5（普遍多算 1 分钟）。
//
// ============================================================
// 【易错点（本题实测踩过的）】
// ============================================================
//   ① queue 只有 push，没有 push_back（push_back 是 vector 的接口）
//   ② 返回值：函数声明是 int，别写 return false / return true
//      （bool→int 隐式转换，编译器不报，但永远只返回 0/1）
//      应为：还有新鲜橘子 → return -1；否则 → return ret
//   ③ ret++ 要"本层真扩散才 +1"，否则第 0 层也被算成 1 分钟
//   ④ 用 grid[0].size() 前要保证 grid 非空（本题约束保证 1<=m,n）
//
// 【408 标注】BFS 求【无权图的最短路径】是 408 图论核心考点
//   （历年多次考"BFS 求最短路径长度"）。本题本质就是网格上的无权最短路，
//   只是把"路径长度"换成了"传染轮数"，考法与 408 同源。
// ============================================================

class Solution {
int dx[4]={0,0,-1,1};
int dy[4]={-1,1,0,0};
public:
int orangesRotting(vector<vector<int>>& grid) {
int n=grid.size(),m=grid[0].size();
queue<pair<int,int>> q;
for(int i=0;i<n;i++)
{
for(int j=0;j<m;j++)
{
if(grid[i][j]==2)
{
q.push(make_pair(i,j));
}
}
}
int ret=0;
while(q.size())
{
int size=q.size();
bool flag=false;
while(size--)
{
int x=q.front().first;
int y=q.front().second;
q.pop();
for(int a=0;a<4;a++)
{
int i=x+dx[a],j=y+dy[a];
if(i>=0&&i<n&&j>=0&&j<m&&grid[i][j]==1)
{
grid[i][j]=2;
q.push(make_pair(i,j));
flag=true;
}
}
}
if(flag)
{
ret++;
flag=false;
}
}
for(auto e:grid)
{
for(auto ee:e)
{
if(ee==1) return -1;
}
}
return ret;
}
};
