// ============================================================
// LeetCode 695. 岛屿的最大面积
// 考点：Flood Fill + **承接返回值的 DFS**（int 返回值四方向累加）
// 复杂度：时间 O(n*m)，空间 O(n*m)
// 日期：2026-09-18  （经三版修正，第三版通过）
// ============================================================
//
// 【题意】
// grid 是 0/1 网格，1 为陆地。求最大连通块（四方向相连）的面积。
//
// 【注意 grid 的类型】
// 本题 grid 是 vector<vector<int>>，判断写 `grid[i][j] == 1`；
// LC 200 是 vector<vector<char>>，写 `== '1'`。
// 抄上一题的代码时，**先看形参类型**。（首版就栽在这，恒 false → 返回 0）
//
// 【核心：dfs 的返回值代表什么】
//     返回"以 (i,j) 为根的这块连通区域共有多少格"
//
// 本版采用「调用者标记 + 累加」的约定：
//   - 外层发现新陆地时：先 use[i][j] = true，再调用 dfs
//   - dfs 内部：不检查自己（调用者已保证 (i,j) 是可用且刚标记的），
//     只负责遍历四个邻居；邻居可用 → 标记 + 把递归结果累加进 flag
//   - 返回 flag + 1：flag 是四个方向报上来的格数，+1 是自己这一格
//
// 【为什么 return 必须在循环外】
// 四个方向是四份**独立**的报告，必须全部收齐才能相加。
// 把 `return` 写在循环内 → 只问第一个方向就结束 → 无论岛多大都只返回 1
// （实测：修掉其它问题但保留循环内 return，官方示例返回 1 而非 6）。
//
// 【网格 DFS 的两套调用约定 —— 不能混用】
//
//   模式 A「调用者标记」（本法 / LC 200 风格）
//     外层：use[i][j]=true; 再 dfs(i,j)
//     dfs ：不检查自己，直接遍历邻居，邻居可用就标记 + 递归
//     返回值：可以是 void，也可以像本题一样返回 int
//
//   模式 B「自足式」
//     外层：不预标记，直接 dfs(i,j)
//     dfs ：进来先判自己（越界 / 非陆地 / 已访问 → 返回 0）→ 标记自己 → 四方向累加
//     返回值：int
//
//   混用的后果（实测）：外层用 A 的预标记 + dfs 里用 B 的"检查自己"守卫
//     → 守卫必然命中 → dfs 恒返回 0 → 整题返回 0
//
// 【易错 ⑥：成员变量 ret 不复位 —— 第 5 次】
//   原稿把 ret 写成成员变量且入口不复位。
//   实测（同一对象连续调用）：
//     先跑面积 4，再跑面积 1  →  4 / 4    （应为 4/1）
//     先跑 1×3(=3)，再跑单格  →  3 / 3    （应为 3/1）
//   力扣每用例新建对象所以不触发；本地多测 / 调试连续调用必错。
//   改成 maxAreaOfIsland 里的**局部变量**即可（局部天然每次重生）。
//   同类前科：LC 51、LC 1094、LC 46、LC 200。
//
// 【为什么 int 够用】
//   n, m ≤ 50 → 面积最大 2500，远小于 int 上限。
// ============================================================

class Solution {
    int n, m;
    vector<vector<bool>> use;
    int dx[4] = {0, 0, -1, 1};
    int dy[4] = {-1, 1, 0, 0};
public:
    int maxAreaOfIsland(vector<vector<int>>& grid) {
        n = grid.size(), m = grid[0].size();
        use.assign(n, vector<bool>(m, false));
        int ret = 0;                             // 原为成员变量，见【易错 ⑥】

        for (int i = 0; i < n; i++) {
            for (int j = 0; j < m; j++) {
                if (grid[i][j] == 1 && use[i][j] == false) {
                    use[i][j] = true;            // 调用者负责标记起点
                    ret = max(ret, dfs(grid, i, j));
                }
            }
        }
        return ret;
    }

    int dfs(vector<vector<int>>& grid, int i, int j) {
        int flag = 0;                            // 收四个方向报上来的格数
        for (int a = 0; a < 4; a++) {
            int x = i + dx[a], y = j + dy[a];
            if (x >= 0 && x < n && y >= 0 && y < m
                && grid[x][y] == 1 && use[x][y] == false) {
                use[x][y] = true;
                flag += dfs(grid, x, y);         // 累加，不能 return
            }
        }
        return flag + 1;                         // return 在循环外，+1 是自己
    }
};
