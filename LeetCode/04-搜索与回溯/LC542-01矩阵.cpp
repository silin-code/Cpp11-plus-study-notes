// ============================================================
// LeetCode 542. 01 矩阵
// 考点：多源 BFS（起点是【所有 0】）+ 每格记录「被第几层覆盖」即距离
// 复杂度：时间 O(n*m)，空间 O(n*m)
// 日期：2026-09-22
// ============================================================
//
// 【题意】
// 给定 01 矩阵 mat，返回等大矩阵，其中 ret[i][j] = mat[i][j] 到【最近的 0】
// 的距离（上下左右走，每步 1）。题面保证至少有一个 0。
//
// ============================================================
// 【核心一：起点是所有的 0，不是 1】
// ============================================================
// 直觉容易从"每个 1 去找最近的 0"出发 —— 那就是对每个 1 各跑一次 BFS，
// 复杂度 O((nm)^2)，太慢。
//
// 反过来：把【所有 0】一次性入队当多源起点，往外扩。
// 第一次被扩到的格子，就是"离某个 0 最近"的距离 —— BFS 的层序天然保证最短。
//
// 这跟 LC 994 是同一个多源 BFS 骨架，区别只是：
//   LC 994：问【最后一层在第几分钟】（还要判断有没有烂不到的 → -1）
//   LC 542：问【每个格子在第几层被覆盖】（每格各记一个数）
//
// ============================================================
// 【核心二：层号 = 距离（本题不用 -1 修正）】
// ============================================================
// LC 994 里"第 0 层不算时间"，要小心 ±1；本题反而简单：
//   0 自己就是距离 0（ret 初始化为 0，不入队时改），
//   第 1 层扩到的格子距离 = 1，第 2 层 = 2 …
//   → count 从 0 起、每进入新一层就 ++，出队时把 count 记到该格即可。
//
// 关键区别：**本题的"源"本身答案是 0，所以层级和距离严格对齐**；
// LC 994 的"源"（初始烂橘子）答案是"第 0 分钟"，所以要在时间上把它排除。
//
// ============================================================
// 【核心三：visited 必标，且无需 -1 兜底】
// ============================================================
// ① 入队即标记 vist[x][y]=true，否则同一格会被多个邻居重复入队（指数级膨胀）。
// ② 本题所有格子都可通行（0 / 1 都能走），没有任何障碍，
//    所以【每个 1 必定能到达某个 0】→ 不存在"到不了"的格子，无需 -1 分支。
//    （这点和 LC 994 不同：994 有 0 当墙，会把新鲜橘子隔断，所以要判 -1。）
//
// ============================================================
// 【易错点】
// ============================================================
//   ① 起点选错：从 1 出发逐个找 0 → 复杂度爆掉。要从所有 0 出发。
//   ② 漏 visited：重复入队 → 结果可能对但会超时/膨胀。
//   ③ 误抄 LC 994 的 ±1 修正：本题 count 直接就是距离，不减。
//
// 【408 标注】BFS 求【无权图的最短路径】是 408 图论核心考点。
//   本题 = 网格上的"多源最短路"，与 LC 994 同源，只是把"最长时间"换成"每点距离"。
// ============================================================

class Solution {
int dx[4]={0,0,-1,1};
int dy[4]={-1,1,0,0};
public:
vector<vector<int>> updateMatrix(vector<vector<int>>& mat) {
int n=mat.size(),m=mat[0].size();
vector<vector<int>> ret(n,vector<int>(m,0));
vector<vector<bool>> vist(n,vector<bool>(m,false));
queue<pair<int,int>> q;
for(int i=0;i<n;i++)
{
for(int j=0;j<m;j++)
{
if(mat[i][j]==0)
{
vist[i][j]=true;
q.push(make_pair(i,j));
}
}
}
int count=0;
while(q.size())
{
int size=q.size();
count++;
while(size--)
{
int i=q.front().first;
int j=q.front().second;
q.pop();
for(int a=0;a<4;a++){
int x=i+dx[a],y=j+dy[a];
if(x>=0&&x<n&&y>=0&&y<m&&vist[x][y]==false)
{
ret[x][y]=count;
vist[x][y]=true;
q.push(make_pair(x,y));
}
}
}
}
return ret;
}
};
