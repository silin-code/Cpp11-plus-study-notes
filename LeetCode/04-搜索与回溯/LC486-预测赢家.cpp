// ============================================================
// LeetCode 486. 预测赢家
// 考点：记忆化搜索（状态 = **区间 [l, r]**）+ 博弈（**分差法**）
// 复杂度：时间 O(n^2)（状态数 = 区间个数），空间 O(n^2)
// 日期：2026-09-28（七轮打磨；入库时把哨兵从 -0x3f3f3f 改为 INT_MIN）
//       2026-10-01 间隔重做：又暴露「缺出口 + 转移用加号」；
//                并发现 -0x3f3f3f 当**起手值**时会算错（不只是丢缓存）
// ============================================================
//
// 【题意】
// 数组 nums，两人轮流从**任意一端**取走一个数，两人都走最优，玩家 1 先手。
// 玩家 1 最终总分 >= 玩家 2（**平局也算玩家 1 赢**）→ 返回 true。
//
// ============================================================
// 【核心一：状态是【区间】，不是坐标】
// ============================================================
//     f(l, r) = 当前要动手的人，在区间 [l, r] 上能取得的【最大分差】
//
// 每走一步之后，"还剩下什么"永远是**一段连续区间** —— 所以状态就是左右两个端点。
// 这是本题与前几道（坐标 / 坐标+维度）的**状态形态差异**。
//
// ============================================================
// 【核心二：定义"分差"，不要定义"总分"（本题的灵魂）】
// ============================================================
//   不要定义 "当前玩家拿了多少分"，要定义 "**当前玩家领先对手多少分**"。
//
//   为什么？—— 因为只有"分差"能让**对手的最优解直接减过来**：
//       我取走 x 之后，剩下那段轮到对手，
//       他在那段上的分差是 f(...)  →  我的净分差 =  x − f(...)
//
//   如果记"总分"，你就得同时追踪两个人的分数（状态爆炸）；
//   记"分差"，对手的收益取个负号就变成你的损失，一个函数就够。
//
// ============================================================
// 【核心三：不需要"轮到谁"这个参数】
// ============================================================
//   f(l, r) 的定义是"**当前要动手的那个人**"的分差。
//   递归下去时，**对手就成了"当前要动手的人"** —— 同一个函数换个人用而已。
//
//        f(0, n-1) 算的是【玩家 1】的分差
//        f(1, n-1) 算的是【玩家 2】的分差（因为那一层轮到玩家 2 动手）
//        而函数体**一模一样**。
//
//   所以 `dfs(nums, l, r, 轮到谁)` 里的那个参数是多余的
//   （真要判，它也能由区间长度推出来 —— **凡是能推出来的，都不该当参数**）。
//
// ============================================================
// 【核心四：转移只有【两个】选择 —— 这题没有 for 循环】
// ============================================================
//   前几道记忆化题的递归都在 `for (四个方向)` 里；本题**没有遍历**，
//   只有两个固定选择，直接写两行、取 max：
//
//       取左端 → 剩余 [l+1, r]      净分差 = nums[l] − f(l+1, r)
//       取右端 → 剩余 [l, r-1]      净分差 = nums[r] − f(l, r-1)
//       两条路都算，谁大听谁的
//
//   （l < r 时 l+1 ≤ r、l ≤ r-1 都成立，不会递归出非法区间，无需额外判断。）
//
// ============================================================
// 【易错点 / 七轮踩坑记录（信息密度极高，值得反复看）】
// ============================================================
//   ① 【状态里塞了多余的参数】最初写成 `dfs(nums, l, r, gap, flag)`：
//      · `flag`（轮到谁）多余 —— 见核心三
//      · `gap`（累积分差）多余，**而且有害** —— 分差应由**返回值**算出，
//        当参数传会让状态变成 `(l, r, gap)`，gap 的取值范围是整条分数轴
//        → 状态爆炸 → **记忆化直接失效**
//      **判据：一个量该进状态，问它是"被问出来的【答案】"还是"必须交代的【前提】"。**
//      gap 是答案的一部分 → 让它当**返回值**。
//
//   ② 【写不出递推】因为**在等一个不存在的循环** —— 见核心四。
//
//   ③ 【起手值与累积函数不配对】`int flag = 0; flag = max(flag, ...)`
//      → **偷偷加了"结果 ≥ 0"的前提**，而分差可以是负的。
//      实测 `[1,5,2]` 返回 true（应 false）；随机 8000 组错 **854** 组。
//      **对 max 来说，"中性"值是 −∞（INT_MIN），不是 0。**
//      （同类错误见 LC 410 的 `lo = INT_MAX` 配 `max()` —— 这是同一个类的第二次。）
//      更干净的做法：**选项数量固定时根本不用累加器**，直接 `max(两项)`。
//
//   ④ 【`memset` 按字节填充】`memset(memo, INT_MIN, sizeof(memo))`
//      → INT_MIN = 0x80000000，memset 只取**最低字节 0x00** → 实测填出 `0 0 0 0`
//      → "没算过"的判断恒成立 → 一律返回 0 → 恒 true。
//      又试 `memset(memo, -0x3f3f3f, ...)` → 32 位数被砍成最低字节 0xC1
//      → 填成 0xC1C1C1C1，与比较值对不上。
//      **规则：`memset` 只对"每个字节都一样"的值安全**：`0x00`(=0)、`0xFF`(=-1)、`0x3F`。
//
//   ⑤ 【类内成员不能用 () 给初值】`vector<vector<int>> memo(21, ...);` 写在类内
//      → **编译不过**：`error: expected identifier before numeric constant`
//      （C++ 把它当**函数声明**解析）。类内只能用 `=` 或 `{}`。
//      **本解采用最稳的第三种：成员只声明，在入口函数里 `assign`。**
//
//   ⑥ 【成员容器没在入口复位】`memo` 的初始化若只在构造时发生，
//      同一个对象**连调两次**就会读到上一轮的残留值。
//      实测：第 2 次分差算成 9（应 222）；随机连调 2000 次，**算错 1237 次（62%）**。
//      → **入口第一件事就是 `assign()` 复位。**
//
//   ⑦ 【哨兵的取值】——**这一条有两层，第二层会算错**
//
//      原稿用 `-0x3f3f3f`（= -4144959）当哨兵。但 `|分差| ≤ 20 × 10⁷ = 2×10⁸`，
//      这个值**落在合法分差的范围内**。实测 `nums = [0, 4144959, 0]` 的真实分差
//      就是 **-4144959**，正好撞上。
//
//      **第一层（memo 层）：只丢缓存，不算错。**
//        撞上之后 `memo[l][r] != -0x3f3f3f` 判为"没算过" → 重算一遍。
//        但重算的结果还是同一个值，所以答案不受影响。
//        （违反的判据是："哨兵必须取一个**不可能是合法答案**的值"。）
//
//      **第二层（起手值层）：会算错！**  ← 2026-10-01 间隔重做时才发现
//        `int flag = -0x3f3f3f;  flag = max(flag, 候选1);  flag = max(flag, 候选2);`
//        当**两个候选都小于 -4144959** 时，`max()` 会卡在起手值上：
//            max(-4144959, -5000000) = -4144959   ← 错，应取 -5000000
//        **对 max 来说，"中性值"是 −∞，不是任何一个"看起来很小"的常数。**
//
//        实测（10-01）：
//          · 枚举 n=3..6、值取 {0, 4144959, 5000000, 9999999} 共 5440 个数组
//            → 用 -0x3f3f3f 起手：错 **92** 个；用「第一个候选起手」：错 **0** 个
//          · 随机大数值对拍 20000 组 → 错 **761** 组（**3.8%**）
//          · 第一个出错用例 `[4144959, 0, 5000000, 0, 0]`：正确 false，错解 **true**
//          · **`nums[i] < 1000` 时错 0 组** —— 所以官方示例（1,5,2 / 1,5,233,7）
//            和"小数值随机测试"**都发现不了它**
//
//      → 已把哨兵改为 `INT_MIN`（它在本题永远不可能是答案，彻底安全）；
//        并且**起手值不再借哨兵**，直接用第一个候选：
//            int flag = nums[left] - dfs(nums, left + 1, right);
//            flag = max(flag, nums[right] - dfs(nums, left, right - 1));
//        （这也是本题踩坑 ③「起手值与累积函数不配对」的第三次出现。）
//
// 【408 标注】记忆化搜索 = 自顶向下 DP；本题的"区间状态"也是区间 DP 的入门形态
//   （同一个递推改成按区间长度从小到大迭代，就是自底向上的区间 DP）。
// ============================================================

class Solution {
vector<vector<int>> memo;   // 只声明，不在类内给初值（类内不能用 () 初始化）
public:
bool predictTheWinner(vector<int>& nums) {
// 入口第一件事：复位整张表。
//   成员容器不能只靠"构造时初始化" —— 同一个对象被连续调用时会读到上一轮的残留值。
// 哨兵选 INT_MIN：本题 |分差| 最大只有 2×10^8，INT_MIN 永远不可能是真实答案。
memo.assign(21, vector<int>(21, INT_MIN));
return dfs(nums, 0, nums.size() - 1) >= 0;   // 平局也算玩家 1 赢 → 用 >= 0
}
int dfs(vector<int>& nums, int left, int right) {
// ② 查表：这个区间算过就直接返回
if (memo[left][right] != INT_MIN) {
return memo[left][right];
}
// ① 出口：区间只剩一个数，当前玩家只能拿走它，分差就是它本身
if (left == right) {
return nums[left];
}
// ③ 展开：**只有两个选择，没有循环**
int takeL = nums[left]  - dfs(nums, left + 1, right);   // 取左端 → 剩余 [left+1, right]
int takeR = nums[right] - dfs(nums, left, right - 1);   // 取右端 → 剩余 [left, right-1]
// ④ 存表 + 返回：两条路都能走，挑对我更有利的
return memo[left][right] = max(takeL, takeR);
}
};
