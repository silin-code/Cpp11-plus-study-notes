// ============================================================
// LeetCode 2328. 网格图中递增路径的数目
// 考点：记忆化搜索（LC 329 的【同型迁移】：求"条数"而非"最长"）
// 复杂度：时间 O(m*n)，空间 O(m*n)
// 日期：2026-09-27
// ============================================================
//
// 【题意】
// 统计网格中【严格递增】路径的总条数（每条路径至少含一格，起点终点任意）。
// 答案对 1e9+7 取模。
//
// ============================================================
// 【与 LC 329 的关系：状态同型，转移从 max 变成累加】
// ============================================================
//    LC 329 ：f(i,j) = 从 (i,j) 出发的【最长】递增路径长度
//    本题   ：f(i,j) = 从 (i,j) 出发的【递增路径条数】
//
//    转移：两者都只看"值更大的邻居"，
//          329 取 max，本题【累加】。
//
//    f(i,j) = 1 + Σ f(邻居)      对每个满足 grid[邻居] > grid[i][j] 的邻居
//             ↑
//        这个 1 是【"只有 (i,j) 自己"这一条路径】—— 每条路径都可以选择
//        "到此为止"，它本身就是一条合法路径。漏了这个 1，答案会少算。
//
// ============================================================
// 【易错点（本题实际踩到的两个）】
// ============================================================
//   ① 条件写成 `<=`（应为 `<`）
//      "严格"二字不能松：等值不能走。
//      ⚠️【更要紧的后果】宽松成 `<=` 会**破坏"无环"这个前提**：
//         两个相邻的等值格子会【互相指向】→ 出现环 → 记忆化彻底失效
//         （因为 memo 是在递归返回【之后】才写回的，有环就永远回不来）。
//      → **"严格递增"不只是题目要求，它还是"这题可以记忆化"的前提。**
//
//   ② 递归调用了【自己】而不是邻居：`dfs(grid,i,j)` 应为 `dfs(grid,x,y)`
//      后果：自调用 → 无限递归 → **栈溢出**
//      实测（原稿）：跑 `[[1,2]]` 直接崩，退出码 0xC00000FD = STACK_OVERFLOW。
//      【教训】写递归时，括号里的参数一定和"当前处理的格子"分开看：
//      这一层的参数是 (i,j)，递归下去要换成【邻居】的 (x,y)。
//
// ============================================================
// 【其他要点】
// ============================================================
//   · 累加要**随时取模**（`flag %= MOD`），否则中间值会溢出
//   · 返回值类型 int 够用（`flag` 恒 < MOD < INT_MAX）：
//     `long long flag` 算中间值 → 写回 `int` 的 memo → `return`，
//     这个"用 long long 算、用 int 存"的搭配是安全的
//   · 起手 `flag = 1`（兜底：走不动了，自己也算一条路径）
//
// 【另一种解法】按值【从大到小】排序后直接 DP（自底向上），O(m*n log(m*n))。
//   因为处理到某格时，所有比它大的格子都已算完 → 可直接查表。
//   本仓库用它当独立对拍基准（机制与记忆化 DFS 完全不同，互证才可信）。
//
// 【408 标注】记忆化搜索 = 自顶向下 DP，与 408 的 DP 思想同源。
// ============================================================

class Solution {
int dx[4]={0,0,-1,1};
int dy[4]={-1,1,0,0};
int n,m;
vector<vector<int>> memo;   // 记录从 (i,j) 出发的递增路径条数
const int MOD=1e9+7;
public:
int countPaths(vector<vector<int>>& grid) {
long long ret=0;
n=grid.size();m=grid[0].size();
memo.assign(n,vector<int>(m,-1));
for(int i=0;i<n;i++)
{
for(int j=0;j<m;j++)
{
ret+=dfs(grid,i,j);
ret%=MOD;
}
}
return ret;
}
int dfs(vector<vector<int>>& grid,int i,int j)
{
if(memo[i][j]!=-1)
{
return memo[i][j];
}
long long flag=1;                // 兜底：只有自己这一格，也算 1 条路径
for(int a=0;a<4;a++)
{
int x=i+dx[a],y=j+dy[a];
if(x>=0&&x<n&&y>=0&&y<m&&grid[i][j]<grid[x][y])   // 严格递增（等值不能走）
{
flag+=dfs(grid,x,y);          // 递归的是【邻居】(x,y)，不是自己
flag%=MOD;
}
}
memo[i][j]=flag;
return flag;
}
};
