// ============================================================
// LeetCode 130. 被围绕的区域
// 考点：网格 DFS 的「反向思考」—— 从边界出发，而不是从内部逐个判断
// 复杂度：时间 O(n*m)，空间 O(n*m)
// 日期：2026-09-20
// ============================================================
//
// 【题意】
// m×n 的 board，元素 'X' / 'O'。把所有【被 'X' 完全包围】的 'O' 翻成 'X'。
// 边界上的 'O' 永远不会被包围（它总能"透出去"）。原地修改，返回 void。
//
// 【核心：别顺着想，反过来想】
// 正面做法（难）：对每个 'O' 单独判断"能不能走到边界" —— 每个都搜一遍，容易写乱。
//
// 反向做法（简单得多），利用这个等价关系：
//      「被包围」 ⟺ 「从它出发走不到边界的任何一个 'O'」
// 于是先找出「能走到边界的」—— 从【边界上的 'O'】出发往里渗，
// 凡是能渗到的都标记为"安全"；剩下的没被标记的 'O' 就是被包围的。
//
// 【三段结构】
//   ① 扫四条边界，遇到 'O' 就从它出发 DFS，把连通的 'O' 全部标记为安全
//   ② 再全图扫一遍：仍是 'O' 且未被标记 → 改成 'X'
//
// 【要不要撤销？—— 不需要】
// 同 LC 200 / 695：一个格子属不属于"安全区"是固定事实，走过一次就永久标记，
// 以后再也不用碰。判据：结论只依赖"格子本身" → 永久标记；
// 结论依赖"到达路径" → 才需要撤销（如 LC 79）。
//
// ============================================================
// 【易错 —— 本次踩的三处，全是"行列混用"】
// ============================================================
// 1. **字符大小写**：题目是 'O' / 'X'（大写）。若写成 'o' / 'x'，
//    所有 if 恒为 false —— 【整个算法什么都不做，原样返回】。
//    ⚠️ 这种错有时会"假通过"：若测试用例里所有 'O' 恰好都在边界、
//    本来就该保留，那么"什么都不做"恰好等于"全部保留"。
//    用例 3×5（边界 O 在第 3 列）时：
//      b[0][3]=='O' 但上边界循环写成 j<n(=3) → 只扫到列 0..2，漏掉它
//      → 与它连通的 (1,3) 没被标记 → 被误改成 'X'
//    另外 n > m 时 j<n 会【越界】访问（5 行 3 列时访问 board[0][4]），
//    vector 不检查边界，读到垃圾。
// 2. **上下边界循环用 j < n**：遍历【列】就该用列数 m，不是行数 n。
// 3. **dfs 里 y < n**：x 管行（用 n），y 管列（用 m），两个不能都用 n。
//
// 【自检习惯】写网格题时，看到 n / m 就问一句：
//   "这个位置管的是【行】还是【列】？"
//
// 【408 标注】408 也考图的 DFS/BFS，但要求在邻接矩阵 / 邻接表上手写并分析复杂度；
// "从边界反向渗"这个思维技巧 408 不直接考。
// ============================================================

class Solution {
    int n, m;
    vector<vector<bool>> use;
    int dx[4] = {0, 0, -1, 1};
    int dy[4] = {-1, 1, 0, 0};
public:
    void solve(vector<vector<char>>& board) {
        n = board.size(), m = board[0].size();
        use.assign(n, vector<bool>(m, false));

        // ① 左右两条边
        for (int i = 0; i < n; i++) {
            if (board[i][0] == 'O' && use[i][0] == false) {
                use[i][0] = true;  dfs(board, i, 0);
            }
            if (board[i][m - 1] == 'O' && use[i][m - 1] == false) {
                use[i][m - 1] = true;  dfs(board, i, m - 1);
            }
        }
        // ① 上下两条边（遍历列 → 用 m）
        for (int j = 0; j < m; j++) {
            if (board[0][j] == 'O' && use[0][j] == false) {
                use[0][j] = true;  dfs(board, 0, j);
            }
            if (board[n - 1][j] == 'O' && use[n - 1][j] == false) {
                use[n - 1][j] = true;  dfs(board, n - 1, j);
            }
        }
        // ② 剩下的 'O' 就是被包围的
        for (int i = 1; i < n; i++) {
            for (int j = 1; j < m; j++) {
                if (board[i][j] == 'O' && use[i][j] == false) {
                    board[i][j] = 'X';
                    use[i][j] = true;
                    dfs2(board, i, j);
                }
            }
        }
    }

    void dfs(vector<vector<char>>& board, int i, int j) {
        for (int a = 0; a < 4; a++) {
            int x = i + dx[a], y = j + dy[a];
            if (x >= 0 && x < n && y >= 0 && y < m          // x 用 n，y 用 m
                && board[x][y] == 'O' && use[x][y] == false) {
                use[x][y] = true;
                dfs(board, x, y);                          // 无撤销：永久标记
            }
        }
    }

    void dfs2(vector<vector<char>>& board, int i, int j) {
        for (int a = 0; a < 4; a++) {
            int x = i + dx[a], y = j + dy[a];
            if (x >= 0 && x < n && y >= 0 && y < m
                && board[x][y] == 'O' && use[x][y] == false) {
                use[x][y] = true;
                board[x][y] = 'X';
                dfs2(board, x, y);
            }
        }
    }
};
