// ============================================================
// LeetCode 733. 图像渲染
// 考点：网格 BFS / Flood Fill（把起点所在的四连通同色块整体染色）
// 复杂度：时间 O(n*m)，空间 O(n*m)
// 日期：2026-09-24
// ============================================================
//
// 【题意】
// 给定图像 image（每个数是一个颜色）、起点 (sr, sc)、新颜色 color。
// 把起点所在的【同色四连通区域】全部改成 color，返回修改后的图像。
//
// ============================================================
// 【核心一：开头那行 if 是【防死循环的刚需】，不是可省的优化】
// ============================================================
//     if (image[sr][sc] == color) return image;
//
// 本题用「把格子改成新颜色」来兼任 visited 标记：
//     进入某格 → 立刻改色 → 之后判断 image[i][j] == 旧颜色 就等价于"没访问过"。
//
// 但如果 **新颜色 == 旧颜色**，改完颜色还是旧颜色，标记【失效】：
//     同一格会被反复判定为"未访问" → 反复入队 → 死循环 / 内存爆掉。
// 所以那一行早退是【必须】的。（对照：若另开一个 visited 数组，就不需要它。）
//
// ============================================================
// 【核心二：调色兼标记，一个数组顶两个】
// ============================================================
// 用 `ret[i][j] == srccolor` 同时表达两件事：
//     ① 还在原来的连通块里（颜色对得上）
//     ② 还没被访问过（访问过的话颜色已经变了）
// 所以不需要单独开 visited —— 这是本题比 LC 200/695 更省的地方。
//
// 【注意】：这个技巧有个前提 —— `srccolor` 必须在开跑前就存下来（本解存进 srccolor），
//           否则第一格被改色后，后面就没法判断"原来的颜色"是什么了。
//
// ============================================================
// 【易错点 / 可精简处】
// ============================================================
//   ① 漏了开头的同色早退 → 新色==旧色时死循环（本题唯一的坑）。
//   ② 层切分 `while(q.size()){ int size=q.size(); while(size--){...} }`
//      **在这里是多余的** —— 本题只染色，不记"第几层/多少分钟"，
//      写成 `while (!q.empty()) { ... }` 完全等价。
//      这是从 LC 994 / 542 带过来的习惯（那两题的层是必需的，本题不是）。
//
// 【408 标注】Flood Fill 就是【图的遍历】——把网格看成图，四连通就是边。
//   本题 = "染色一个连通分量"，与 408「图的连通性 / 连通分量」同源，
//   DFS 或 BFS 都能做（408 两种实现都考过）。
// ============================================================

class Solution {
int dx[4]={0,0,-1,1};
int dy[4]={-1,1,0,0};
public:
vector<vector<int>> floodFill(vector<vector<int>>& image, int sr, int sc, int color) {
if(image[sr][sc]==color) return image;
int n=image.size(),m=image[0].size();
vector<vector<int>> ret=image;
int srccolor=ret[sr][sc];
queue<pair<int,int>> q;
q.push(make_pair(sr,sc));
ret[sr][sc]=color;
while(q.size())
{
int size=q.size();
while(size--)
{
int x=q.front().first;
int y=q.front().second;
q.pop();
for(int a=0;a<4;a++)
{
int i=x+dx[a],j=y+dy[a];
if(i>=0&&i<n&&j>=0&&j<m&&ret[i][j]==srccolor)
{
ret[i][j]=color;
q.push(make_pair(i,j));
}
}
}
}
return ret;
}
};
