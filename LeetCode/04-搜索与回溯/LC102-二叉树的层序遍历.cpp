// ============================================================
// LeetCode 102. 二叉树的层序遍历
// 考点：二叉树 BFS（按层切分，输出二维数组）
// 复杂度：时间 O(n)，空间 O(n)
// 日期：2026-09-24（11'38"，含排查 bug 的时间）
// ============================================================
//
// 【题意】
// 按层返回节点值：第 k 个子数组 = 第 k 层的所有节点（从左到右）。
//
// ============================================================
// 【核心：和网格 BFS 是【同一副骨架】，只换了"邻居"的定义】
// ============================================================
// LC 994 / 542（网格）：邻居 = 上下左右 4 个方向
// LC 102（本题、树）  ：邻居 = left / right 两个孩子
//
//     while (队列非空) {
//         int size = 队列当前长度;        // 先锁住"本层有几个"
//         while (size--) { 处理本层一个节点; 把它的孩子入队 }   // 孩子留到下一层
//         本层结果收尾
//     }
//
// 关键就在 `int size = q.size()` 这一行：**先把本层长度记下来**，
// 内层新入队的（下一层）在这一轮不会被碰到。
//
// ============================================================
// 【层切分在这里【必需】——与 LC 733 正好相反】
// ============================================================
//    LC 733 图像渲染：只染色，不记层   → 层切分多余，`while(!q.empty())` 即可
//    LC 102（本题）  ：输出本身就按层组织 → 层切分必需
//
// 判据：**层切分只在"层本身有含义"时才需要**（时间 / 距离 / 按层输出）。
//
// ============================================================
// 【易错点（本题实际踩到的两个）】
// ============================================================
//   ① `q.push(root)` **没判空** → 空树（root = nullptr）时队里是 nullptr，
//      下一行 `cur->left` 空指针解引用 → 段错误。
//      实测：空树用例 exit code = 0xC0000005（ACCESS_VIOLATION）。
//      → 入口处 `if (root == nullptr) return ret;`
//
//   ② **预开一大块、返回前忘了截断** → 层级内容全对，但多出大量空行。
//      实测：`ret.size() = 2000`，实际只需 3 行 → 力扣按精确输出比对，直接 WA。
//      → 返回前 `ret.resize(level);`
//
//   ③ `ret.resize(2001)` 里的 2001 是**魔数**（只是恰好 ≥ 最大深度：
//      LC 约束节点数 ≤ 2000，最深一条链 2000 层）。约束一变就出问题。
//
// 【更稳的写法（值得记）】不要"先开一大块再截断"，而是**边遍历边长出层**：
//   每层内层循环结束后，把这一层的结果整体 push_back 进 ret。
//   这样长度天然精确，连 resize 都不需要。
//
// 【408 标注】层序遍历是 408 树章节的基础考点，常接着考
//   「求树高 / 求第 k 层节点数 / 求某层最右节点」——都是这个框架的变体。
// ============================================================

class Solution {
public:
vector<vector<int>> levelOrder(TreeNode* root) {
vector<vector<int>> ret;
if(root==nullptr) return ret;
ret.resize(2001);
int level=0;
queue<TreeNode*> q;
q.push(root);
while(q.size())
{
int size=q.size();
while(size--)
{
TreeNode* cur=q.front();
q.pop();
if(cur->left!=nullptr) q.push(cur->left);
if(cur->right!=nullptr) q.push(cur->right);
ret[level].push_back(cur->val);
}
level++;
}
ret.resize(level);
return ret;
}
};
