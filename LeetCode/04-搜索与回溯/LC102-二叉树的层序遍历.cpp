// ============================================================
// LeetCode 102. 二叉树的层序遍历
// 考点：二叉树 BFS（按层切分，输出二维数组）
// 复杂度：时间 O(n)，空间 O(n)
// 日期：2026-09-24（三版打磨，最终版见下）
// ============================================================
//
// 【题意】
// 按层返回节点值：第 k 个子数组 = 第 k 层的所有节点（从左到右）。
//
// ============================================================
// 【核心一：和网格 BFS 是【同一副骨架】，只换了"邻居"的定义】
// ============================================================
// LC 994 / 542（网格）：邻居 = 上下左右 4 个方向
// LC 102（本题、树）  ：邻居 = left / right 两个孩子
//
//     while (队列非空) {
//         int size = 队列当前长度;        // 先锁住"本层有几个"
//         while (size--) { 处理本层一个节点; 把它的孩子入队 }   // 孩子留到下一层
//     }
//
// 关键就是 `int size = q.size()` 这一行：**先把本层长度记下来**，
// 内层新入队的（下一层）在这一轮不会被碰到。
//
// ============================================================
// 【核心二：层切分在这里【必需】——与 LC 733 正好相反】
// ============================================================
//    LC 733 图像渲染：只染色，不记层   → 层切分多余，`while(!q.empty())` 即可
//    LC 102（本题）  ：输出本身就按层组织 → 层切分必需
//
// 判据：**层切分只在"层本身有含义"时才需要**（时间 / 距离 / 按层输出）。
//
// ============================================================
// 【核心三：返回【二维数组】时，不要"预开一大块再截断"】
// ============================================================
// 每层开始时先长出一行，再往这一行里填：
//     ret.push_back(vector<int>());     // 本层开一个空行
//     ... ret[level].push_back(cur->val);
// 长度天然精确，不需要任何 resize，也没有魔数。
//
// 等价更短的写法：把 `ret[level]` 换成 `ret.back()`，连 level 变量都省了
// （此时 `level` 恒等于 `ret.size()-1`，是个冗余变量）。
// 两种写法都验过，结果完全一致。
//
// ============================================================
// 【演进记录（三版，两个 bug 一个坏味道）】
// ============================================================
//    v1：`q.push(root)` 没判空 + `ret.resize(2000)` 预开未截断
//        → 空树段错误（实测 exit code 0xC0000005），且非空树也多输出 1995 行空行
//    v2：补了判空与末尾 `resize(level)`，但 `resize(2001)` 仍是魔数（恰好 ≥ 最大深度 2000）
//    v3（本文件）：改成"每层 push_back 长一行"，魔数与截断都消失
//
// 【易错点】
//   ① 空输入不判空 → 空指针解引用。**入口第一件事就是判空**
//      （树判 `root`、链表判 `head`、网格先判外层非空）。力扣一定会测空输入。
//   ② 预开容器尺寸要"返回前截断"，漏了就 WA（多一行都算错）。
//
// 【408 标注】层序遍历是 408 树章节的基础考点，常接着考
//   「求树高 / 求第 k 层节点数 / 求某层最右节点」——都是这个框架的变体。
// ============================================================

class Solution {
public:
vector<vector<int>> levelOrder(TreeNode* root) {
vector<vector<int>> ret;
if(root==nullptr) return ret;
int level=0;
queue<TreeNode*> q;
q.push(root);
while(q.size())
{
ret.push_back(vector<int>());
int size=q.size();
while(size--)
{
TreeNode* cur=q.front();
q.pop();
if(cur->left!=nullptr) q.push(cur->left);
if(cur->right!=nullptr) q.push(cur->right);
ret[level].push_back(cur->val);
}
level++;
}
return ret;
}
};
