// ============================================================
// LeetCode 329. 矩阵中的最长递增路径
// 考点：记忆化搜索（DFS + 记录已算过的状态）—— 本质是【自顶向下 DP】
// 复杂度：时间 O(m*n)（每个格子只算一次），空间 O(m*n)
// 日期：2026-09-26（12'49"，一遍过）
// ============================================================
//
// 【题意】
// 找最长的【严格递增】路径长度。每步只能上下左右走，不能斜走、不能出界。
//     [[9,9,4],
//      [6,6,8],
//      [2,1,1]]        答案 4  （1 → 2 → 6 → 9）
//
// ============================================================
// 【核心一：为什么要记忆化 —— 同一格被反复算】
// ============================================================
// 暴力思路：从每个格子出发 DFS，能走多深走多深，取最大。
// 问题：同一个格子会被**不同的起点/不同的来路**反复算到。
//
//     1 → 2 → 3
//             ↑
//     4 → 5 → 6
//
// "从 3 往下还能走多长"这件事，从 6、从 5、从 2 出发时都要各算一遍。
// 格子一多（m,n ≤ 200 → 4 万个），重复量爆炸。
//
// 解药：算过一次就存进表 `memo[i][j]`，之后**直接读表**。
// 骨架一行不改，只多"先查表、算完存表"两个动作。
//
// ============================================================
// 【核心二：能不能记忆化？判据 =「同一状态，答案是否唯一」】
// ============================================================
//    LC 79 单词搜索：memo[i][j] 的答案**还取决于已经走过哪些格子**（visit 集合）
//                    → 状态描述不完整、不唯一 → 【不能】记忆化
//    LC 329（本题） ：f(i,j) 只取决于 (i,j) 自己，与"怎么走到这儿的"无关
//                    → 状态唯一 → 【可以】记忆化
//
// **这条判据会反复出现，务必背下来。**
//
// ============================================================
// 【核心三：状态定义与转移】
// ============================================================
//    f(i,j) = 以 (i,j) 为【起点】能走出的最长递增路径长度
//
//    f(i,j) = 1 + max{ f(邻居) }    对每个满足 matrix[邻居] > matrix[i][j] 的邻居
//    f(i,j) = 1                     没有这样的邻居（走到头了）
//
// 【正推的推法】先枚举从 (i,j) 出发的所有合法路径 —— 第一步只有四种可能
//   （上下左右，且必须值更大）。第一步之后剩下的部分，**恰好就是"从那个邻居
//   出发的最长长度"**。所以来路只有四条，取最大 + 1，加一条兜底（无路可走 → 1）。
//
// ============================================================
// 【核心四：本题【不需要】visit 数组 —— 为什么？】
// ============================================================
//   "只能往【值更大】的格子走"这个约束天然保证不会绕圈
//   （不可能 A > B 又 B > A）→ 图是【有向无环图(DAG)】。
//   所以 DFS 一定终止，不需要任何一种"防回头"的机制。
//
//   这正是它与 LC 79 的根本区别：79 靠 visit 防回环，329 靠【值的大小关系】。
//
// ============================================================
// 【易错点】
// ============================================================
//   ① memo 的【哨兵值】要想清楚：必须取一个**不可能是合法答案**的值。
//      本题最短也是 1（至少包含自己），所以 -1 和 0 都安全。
//      本解用 -1（更明确地表示"没算过"）。
//   ② 成员容器复位用 **assign 不用 resize**（LC 200 的教训）：
//      `memo.assign(n, vector<int>(m,-1));` —— resize 在尺寸不变时不重置元素值。
//   ③ `matrix[0].size()` 前要保证 matrix 非空（本题约束 m,n ≥ 1）。
//
// ============================================================
// 【另一种解法（值得知道）：按值排序 + DP，O(m*n log(m*n))】
// ============================================================
//   把格子按值【从大到小】排序，依次处理：
//       f(cell) = 1 + max{ f(邻居) }   只看值更大的邻居
//   因为处理到 cell 时，所有比它大的格子都已经算完了 → 直接可查。
//   这是"把记忆化搜索【自顶向下】翻成【自底向上】"的等价写法，
//   也正好用来当本题的对拍基准（两套机制完全不同，互证才可信）。
//
// 【408 标注】记忆化搜索 = 自顶向下 DP。408 不直接考它，但"**子问题重叠 →
//   把算过的记下来，避免重复计算**"这条思路与 408 的 DP 思想是同一件事。
// ============================================================

class Solution {
int dx[4]={0,0,-1,1};
int dy[4]={-1,1,0,0};
int n,m;
vector<vector<int>> memo;
public:
int longestIncreasingPath(vector<vector<int>>& matrix) {
n=matrix.size(),m=matrix[0].size();
memo.assign(n,vector<int>(m,-1));
int ret=0;
for(int i=0;i<n;i++)
{
for(int j=0;j<m;j++)
{
ret=max(ret,dfs(matrix,i,j));
}
}
return ret;
}
int dfs(vector<vector<int>>& matrix,int i,int j)
{
if(memo[i][j]!=-1)
{
return memo[i][j];               // 算过就直接读表
}
int flag=1;                          // 兜底：走不动了，长度 1（含自己）
for(int a=0;a<4;a++)
{
int x=i+dx[a],y=j+dy[a];
if(x>=0&&x<n&&y>=0&&y<m&&matrix[x][y]>matrix[i][j])
{
flag=max(flag,dfs(matrix,x,y)+1);
}
}
memo[i][j]=flag;                     // 算完存表
return memo[i][j];
}
};
