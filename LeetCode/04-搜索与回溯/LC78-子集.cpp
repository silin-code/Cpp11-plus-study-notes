// ============================================================
// LeetCode 78. 子集
// 考点：子集枚举 —— **位掩码解法**（对照回溯解法）
// 复杂度：时间 O(n * 2^n)（2^n 个子集，每个最多取 n 个元素），空间 O(n * 2^n)（存结果）
// 日期：2026-09-30（位掩码解法；三轮打磨，见文末「这一道是怎么学会的」）
// ============================================================
//
// 【题意】
// 给一个【不含重复元素】的数组，返回它的所有子集（顺序不限）。
//
//     nums = [1,2,3]
//     -> {}, {1}, {2}, {1,2}, {3}, {1,3}, {2,3}, {1,2,3}     共 8 个
//
// ============================================================
// 【两种解法：回溯 vs 位掩码】
// ============================================================
//   回溯（dfs + 选/不选）：每个元素两个选择，走出一棵二叉树。
//       —— 更通用（去重、剪枝、限制条件都能加），复杂度一样。
//
//   位掩码（本文件）：**一个 mask ⟺ 一个子集**，直接枚举 0 ~ 2^n-1。
//       —— 只适合"没有额外约束"的纯枚举，但代码短、无递归。
//
//   | 解法 | 适合场景 |
//   |---|---|
//   | 回溯 | 有去重 / 有剪枝 / 有额外条件（如 LC 90、LC 46） |
//   | 位掩码 | 纯枚举所有子集；或者状态本身就是"选了什么集合"时（状压 DP） |
//
// ============================================================
// 【核心一：一个 mask ⟺ 一个子集】（本题的全部）
// ============================================================
//     mask 的第 i 位 = 1  表示【nums[i] 被选进了这个子集】
//
//         mask = 0b000  ->  {}               （一个都没选）
//         mask = 0b001  ->  { nums[0] }
//         mask = 0b101  ->  { nums[0], nums[2] }
//         mask = 0b111  ->  { nums[0], nums[1], nums[2] }
//
//     n 个元素 -> 一共 2^n 个 mask -> 正好是 2^n 个子集。
//
// ============================================================
// 【核心二：枚举所有 mask】
// ============================================================
//     for (int mask = 0; mask < (1 << n); mask++) { ... }
//
//     ★ mask【就是循环变量本身】—— 不要另外定义一个变量去"算"它。
//       （踩过这个坑，见易错点 ①。）
//
// ============================================================
// 【核心三：从一个 mask 里把元素取出来】
// ============================================================
//     for (int i = 0; i < n; i++)
//         if (mask & (1 << i)) result.push_back(nums[i]);
//
//     这个"逐位检查"的循环，和 printSet / canWinInOneMove 里那个是同款。
//
// ============================================================
// 【易错点（本题踩过的）】
// ============================================================
//   ① 【mask 不该被"累加"出来】最初写成：
//          int mask = 0;
//          for (int i = 0; i < pow(2,n); i++) { mask += i;  ... }
//      → 得到的不是 0..2^n-1，而是**三角数** T_i = i(i+1)/2 = 0,1,3,6,10,15,21,28,...
//
//      ⚠️ **但这份代码当时能 AC！** 实测：
//        · **T_i mod 2^n 恰好是 0..2^n-1 的一个排列**（n = 1..16 全部验证成立）
//        · 而 `mask & (1<<i)` 只看低 n 位，等价于取模
//        · 所以结果【集合】完全正确，只是顺序不同；而 LC 78 接受任意顺序
//
//      改成 `mask += 1`（mask 从 1 走到 2^n）**同样能 AC**——
//      因为 1,2,...,2^n-1,0 的低 n 位还是一个排列。
//
//      **这才是本题最值钱的一课：**
//          「**能过 ≠ 对**」。代码里"你不懂它为什么对、但结果对"的部分 = 定时炸弹。
//          只要循环起点/检查方式/范围一改，立刻全错，而且你根本不知道错在哪。
//          （同源案例：LC 207 建反图照样 AC —— 因为"判环"对方向不敏感。）
//
//      **正确写法**：mask 就是循环变量，删掉那个中间变量。
//
//   ② 【成员容器没在入口复位】`ret` 是成员变量，`subsets` 里没 `clear()`：
//          同一个对象第 1 次调用 [1,2,3] -> 8 个
//          同一个对象第 2 次调用 [9]     -> 10 个（上一次的还留着）
//      ⚠️ **LeetCode 每题新建一个 Solution 对象，所以在提交页面上看不到这个错**；
//         但【本地多测 / 面试白板 / 蓝桥杯一题多次调用】一定炸。
//      —— 这是**第四次**遇到（LC 46 / LC 200 / LC 486 / LC 78）。
//      **纪律：写成员容器当返回值或缓存时，入口第一件事就是复位。**
//
//   ③ 【`pow(2, n)` 取 2 的幂】它需要 <cmath>、返回 double。
//      实测 n ≤ 52 时与 `1 << n` 完全一致（double 精确到 2^53），**所以不会算错**，
//      但意图不清楚、且多一个头文件依赖。
//      本文件保留了原写法；**建议改成 `1 << n`**（纯整数、不需要额外 include）。
//
//   ④ 【空数组】n = 0 时 `1 << 0 = 1`，循环跑一次，得到 `{}` 一个子集 —— 正确。
//      （实测 n=0..15 全部与参考一致。）
//
// 【408 标注】子集枚举是"幂集"的实现；位掩码版本对应 408 里的"用位向量表示集合"
//   （位向量/位示图是 408 存储管理里的常见概念）。
// ============================================================

class Solution {
vector<vector<int>> ret;
int n;
public:
vector<vector<int>> subsets(vector<int>& nums) {
ret.clear();                                  // ★ 入口复位（成员容器），见易错点 ②
n = nums.size();

// mask 就是循环变量本身：0, 1, 2, ..., 2^n - 1，每个 mask 对应一个子集
for (int mask = 0; mask < pow(2, n); mask++)  // 建议写成 (1 << n)
{
check(mask, nums);
}
return ret;
}

// 把一个 mask 翻译成一个子集
void check(int mask, vector<int>& nums)
{
vector<int> cur;
for (int i = 0; i < n; i++)               // 逐位检查第 i 位
{
if (mask & (1 << i)) cur.push_back(nums[i]);   // 第 i 位是 1 -> nums[i] 在这个子集里
}
ret.push_back(cur);
return ;
}
};

