// ============================================================
// LeetCode 576. 出界的路径数
// 考点：记忆化搜索（状态第一次带「剩余步数」这一维）+ 计数型
// 复杂度：时间 O(m*n*maxMove)，空间 O(m*n*maxMove)
// 日期：2026-09-27（修正后通过）
// ============================================================
//
// 【题意】
// m×n 网格，球初始在 (startRow, startColumn)。每步上下左右走一格，
// 可以走出网格。最多走 maxMove 步，求【把球走出边界】的方案数（对 1e9+7 取模）。
//
// ============================================================
// 【核心一：状态要加一维 —— 剩余步数】
// ============================================================
//     f(i, j, step) = 从 (i,j) 出发、【还剩 step 步】时，能走出边界的方案数
//
// 为什么必须加这一维：同一个格子，在"还剩 1 步"和"还剩 5 步"时的答案
// 完全不同 —— 光有 (i, j) 描述不了状态。
//
// 状态数 = m × n × (maxMove+1)。本题 m,n ≤ 50、maxMove ≤ 50 → 约 12.75 万，
// 记忆化绰绰有余。
//
// ============================================================
// 【核心二：出口是「动作」，不是「位置」—— 与 329/2328 的根本区别】
// ============================================================
//   LC 329 / 2328：出口 = **走不动了**（没有值更大的邻居）→ 那个格子本身算一条
//   LC 576（本题）：出口 = **"走出边界"这个动作本身**
//
//   ⚠️ 这是本题唯一的难点。方案不是在某个【格子】上结束的，
//      而是在"跨出边界的那一步"结束的。
//      → 所以走出界必须【当场记账】，而不是继续递归下去。
//
//   一句话心智模型：
//       **每一步都有两个命运 —— 要么"出去了"（成功，当场 +1），
//         要么"还在里面"（继续走，剩余步数 -1）。**
//
// ============================================================
// 【核心三：转移与边界】
// ============================================================
//     f(i,j,step) = Σ over 四个方向:
//                       邻居在界外 → +1            （这一步就出去了）
//                       邻居在界内 → + f(邻居, step-1)
//
//     f(i,j,0) = 0      // 一步都走不了了 → 还没出去 → 0 条
//
//   主函数：return f(startRow, startColumn, maxMove);
//
// ============================================================
// 【代码 ↔ 逻辑 逐行对应（记忆化 DFS 的四步骨架）】
// ============================================================
// 任何记忆化 DFS 都是这四步，位置固定 —— 先把它们对上，再看细节：
//
//     int dfs(状态参数) {
//         ① 【出口】  满足什么就不用再算了？   →  if (step == 0) return 0;
//         ② 【查表】  这个状态算过吗？        →  if (memo[...] != -1) return memo[...];
//         ③ 【展开】  把大问题拆成同类小问题  →  for 四个方向 { ... 递归 ... }
//         ④ 【存表】  记下来，下次别重算      →  memo[...] = 结果;  return 结果;
//     }
//
// 本题第 ③ 步里，"四个方向各试一次"的**每次**只有两种结果，
// 这就是全题最容易看不懂的地方 —— 它是**两个不同量级的东西相加**：
//
//     这一步【走出界】   →  贡献 1 条完整方案          （代码：flag += 1）
//                           它到此为止，不再往下递归
//     这一步【还在界内】 →  贡献 f(邻居, step-1) 条方案 （代码：flag += dfs(x,y,step-1)）
//                           把问题原封不动交给邻居
//
//   ⚠️ 所以 `flag` 是【累加和】（"一共多少条方案"），
//      不是布尔开关 —— 名字起得容易误解，读的时候心里换成 `ways` 更顺。
//
//   为什么"界内"那一项是 `dfs(x,y,step-1)` 而不是 `dfs(i,j,step)`？
//      · 位置：这一步之后人在【邻居】(x,y)，不在原地 → 参数换成 x,y
//      · 步数：走一步就少一步 → step-1
//
// ============================================================
// 【易错点（本题实际踩到的三个）】
// ============================================================
//   ① `memset(memo, sizeof(memo), -1)` —— **参数顺序写反**！
//      正确顺序：`memset(指针, 值, 字节数)` → `memset(memo, -1, sizeof(memo))`。
//      写反的后果极严重：第三个参数变成 (size_t)(-1) = 1.8e19 字节，
//      程序向内存外狂写 → **段错误**（实测退出码 0xC0000005）。
//      ⚠️ **这是同一个错第二次犯**（09-11 LC 1094 的 `memset(num, sizeof(num), 0)`）。
//      口诀：**值在中间，大小在最后。**
//
//   ② **少了"走出界 +1"** —— 循环只写了"界内才递归"，界外什么都没做。
//      后果：算出来的其实是"**恰好 k 步后还留在网格里**的走法数"，正好是答案的反面。
//      实测（只把 memset 修好、其余不动）：官方示例 1 返回 4，正确是 6。
//
//   ③ `if(step==0) return 1;` —— 应为 `return 0`。
//      step==0 表示"一步都走不了"，此时还没出去 → 0 条；
//      写成 1 等于把"困在里面"算成了成功。
//
//   ⚠️【哨兵必须用 -1，不能用 0】本题答案**可以是 0**（比如 step==0 时），
//      拿 0 当"没算过"的标记会直接把错误答案当成已算过的结果读回来。
//      —— 这就是"哨兵值必须取一个不可能是合法答案的值"这条规则的实际用场。
//
// 【另一种解法】按 step 从小到大做自底向上 DP（因为 step 只依赖 step-1），
//   可省掉递归栈；也正好可以用来当独立对拍基准。
//
// 【408 标注】记忆化搜索 = 自顶向下 DP。
// ============================================================

class Solution {
int mm, nn;
int memo[51][51][51];
int dx[4] = {0, 0, -1, 1};
int dy[4] = {-1, 1, 0, 0};
const int MOD = 1e9 + 7;
public:
int findPaths(int m, int n, int maxMove, int startRow, int startColumn) {
// 递归函数 dfs 的参数里没有 m / n，所以先存成成员变量，供它内部判断越界用
mm = m, nn = n;
// 整张表刷成 -1 = "这个状态还没算过"
//   （必须用 -1：本题答案可以是 0，拿 0 当"没算过"会把错误答案当结果读回来）
//   注意参数顺序：memset(指针, 值, 字节数)
memset(memo, -1, sizeof(memo));
// 状态定义就是"从 (i,j) 出发、还剩 step 步" ——
// 起点和总步数题目直接给了，所以这一步就是最终答案，不需要再 max/累加
return dfs(startRow, startColumn, maxMove);
}
int dfs(int i, int j, int step) {
// ① 出口：一步都走不了了 → 还没出去 → 0 条
if (step == 0) {
return 0;
}
// ② 查表：这个状态算过就直接读，不重算
if (memo[i][j][step] != -1) {
return memo[i][j][step];
}
// ③ 展开：flag = "从 (i,j) 出发的出界方案总数"的累加器（读作 ways 更顺）
long long flag = 0;
for (int a = 0; a < 4; a++) {
int x = i + dx[a], y = j + dy[a];
if (x >= 0 && x < mm && y >= 0 && y < nn) {
// 还在界内 → 这一步没出去，把问题交给【邻居】
// 位置换成 (x,y)、步数减 1
flag += dfs(x, y, step - 1);
} else
// 走出界 → 这一步本身就构成 1 条完整方案，到此为止
flag += 1;
flag %= MOD;                          // 随时取模，防止中间值撑爆
}
// ④ 存表 + 返回
memo[i][j][step] = flag;
return flag;
}
};

