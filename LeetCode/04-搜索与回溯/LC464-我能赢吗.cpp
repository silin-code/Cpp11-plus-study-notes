// ============================================================
// LeetCode 464. 我能赢吗
// 考点：记忆化搜索 + **位掩码状态（状压）** + 博弈（布尔型胜负）
// 复杂度：时间 O(2^m * m)（状态数 2^m，每个状态试 m 个数），空间 O(2^m)
// 日期：2026-09-30（**从零自己写出来的**，详见文末「这一道是怎么学会的」）
// ============================================================
//
// 【题意】
// 从 1..maxChoosableInteger 里轮流取数（取过的不能再取），
// 谁先让【累计和 >= desiredTotal】谁赢。玩家 1 先手。问先手是否必胜。
//
//      maxChoosableInteger = 10, desiredTotal = 11  ->  false
//      maxChoosableInteger = 10, desiredTotal = 0   ->  true
//
// 【为什么能用位掩码】（约束给了信号）
//      maxChoosableInteger <= 20  ->  2^20 ≈ 100 万种局面，装得下
//
// ============================================================
// 【核心一：状态 = 一个 bitmask】
// ============================================================
//     mask 的第 i 位 = 1  表示【数字 i 已经被拿走了】（i 从 1 到 m）
//
//     起始局面 mask = 0            （一个都没拿）
//     加入数字 i： mask | (1 << i)  （置位）
//     判断 i 是否已被拿： mask & (1 << i)
//
//   一个 mask 就唯一确定了"现在是什么局面" —— 这是能用它当状态的前提。
//
// ============================================================
// 【核心二：sum 从 mask 推出来，绝不当参数】
// ============================================================
//    已经拿走的数之和 sum 完全由 mask 决定 —— 它就是"mask 里那些位的编号和"。
//
//    ⚠️ 为什么不能当参数：一旦状态变成 (mask, sum)，
//       记忆化表就得开 `2^m × sum的范围` ≈ 2^20 × 300 ≈ 3 亿格，直接爆内存。
//
//    **判据（和 LC 486 的 gap 同一条）：**
//       一个量该进状态，问它是"被问出来的【答案】"还是"必须交代的【前提】"。
//       sum 是状态的函数 → 让它当【函数内现算的值】，不要进状态。
//
// ============================================================
// 【核心三：dfs 的返回值 = "当前要动手的人能不能必胜"】（本题的灵魂）
// ============================================================
//    dfs(mask) 返回的不是"我能得几分"，而是 **"轮到谁动手，谁能不能必胜"**。
//
//    这条定义带来一个漂亮的后果：**同一个函数，两个人轮流用**。
//        dfs(0)              现在轮到【玩家 1】动手 -> 算的是玩家 1 能不能赢
//        dfs(mask|(1<<i))    现在轮到【玩家 2】动手 -> 算的是玩家 2 能不能赢
//    函数体完全一样，不需要任何"我是谁"的参数。
//
//    （和 LC 486 的"分差函数"是同一个思想：486 用分数，这题用胜负。）
//
// ============================================================
// 【核心四：分支二的 `!` 与"为什么直接返回"】
// ============================================================
//    拿走 i 之后，局面变成 mask|(1<<i)，轮到【对手】动手，
//    所以 `dfs(mask | (1 << i))` 说的是 **"对手能不能必胜"**。
//
//        对手能必胜（返回 1） -> 我这一步走坏了 -> 换下一个 i 试
//        对手不能必胜（返回 0）-> **那赢的人就是我** -> 立刻返回 1
//
//    所以写成 `if (!dfs(mask | (1 << i))) return memo[mask] = 1;`
//
//    ⚠️ 为什么可以【直接返回】而不是继续试其他 i？
//       因为这个问题问的是"**能不能**"（存在性），不是"有多少种"。
//       只要找到【一条】能让我赢的走法，答案就已经是"能"了 ——
//       剩下的 i 不用再试。（存在性 → 找到一个就可以收工。
//         对比 LC 2328 求"条数"，那就必须把四个方向的贡献全收齐。）
//
// ============================================================
// 【两个必须在入口判的前提（漏了会算错）】
// ============================================================
//    ① target <= 0：开局总和 0 就已达标 -> 先手直接赢
//
//    ② (1+2+...+m) < target：全部数字加起来都够不到目标
//       -> **这局没人能赢（平局）** -> 先手输
//
//    ⚠️ ②为什么必须写：转移里有"对手赢不了 ⇒ 我赢"，
//       而【平局时对手确实赢不了】—— 会被误判成"我赢"。
//       实测：漏掉这条，m=1、T=2..13 那一整片的结论会反过来。
//
// ============================================================
// 【易错点（本题实际踩过的）】
// ============================================================
//    ① 【sum 当成了 mask】写 `mask + i >= target` ——
//       mask 是"位模式"，sum 是"那些位代表的数字之和"，**两个不同的数**：
//          mask = 0b0110(bit1、bit2 亮) -> mask 的数值 = 6，但 sum = 1+2 = 3
//       → 必须**单独一个循环先算 sum**，再"另起一个循环试走法"。
//
//    ② 【少了 `continue`】-> **栈溢出**（实测退出码 0xC00000FD）
//       如果 i 已经被拿走，`mask | (1 << i)` **还是 mask 自己**（该位本来就是 1），
//       于是 `dfs(mask)` 调 `dfs(mask)` —— 自己调自己，
//       而 memo[mask] 此刻还没写回，拦不住 -> 无限递归。
//       → **`continue` 的作用是"把关卡提前"**：保证从下一行起 i 一定没被拿过，
//         后面的 `mask | (1 << i)` 才一定是个新局面。
//
//    ③ 【`&` 与 `&&` 的优先级】`&` 比 `&&` 低，`mask & (1<<i) && x` 会被解析成
//       `mask & ((1<<i) && x)` —— 位运算和逻辑运算混用时括号要加够。
//
//    ④ 【哨兵不能用 0】答案就是 0/1，所以哨兵必须是 -1（或别的非法值）。
//
//    ⑤ 【成员容器入口复位】`memo.assign(...)` 必须在入口处 ——
//       否则同一个对象连调两次会读到上一轮的残留值（LC 486 踩过）。
//
// 【408 标注】记忆化搜索 = 自顶向下 DP；"位掩码表示集合"是状压 DP 的基础。
// ============================================================

class Solution {
int m, target;
vector<int> memo;   // memo[mask]：-1 = 没算过 ／ 0 = 输 ／ 1 = 赢
public:
bool canIWin(int maxChoosableInteger, int desiredTotal) {
m = maxChoosableInteger, target = desiredTotal;

// 位号用 1..m，所以 mask 最大是 2^(m+1)-1，表开 1<<(m+1)
memo.assign((1 << (m + 1)), -1);          // ★ 入口复位（每次调用都要）

// 前提一：目标 <= 0，先手直接赢
if (target <= 0) return true;

// 前提二：全部数字加起来都够不到目标 -> 这局没人能赢
if ((long long)m * (m + 1) / 2 < target) return false;

return dfs(0);                            // 起始局面：一个数都没拿
}

// 返回：从 mask 这个局面出发，【当前要动手的人】能不能必胜
bool dfs(int mask) {
// ① 查表
if (memo[mask] != -1) {
return memo[mask];
}

// ② 算当前总和 —— 从 mask 推出来，不当参数
int sum = 0;
for (int i = 1; i <= m; i++) {
if (mask & (1 << i)) sum += i;
}

// ③ 试每一个【还没被拿走】的数
for (int i = 1; i <= m; i++) {
if (mask & (1 << i)) continue;        // ★ 少了这行会无限递归（见易错点②）

// 分支一：拿走 i 就够到目标 -> 我这一手直接赢
if (sum + i >= target) {
return memo[mask] = 1;
}

// 分支二：还没够 -> 轮到【对手】在新局面里玩
//   新局面 = mask | (1 << i)（把 i 加进"已拿集合"）
//   dfs(新局面) 返回的是【对手】能不能必胜 -> 取反就是我的结论
//   问的是"能不能"（存在性），找到一条赢路就可以直接返回
if (!dfs(mask | (1 << i))) {
return memo[mask] = 1;
}
}

// ④ 所有 i 都试完，一个都赢不了 -> 我必败
return memo[mask] = 0;
}
};

