// ============================================================
// LeetCode 200. 岛屿数量
// 考点：Flood Fill（网格连通块）· 永久标记，不需要撤销
// 复杂度：时间 O(n*m)，空间 O(n*m)
// 日期：2026-09-18  4'54"（自述"以前做过"）
// ============================================================
//
// 【题意】
// grid 中 '1' 是陆地、'0' 是水，上下左右相连的陆地算一座岛，求岛屿个数。
//
// 【本题最重要的认知：为什么不需要撤销】
// LC 79（单词搜索）和本题都是网格 DFS，但 79 必须用 visit 回溯还原，
// 本题一旦标记就永不还原。判据只有一句：
//
//     这个格子以后还要不要留给"另一条路"用？
//
//   LC 79：一个格子可能被多条路径经过。从 (i,j) 出发能否走通，
//          取决于"哪些格子已被占" → 结论依赖到达路径 → 必须撤销
//   LC 200：一个格子属不属于某块岛是固定事实。确认连通后整块岛
//          会被一次性吃干净并标记，以后再也不需要碰它
//          → 结论只依赖格子本身 → 永久标记
//
//   一句话：结论依赖"怎么走到这里"就撤销；只依赖"状态本身"就永久标记。
//
// 【标号法：为什么 use 数组而不是原地改 grid】
// 两种都行。原地改 grid[i][j] = '0' 更省空间，前提是改成的字符
// 绝不会出现在合法数据里（'0' 不是陆地，满足）。
// 本版用 use 数组：不破坏输入、意图更清楚，代价是 O(n*m) 额外空间。
//
// 【外层计数的关键：进入 dfs 前先标记】
// 外层发现 grid[i][j]=='1' 且未访问时：先 use[i][j]=true，再 ret++，
// 再 dfs。顺序不能反 —— 先标记再递归，才不会在同一块岛里重复计数。
//
// 【易错 ⑥：成员容器在多次调用间不复位 —— 本版踩中】
//   原写法：use.resize(n, vector<bool>(m, false));
//   resize 只保证"元素个数"正确，**尺寸不变时不会重置任何元素的值**。
//
//   实测后果（同一对象连续调用）：
//     跑 3 次 3x3 → 2 / 0 / 0      （应为 2/2/2）
//     先跑 2x3 再跑 1x1 → 1 / 0    （应为 1/1）
//   力扣每个用例新建对象，所以不触发；但本地多测、调试连续调用必错。
//
//   正确写法：use.assign(n, vector<bool>(m, false));
//   assign 先清空再填，与尺寸是否变化无关。
//
//   同类前科：LC 46（成员 ret / path 没清空，本地连调会累积结果）。
//   纪律：**成员容器在每次入口函数开头复位，不要靠 resize 撞运气。**
//
// 【其他】
// - vector<bool> 是位压缩特化，取地址（&use[i][j]）会失效；
//   本题不取地址所以无害，但一般建议用 vector<char> 或 vector<int>。
// - grid 为空时 grid[0] 会崩；本题约束保证 m, n >= 1。
// ============================================================

class Solution {
    int n, m;
    vector<vector<bool>> use;
    int dx[4] = {0, 0, -1, 1};
    int dy[4] = {-1, 1, 0, 0};
public:
    int numIslands(vector<vector<char>>& grid) {
        n = grid.size(), m = grid[0].size();
        int ret = 0;
        use.assign(n, vector<bool>(m, false));   // 原为 resize，见【易错 ⑥】

        for (int i = 0; i < n; i++) {
            for (int j = 0; j < m; j++) {
                if (grid[i][j] == '1' && use[i][j] == false) {
                    use[i][j] = true;            // 先标记，再递归
                    ret++;
                    dfs(grid, i, j);
                }
            }
        }
        return ret;
    }

    void dfs(vector<vector<char>>& grid, int i, int j) {
        for (int a = 0; a < 4; a++) {
            int x = i + dx[a], y = j + dy[a];
            if (x >= 0 && x < n && y >= 0 && y < m
                && use[x][y] == false && grid[x][y] == '1') {
                use[x][y] = true;
                dfs(grid, x, y);                 // 无撤销行 —— 本题的核心
            }
        }
    }
};
