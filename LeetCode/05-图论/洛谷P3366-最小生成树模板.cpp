// ============================================================
// 洛谷 P3366 【模板】最小生成树 —— Kruskal 的标准形态
// ------------------------------------------------------------
// 平台：洛谷（https://www.luogu.com.cn/problem/P3366）
// 难度：模板题（绿）
// 复杂度：O(m log m)（排序主导）
// 日期：2026-11-10（13 个测试点全 AC，324ms / 2.85MB）
// ------------------------------------------------------------
// 题意：
//   n 个点、m 条边的无向图，求最小生成树的总权值。
//   图不连通 -> 输出 "orz"。
//
//   输入：n m，然后 m 行 u v w
//   输出：MST 权值 或 orz
//
//   样例：
//     4 5
//     1 2 2
//     1 3 2
//     1 4 3
//     2 3 4
//     3 4 3
//     -> 7
//
//   数据范围：n <= 5000，m <= 200000，w <= 1e4
//
// ============================================================
// 【和 LC 1584（完全图 MST）的三处差别】
// ============================================================
//                    LC 1584                 本题
//   边从哪来         自己造（n² 条完全图）    题目直接给（m 条）
//   一定连通吗       是（完全图）             【否】-> 要判 cnt != n-1
//   编号             0..n-1                  1..n -> 需要转成 0-based
//
// ============================================================
// 【本题的编号处理：统一转 0-based】
// ============================================================
//   读入时 u-1、v-1，之后所有地方都按 0..n-1 处理：
//       点的编号：0 .. n-1
//       并查集   ：p.assign(n, -1)
//       数组大小 ：n
//
//   ★ 关键：转了就【全程一致】。
//     不要"边里存 1..n、并查集开 n"（那样访问 p[n] 越界），
//     也不要"一半转一半不转"。
//
//   另一种写法是不转（边里存 1..n），那并查集要开 n+1：
//       p.assign(n + 1, -1);
//     两种都对，但必须配套。
//
// ============================================================
// 【这版写对的六个点】
// ============================================================
//   ① 0-based 转换和 assign(n) 配套          ✓
//   ② cnt 计数 + 选够 n-1 就 break           ✓
//   ③ 不连通输出 orz                          ✓
//   ④ for (auto& e : vv) 用引用（不拷贝）      ✓
//   ⑤ Union 按秩：if (p[p1] > p[p2]) swap    ✓
//   ⑥ vector<Edge> vv(m) 预分配，不反复扩容   ✓
//
// ============================================================
// 【一处可以更稳的地方（本题数据下不影响）】
// ============================================================
//   int ret 改成 long long。
//
//   本题 w <= 1e4、最多 4999 条边 -> 最大约 5e7，int 够（已 AC）。
//   但如果换成 w <= 1e9 的题（比如 LC 1584 那种 2e6 级别），
//   累加会逼近 / 超过 int 上限 -> 一律用 long long 更保险。
//
// ============================================================
// 【408 视角】
// ============================================================
//   Kruskal vs Prim：
//       Kruskal  O(m log m)   适合【稀疏图】（m 小）
//       Prim     O(n²)        适合【稠密图】（邻接矩阵）
//   本题 m <= 2e5、n <= 5000（m 相比 n² = 2.5e7 很小）-> 稀疏图 -> Kruskal
//   两者都基于贪心，MST 权值唯一，形态可能不唯一。
// ============================================================
// 实测：洛谷 13 个测试点全部 AC（100 分）
// ============================================================

#include <bits/stdc++.h>
using namespace std;

int n, m;
vector<int> p;          // 并查集：p[i] < 0 表示 i 是根，-p[i] = 集合大小

struct Edge {
    int u, v, w;
};

static bool cmp(const Edge& e1, const Edge& e2) {
    return e1.w < e2.w;                 // 只按权值升序
}

int find(int x) {
    if (p[x] < 0) {
        return x;
    }
    return p[x] = find(p[x]);           // 路径压缩
}

void Union(int x, int y) {
    int p1 = find(x);
    int p2 = find(y);
    if (p[p1] > p[p2]) {                // p[i] 是负的集合大小，越大集合越小
        swap(p1, p2);
    }
    p[p1] += p[p2];
    p[p2] = p1;
}

int main() {
    cin >> n >> m;

    p.assign(n, -1);                    // ★ 配合下面的 u-1：0-based，开 n 就够

    vector<Edge> vv(m);                 // 预分配 m 个，避免反复扩容
    for (int i = 0; i < m; i++) {
        int u, v, w;
        cin >> u >> v >> w;
        vv[i].u = u - 1;                // 1..n -> 0..n-1
        vv[i].v = v - 1;
        vv[i].w = w;
    }

    sort(vv.begin(), vv.end(), cmp);

    int ret = 0;                        // 本题数据下 int 够（见注释）
    int cnt = 0;                        // 已选边数

    for (auto& e : vv) {
        if (cnt == n - 1) break;        // 选够就停（提前退出）

        int u = e.u, v = e.v, w = e.w;

        if (find(u) == find(v)) {       // 已连通 -> 成环 -> 跳过
            continue;
        }
        Union(u, v);
        cnt++;
        ret += w;
    }

    if (cnt != n - 1) {                 // 不连通：选不满 n-1 条边
        cout << "orz";
        return 0;
    }
    cout << ret;
    return 0;
}
