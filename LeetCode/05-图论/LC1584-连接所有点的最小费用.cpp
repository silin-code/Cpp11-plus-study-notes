// ============================================================
// LC 1584 连接所有点的最小费用 —— Kruskal + 完全图造边
// ------------------------------------------------------------
// 考点：最小生成树（Kruskal）+ 自写并查集 + 完全图边数
// 复杂度：时间 O(n² log n)（排序主导），空间 O(n²)
// 日期：2026-11-09（21 分钟从零手搓；改掉 2 处后全过）
// ------------------------------------------------------------
// 题意：
//   给 n 个点坐标，连接两点的代价 = 曼哈顿距离 |xi-xj| + |yi-yj|。
//   求把所有点连成一整块的最小总代价。
//
//     points = [[0,0],[2,2],[3,10],[5,2],[7,0]]  ->  20
//
// ------------------------------------------------------------
// 【和"标准 MST 题"的唯一差别：边没有给，要自己造】
// ------------------------------------------------------------
//   标准 MST：题目给边表 [u, v, w]
//   本题    ：只给坐标 -> 任意两点之间都有边（【完全图】）
//
//   n 个点 -> n(n-1)/2 条边
//   n <= 1000 -> 最多约 50 万条边 -> 排序约 1000 万次比较，能过
//
// ------------------------------------------------------------
// 【Kruskal 三步】
// ------------------------------------------------------------
//   ① 所有边按权值升序排序
//   ② 依次看每条边：两端已连通 -> 跳过（成环）；否则选它并合并
//   ③ 选够 n-1 条就停（n 个点的生成树恰好 n-1 条边）
//
// ------------------------------------------------------------
// 【并查集：负数约定】
// ------------------------------------------------------------
//   p[i] < 0  ->  i 是根，-p[i] = 这个集合的元素个数
//   find 带路径压缩（p[x] = find(p[x])）
//   合并时让【集合大的当根】，这样树高不会退化
//
//   ★ 比较的是 p[p1] / p[p2]（负的集合大小），不是 p1 / p2（节点编号）
//
// ------------------------------------------------------------
// 【本次踩的两个坑】
// ------------------------------------------------------------
//   ① p.resize(n, -1)  ->  resize 不重置已有元素！
//      同一对象第二次调用时，p 里还是上次的并查集结果
//      -> find 读到脏数据 -> 越界 / 崩溃（实测 Python 复现 IndexError）
//      修：p.assign(n, -1)
//
//      ★ 这是"成员变量没复位"第 6 次：
//        LC 46 / 200（use.resize）/ 486 / 78 / 110 / 1584
//
//   ② Union 里写 if (abs(p1) < abs(p2)) swap(p1, p2)
//      p1 / p2 是【根的下标】，abs 取的是编号绝对值，和集合大小无关
//      -> 按秩合并完全失效，集合退化成一条链
//      实测：8 个节点依次合并，最大深度 7（修正后是 1）
//      修：if (p[p1] > p[p2]) swap(p1, p2);
//
//      注意：这个 bug【不影响正确性】（合并动作本身合法），只影响树高
//
// ------------------------------------------------------------
// 【还能改进的四处（不影响正确性）】
// ------------------------------------------------------------
//   ③ double w：曼哈顿距离是整数，用 int 即可（此处 double 也能精确表示）
//   ④ for (int j = i; ...)：多生成 n 条"自己到自己"的边（w=0），
//      全部走 issame 被跳过 -> 改 j = i + 1 少跑 n 次
//   ⑤ 主循环没有计数：选够 n-1 条后仍遍历剩余边 -> 加 cnt + break
//      50 万条边时这一步能省掉不少
//   ⑥ for (auto e : v)：值拷贝 50 万次 -> 改 const auto& e
//
// ------------------------------------------------------------
// 实测（改后）：
//   官方样例 20 / 18 ✓
//   同一对象连续调用三次 = 20, 18, 4 ✓（改前会崩）
//   单点 / 两点 / 全重合 = 0, 2, 0 ✓
//   随机对拍 3000 组（同一对象反复用，比 LeetCode 更严格）零不一致 ✓
//   树高：8 节点链式合并最大深度 1（改前 7）✓
// ============================================================

#include <vector>
#include <algorithm>
#include <cstdlib>
using namespace std;

struct Edge {
    int u, v;
    double w;
};

class Solution {
public:
    // ---------- 并查集（负数约定）----------
    int find(int x) {
        if (p[x] < 0) {
            return x;
        }
        return p[x] = find(p[x]);          // 路径压缩
    }

    bool issame(int x, int y) { return find(x) == find(y); }

    void Union(int x, int y) {
        int p1 = find(x);
        int p2 = find(y);
        // 让【集合更大】的当根：p[i] 是负的集合大小，越负越大
        // 所以 p[p1] > p[p2] 表示 p1 的集合更小 -> 交换
        if (p[p1] > p[p2]) {
            swap(p1, p2);
        }
        p[p1] += p[p2];
        p[p2] = p1;
    }

public:
    static bool cmp(const Edge& v1, const Edge& v2) { return v1.w < v2.w; }

    int minCostConnectPoints(vector<vector<int>>& points) {
        int n = points.size();

        // ---------- 造完全图的边 ----------
        vector<Edge> v;
        for (int i = 0; i < n; i++) {
            int x1 = points[i][0];
            int y1 = points[i][1];
            for (int j = i; j < n; j++) {       // 提示：j = i + 1 更省
                int x2 = points[j][0];
                int y2 = points[j][1];
                Edge tmp;
                tmp.u = i;
                tmp.v = j;
                tmp.w = abs(x1 - x2) + abs(y1 - y2);   // 曼哈顿距离
                v.push_back(tmp);
            }
        }

        // ★ assign 而不是 resize：resize 不会重置已有元素
        p.assign(n, -1);

        sort(v.begin(), v.end(), cmp);

        // ---------- Kruskal ----------
        int ret = 0;
        for (auto e : v) {
            if (issame(e.u, e.v)) {
                continue;                       // 已连通 -> 成环 -> 跳过
            }
            Union(e.u, e.v);
            ret += e.w;
        }
        return ret;
        // 注：本题必然连通（完全图），所以不需要判 cnt != n-1
    }

private:
    vector<int> p;
};
