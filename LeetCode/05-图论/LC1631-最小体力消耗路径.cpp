// ============================================================
// LC 1631 最小体力消耗路径 —— Dijkstra 的「dist 换含义」变形
// ------------------------------------------------------------
// 考点：Dijkstra（dist 存"路径上的最大值"，不是"和"）+ 网格隐式图
// 复杂度：O(nm log(nm))
// 日期：2026-11-11（先写 DFS 枚举，TLE 后改 Dijkstra）
// ------------------------------------------------------------
// 题意：
//   给 rows x cols 的高度图，从 (0,0) 走到 (rows-1, cols-1)，
//   每次上下左右走一格。
//   一条路径的【耗费】= 路径上【相邻两格高度差绝对值】的【最大值】。
//   求最小耗费。
//
//     [[1,2,2],[3,8,2],[5,3,5]]  ->  2
//     [[1,2,3],[3,8,4],[5,3,5]]  ->  1
//     [[1,10,1,1]]               ->  9
//
// ============================================================
// 【一、为什么这是 Dijkstra（这是本题的核心）】
// ============================================================
//   Dijkstra 不是"求最短路"的专用算法，它是：
//       按"代价"从小到大，逐个确定每个点的最优值。
//
//   它唯一的硬性要求：【代价单调不减】—— 走远一步，代价不会变小。
//
//       LC 743（边权和） ：nd = dist[u] + w
//                          w >= 0 -> 加只会变大 ✓
//       本题（路径最大值）：nd = max(dist[u], w)
//                          max 只会不变或变大 ✓
//
//   两个公式不同，算法流程【一字不差】：
//       小根堆 → 出堆判过期 → 松弛邻居 → 只压变好的
//
// ------------------------------------------------------------
// 【二、为什么可以"每个格子只留一个最优值"】
// ------------------------------------------------------------
//   假设两条路到格子 X：
//       路径 A：前面最大差值 = 5
//       路径 B：前面最大差值 = 100
//
//   从 X 往后走，无论后面是什么：
//       A 的总 max = max(5,   后面)
//       B 的总 max = max(100, 后面)
//       max(5, 后面) <= max(100, 后面)  ->  B 永远更差，直接丢
//
//   -> 每个格子只保留"最小的 max" 就够了，状态数 = n*m
//
//   【这正是 DFS 枚举 TLE 的原因】：
//       DFS 没有这个"合并"，把每一条到达 X 的路都当新分支展开 -> 指数级
//
// ------------------------------------------------------------
// 【三、不建邻接表：格子图是"隐式图"】
// ------------------------------------------------------------
//   Dijkstra 只需要一种能力：给一个点，能枚举邻居 + 代价。
//
//       LC 743：题目给边表 -> 建邻接表 -> 到时候【查表】
//       本题   ：格子天生 4 个邻居，代价 = 高度差 -> 到时候【现算】
//
//   两者对算法没有区别，只是"邻居从哪来"不同。
//
// ------------------------------------------------------------
// 【四、用 tuple 表示状态（C++11 写法）】
// ------------------------------------------------------------
//   typedef tuple<int,int,int> State;      // {代价, 行, 列}
//   priority_queue<State, vector<State>, greater<State>> q;
//
//   ★ 代价必须放在第一个位置：
//       tuple 的 operator< 是【字典序】，先比第一个
//       greater 据此升序 -> 堆顶是最小代价
//       写成 {行, 列, 代价} 就变成按行号排序了（和 743 的"距离在前"同理）
//
//   ★ C++11 不能用结构化绑定：
//       auto [d,i,j] = q.top();   // ✗ C++17
//       int d = get<0>(t);        // ✓ C++11
//
// ============================================================
// 【五、本次踩的三个坑】
// ============================================================
//   ① （DFS 版）gap 没取 max
//        dfs(x, y, abs(当前差))            // 只传了"这一步的差"
//        正确的是 max(gap, abs(...))       // 累积到"整条路径的最大值"
//      症状：官方样例能过（最优路径各边差值恰好相同），
//            [[1,10,1,1]] 返回 0（正确 9）—— 典型的"能过≠对"
//
//   ② （Dijkstra 版）松弛判断指向了自己
//        if (nd < dist[x][y]) { dist[i][j] = nd; ... }
//                    ↑ 当前格      ↑ 邻居
//      后果：数学上恒不成立
//           nd = max(cost, w) >= cost >= dist[x][y]
//           -> 一条边都压不进堆 -> 返回 INF（4144959 = 0x3f3f3f）
//      判据：【松弛=改进邻居】，判断和赋值必须指向同一个格子
//
//   ③ j 写成了 x + dy[a]
//        int i = x + dx[a], j = x + dy[a];   // ✗ 横坐标加了纵偏移
//
// ============================================================
// 【六、Dijkstra 的 dist 可以存什么（这张表值得记）】
// ============================================================
//   存"和"        -> 标准最短路           LC 743
//   存"最大值"    -> 最小化"最坏的那一步"  LC 1631（本题）
//   存"最小值"    -> 最大化"最窄的瓶颈"    LC 1102
//   加一维状态    -> 状态图最短路          LC 787（城市+中转次数）
//
//   模板一行不改，只换 dist 的定义和松弛式。
//
// ============================================================
// 实测：6 个固定用例（含 [[1,10,1,1]]）+ 与 DFS 暴力随机对拍 1500 组
//       零不一致
// ============================================================

#include <vector>
#include <tuple>
#include <queue>
#include <cstdlib>
#include <algorithm>
using namespace std;

class Solution {
    int dx[4] = {0, 0, 1, -1};
    int dy[4] = {1, -1, 0, 0};

public:
    int minimumEffortPath(vector<vector<int>>& heights) {
        using State = tuple<int, int, int>;      // {代价, 行, 列}  代价必须在第一位

        int n = heights.size(), m = heights[0].size();

        // dist[i][j] = 走到 (i,j) 的"路径最大高度差"的最小值
        vector<vector<int>> dist(n, vector<int>(m, 0x3f3f3f));

        // 小根堆：按 tuple 字典序，第一元素（代价）最小者在堆顶
        priority_queue<State, vector<State>, greater<State>> q;

        dist[0][0] = 0;
        q.push(make_tuple(0, 0, 0));

        while (q.size()) {
            State t = q.top();
            q.pop();

            int cost = get<0>(t);          // 走到 (x,y) 时的"路径最大差值"
            int x = get<1>(t);
            int y = get<2>(t);

            if (cost > dist[x][y]) continue;         // 过期记录，跳过

            if (x == n - 1 && y == m - 1) return cost;   // 终点弹出即答案

            // 枚举四个邻居（隐式图，不建邻接表）
            for (int a = 0; a < 4; a++) {
                int i = x + dx[a];
                int j = y + dy[a];                   // ★ 是 y，不是 x

                if (i < 0 || i >= n || j < 0 || j >= m) continue;

                int w = abs(heights[x][y] - heights[i][j]);   // 这一步的高度差

                int nd = max(cost, w);               // ★ 核心：取 max，不是加

                if (nd < dist[i][j]) {               // ★ 判断的是【邻居】
                    dist[i][j] = nd;
                    q.push(make_tuple(nd, i, j));    // 只压变好的
                }
            }
        }
        return dist[n - 1][m - 1];       // 兜底（正常会从上面的 return 出去）
    }
};
