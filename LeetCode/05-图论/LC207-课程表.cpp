// 【408 标注】拓扑排序是 408 图论高频考点（AOV 网、拓扑序列、判环）。
//   本题还正好踩到 408 的经典考点：**邻接表存的是【出边】，求入度需要额外信息**
//   —— 所以入度数组必须单独统计，不能从邻接表读出来。
// ============================================================

class Solution {
public:
bool canFinish(int n, vector<vector<int>>& p) {
// p[1] -> p[0]：需要学完 p[1]，才能学 p[0]
vector<int> in(n, 0);
vector<vector<int>> out(n);   // 邻接表：out[b] = { 所有以 b 为先修课的课 }
for (auto& e : p) {
in[e[0]]++;                    // a 多了一个先修课
out[e[1]].push_back(e[0]);     // b 的后继清单里加上 a
}
queue<int> q;
for (int i = 0; i < n; i++) {
if (in[i] == 0) q.push(i);     // 没有前置依赖的课，现在就能学
}
while (q.size()) {
int size = q.size();
while (size--) {
int cur = q.front();
q.pop();
for (int i = 0; i < (int)out[cur].size(); i++) {
if (--in[out[cur][i]] == 0) q.push(out[cur][i]);   // 自减与判零合并
}
}
}
for (auto e : in) {
if (e != 0) return false;      // 还有课没被解锁 → 有环 → 修不完
}
return true;
}
};
