// 【题意】
// n 门课，prerequisites[i] = [a, b] 表示「想修 a，必须先修 b」。
// 判断能否修完所有课 —— 等价于【判断这个有向图有没有环】。
//
// ============================================================
// 【建图三问（提交前必过一遍，本题实测栽在第 ① 问）】
// ============================================================
//   ① 方向：题面里谁是"先修"？`[a, b]` = 先修 b → 边 **b → a**。
//      ⚠️ 数组里 **b 在后面**，直觉容易反过来。先写在纸上再敲。
//   ② 桶  ：从【先修课】出发装它的后继 → 桶是 `out[b]`。
//   ③ 推的值：桶里装【后继 a】，不是 b 自己（装成 b 就是自环）。
//
// ============================================================
// 【核心判据】
// ============================================================
//   入度 = 0  →  没有任何前置依赖  →  【现在就能学】（这批一起入队，又是"多源"）
//   出队一门课 → 把它所有后继的入度 -1 → 谁减到 0 谁入队
//   收尾     →  出队数量 == n ？ 相等 ⟺ 无环 ⟺ 能修完
//
// ============================================================
// ⚠️【本题最大的陷阱：判环对边的方向不敏感 —— 建反了照样能过】
// ============================================================
//   有向图有环 ⟺ 它的【反图】也有环。
//   而本题只问"有没有环"——这个输出量太粗，恰好掩盖了方向错误。
//
//   实测（把 [a,b] 建成了 a→b 的反方向）：
//     · canFinish 布尔值：6 定点 + 5000 组随机对拍 → 【零不一致】，207 真的过
//     · 但用同一张反图去"推学习顺序"：n=2 [[1,0]] 给出 [1,0]（应为 [0,1]）
//     · 随机 1651 个无环用例中，反图给出的顺序有 【997 个非法（60%）】
//
