// ============================================================
// LeetCode 210. 课程表 II
// 考点：拓扑排序（输出具体顺序）+ 判环（Kahn 算法：BFS + 入度）
// 复杂度：时间 O(V+E)，空间 O(V+E)
// 日期：2026-09-24
// ============================================================
//
// 【题意】
// 与 LC 207 完全相同的输入，但要求返回【一个合法的学习顺序】；
// 若无法修完（有环）→ 返回【空数组】。
//
// ============================================================
// 【与 LC 207 的差异：只有三处】
// ============================================================
//   |  | LC 207      | LC 210                    |
//   |--|-------------|---------------------------|
//   | 返回类型 | bool | vector<int>          |
//   | 出队时   | 什么都不用做 | 【把出队的课记进结果】 |
//   | 判环     | 入度非零 → false | 结果长度 ≠ n → 返回【空数组】 |
//
// 【骨架、建图、BFS 全都一样】——所以 207 和 210 应该连起来看：
//   207 只问"有没有环"（输出量粗，方向错了也能过）；
//   210 要具体顺序（输出量细，方向错了必翻车）。
//
// ============================================================
// 【本题实测踩的坑：建图时把"推进桶里的值"写错 → 自环】
// ============================================================
//   写成了：out[e[1]].push_back(e[1]);   // 应该是 e[0]！
//   后果  ：out[b] = {b, b, b, ...} 成了【自环】。
//           弹出 b 时 in[b]-- （本已 0 → 变成 -1），
//           而真正的后继 a 的入度【永远减不到 0】→ 最后 in != 0 → 返回 {}
//
//   实测：官方示例 1、2 全部返回 []（应为 [0,1] / [0,1,2,3]）；
//         随机 4000 组错 1822 组；只把 e[1] 改成 e[0] → 错 0 组。
//
//   ⚠️ 有两个用例"看起来对"，是巧合：
//      · n=1 无任何边 → out 全空，typo 没机会生效
//      · 有环的用例 → 本来就该返回 []，因 bug 返回空反而"对"了
//   所以：**别拿"过了几个用例"判断对错，要拿对拍**。
//
// 【建图三问（提交前必过）】
//   ① 方向：`[a, b]` = 先修 b → 边 b → a
//   ② 桶  ：从先修课出发 → out[b]
//   ③ 推的值：装后继 a，**不是 b 自己**
//
// 【408 标注】与 207 同源。408 也考拓扑排序的 **DFS 实现**（逆后序），
//   两种实现都值得会；Kahn 版的好处是"顺便就判了环"。
// ============================================================

class Solution {
public:
vector<int> findOrder(int n, vector<vector<int>>& p) {
vector<int> ret;
// p[1] -> p[0]：需要学完 p[1]，才能学 p[0]
vector<int> in(n, 0);
vector<vector<int>> out(n);   // 邻接表：out[b] = { 所有以 b 为先修课的课 }
for (auto e : p) {
in[e[0]]++;                    // a 多了一个先修课
out[e[1]].push_back(e[0]);     // b 的后继清单里加上 a
}
queue<int> q;
for (int i = 0; i < (int)in.size(); i++) {
if (in[i] == 0) {              // 没有前置依赖的课，现在就能学
q.push(i);
ret.push_back(i);          // 207 没有这一行
}
}
while (q.size()) {
int size = q.size();
while (size--) {
int cur = q.front();
q.pop();
for (int i = 0; i < (int)out[cur].size(); i++) {
in[out[cur][i]]--;
if (in[out[cur][i]] == 0) {
q.push(out[cur][i]);
ret.push_back(out[cur][i]);   // 207 没有这一行
}
}
}
}
for (auto e : in) {
if (e != 0) return {};         // 有环 → 返回【空数组】，不是已排的那部分
}
return ret;
}
};
