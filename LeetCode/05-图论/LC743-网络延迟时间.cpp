// ============================================================
// LC 743 网络延迟时间（中等）—— Dijkstra 模板的第一道实战
// ------------------------------------------------------------
// 考点：单源带权最短路（Dijkstra）
// 复杂度：O((n + m) log n)
// 日期：2026-11-02（一遍过，AC）
// ------------------------------------------------------------
// 题意：
//   n 个网络节点（编号 1..n），times[i] = [u, v, w] 表示 u 到 v 需要 w 时间。
//   从节点 k 发出信号，求【所有节点都收到信号】的最少时间。
//   有节点收不到 -> 返回 -1。
//
//     times = [[2,1,1],[2,3,1],[3,4,1]], n=4, k=2  ->  2
//     times = [[1,2,1]],                  n=2, k=2  ->  -1
//
// ------------------------------------------------------------
// 【这题 = Dijkstra 模板 + 三行收尾】
// ------------------------------------------------------------
//   和 Algorithm/Lanqiao_competiotion/Dijkstra.hpp 的对应：
//
//   Dijkstra.hpp 里的写法           本题的写法
//   -----------------------------  ------------------------------------
//   g[u] = {{v, w}, ...}           g[u] = {(w, v), ...}      ← 反过来了
//   vector<long long> dist         vector<int> dist          ← 本题数据小，int 够
//   dist 初值 INF（4.5e18）        dist 初值 0x3f3f3f（约 4.1e6）
//   返回整个 dist                  取 max(dist[1..n])，有 INF 则 -1
//
//   ★ 注意 g 里 pair 的顺序：本题把【距离放在 first】。
//     这样 pq 和 g 都是 "pair<距离, 点>"，全篇统一，不容易搞混。
//
// ------------------------------------------------------------
// 【这题特有的三步收尾】
// ------------------------------------------------------------
//   1. 答案不是 dist[某个点]，是 max(dist[1..n])
//      —— 题目问"所有节点都收到"的时间 = 最晚收到那个的时间。
//
//   2. 有节点 INF -> 返回 -1
//      —— 只要有一个点不可达，信号就覆盖不了全网。
//
//   3. 节点编号 1..n，所以 vector 开 n+1，下标 0 空着
//      —— 也可以减 1 变成 0-based，但要全篇一致。
//
// ------------------------------------------------------------
// 【为什么 dist 用 int 就够（本机实测）】
// ------------------------------------------------------------
//   本题约束：n <= 100，w <= 100
//   -> 最长路径 <= 100 * 100 = 10^4
//   -> 用 0x3f3f3f（4144959，约 4.1e6）当 INF 完全够，且不会溢出。
//
//   ⚠️ 但如果题目把 w 放大到 1e9、n 放到 1e5：
//      最长路径能到 1e14 -> 必须改用 long long + 0x3f3f3f3f3f3f3f3f。
//      （Dijkstra.hpp 里用的就是这个 long long 版本）
//
// ------------------------------------------------------------
// 【易错点（这版没踩，但要知道）】
// ------------------------------------------------------------
//   ① 把 g 里存的 (w, v) 和 pq 里的 (dist, node) 顺序搞混
//      -> 松弛时把距离当成点了，答案乱。
//      建议全篇统一成 "pair<距离, 点>"。
//
//   ② 忘了 `if (dist[u] < d) continue;`（过期判断）
//      -> 同一个点被反复扩展，可能 TLE。
//      本题正确性不一定受影响（因为松弛条件还在），但性能会退化。
//
//   ③ 答案写成 dist[n]
//      -> 那是"到最后一个节点"的时间，不是"全网覆盖"的时间。
//
//   ④ 忘了判不可达
//      -> max 里混进 INF（4.1e6），返回一个巨大的数。
//
// ------------------------------------------------------------
// 实测：4 个用例全过（含样例 1/2、单边、三选）
// ============================================================

#include <vector>
#include <queue>
#include <utility>
using namespace std;

class Solution {
public:
    int networkDelayTime(vector<vector<int>>& times, int n, int k) {
        // 处理邻接表
        // g[u] = { (w, v), ... }  —— 距离在前，和 pq 里的顺序一致
        vector<vector<pair<int, int>>> g(n + 1);
        for (auto e : times) {
            g[e[0]].push_back(make_pair(e[2], e[1]));
        }

        vector<int> dist(n + 1, 0x3f3f3f);
        priority_queue<pair<int, int>, vector<pair<int, int>>,
                       greater<pair<int, int>>> q;
        q.push(make_pair(0, k));
        dist[k] = 0;

        while (q.size()) {
            int d = q.top().first;
            int u = q.top().second;
            q.pop();

            if (dist[u] < d) continue;      // 过期：这条是改进前的老记录

            // 从当前节点往外扩
            for (int i = 0; i < (int)g[u].size(); i++) {
                int spot = g[u][i].second;          // 边指向的点
                int distance = g[u][i].first;       // 这条边的代价

                // 如果 src 到 spot 的距离 大于 src 到 u 再到 spot
                // 进行松弛
                if (dist[spot] > dist[u] + distance) {
                    dist[spot] = dist[u] + distance;
                    q.push(make_pair(dist[spot], spot));
                }
            }
        }

        // 收尾：所有节点都收到 = 最晚那个的时间
        int ret = 0;
        for (int i = 1; i <= n; i++) {
            ret = max(ret, dist[i]);
        }
        return ret == 0x3f3f3f ? -1 : ret;
    }
};
