// ============================================================
// LC 787 K 站中转内最便宜的航班 —— 「状态扩展」的经典题
// ------------------------------------------------------------
// 考点：Dijkstra + 状态扩展（dist 从一维变二维）
// 复杂度：时间 O((n·k) log(n·k) + E·k)，空间 O(n·k)
// 日期：2026-11-13 首次（三版未独立写出，最后照分层版抄）
//       2026-11-16 间隔重做，一次写对它（本文件）
// ------------------------------------------------------------
// 题意：
//   n 个城市（0..n-1），flights[i] = [from, to, price] 是一条单向航线。
//   从 src 飞到 dst，最多经过 k 个中转站，求最便宜价格；不可达返回 -1。
//
//     n=3, [[0,1,100],[1,2,100],[0,2,500]], src=0, dst=2, k=1  ->  200
//     同上但 k=0                                              ->  500
//     n=3, [[0,1,100]], src=0, dst=2, k=1                     ->  -1
//
// ============================================================
// 【一、为什么一维 dist 必错（这题的分界线）】
// ============================================================
//   反例：
//       0 → 1  花 100
//       0 → 2  花 1
//       2 → 1  花 1
//       1 → 3  花 1
//       src=0, dst=3, k=1
//
//   正确答案：0 → 1 → 3，花 101（1 次中转：城市 1）
//
//   如果用一维 dist：
//       处理 0：dist[1]=100, dist[2]=1
//       处理 2：到 1 花 1+1=2 < 100  ->  dist[1] 被覆盖成 2
//       处理 1：dist[3] = 2+1 = 3
//       -> 返回 3
//
//   但 0 → 2 → 1 → 3 用了【2 次中转】（城市 2 和城市 1），k=1 根本不允许！
//
//   ★ 一维 dist 把"花费小但中转多"的路径留下，
//     把"花费大但中转少"的合法路径丢掉了。
//   ★ 同一个城市，不同的中转次数是【不同状态】，必须都保留。
//
// ============================================================
// 【二、视角转换：把 "(城市, 中转数)" 当成一个新的"虚拟城市"】
// ============================================================
//   原来的图
//       节点 = 城市 0..n-1
//       边   = 航线
//
//   换视角后的图
//       节点 = (城市, 已用中转数)   —— (2,0)、(2,1)、(2,2) 是三个不同节点
//       边   = 从 (u,c) 飞到 (v,c+1)，代价 = 票价
//
//   -> 这就变成了【一道普通的单源最短路】
//
//   dist[u][c] = 到"虚拟节点 (u,c)"的最短距离
//              = 到城市 u、且用了 c 次中转的最小花费
//
//   ★ 二维数组只是"虚拟节点"的编号方式：(u,c) -> dist[u][c]
//
// ============================================================
// 【三、状态与转移】
// ============================================================
//   dist[u][c]       u: 0..n-1，c: 0..k+1
//                    最多 k 次中转 = 最多 k+1 条边，所以 c 上界是 k+1
//
//   初始：dist[src][0] = 0，起点入堆 (0, src, 0)
//
//   转移（从 (u,c) 飞一条 u->v 的边，票价 w）：
//       nd = dist[u][c] + w
//       如果 nd < dist[v][c+1]  ->  更新，入堆 (nd, v, c+1)
//
//   答案：第一次弹出 dst 时的 cost（Dijkstra 性质）
//
//   ★ 堆里必须是 (花费, 城市, 中转数) 三个元素，且【花费在第一位】
//     （tuple 的 operator< 是字典序，花费在前才是小根堆）
//
// ============================================================
// 【四、两个边界（都踩过）】
// ============================================================
//   ① if (count > k) continue;
//       这个虚拟节点 (u,count) 已经不能再往外飞了（飞完就是 k+2 条边）
//       ★ 用 continue，不是 break！
//         break 会直接退出整个 while，队列里剩下的节点全部丢弃，
//         如果 dst 还没被弹出 -> 明明有解却返回 -1。
//
//   ② if (current == dst) return cost;
//       Dijkstra 第一次弹出终点，就是答案（堆按花费升序）
//
// ============================================================
// 【五、本次踩的坑：dist 第二维的变量名混用】
// ============================================================
//   第一版写成了：
//       if (cc + cost < dist[next][current + 1])
//                                        ↑ current 是【城市】，不是中转数
//
//   current 是城市编号（0..n-1），而 dist 第二维只有 k+2 个格子。
//   城市编号 > k+1 时直接越界；即使不越界，语义也全错。
//
//   正确：dist[next][count + 1]     （count 才是已用中转数）
//
//   ★ 同类坑第 3 次：
//       LC 1650  e 是"值"不是"下标"
//       LC 1584  v 是"vector"还是"int"（遮蔽）
//       LC 787   current 是"城市"还是"中转数"
//
//   判据：dist[a][b] 里 a 必须是"城市"，b 必须是"中转数"。
//
// ============================================================
// 【六、这题有两种写法，都对】
// ============================================================
//   写法 A（本文件）：二维 dist + Dijkstra        O(nk log(nk))
//       dist[u][c]，堆存 (花费, 城市, 中转数)
//
//   写法 B：按"飞了几条边"分层               O(k·E)
//       dist 一维，做 k+1 轮，每轮 nd = dist 拷贝后扫所有边
//       ★ 关键：必须拷贝 nd，否则同一轮内会连续飞多条边
//
//   对比：
//       A 更通用（任何"状态图最短路"都能套），代码长
//       B 更短（15 行），但只能用于"按层推进"的场景
//
//   ★ 上一版（11-13）抄的是 B，这次自己写的是 A —— 两种都掌握了。
//
// ============================================================
// 实测：
//   6 个固定用例（含 101 反例 / 不可达 / k=0 / src=dst 反向）全过
//   与分层版随机对拍 3000 组零不一致
// ============================================================

#include <vector>
#include <tuple>
#include <queue>
using namespace std;

class Solution {
    const int INF = 0x3f3f3f;

public:
    int findCheapestPrice(int n, vector<vector<int>>& flights, int src, int dst, int k) {
        using State = tuple<int, int, int>;      // (花费, 城市, 已用中转数)

        // dist[u][c] = 到城市 u、用了 c 次中转的最小花费
        // c 的范围 0..k+1（最多 k 次中转 = 最多 k+1 条边）
        vector<vector<int>> dist(n, vector<int>(k + 2, INF));
        dist[src][0] = 0;

        // 邻接表
        vector<vector<pair<int, int>>> g(n);
        for (auto& e : flights) {
            g[e[0]].push_back(make_pair(e[1], e[2]));   // (目的地, 票价)
        }

        // 小根堆：花费在第一位（tuple 按字典序比较）
        priority_queue<State, vector<State>, greater<State>> q;
        q.push(make_tuple(0, src, 0));

        while (q.size()) {
            State t = q.top();
            q.pop();

            int cost    = get<0>(t);
            int current = get<1>(t);       // 城市
            int count   = get<2>(t);       // 已用中转数

            if (cost > dist[current][count]) continue;   // 过期：改进前的旧记录
            if (current == dst) return cost;             // 第一次弹出终点 = 答案
            if (count > k) continue;                     // 中转次数用完，只跳过这个节点

            for (auto& e : g[current]) {
                int next = e.first;
                int cc   = e.second;
                int nd   = cost + cc;

                // 虚拟节点是 (next, count+1)，不是 (next, current+1)
                if (nd < dist[next][count + 1]) {
                    dist[next][count + 1] = nd;
                    q.push(make_tuple(nd, next, count + 1));
                }
            }
        }
        return -1;
    }
};
