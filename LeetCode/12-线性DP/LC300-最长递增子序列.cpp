// ============================================================
// LC 300 最长递增子序列（LIS）—— 线性 DP 的核心模型
// ------------------------------------------------------------
// 考点：线性 DP · 状态 = "以 i 结尾"（子序列模型的标志性定义）
//       + O(n log n) 的二分 + 贪心优化
// 复杂度：解一 O(n²) / 解二 O(n log n) / 解三 O(n log n)（手写二分）
// 日期：2026-11-03（O(n²) 版，5 分钟写对）
//       2026-11-14（O(n log n) 二分版，用 lower_bound）
//       2026-11-24（同思路手写二分，不依赖 STL）
// ------------------------------------------------------------
// 题意：
//   给整数数组 nums，找最长的【严格递增】子序列长度（可不连续，顺序不变）。
//
//     [10,9,2,5,3,7,101,18]  ->  4   （[2,3,7,101] 或 [2,3,7,18]）
//     [0,1,0,3,2,3]          ->  4
//     [7,7,7,7]              ->  1   （严格递增，相等不算）
//
// ============================================================
// 【解一：O(n²) DP —— 状态怎么定是唯一难点】
// ============================================================
//   错定义：dp[i] = "前 i 个元素的最长递增子序列"  -> 推不出来
//     （因为不知道第 i 个能不能接上，取决于"前面那个子序列最后是谁"）
//
//   对定义：dp[i] = 以 nums[i]【结尾】的最长递增子序列长度
//
//   判据：要判断"nums[i] 能不能接在某个子序列后面"，
//        必须知道那个子序列的【最后元素】 -> 状态必须钉住"结尾是谁"。
//
//   转移：dp[i] = max( dp[j] + 1 )   对所有 j < i 且 nums[j] < nums[i]
//   答案：max(dp[0..n-1])            ← 最长的不一定在最后一个
//
//   和背包的区别：
//       背包   ：状态 = "前 i 个 + 容量"，问"选哪些"
//       LIS    ：状态 = "以 i 结尾"，问"接在谁后面"
//
// ============================================================
// 【解二：O(n log n) —— 二分 + 贪心（蓝桥杯进阶会考）】
// ============================================================
//   ★ 核心数组 tails：
//
//       tails[k] = 所有长度为 (k+1) 的递增子序列中，【结尾最小】的那个值
//
//   为什么关心"结尾最小"：
//       结尾越小，后面越容易接上新元素 —— 这是一个纯贪心的选择。
//
//   对每个 nums[i]：
//       在 tails 里用 lower_bound 找【第一个 >= nums[i] 的位置】
//           找到了 -> tails[pos] = nums[i]      （用更小的结尾替换掉）
//           没找到 -> 追加到末尾                 （说明能接出更长的）
//
//   答案 = tails.size()
//
//   ------------------------------------------------------------
//   【★ 必须记住：tails 不一定是真实存在的子序列】
//   ------------------------------------------------------------
//       看 [3,4,5,1]：
//           3 -> [3]
//           4 -> [3,4]
//           5 -> [3,4,5]
//           1 -> 第一个 >=1 是 3，替换 -> [1,4,5]
//
//       tails = [1,4,5]，但原数组里 1 在 4、5 后面，
//       不存在子序列 [1,4,5]。
//
//       但长度 3 是对的（真实 LIS 是 [3,4,5]）。
//
//       -> tails 只保证"长度正确"，不保证"内容是一个真实子序列"。
//          所以这题不能用来输出具体的 LIS（要输出得另记前驱）。
//
//   ------------------------------------------------------------
//   【lower_bound vs upper_bound（选错就差在这一个边界）】
//   ------------------------------------------------------------
//       lower_bound(begin, end, x) -> 第一个【>= x】的位置
//       upper_bound(begin, end, x) -> 第一个【>  x】的位置
//
//       本题是【严格递增】(nums[j] < nums[i])  ->  lower_bound
//       若题目改成"非严格递增"(<=)              ->  upper_bound
//
//       例：[1,3,5]，x=3
//           lower_bound 指向 3
//           upper_bound 指向 5
//
// ============================================================
// 【本次踩的坑：替换位置找成了"末尾"】
// ============================================================
//   第一版写成：
//       if (!tmp.empty() && tmp.back() >= e) {
//           tmp.pop_back();
//           tmp.push_back(e);        // 只和末尾比，然后替换末尾
//       }
//
//   错因：e 该替换的位置往往【不是末尾】。
//
//       看 [1,3,5,2,4]：
//           e=2 时 tmp=[1,3,5]，你的代码替换末尾的 5 -> [1,3,2]
//           ★ 数组不再递增！size() 就失去意义了
//           正确：2 应该替换 3（第一个 >=2 的位置）-> [1,2,5]
//
//   实测：2000 组随机数据里错 702 组（35%）。
//   而官方样例 [10,9,2,...] 恰好每次替换都在末尾 -> 碰巧对。
//
//   判据：**tails 必须始终递增**，否则"长度"这个答案就没有意义。
//
// ============================================================
// 实测：
//   解一：6 个用例全过
//   解二：8 个用例 + 与解一随机对拍 3000 组零不一致
//        n = 100000 时（Python 等价实现）0.0094 秒
// ============================================================

#include <vector>
#include <algorithm>
using namespace std;

// ------------------------------------------------------------
// 解一：O(n²) DP —— 用来理解模型
// ------------------------------------------------------------
class Solution {
public:
    int lengthOfLIS(vector<int>& nums) {
        int n = nums.size();
        // dp[i] = 以 nums[i] 结尾的最长递增子序列长度
        vector<int> dp(n, 1);                  // 至少自己一个
        int ret = 1;

        for (int i = 0; i < n; i++) {
            for (int j = 0; j < i; j++) {      // 只看前面的元素
                if (nums[j] < nums[i]) {       // 严格递增
                    dp[i] = max(dp[i], dp[j] + 1);
                }
            }
            ret = max(ret, dp[i]);
        }
        return ret;
    }
};

// ------------------------------------------------------------
// 解二：O(n log n) 二分 + 贪心
// ------------------------------------------------------------
class Solution2 {
public:
    int lengthOfLIS(vector<int>& nums) {
        vector<int> tails;       // tails[k] = 长度 k+1 的递增子序列中，最小的结尾

        for (auto e : nums) {
            // 第一个 >= e 的位置（严格递增用 lower_bound）
            auto it = lower_bound(tails.begin(), tails.end(), e);

            if (it == tails.end()) {
                tails.push_back(e);      // 全都比 e 小 -> 能接出更长的
            } else {
                *it = e;                 // 用更小的结尾替换掉
            }
        }
        return tails.size();
    }
};

// ------------------------------------------------------------
// 解三：O(n log n) —— 同样的 tails，但二分手写（2026-11-24）
// ------------------------------------------------------------
//   和解二完全等价，只是把 lower_bound 自己写出来。
//   考场上如果不想记 lower_bound / upper_bound 的差别，
//   手写这个更容易控制边界。
//
//   【手写 lower_bound 的标准骨架】
//       left = 0, right = size - 1
//       while (left < right) {
//           mid = (left + right) / 2;
//           if (arr[mid] < x) left = mid + 1;   // 太小，往右找
//           else              right = mid;      // 够大，mid 可能就是答案
//       }
//       // 循环结束时 left == right，且 arr[left] 是第一个 >= x 的位置
//
//   【为什么用 while(left < right) 而不是 <=】
//       用 < 的时候，区间是 [left, right] 且 left 永远不会超过 right，
//       退出时 left 就停在"第一个满足条件的下标"上，不用再判断一次。
//       这是最省心的写法：结束时直接 ret[left] = nums[i]。
//
//   【为什么 left 一定不会越界】
//       进入 else 分支的前提是 nums[i] <= ret.back()（否则在上面的 if 里
//       就 push_back 了）。所以 ret 里至少存在一个 >= nums[i] 的元素，
//       即位置 size-1 合格，left 一定落在 [0, size-1] 内。
//
//   【一个不影响的细节】
//       mid = (left + right) >> 1 在 left+right 溢出 int 时会出错。
//       本题 n <= 2500，left+right <= 5000，安全。
//       若数据量到 1e9 级，要写成 left + (right - left) / 2。
//
//   【验证】
//       8 组定点（含 [3,4,5,1] 这种 tails 不等于真实子序列的用例）
//       + 与 O(n²) DP 随机对拍 20000 组零不一致
//       + n = 1e5 实测 5.86 ms
// ------------------------------------------------------------
class Solution3 {
public:
    int lengthOfLIS(vector<int>& nums) {
        int n = nums.size();
        vector<int> ret;
        ret.push_back(nums[0]);

        for (int i = 1; i < n; i++) {
            if (nums[i] > ret.back()) {
                ret.push_back(nums[i]);          // 能接出更长的
            } else {
                // 手写 lower_bound：找第一个 >= nums[i] 的位置
                int left = 0, right = ret.size() - 1;
                while (left < right) {
                    int mid = (right + left) >> 1;
                    if (ret[mid] < nums[i]) left = mid + 1;   // 太小，往右
                    else                    right = mid;      // 够大，mid 可能是答案
                }
                ret[left] = nums[i];             // 用更小的结尾替换
            }
        }
        return ret.size();
    }
};
