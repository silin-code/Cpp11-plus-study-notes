// ============================================================
// LC 300 最长递增子序列（LIS）—— 线性 DP 的核心模型
// ------------------------------------------------------------
// 考点：线性 DP · 状态 = "以 i 结尾"（子序列模型的标志性定义）
// 复杂度：时间 O(n²)，空间 O(n)
// 日期：2026-11-03（5 分钟写对）
// ------------------------------------------------------------
// 题意：
//   给整数数组 nums，找最长的【严格递增】子序列长度（可不连续，顺序不变）。
//
//     [10,9,2,5,3,7,101,18]  ->  4   （[2,3,7,101] 或 [2,3,7,18]）
//     [0,1,0,3,2,3]          ->  4
//     [7,7,7,7]              ->  1   （严格递增，相等不算）
//
// ------------------------------------------------------------
// 【★ 本题唯一的难点：状态怎么定】
// ------------------------------------------------------------
//   错定义：dp[i] = "前 i 个元素的最长递增子序列"  -> 推不出来
//     （因为不知道第 i 个能不能接上，取决于"前面那个子序列最后是谁"）
//
//   对定义：dp[i] = 以 nums[i]【结尾】的最长递增子序列长度
//     （"必须选 nums[i] 当结尾" -> 最后一个是确定的 -> 可以判断能不能接）
//
//   判据：要判断"nums[i] 能不能接在某个子序列后面"，必须知道那个子序列的【最后元素】。
//        -> 所以状态必须钉住"结尾是谁"。
//
// ------------------------------------------------------------
// 【转移】
// ------------------------------------------------------------
//   dp[i] = max( dp[j] + 1 )      对所有 j < i 且 nums[j] < nums[i]
//   （接到以 nums[j] 结尾的递增子序列后面，长度 +1）
//   如果没有这样的 j -> dp[i] = 1（自己单独一个）
//
//   答案 = max(dp[0..n-1])        ← 最长的不一定在最后一个，必须扫一遍取 max
//
// ------------------------------------------------------------
// 【和之前那些 DP 的关系】
// ------------------------------------------------------------
//   背包   ：状态 = "前 i 个 + 容量"，问"选哪些"
//   LIS/子序列：状态 = "以 i 结尾"，问"接在谁后面"
//   这是两类不同的模型，别混（LC 474 那次就是把"以 i 结尾"套到了背包上）。
//
// ------------------------------------------------------------
// 【两种解法】
// ------------------------------------------------------------
//   ① O(n²) DP（本文件）：dp[i] = max(dp[j] + 1)
//   ② O(n log n) 二分 + 贪心：维护一个"最小结尾"数组 tails，
//      用 lower_bound 替换。蓝桥杯进阶会考，学完 ① 再补。
//
// ------------------------------------------------------------
// 实测：6 个用例全过（含官方样例 / 全相等 / 单元素 / 严格递增）
// ============================================================

#include <vector>
#include <algorithm>
using namespace std;

class Solution {
public:
    int lengthOfLIS(vector<int>& nums) {
        int n = nums.size();
        // dp[i] = 以 nums[i] 结尾的最长递增子序列长度
        vector<int> dp(n, 1);                  // 至少自己一个
        int ret = 1;

        for (int i = 0; i < n; i++) {
            for (int j = 0; j < i; j++) {      // 只看前面的元素
                if (nums[j] < nums[i]) {       // 严格递增
                    dp[i] = max(dp[i], dp[j] + 1);
                }
            }
            ret = max(ret, dp[i]);
        }
        return ret;
    }
};
