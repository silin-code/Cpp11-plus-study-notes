// ============================================================
// LC 674 最长连续递增序列 —— LIS 的"连续"版，退化成一趟扫描
// ------------------------------------------------------------
// 考点：连续子数组的线性扫描（DP 的退化形态）
// 复杂度：时间 O(n)，空间 O(1)
// 日期：2026-11-24（一次写对）
// ------------------------------------------------------------
// 题意：
//   找【连续】且严格递增的最长子数组长度。
//     [1,3,5,4,7]  -> 3   （1,3,5）
//     [2,2,2,2,2]  -> 1   （严格递增，相等不算）
//
// ============================================================
// 【和 LC 300 只差一个词：连续】
// ============================================================
//   LC 300（子序列，可不连续）：
//       dp[i] = max(dp[j] + 1)  对所有 j < i 且 nums[j] < nums[i]
//       -> 要看前面所有元素，必须二重循环
//       -> 想优化到 O(n log n) 得额外维护 tails 数组
//
//   LC 674（子数组，必须连续）：
//       dp[i] = nums[i] > nums[i-1] ? dp[i-1] + 1 : 1
//       -> 只依赖【前一个】元素，一重循环
//       -> dp 数组都不用开，一个变量 tmp 就够
//
//   对照表：
//   ---------------------------------------------------------
//   | | LC 300 LIS | LC 674 LCIS |
//   |---|---|---|
//   | 是否连续 | 不要求 | 必须连续 |
//   | 转移依赖 | 前面所有 j | 只有 i-1 |
//   | 复杂度 | O(n²) / O(n log n) | O(n) |
//   | 辅助结构 | tails 数组 | 一个变量 |
//   ---------------------------------------------------------
//
//   ★ 一句话：「连续」这个约束把"看前面所有元素"降成了"只看前一个"。
//     这是所有"子数组 vs 子序列"题的第一分叉点，先判断这个再动手。
//
// ============================================================
// 【代码里的两个写法细节】
// ============================================================
//   1. while (++right < nums.size())
//      ++right 是【先自增再比较】，所以第一次进入循环体时 right == 1，
//      访问 nums[right-1] == nums[0]，正好从第 2 个元素开始比。
//
//   2. 循环结束后还要再来一次 ret = max(ret, tmp)
//      因为最后一段递增可能在数组末尾"没收尾"：
//        [1,2,3,2,3,4,5] 最后一段 2,3,4,5 一直没遇到"下降"，
//        不补这一句，答案会停在 3 而不是 4。
//      ★ 这是"边扫边结算"类题目的通用坑：
//        循环里只在【断开时】结算，最后一段必须在循环外补一次。
//
// ============================================================
// 【验证】
// ============================================================
//   8 组定点：两个官方示例 + 全递增 + 全递减 + n=1 + n=2（升/降）
//            + [1,2,3,2,3,4,5,1]（末段最长）
//   与 O(n²) 暴力随机对拍 20000 组（n<=20，值<10）零不一致。
// ============================================================

#include <vector>
#include <algorithm>
using namespace std;

class Solution {
public:
    int findLengthOfLCIS(vector<int>& nums) {
        int ret = 1;             // 至少 1 个
        int tmp = 1;             // 当前这段连续递增的长度
        int right = 0;

        // ++right 先自增：第一次进来 right == 1
        while (++right < (int)nums.size()) {
            if (nums[right] > nums[right - 1]) {
                tmp++;                       // 还在爬坡，继续加长
            } else {
                ret = max(ret, tmp);         // 坡断了，结算
                tmp = 1;                     // 从当前元素重新起算
            }
        }

        ret = max(ret, tmp);     // ★ 收尾：最后一段可能一直没断
        return ret;
    }
};
