// ============================================================
// LC 198 打家劫舍（House Robber）—— 「选 / 不选」型线性 DP
// ------------------------------------------------------------
// 考点：线性 DP · 选不选（相邻不能同时选）
// 复杂度：时间 O(n)，空间 O(n)
// 日期：2026-11-05（初版 dp[1] 初始化漏了"二选一"，改一处后 AC）
// ------------------------------------------------------------
// 题意：
//   一排房子，每间金额 nums[i]。相邻两间不能同时偷，求最多偷多少。
//
//     [1,2,3,1]   ->  4   （偷第 1、3 间：1+3）
//     [2,7,9,3,1] ->  12  （2+9+1）
//
// ------------------------------------------------------------
// 【状态定义】（用户版："前 i+1 个"，下标从 0 起）
// ------------------------------------------------------------
//   dp[i] = 前 i+1 个房子（第 0..i 间）能偷到的最大金额
//
//   对应标准版（"前 i 个"）就是 dp[i] = 前 i 个房子，答案 dp[n]。
//   两种都是"选不选"模型，只是下标错位。
//
// ------------------------------------------------------------
// 【转移：对第 i 个房子，两种选择】
// ------------------------------------------------------------
//   不偷第 i 个 -> dp[i-1]
//   偷第 i 个   -> dp[i-2] + nums[i]     （第 i-1 个不能偷，跳到 i-2）
//
//   dp[i] = max(dp[i-1], dp[i-2] + nums[i])
//
// ------------------------------------------------------------
// 【边界】
// ------------------------------------------------------------
//   dp[0] = nums[0]                          （只有第 0 间，偷它）
//   dp[1] = max(nums[0], nums[1])            （前 2 间，相邻只能二选一）
//
//   ★ 本次踩的坑：初版写 dp[1] = nums[1]，等于默认"一定偷第 1 间、放弃第 0 间"，
//     漏了 nums[0] > nums[1] 的情况。
//     反例 [5,1,1,5]：dp[1]=1 把 5 丢了 -> 一路错 -> 得 6（应 10）。
//
// ------------------------------------------------------------
// 【线性 DP 的四类模型（到这里就齐了）】
// ------------------------------------------------------------
//   以 i 结尾          LIS 300         状态必须钉住"结尾是谁"
//   前 i vs 前 j       LCS 1143 / 编辑距离 72   双序列
//   选 / 不选          打家劫舍 198      （最像背包，但只有一维、没容量）
// ------------------------------------------------------------
// 实测：8 个用例全过（含官方 / 首尾都要偷 / 跳过中间 / 单元素 / 两元素）
// ============================================================

#include <vector>
#include <algorithm>
using namespace std;

class Solution {
public:
    int rob(vector<int>& nums) {
        int n = nums.size();
        vector<int> dp(n + 1, 0);

        if (n < 2) {
            return nums[0];
        }

        dp[0] = nums[0];                       // 只有第 0 间，偷它
        dp[1] = max(nums[0], nums[1]);         // 前 2 间，相邻只能二选一

        for (int i = 2; i < n; i++) {
            // 不偷第 i 个 vs 偷第 i 个（跳到 i-2）
            dp[i] = max(dp[i - 1], dp[i - 2] + nums[i]);
        }
        return max(dp[n - 2], dp[n - 1]);      // 最长的不一定在最后一个
    }
};
