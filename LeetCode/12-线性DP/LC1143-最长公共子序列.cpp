// ============================================================
// LC 1143 最长公共子序列（LCS）—— 「两个序列」的二维 DP
// ------------------------------------------------------------
// 考点：二维 DP · 双序列（和 LIS 的"以 i 结尾"是不同模型）
// 复杂度：时间 O(n×m)，空间 O(n×m)
// 日期：2026-11-04（2 分 37 秒写对）
// ------------------------------------------------------------
// 题意：
//   给两个字符串，求最长公共子序列的长度（可不连续，顺序保持）。
//
//     "abcde" vs "ace"  ->  3   （"ace"）
//     "abc"   vs "def"  ->  0
//
// ------------------------------------------------------------
// 【状态定义】
// ------------------------------------------------------------
//   dp[i][j] = text1 前 i 个字符 和 text2 前 j 个字符 的最长公共子序列长度
//
//   下标 0 表示"空串" -> dp[i][0] = 0、dp[0][j] = 0（和空串无公共子序列）
//
// ------------------------------------------------------------
// 【转移：只看最后一个字符】
// ------------------------------------------------------------
//   情况 A：text1[i-1] == text2[j-1]（最后两个字符相同）
//       dp[i][j] = dp[i-1][j-1] + 1
//       这对字符一定在公共子序列里，都选上。
//
//   情况 B：不同
//       dp[i][j] = max(dp[i-1][j], dp[i][j-1])
//       两个字符不可能同时在公共子序列里 -> 至少丢一个，取大的。
//
// ------------------------------------------------------------
// 【和 LIS 的区别（两个模型别混）】
// ------------------------------------------------------------
//   LIS：  一个序列，状态 = "以 i 结尾"（要知道前一个子序列最后是谁）
//   LCS：  两个序列，状态 = "前 i 个 vs 前 j 个"（双指针各扫一个）
//   编辑距离(LC72)：LCS 的升级，转移有三种操作（增/删/改）
//
// ------------------------------------------------------------
// 实测：6 个用例全过（含官方 / 空串 / 相同串 / 无公共）
// ============================================================

#include <vector>
#include <string>
#include <algorithm>
using namespace std;

class Solution {
public:
    int longestCommonSubsequence(string text1, string text2) {
        int n = text1.size();
        int m = text2.size();

        // dp[i][j] = text1 前 i 个 和 text2 前 j 个 的最长公共子序列长度
        vector<vector<int>> dp(n + 1, vector<int>(m + 1, 0));

        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= m; j++) {
                if (text1[i - 1] == text2[j - 1]) {
                    dp[i][j] = dp[i - 1][j - 1] + 1;   // 相同：左上角 +1
                } else {
                    dp[i][j] = max(dp[i - 1][j], dp[i][j - 1]);  // 不同：取上/左较大
                }
            }
        }
        return dp[n][m];
    }
};
