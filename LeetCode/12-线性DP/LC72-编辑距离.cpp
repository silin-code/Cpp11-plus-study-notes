// ============================================================
// LC 72 编辑距离（Edit Distance）—— LCS 的升级版
// ------------------------------------------------------------
// 考点：二维 DP · 双序列 · 三种操作（增/删/改）
// 复杂度：时间 O(n×m)，空间 O(n×m)
// 日期：2026-11-04（卡在边界，补全后 AC）
// ------------------------------------------------------------
// 题意：
//   把 word1 转成 word2，三种操作（插入/删除/替换）各算 1 次，求最少操作数。
//
//     "horse" -> "ros"          ->  3
//     "intention" -> "execution" ->  5
//
// ------------------------------------------------------------
// 【状态定义】
// ------------------------------------------------------------
//   dp[i][j] = 把 word1 前 i 个字符，转成 word2 前 j 个字符，最少操作几次
//
// ------------------------------------------------------------
// 【边界（这题的核心，和 LCS 最大的不同）】
// ------------------------------------------------------------
//   dp[i][0] = i   把 word1 前 i 个字符【删光】成空串，每个字符删一下 -> i 次
//   dp[0][j] = j   把空串【插入】成 word2 前 j 个字符，每个字符插一下 -> j 次
//
//   ★ 这两个边界不是"特判"，是"把串删光 / 从零插入"这两种【合法中间状态】
//     的真值。转移里的 dp[i-1][0]、dp[i][0] 随时引用它们，所以必须填真值，
//     不能是 INF（会炸）也不能是 0（会偏小）。
//
// ------------------------------------------------------------
// 【转移：只看最后一个字符，三种动作】
// ------------------------------------------------------------
//   情况 A：word1[i-1] == word2[j-1]（最后两个字符相同）
//       dp[i][j] = dp[i-1][j-1]         // 白捡，不用动
//
//   情况 B：不同，三种操作取最小：
//       ① 删除 word1 的最后一个   -> dp[i-1][j]   + 1   （上方）
//       ② 插入 word2 的最后一个   -> dp[i][j-1]   + 1   （左方）
//       ③ 替换（改成一样）        -> dp[i-1][j-1] + 1   （左上角）
//       dp[i][j] = 1 + min(dp[i-1][j], dp[i][j-1], dp[i-1][j-1])
//
// ------------------------------------------------------------
// 【三个操作的方向口诀】
// ------------------------------------------------------------
//   上（删）· 左（插）· 左上（改）
//
// ------------------------------------------------------------
// 【踩过的坑（本次）】
// ------------------------------------------------------------
//   初版只写了 dp[0][0] = 0，其余全 INF，还加了个 if(n==0||m==0) 特判。
//   结果 8/9 用例"碰巧对"，唯独 "abc"->"yabd" 错（4，应为 2）。
//   原因：dp[i][0]（i≥1）和 dp[0][j]（j≥1）没填，而它们会在两个串都不为空
//         时被转移引用 -> 取到 INF -> 答案偏大。
//   修法：删掉特判，填全两行边界。
// ------------------------------------------------------------
// 实测：9 个用例全过（含官方 / 删空 / 插空 / 全相同 / LC 标准题 abc->yabd=2）
// ============================================================

#include <vector>
#include <string>
#include <algorithm>
using namespace std;

class Solution {
public:
    int minDistance(string word1, string word2) {
        int n = word1.size();
        int m = word2.size();

        vector<vector<int>> dp(n + 1, vector<int>(m + 1, 0x3f3f3f));

        // 边界①：把 word1 前 i 个字符删光 -> i 次
        for (int i = 0; i <= n; i++)
            dp[i][0] = i;

        // 边界②：把空串插成 word2 前 j 个字符 -> j 次
        for (int j = 0; j <= m; j++)
            dp[0][j] = j;

        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= m; j++) {
                if (word1[i - 1] == word2[j - 1]) {
                    dp[i][j] = dp[i - 1][j - 1];          // 相同：白捡
                } else {
                    // 不同：三种操作取最小（上=删、左=插、左上=改）
                    dp[i][j] = 1 + min(dp[i - 1][j],
                              min(dp[i - 1][j - 1], dp[i][j - 1]));
                }
            }
        }
        return dp[n][m];
    }
};
