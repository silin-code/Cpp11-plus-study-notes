// ============================================================
// LC 1202 交换字符串中的元素 —— 并查集 + 分组排序
// ------------------------------------------------------------
// 考点：识别"等价关系" -> 并查集；组内排序
// 复杂度：时间 O(n log n + p·α(n))，空间 O(n)
// 日期：2026-11-18
// 自我评价：**完全没思路**（卡在"想不到用并查集"，不是实现）
// ------------------------------------------------------------
// 题意：
//   给字符串 s 和索引对 pairs。
//   pairs[i] = [a, b] 表示可以交换 s[a] 和 s[b]（任意多次、任意顺序）。
//   求经过若干次交换后，字典序最小的 s。
//
//     s="dcab", pairs=[[0,3],[1,2]]        ->  "bacd"
//     s="dcab", pairs=[[0,3],[1,2],[0,2]]  ->  "abcd"
//     s="cba",  pairs=[[0,1],[1,2]]        ->  "abc"
//
//   数据范围：n <= 1e5，pairs <= 1e5 —— 暴力枚举交换必超时。
//
// ============================================================
// 【一、这题的坎：看出"可以交换"是一种【等价关系】】
// ============================================================
//   你做过 547（数连通块）/ 684（找多余边）/ 990（等式方程），
//   那三道题都在题干里【明说】或强烈暗示"用并查集"。
//
//   这题没有。它要你自己看出：
//
//       位置 0 和 3 能换，3 和 5 能换
//       -> 位置 0 上的字符能到 5（0 -> 3 -> 5）
//       -> 所以"能互相交换"具有【传递性】
//
//   自反 + 对称 + 传递 = 等价关系 = 把位置划成若干组
//
//   ★ 判据（背这一条）：
//       题目里出现"可以互相到达 / 可以互换 / 传递性"的关系，
//       且问"能不能 / 怎么分组" -> 想到并查集。
//
//   同类型信号：
//       "朋友的朋友也是朋友"      -> 并查集
//       "两个邮箱属于同一个人"    -> 并查集
//       "位置 i 和 j 可以交换"    -> 并查集
//
// ============================================================
// 【二、三步解法】
// ============================================================
//   ① 并查集：把每个 pair 的两端合并 -> 得到若干"可互换组"
//
//   ② 按根分组：根 -> 该组的所有位置；根 -> 该组的所有字符
//      两张表可以【一次遍历】同时填好
//
//   ③ 组内排序后填回：
//      每组字符升序排列，按位置从小到大依次放回
//
//   为什么③最优：
//      组内位置是固定的，字符可以在组内任意摆放
//      -> 让小的字符占小的位置，字典序必然最小
//
// ============================================================
// 【三、两个坑（都踩了）】
// ============================================================
//   ① Union 少了 "同一组直接返回"
//
//        void Union(int x, int y) {
//            int p1 = find(x), p2 = find(y);
//            // 少 if (p1 == p2) return;
//            if (p[p1] > p[p2]) swap(p1, p2);
//            p[p1] += p[p2];
//            p[p2] = p1;
//        }
//
//      如果 p1 == p2（两端已在同一组）：
//            p[p1] += p[p2]   ->  -3 变成 -6（自己加自己）
//            p[p2]  = p1      ->  p[p1] = p1，把【负数根】覆盖成【正数下标】
//      -> find 时 p[x] 不小于 0 -> 继续递归 -> 无限递归 -> 栈溢出
//
//      ★ 判据：Union 的第一件事永远是"是不是同一组"，是就直接 return。
//        684 / 990 的代码里都有这一行，这次漏了。
//
//   ② find 写成 return p[x] = find(p[x]);
//
//        int find(int x) {
//            if (p[x] < 0) return p[x] = find(p[x]);   // ✗
//        }
//
//      p[x] < 0 表示"x 是根"，应该直接 return x。
//      写成递归会对负数下标继续查找 —— 又是无限递归。
//
// ============================================================
// 【四、为什么"位置按 i 升序收集"很重要】
// ============================================================
//   同一个根下：
//       groups[r] 是按 i 从 0 到 n-1 收集的 -> 天然升序
//       chars[r]  也是同样的顺序收集          -> 和 groups[r] 一一对应
//
//   排序 chars[r] 之后：
//       第 k 小的位置（groups[r][k]）放第 k 小的字符（chars[r][k]）
//
//   ★ 如果 groups[r] 不是升序，这个"第 k 个对第 k 个"的对应就错了。
//     这也是为什么两张表要在同一个 for 里、按 i 递增同时收集。
//
// ============================================================
// 实测：
//   7 个固定用例（含空 pairs / 单字符 / 全连通）全过
//   与 BFS 暴力（枚举所有可达字符串）随机对拍 2000 组零不一致
//   n = 100000 + pairs 100000：0.085 秒
// ============================================================

#include <string>
#include <vector>
#include <algorithm>
using namespace std;

class Solution {
    int n;
    vector<int> p;

    // 负数约定：p[x] < 0 表示 x 是根，-p[x] = 集合大小
    int find(int x) {
        if (p[x] < 0) {
            return x;                    // ★ 根就返回自己，不要再递归
        }
        return p[x] = find(p[x]);        // 路径压缩
    }

    void Union(int x, int y) {
        int p1 = find(x);
        int p2 = find(y);
        if (p1 == p2) return;            // ★ 同一组直接返回，否则会把自己挂成环

        if (p[p1] > p[p2]) {             // p[i] 是负的集合大小，越大集合越小
            swap(p1, p2);
        }
        p[p1] += p[p2];
        p[p2] = p1;
    }

public:
    string smallestStringWithSwaps(string s, vector<vector<int>>& pairs) {
        n = s.size();
        p.assign(n, -1);

        // ① 合并所有可交换的位置
        for (auto& e : pairs) {
            Union(e[0], e[1]);
        }

        // ② 按根分组：一次遍历，两张表同时填
        vector<vector<int>>  groups(n);      // 根 -> 该组的位置（天然升序）
        vector<vector<char>> chars(n);       // 根 -> 该组的字符（与 groups 一一对应）

        for (int i = 0; i < n; i++) {
            int r = find(i);
            groups[r].push_back(i);
            chars[r].push_back(s[i]);
        }

        // ③ 每组：字符升序 -> 第 k 小的位置放第 k 小的字符
        for (int r = 0; r < n; r++) {
            sort(chars[r].begin(), chars[r].end());

            for (int k = 0; k < (int)groups[r].size(); k++) {
                s[groups[r][k]] = chars[r][k];
            }
        }
        return s;
    }
};
