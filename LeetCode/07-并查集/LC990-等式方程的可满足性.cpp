// ============================================================
// LC 990 等式方程的可满足性
// ------------------------------------------------------------
// 考点：并查集（**负数约定**）+ 「两趟处理」
// 复杂度：时间 O(n · α(26)) ≈ O(n)（每个方程一次 find/unite），空间 O(26)
// 日期：2026-10-02（当天从零学并查集：零件 → 547 → 本题）
// ------------------------------------------------------------
// 题意：
//   给一堆形如 "a==b" / "a!=b" 的方程（变量是单个小写字母），
//   问这组方程能不能【同时成立】。
//     ["a==b","b!=a"]         -> false
//     ["b==a","a==b"]         -> true
//     ["a==b","b==c","a==c"]  -> true
//     ["a==b","b!=c","c==a"]  -> false
// ------------------------------------------------------------
// 思路（关键：**两趟**）：
//   ① 第一趟：只看 "=="，把它们全部 unite —— 先把所有"必须相等"的关系建起来
//   ② 第二趟：只看 "!="，检查两端是否已在同一组；在 → 矛盾，返回 false
//
//   为什么必须两趟？
//     若按数组顺序一条条处理，遇到 "!=" 时它依赖的 "==" 可能还没被执行。
//     例：["a!=b","a==b"] 单趟会漏检（检查时 a、b 还没合并）→ 错答 true。
//     第一趟结束后，"相等关系"已经全部就位，第二趟的每个检查都是最终的。
//
//   变量映射：'a'..'z' → 0..25，就是 `c - 'a'`（与 LC 1684 同一个动作）。
// ------------------------------------------------------------
// 易错点：
//   ① 【最隐蔽】判据写成 `e[2]` —— **`e[2]` 永远是 `'='`**
//        "a==b"  ->  [0]='a' [1]='=' [2]='=' [3]='b'
//        "a!=b"  ->  [0]='a' [1]='!' [2]='=' [3]='b'
//      符号位在 **`e[1]`**。写 `if (f == '=')` 会对【所有】方程成立 →
//      所有 `!=` 被当成 `==` 合并，检查分支永不执行 → **恒返回 true**
//      （实测 4 个官方用例错 2 个：全都返回 true）
//   ② `find(c1)` 少了 `- 'a'` —— 合并走 p[0..25]，检查走 p[97..122]（ASCII 值），
//      **两条路完全不重叠**，检查永远看不到合并。
//      （原稿把数组开到 501，恰好把越界盖住了：不崩、但答案全错）
//   ③ 单趟处理 → 顺序依赖（见上「为什么必须两趟」）
//   ④ `p.resize(26, -1)` 多组数据不复位：**尺寸相同时 resize 什么都不做** →
//      第二次调用仍带着上一次的合并结果。实测 call1 ["a==b"]→true、
//      call2 ["a!=b"]→false（应 true）。改用 **`assign`**。
//      （同类坑第三次：LC 78 的 `ret` 未清空、LC 200 的 `resize`）
// ------------------------------------------------------------
// 实测：7 个用例（4 官方 + 3 反序）全对；
//      30000 组随机对拍 vs 独立参考（substr 解析 + BFS 判连通）零不一致；
//      同一对象连续调用正确（assign 复位生效）
// ============================================================

class Solution {
public:
    bool equationsPossible(vector<string>& equations) {
        p.assign(26, -1);                                     // 负数约定：-1 = 自成一派

        // 第一趟：只合并 "==" —— 所有"必须相等"的关系先建立起来
        for (auto& e : equations) {
            if (e[1] == '=') {
                unoin(e[0] - 'a', e[3] - 'a');
            }
        }

        // 第二趟：只检查 "!=" —— 两端若已在同一组，矛盾
        for (auto& e : equations) {
            if (e[1] == '!' && find(e[0] - 'a') == find(e[3] - 'a'))
                return false;
        }
        return true;
    }

    int find(int x) {
        if (p[x] < 0)                       // 负数约定：p[x] < 0 表示 x 是根
            return x;
        return p[x] = find(p[x]);           // 路径压缩
    }

    void unoin(int x, int y) {
        int f1 = find(x), f2 = find(y);
        if (f1 == f2)
            return;
        if (p[f1] > p[f2]) {                // 让 f1 成为"人多的那一组"
            swap(f1, f2);
        }
        p[f1] += p[f2];                     // 负数相加 = 人数相加
        p[f2] = f1;                         // 小树的根挂到大树的根（按大小合并）
    }

private:
    vector<int> p;
};
