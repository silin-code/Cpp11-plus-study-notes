// ============================================================
// LC 684 冗余连接
// ------------------------------------------------------------
// 考点：并查集（**负数约定**）+ 「动态加边判环」
// 复杂度：时间 O(n · α(n))，空间 O(n)
// 日期：2026-10-02（当天从零学并查集：零件 → 547 → 990 → 本题）
// ------------------------------------------------------------
// 题意：
//   n 个节点（编号 1..n），edges 里是 n 条边。这些边本应构成一棵树，
//   但多了一条（恰好形成一个环）。找出那条【多余】的边；
//   若有多个答案，返回输入中【最后出现】的那条。
//     [[1,2],[1,3],[2,3]]             ->  [2,3]
//     [[1,2],[2,3],[3,4],[1,4],[1,5]] ->  [1,4]
// ------------------------------------------------------------
// 思路（并查集最漂亮的一个用法）：
//   一条边是"多余的" ⟺ **加它的时候，它的两个端点已经连通**。
//
//   于是按输入顺序逐条加边：
//     ① 先问 same(u, v)：两端已经同根？
//          是 → 加它就成环 → **这条就是多余的**（记下来）
//          否 → unite(u, v)，继续下一条
//     ② 题目要求"有多个答案时返回最后出现的"，所以【记录所有】
//        成环的边，最后返回最后一次记录的那条（而不是一找到就 return）
//
//   为什么非得用并查集：要的是【动态连通性】—— 边一条一条地加进来，
//   每加一条都问一次"这两点现在连通吗"。DFS 是静态的（一次问一整张图），
//   用它做这题要反复重建图。
// ------------------------------------------------------------
// 易错点：
//   ① 【数组大小】节点编号是 **1..n**（1-based），而 `edges.size()` 是【边数】。
//      写 `p.assign(n, -1)` 只得到下标 0..n-1，访问 p[n] 就【越界】。
//      必须 `p.assign(n + 1, -1)`。
//      ★ 这次踩坑特别值得记：原稿越界后**两个官方用例竟然都返回了正确答案**
//        （越界那一格恰好可读可写，冒充成了第 n+1 个元素）。
//        加边界探针后真相：case1 越界**读 8 次、写 2 次**；把 p[x] 换成受检访问
//        （越界时假设读到 -1）后答案变成 [0,0]（错）。
//        → 同一份逻辑、两种环境、两个不同答案 = **未定义行为**。
//        「能过 ≠ 对」的又一形态（前例：LC 207 反图照样 AC、LC 78 三角数巧合）。
//   ② `union` 是 C++ **关键字**，不能当函数名 → 用 `Union` / `unite`
//   ③ 别写成"一发现成环就 return" —— 题目要的是【最后出现】的那条
// ------------------------------------------------------------
// 实测：2 个官方用例 + 边界（重边 [[1,2],[1,2]]、乱序）全对；
//      20000 组随机对拍 vs 独立暴力删边法零不一致；n = 5000 大环通过；
//      边界探针确认 0 次越界
// ============================================================

class Solution {
public:
    vector<int> findRedundantConnection(vector<vector<int>>& edges) {
        int n = edges.size();
        p.assign(n + 1, -1);            // 节点编号 1..n，所以要 n+1 个格子
        vector<int> ret(2);
        for (auto& e : edges) {
            if (same(e[0], e[1])) {
                // 两端已经连通 -> 这条边多余（记下来，继续看后面的）
                ret[0] = e[0];
                ret[1] = e[1];
            } else {
                Union(e[0], e[1]);
            }
        }
        return ret;
    }

    int find(int x) {
        if (p[x] < 0)                       // 负数约定：p[x] < 0 表示 x 是根
            return x;
        return p[x] = find(p[x]);           // 路径压缩
    }

    void Union(int x, int y) {
        int f1 = find(x);
        int f2 = find(y);
        if (f1 == f2) return;
        if (p[f1] > p[f2]) {                // 让 f1 成为"人多的那一组"
            swap(f1, f2);
        }
        p[f1] += p[f2];                     // 负数相加 = 人数相加
        p[f2] = f1;                         // 小树的根挂到大树的根（按大小合并）
    }

    bool same(int x, int y) {
        return find(x) == find(y);
    }

private:
    vector<int> p;
};
