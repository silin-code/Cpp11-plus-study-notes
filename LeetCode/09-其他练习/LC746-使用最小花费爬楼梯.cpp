// ============================================================
// LC 746 使用最小花费爬楼梯（简单）—— 线性 DP 入门
// ------------------------------------------------------------
// 考点：一维线性 DP（相邻两项转移）
// 复杂度：时间 O(n)，空间 O(n)（可压到 O(1)）
// 日期：2026-11-01（15 分钟轻量题）
// ------------------------------------------------------------
// 题意：
//   cost[i] = 从第 i 级台阶向上爬要付的费用。
//   可以从下标 0 或 1 开始，每次爬 1 或 2 级，求到达楼顶的最小花费。
//   （"楼顶" = 越过最后一级，答案取最后两步的较小值）
//
//     cost = [10, 15, 20]                    -> 15
//     cost = [1,100,1,1,1,100,1,1,100,1]     -> 6
//
// ------------------------------------------------------------
// 【本文件的定义（更直观）】
// ------------------------------------------------------------
//   dp[i] = 站在第 i 级台阶上、并且【已经付了 cost[i]】的最小花费
//
//   dp[0] = cost[0]
//   dp[1] = cost[1]
//   dp[i] = min(dp[i-1], dp[i-2]) + cost[i]      // 从上一步爬上来，再付 i 的钱
//
//   答案 = min(dp[n-2], dp[n-1])                 // 从最后两级任一级直接跳顶
//
// ------------------------------------------------------------
// 【另一种常见定义（对比）】
// ------------------------------------------------------------
//   dp[i] = 到达第 i 级、还【没付】cost[i] 的最小花费
//
//   dp[0] = 0,  dp[1] = 0                        // 起点不花钱
//   dp[i] = min(dp[i-1] + cost[i-1], dp[i-2] + cost[i-2])
//   answer = dp[n]                               // 楼顶是第 n 级
//
//   两种定义结果相同（本文件用的是前一种）。
//   ★ 区别只在"dp 的含义里含不含当前格的费用"，转移式随之调整。
//     写 DP 时先把这个说清楚，转移就不会错。
//
// ------------------------------------------------------------
// 【与 LC 70 爬楼梯的区别】
// ------------------------------------------------------------
//   LC 70：问"多少种走法" -> 累加（dp[i] = dp[i-1] + dp[i-2]）
//   LC 746：问"最小花费"   -> 取 min（再叠加当前格费用）
//   骨架一样，只换转移里的运算符 —— 和背包的"max / min / += / |="同理。
//
// ------------------------------------------------------------
// 实测：两个官方样例手算一致（15 / 6）
//      （本机 PowerShell 调 exe 被安全策略拦，未跑编译产物）
// ============================================================

#include <vector>
#include <algorithm>
using namespace std;

class Solution {
public:
    int minCostClimbingStairs(vector<int>& cost) {
        int n = cost.size();
        vector<int> dp(n + 1, 0x3f3f3f);
        dp[0] = cost[0];
        dp[1] = cost[1];
        for (int i = 2; i < n; i++) {
            dp[i] = min(dp[i - 1], dp[i - 2]) + cost[i];
        }
        return min(dp[n - 2], dp[n - 1]);
    }
};
