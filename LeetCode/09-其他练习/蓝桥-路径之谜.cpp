// ============================================================
// 蓝桥杯 路径之谜 —— DFS + 计数剪枝（棋盘路径还原）
// ------------------------------------------------------------
// 平台：蓝桥杯（真题）
// 考点：DFS 回溯 + 两个方向的计数约束
// 复杂度：DFS 搜索，靠"每行每列计数上限"剪枝
// 日期：2026-11-15
// ------------------------------------------------------------
// 题意：
//   n×n 的方格，骑士从【西北角 (0,0)】走到【东南角 (n-1,n-1)】。
//   只能横竖走，不能斜走、不能跳。
//   每走到一个【新】方格，就向【正北】和【正西】各射一箭。
//   同一个方格只允许经过一次（但不必走完所有方格）。
//
//   给北墙的 n 个靶（自西向东）和西墙的 n 个靶（自北向南）上的箭数，
//   求骑士的行走路线（测试数据保证路径唯一）。
//
//   输出：路径经过的格子编号（行优先，0..n²-1），空格分隔。
//
// ============================================================
// 【一、先把坐标体系定死（最容易搞反的地方）】
// ============================================================
//   本文件用 x = 列、y = 行（和"横坐标/纵坐标"的直觉一致）：
//
//       dfs(x, y)      x ∈ [0, n-1] 是列，y ∈ [0, n-1] 是行
//       起点 (0,0)     终点 (n-1, n-1)
//
//   射箭方向 -> 打到哪个靶：
//       站在 (x, y) 向【正北】射  ->  打到北墙第【x】个靶（自西向东数）
//       ->  所以 X[x] = 第 x 列被经过的格子数
//
//       站在 (x, y) 向【正西】射  ->  打到西墙第【y】个靶（自北向南数）
//       ->  所以 Y[y] = 第 y 行被经过的格子数
//
//   ★ 一句话记：**北墙数列，西墙数行**。
//
//   ★ 输出编号：格子 (x,y) 的行优先编号 = y * n + x
//     （第 y 行前面有 y*n 个格子，本行第 x 个）
//
// ============================================================
// 【二、剪枝：这题能不能过，全看这一行】
// ============================================================
//   进入格子 (i,j) 之前，先检查：
//
//       xcount[i] + 1 <= X[i]      // 这一列的配额还没用完
//       ycount[j] + 1 <= Y[j]      // 这一行的配额还没用完
//
//   两个都满足才进去。
//
//   为什么这个剪枝这么强：
//       每次走一步都要消耗"一列配额 + 一行配额"，
//       配额有限 -> 大部分方向一开始就被砍掉了。
//
//   还能再早一步剪（本文件未做，可作优化）：
//       如果某个方向进去后，剩余格子无法走到终点，也可以剪。
//
// ============================================================
// 【三、踩过的两个坑】
// ============================================================
//   ① vis[0][0] 没有标记
//        起点被当成"未访问"，理论上可以绕回 (0,0) 再走一遍。
//        实测多数数据会被剪枝挡住（绕回时 xcount[0]+1 > X[0]），
//        但这是确凿的 bug，必须改。
//
//   ② 找到答案后只 return 当前层
//        path = ret; return;   // 只结束这一帧
//        父层的 for 循环还在继续，会继续探索。
//        如果那个用例存在【两条】满足条件的路径（题目说唯一，数据不一定严谨），
//        后找到的会覆盖先找到的 -> 答案错误。
//
//        ★ 改法：找到就【全局退出】——
//           直接把结果输出然后 exit(0)；
//           （或者用一个 bool found 只记第一条）
//
//        本文件采用 exit(0)：最短、最不容易出错。
//        ★ 竞赛里 exit(0) 是合法手段，不要在正式工程里这么写。
//
// ============================================================
// 【四、为什么"起点和终点都要算一次"】
// ============================================================
//   题目："每走到一个【新】方格，就射一箭"。
//   起点 (0,0) 是第一个到达的方格 -> 算一次（往北、往西各射）
//   终点 (n-1,n-1) 是最后一个到达的 -> 也算一次
//
//   所以初始化时就要 xcount[0]++、ycount[0]++，
//   而进入终点时（在 for 循环里 push 之前）已经加过了。
//
// ============================================================
// 【五、408 视角】
// ============================================================
//   本题是 DFS 回溯的典型形态：**路径 + 状态存取 + 撤销**。
//   和 408 里"图的深度优先遍历"骨架一致，区别是：
//       · 要记录路径（ret）
//       · 要维护"路径上的额外约束"（xcount/ycount）
//       · 找到解可以提前终止
//
//   撤销的三样东西（必须成对）：
//       vis / xcount+ycount / ret
//   漏一个，后面的分支就会被错误的状态影响。
// ============================================================

#include <bits/stdc++.h>
using namespace std;

int n;
int dx[4] = {0, 0, -1, 1};      // 配 x（列）：0 是列不变
int dy[4] = {-1, 1, 0, 0};      // 配 y（行）：-1 是上、+1 是下

vector<int> X, Y;               // X = 北墙（每列配额），Y = 西墙（每行配额）
vector<pair<int, int>> ret;     // 当前路径
bool vis[22][22];

void dfs(int x, int y, vector<int>& xcount, vector<int>& ycount) {
    // 到达终点，且两边的配额都恰好用完 -> 找到唯一解
    if (x == n - 1 && y == n - 1 && xcount == X && ycount == Y) {
        for (auto e : ret) {
            cout << e.second * n + e.first << " ";   // 行优先编号
        }
        exit(0);                  // ★ 找到即全局退出，避免被后续解覆盖
    }

    for (int a = 0; a < 4; a++) {
        int i = x + dx[a];        // 新的列
        int j = y + dy[a];        // 新的行

        // 边界 + 未访问 + 两个方向的配额都还有
        if (i >= 0 && i < n && j >= 0 && j < n && vis[i][j] == false
            && xcount[i] + 1 <= X[i] && ycount[j] + 1 <= Y[j]) {

            vis[i][j] = true;     // ① 标记
            xcount[i]++;
            ycount[j]++;
            ret.push_back(make_pair(i, j));

            dfs(i, j, xcount, ycount);

            ret.pop_back();       // ② 撤销（三样必须成对）
            xcount[i]--;
            ycount[j]--;
            vis[i][j] = false;
        }
    }
}

int main() {
    cin >> n;
    X.resize(n);
    Y.resize(n);
    memset(vis, false, sizeof(vis));

    for (int i = 0; i < n; i++) cin >> X[i];    // 第二行：北墙，自西向东
    for (int i = 0; i < n; i++) cin >> Y[i];    // 第三行：西墙，自北向南

    vector<int> xcount(n, 0);
    vector<int> ycount(n, 0);

    // 起点也算"走到"一次
    vis[0][0] = true;           // ★ 坑①：起点必须标记
    ret.push_back(make_pair(0, 0));
    xcount[0]++;
    ycount[0]++;

    dfs(0, 0, xcount, ycount);
    return 0;
}
