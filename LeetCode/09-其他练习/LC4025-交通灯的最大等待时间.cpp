// ============================================================
// LC 4025 交通灯的最大等待时间 —— 一次观察，O(m) 解决
// ------------------------------------------------------------
// 考点：模拟 + 关键观察（不是 DP，也不是图论）
// 复杂度：时间 O(m + len(arrivalTime))，空间 O(1)
// 日期：2026-11-12（每日一题，一次写对）
// ------------------------------------------------------------
// 题意：
//   固定循环周期 period；lights[i] = 第 i 个路口的绿灯时长。
//   所有路口在时刻 0 同时变绿，每 period 秒循环一次
//   -> 红灯时长 = period - lights[i]。
//
//   arrivalTime[j] = 第 j 辆车的到达时刻。
//   每辆车【自己挑一个路口】通过；允许多车共用路口、不排队。
//
//   车在 t 时刻到达、选第 i 个路口：
//       r = t % period
//       r <  lights[i]  ->  直接过，等待 0
//       r >= lights[i]  ->  等到本周期结束，等待 period - r
//
//   总代价 = 所有车等待时间的【最大值】。
//   求如何分配路口，使这个最大值最小。
//
// ============================================================
// 【关键观察（三层，缺一层就写不出来）】
// ============================================================
//   ① 每辆车是【独立】的
//      因为允许多车共用一个路口、不排队 —— 一辆车选哪个路口，
//      完全不影响别的车。
//      => 总代价 = max over 每辆车（这辆车能拿到的最小等待）
//      => 每辆车各自追求最优即可，不需要全局协调
//
//   ② 一辆车"完全不用等"的条件
//      存在某个路口 i 满足 r < lights[i]
//      => 等价于  r < max(lights)
//      （因为 max(lights) 是绿灯最长的那个，如果连它都 < r，别的更不行）
//
//   ③ 等不了的时候，等待时间与"选哪个路口"无关
//      r >= max(lights) >= lights[i] 对【所有】i 成立
//      -> 每个路口都是红灯
//      -> 选谁都一样，等待都是 period - r
//      => 不需要枚举路口
//
//   一句话：最坏情况一视同仁，最好情况有得挑。
//
// ============================================================
// 【由此得到的算法】
// ============================================================
//   mx = max(lights)
//   ans = 0
//   for (每个到达时刻 t):
//       r = t % period
//       if (r >= mx) ans = max(ans, period - r)     // 只能等，且等待固定
//       // r < mx 的车等 0，对 max 没贡献
//
// ============================================================
// 【本次踩的坑：LeetCode 允许的语法 ≠ 蓝桥杯允许的语法】
// ============================================================
//   第一版写的是：
//       int mx = ranges::max(lights);        // ✗ C++20
//
//   LeetCode 支持 C++20 所以能过，但【蓝桥杯考场是 Dev-C++ 5.11】，
//   只支持 C++11 —— 这个写法直接编译不过。
//
//   改成 C++11：
//       int mx = *max_element(lights.begin(), lights.end());
//       // 或者手写循环：int mx = lights[0]; for (int x : lights) if (x > mx) mx = x;
//
//   ★ 这类"高版本语法"清单（蓝桥杯一律不能用）：
//       ranges::max / ranges::sort          C++20
//       auto [a, b, c] = ...                C++17（结构化绑定）
//       if (auto it = m.find(k); it != m.end())   C++17（if 初始化语句）
//       std::optional / std::string_view     C++17
//
// ============================================================
// 【验证】
// ============================================================
//   手算用例：
//       period=8,  lights=[2,3], arrival=[5,8]        -> 3
//           r=5 >= 3 -> 等 3；r=0 < 3 -> 等 0
//       period=10, lights=[3,6], arrival=[7,13]       -> 3
//           r=7 >= 6 -> 等 3；r=3 < 6 -> 等 0
//       period=5,  lights=[1,4], arrival=[10,11]      -> 0
//           r=0,1 都 < 4
//       period=6,  lights=[6],   arrival=[3,9,15]     -> 0
//           r=3 都 < 6
//       period=6,  lights=[0],   arrival=[1,2,3]      -> 5
//           mx=0，所有 r >= 0 -> 等 6-1=5
//
//   随机对拍：与"每辆车枚举所有路口"的暴力比，3000 组零不一致
// ============================================================

#include <vector>
#include <algorithm>
using namespace std;

class Solution {
public:
    int minPenalty(int period, vector<int>& lights, vector<int>& arrivalTime) {
        // 绿灯最长的那个路口 —— 它决定了"能不能不等"
        int mx = *max_element(lights.begin(), lights.end());

        int ret = 0;                  // 所有车的最大等待

        for (auto e : arrivalTime) {  // 值拷贝，e %= period 不影响原数组
            e %= period;              // 当前在本周期内的位置

            // r >= mx：所有路口都红灯，等待固定 = period - r
            // r <  mx：能赶上最长绿灯的那个路口，等待 0（对 max 无贡献）
            if (e >= mx) {
                ret = max(ret, period - e);
            }
        }
        return ret;
    }
};
