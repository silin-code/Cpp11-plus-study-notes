// ============================================================
// LC 3665 统计镜子反射路径数目（中等）—— 网格 DP + 记忆化 + 反射链
// ------------------------------------------------------------
// 考点：网格路径计数 + 「镜子 = 转向器」的模拟 + 记忆化搜索
// 复杂度：时间 O(m×n×反射链长)，空间 O(m×n)
// 日期：2026-10-31（每日一题；用户改了 4 版，最后 AC）
// ------------------------------------------------------------
// 题意：
//   m×n 的 0/1 网格。0 = 空格，1 = 镜子。
//   机器人从 (0,0) 出发，只能向右或向下走，问到 (m-1,n-1) 的不同路径数。
//
//   ★ 进入镜子会被反射（而且镜子本身【不被站上】）：
//       想向右进镜子  ->  转向下，落到镜子正下方
//       想向下进镜子  ->  转向右，落到镜子正右方
//     反射后落到镜子 -> 立刻再反射（链式）
//     反射后出界     -> 这条路径无效
//
//   示例1：[[0,1,0],[0,0,1],[1,0,0]] -> 5
//   示例2：[[0,0],[0,0]]             -> 2
//   示例3：[[0,1,1],[1,1,0]]         -> 1
//
// ------------------------------------------------------------
// 【核心认知：镜子不是"格子"，是"转向器"】
// ------------------------------------------------------------
//   机器人永远只站在 0 格上。镜子只用来看"要不要转、转到哪"。
//
//   示例3 的链式反射：
//       (0,0) 想向右 -> 进 (0,1) 是镜子 -> 转向下 -> 落 (1,1)
//       (1,1) 也是镜子！这次是【向下进入】的 -> 转向右 -> 落 (1,2)
//       (1,2) 是 0 -> 站住
//   → 注意每次反射的【进入方向】会变，所以每次都要重新判断。
//
// ------------------------------------------------------------
// 【状态与转移】
// ------------------------------------------------------------
//   dfs(i, j) = 从 (i,j) 出发到终点的路径数        ← 只依赖坐标，两维 memo 够
//
//   对两个方向各走一步：
//       下一格是 0  ->  直接递归它
//       下一格是 1  ->  用 nextpos() 沿反射链算出落点，再递归
//       落点出界    ->  跳过
//
//   ★ 方向【不进状态】—— 因为 "从 (i,j) 出发" 时，两个方向都在函数内部
//     循环试过了，答案已经合并。方向只是 nextpos 的参数。
//
// ------------------------------------------------------------
// 【nextpos：把"反射链"抽成独立函数】
// ------------------------------------------------------------
//   nextpos(i, j, flag)：
//       (i,j) 是空格 -> 返回 (i,j)
//       (i,j) 是镜子 -> 按进入方向转向，继续走
//                       flag == 1（右进）-> 落 (i+1, j)，方向变"下"
//                       flag == 0（下进）-> 落 (i, j+1)，方向变"右"
//       出界 -> 返回 (-1,-1)
//
//   反射链是【确定性】的（给定起点和方向，落点唯一），所以可以单独算好、
//   不必在 DP 里纠缠。
//
// ------------------------------------------------------------
// 【本次踩的 5 个坑（改了 4 版）】
// ------------------------------------------------------------
//   ① 把【行号 i】当【方向】用：`if (i == 0 && ...)` / `else if (i == 1 ...)`
//      -> 只有第 0 行才会命中第一个分支，逻辑全乱。
//      正确：用循环变量 a（0 = 向下，1 = 向右）。
//
//   ② n / m 语义反着用
//      n = grid.size()（行数），m = grid[0].size()（列数）
//      -> 越界写 `i >= m`（应 n）、终点写 `i == m-1`（应 n-1）
//      3×3 时看不出差别，3 行 5 列立刻错。
//
//   ③ nextpos 里转向写反：flag==1（右进）却往 j+1 走（应转向下 i+1）
//
//   ④ 改代码时把 `ans += dfs(grid, x, y);` 整行改丢了 -> ans 恒为 0
//      （"改一半"的变体：不是改错，是改丢）
//
//   ⑤ 成员数组 `d` 每次调用都 push_back -> 多次调用后变成 4 个、6 个元素
//      （第 5 次踩"成员变量没复位"，前四次：LC 46 / 200 / 486 / 78）
//
//   另外：MOD 写成 100000007（少一个 0）。
//
// ------------------------------------------------------------
// 实测：LeetCode 提交 AC（用户报告）；示例 1 手工推导 = 5 一致
// ============================================================

#include <vector>
#include <cstring>
using namespace std;

class Solution {
    int memo[501][501];
    int n, m;                              // n = 行数，m = 列数
    static const int MOD = 1000000007;
    int dx[2] = {1, 0};                    // a = 0：向下
    int dy[2] = {0, 1};                    // a = 1：向右

public:
    int uniquePaths(vector<vector<int>>& grid) {
        n = grid.size();
        m = grid[0].size();
        memset(memo, -1, sizeof(memo));
        return dfs(grid, 0, 0);
    }

    // 沿着反射链走到底，返回最终落点；出界返回 (-1, -1)
    // flag：进入当前格的方向，0 = 向下走来的，1 = 向右走来的
    pair<int, int> nextpos(vector<vector<int>>& grid, int i, int j, int flag) {
        if (i < 0 || i >= n || j < 0 || j >= m)
            return make_pair(-1, -1);
        if (grid[i][j] == 0)
            return make_pair(i, j);                 // 空格：停
        if (flag == 1)
            return nextpos(grid, i + 1, j, 0);      // 右进 -> 转向下
        return nextpos(grid, i, j + 1, 1);          // 下进 -> 转向右
    }

    int dfs(vector<vector<int>>& grid, int i, int j) {
        if (i == n - 1 && j == m - 1)               // 到达终点
            return 1;
        if (memo[i][j] != -1)
            return memo[i][j];

        long long ans = 0;
        for (int a = 0; a < 2; a++) {
            int x = i + dx[a];
            int y = j + dy[a];
            if (x >= n || y >= m)
                continue;                            // 越界

            if (grid[x][y] == 1) {                   // 撞镜子 -> 沿反射链
                pair<int, int> tmp = nextpos(grid, x, y, a);
                x = tmp.first;
                y = tmp.second;
            }
            if (x < 0 || x >= n || y < 0 || y >= m)
                continue;                            // 反射出界 -> 无效

            ans += dfs(grid, x, y);
            ans %= MOD;
        }
        memo[i][j] = (int)ans;
        return memo[i][j];
    }
};
