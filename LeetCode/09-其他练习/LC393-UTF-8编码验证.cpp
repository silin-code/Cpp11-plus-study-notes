// ============================================================
// LC 393 UTF-8 编码验证
// ------------------------------------------------------------
// 考点：位运算 + 分类讨论 + 边界检查
// 复杂度：O(n) 时间，O(1) 空间
// 日期：2026-10-13（用户空闲时随手练的一道）
// ------------------------------------------------------------
// 题意：
//   给一个整数数组 data（每个数 0..255，代表一个字节），验证它是不是合法的 UTF-8 编码。
//   合法形态只有 4 种：
//     1 字节： 0xxxxxxx
//     2 字节： 110xxxxx 10xxxxxx
//     3 字节： 1110xxxx 10xxxxxx 10xxxxxx
//     4 字节： 11110xxx 10xxxxxx 10xxxxxx 10xxxxxx
//   注意：> 4 字节的前缀（11111xxx 及以上）和"孤立出现的续字节"都是非法的。
// ------------------------------------------------------------
// 思路：
//   从左往右扫，看当前字节的【前缀】判断长度 len（1/2/3/4），
//   然后检查：① 后面还有没有 len-1 个字节  ② 那 len-1 个是不是都以 10 开头。
//   都满足就 i += len，否则 return false。
//
//   四种前缀的判断（本次用的写法）：
//     data[i] >> 7 == 0     →  1 字节（0xxxxxxx）
//     data[i] >> 5 == 6     →  2 字节（110xxxxx）
//     data[i] >> 4 == 14    →  3 字节（1110xxxx）
//     data[i] >> 3 == 30    →  4 字节（11110xxx）
//
//   更推荐用位掩码（一眼看得清检查了哪几位）：
//     (data[i] & 0x80) == 0x00 → 1 字节
//     (data[i] & 0xE0) == 0xC0 → 2 字节
//     (data[i] & 0xF0) == 0xE0 → 3 字节
//     (data[i] & 0xF8) == 0xF0 → 4 字节
// ------------------------------------------------------------
// 易错点（本题第一版就踩了）：
//   ★【`else` 兜底别太宽】：把 `else` 当成"4 字节分支"用，会接住两类非法输入 ——
//       · `11111xxx` 及以上（非法的 5-7 字节前缀）
//       · `10xxxxxx`（孤立出现的续字节，它根本不能当"开头字节"）
//     实测：`[248,130,130,130]`（248 = 11111000）被误判为合法 4 字节；
//           随机对拍 200000 组中有 306 组与此类错误相关。
//   ✅ 正确写法：**4 字节也要显式判断前缀**（`>> 3 == 30`），
//      然后**最后的 `else` 无条件 `return false`**。
//
//   通用判据（可复用到所有"分类 + 兜底"的题）：
//     当 `else` 用来兜底一个【合法分支】时，先确认：
//     「非法输入会不会也掉进来？」—— "没匹配前几种" ≠ "就是最后那种"。
// ------------------------------------------------------------
// 实测：9 个用例（含 11111000 / 11111100 / 孤立续字节 / 长度不足）全对；
//      200000 组随机对拍（偏向生成 UTF-8 前缀形态）零不一致；-Wall 无警告
// ============================================================

class Solution {
public:
    bool validUtf8(vector<int>& data) {
        int n = data.size();
        for (int i = 0; i < n;) {
            if ((data[i] >> 7) == 0) // 1字节
            {
                i++;
                continue;
            } else if ((data[i] >> 5) == 6) // 2字节
            {
                if (i + 1 < n && (data[i + 1] >> 6) == 2) {
                    i += 2;
                } else {
                    return false;
                }
            } else if ((data[i] >> 4) == 14) // 3字节
            {
                if (i + 2 < n && (data[i + 1] >> 6) == 2 &&
                    (data[i + 2] >> 6) == 2) {
                    i += 3;
                } else {
                    return false;
                }
            } else if ((data[i] >> 3) == 30) // 4字节
            {
                if (i + 3 < n && (data[i + 1] >> 6) == 2 &&
                    (data[i + 2] >> 6) == 2 && (data[i + 3] >> 6) == 2) {
                    i += 4;
                } else {
                    return false;
                }
            } else {
                return false;   // ★ 其余全部非法（11111xxx / 孤立续字节 / …）
            }
        }
        return true;
    }
};
