// ============================================================
// LC 96 不同的二叉搜索树（中等）—— 分治型 DP（卡特兰数）
// ------------------------------------------------------------
// 考点：枚举「根节点」+ 左右子树独立 → 方案数相乘
// 复杂度：时间 O(n²)，空间 O(n)
// 日期：2026-10-30（用户按自己的规划选的题，独立完成）
// ------------------------------------------------------------
// 题意：
//   给 n，求由 1..n 这 n 个节点组成的【不同二叉搜索树】有多少种。
//
//     n=1 -> 1     n=2 -> 2     n=3 -> 5
//     n=4 -> 14    n=5 -> 42            卡特兰数
//
// ------------------------------------------------------------
// 【这不是背包】
// ------------------------------------------------------------
//   背包：有"容量"、问"选哪些东西" → 组合
//   本题：没有容量，问"分成左右两棵子树有多少种分法"
//        → 分治型 DP（笛卡尔积模型）
//
// ------------------------------------------------------------
// 【状态与转移】
// ------------------------------------------------------------
//   dp[i] = i 个节点能组成的不同 BST 数量
//
//   枚举【根节点的左子树有几个节点】（设左子树 j-1 个，j = 1..i）：
//       左子树   j-1 个节点  ->  dp[j-1] 种
//       根节点   1 个（固定）
//       右子树   i-j 个节点  ->  dp[i-j] 种
//
//       左右两棵子树【互相独立】-> 方案数相乘（笛卡尔积）
//
//   dp[i] = Σ_{j=1..i}  dp[j-1] * dp[i-j]
//
//   ★ 另一视角（等价）：每一对 (左子树, 右子树) 的组合数是乘积
//     这正是"两个独立选择系统"的方案数 = 各自方案数相乘。
//
// ------------------------------------------------------------
// 【边界：dp[0] = 1（空树算 1 种）】
// ------------------------------------------------------------
//   空树是一种合法的"空结构"，所以方案数是 1，不是 0。
//
//   忘了它：dp[1] = dp[0]*dp[0] = 0 -> 整张表全 0。
//   （和「利润至少 0 -> 1 种」是同一类边界思维，见 LC 879）
//
// ------------------------------------------------------------
// 【为什么叫卡特兰数】
// ------------------------------------------------------------
//   1, 1, 2, 5, 14, 42, 132, 429, 1430, 4862, 16796, ...
//   通项：C_n = C(2n, n) / (n+1)
//   同类问题：括号匹配、出栈序列、凸多边形三角剖分 —— 都是这个数列。
//
//   本题 n ≤ 19，C_19 = 1767263190 < 2^31，所以 int 够用。
//
// ------------------------------------------------------------
// 实测：手算 n=1..5 -> 1, 2, 5, 14, 42 与卡特兰数一致
// ============================================================

#include <vector>
using namespace std;

class Solution {
public:
    int numTrees(int n) {
        // dp[i] = 节点个数为 i 时有多少种二叉搜索树
        vector<int> dp(n + 1, 0);
        dp[0] = 1;                    // ★ 空树算 1 种

        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= i; j++) {          // 枚举根节点的"位置"
                dp[i] += dp[j - 1] * dp[i - j];      // 左 j-1 个 × 右 i-j 个
            }
        }
        return dp[n];
    }
};
