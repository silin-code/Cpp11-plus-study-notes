// 考点：贪心 + 堆 + 【整数开根精度】
// 日期：2026-10-19（从 65% → 100%）
// ------------------------------------------------------------
// 题意：
//   n 棵竹子排成一排，第 i 棵高度 h[i]。
//   一次魔法：选【连续的一段相同高度】的竹子（高度 H），
//            把它们全部变为 ⌊√⌊H/2⌋+1⌋。
//   求最少使用多少次魔法，让所有竹子高度变为 1。
//   样例：n=6，h = 2 1 4 2 6 7  →  5
//   数据：20% n≤1000, h≤1e6；  100% n≤2e5, h≤1e18
//
// 思路（贪心 + 堆）：
//   ① 每次砍【当前最高的一段】一定不劣
//        （只有高的会变矮、矮的不会变高，高的一步都不省）
//   ② 大根堆维护 (高度, 下标)；cmp 让「值相同时【下标大的】先出」
//        → 堆顶天然是"最高那一段的【最右】元素"
//   ③ 从堆顶往【左】扩（下标连续 + 高度相同 = 同一段）
//        ★ 不需要往右扩：cmp 已保证堆顶是同值中下标最大的
//   ④ 这一段全部改成 f(H) 后重新入堆（旧值已被 pop，堆里每个下标只有一个元素）
//   ⑤ 直到堆顶高度为 1
//
// ★ 踩过的坑：整数开根的精度
//   h ≤ 1e18 → h/2+1 ≈ 5e17，【超过 double 能精确表示的范围（2^53 ≈ 9e15）】
//   → (ll)sqrt((double)x) 会差 1
//     实测：完全平方数附近约 322296 处不一致
//           （例 x = 4503627007828623 → 算出 67109068，精确值 67109067）
//   → 改用 long double 开根：MinGW 的 long double 是 80 位扩展精度（64 位尾数），
//     能精确表示到 2^64 ≈ 1.8e19，5e17 级输入是精确的。
//   改前 65%，改后 100%（实测大数专项 + 3000 组随机对拍与精确整数开根零差异）。
//
//   ★ 判据：题目出现 h ≤ 1e18 这类范围时，整数开根不要直接用 double。
// ============================================================

#include <bits/stdc++.h>
using namespace std;
using ll = long long;

struct cmp {
    bool operator()(pair<ll, ll> p1, pair<ll, ll> p2) {
        if (p1.first == p2.first) return p1.second < p2.second;  // 值相同：下标大的先出
        return p1.first < p2.first;                              // 值大的先出
    }
};

int main() {
    ll n = 0;
    cin >> n;
    vector<ll> arr(n + 1);
    priority_queue<pair<ll, ll>, vector<pair<ll, ll>>, cmp> q;  // 大根堆，最大值为顶
    // pair<ll,ll> 值+下标，下标按照从小到大排序
    ll mid = 1;  // 最大的下标
    for (int i = 1; i <= n; i++) {
        cin >> arr[i];
        q.push(make_pair(arr[i], i));
    }
    int ans = 0;
    // 每次都从中心往旁边扩，把最大的砍去
    while (q.top().first != 1) {
        ans++;
        // 扩顶部的最大元素
        stack<pair<ll, ll>> st;
        ll change = (ll)sqrt((long double)(q.top().first / 2) + 1);
        st.push(q.top());
        q.pop();
        // 堆顶永远存最大值和最大值的下标
        // 如果值相等，那么下标从小到大排序
        while (q.size() && q.top().second + 1 == st.top().second && st.top().first == q.top().first)  // 拿取最大的元素序列
        {
            st.push(q.top());
            q.pop();
        }
        // 将 tmp 的元素修改以后推回堆顶
        while (st.size()) {
            q.push(make_pair(change, st.top().second));
            st.pop();
        }
    }
    cout << ans;
    return 0;
}
