// 题意：
//   N 棵灌木排成一排，第 i 棵初始高度 0，每天长 1 厘米。
//   小蓝每天修剪【一棵】，把它剪回高度 0；他从第 1 棵开始，
//   走到最右边再往回走，如此反复（端点在折返处只剪一次）。
//   问：每棵灌木在全程中【最高能长到多少】？
//
//   修剪顺序：0,1,...,n-1, n-2,...,1   （一个周期 2n-2 天）
//
// 思路（找规律）：
//   对第 i 棵（0-based），它两次被剪之间的最长空档是：
//       往右走一趟      2 × (n-1-i)
//       往左走一趟      2 × i
//   → 峰值 = 2 × max(i, n-1-i)
//
//   直观理解：小蓝走"离它较远的那一侧"再折返回来，花的时间最长。
//
// ★ 2026-04 时这题只过了 1/8 个测试点（得 1 分）；
//   2026-10-13 重做时一眼看穿、"秒了" —— 这半年的进步可以直接对比出来。
//
// 实测：用暴力模拟（按修剪顺序一天天走、记录每棵最高值）对拍 n=2..8 全部一致
// ============================================================

#include <bits/stdc++.h>
using namespace std;

int main()
{
    long long n;
    cin >> n;
    vector<long long> v(n, 0);
    for (long long i = 0; i < n; i++)
    {
        v[i] = max(v[i], 2 * i);
        v[i] = max(v[i], 2 * (n - 1 - i));
    }
    for (auto e : v)
    {
        cout << e << "\n";
    }
    return 0;
}
