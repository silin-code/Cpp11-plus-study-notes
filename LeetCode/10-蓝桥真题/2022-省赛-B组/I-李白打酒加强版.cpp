// 考点：记忆化搜索（等价于三维 DP）+ 剪枝
// 日期：2026-10-21（用户从「TLE + MLE」→ 记忆化后 0ms）
// ------------------------------------------------------------
// 题意：
//   李白初始有 2 斗酒；遇到店，酒量翻倍；遇到花，喝掉 1 斗。
//   已知一共遇到 N 次店、M 次花，且【最后一次遇到花时正好喝完】，
//   求所有可能的"遇店 / 遇花"顺序的方案数（mod 1e9+7）。
//   样例：N=5, M=10  →  14
//
// ------------------------------------------------------------
// 进化过程（三步，每一步都对应一类错误）
// ------------------------------------------------------------
//   ① 纯 DFS + string path
//        · 逻辑是对的（N=5,M=10 → 14 ✓）
//        · 但 string 按【值传递】，每层递归复制整个串 → 【MLE】
//        · 且 2^(N+M) 指数级 → N=10,M=20 就 77ms
//
//   ② 去掉 path（步数用 s+c、最后一步用 bool）+ 剪枝 money > M-c
//        · 解决 MLE；小数据 0ms
//        · 但 N=20,M=40 仍要 20.7 秒 → 【TLE】
//
//   ③ 记忆化（本文件）
//        · 状态 = (s, c, money, lastFlower)
//        · N=20,M=40 → 0ms；N=50,M=100 → 2ms
//
// ------------------------------------------------------------
// 关键点
// ------------------------------------------------------------
//   ★ 状态必须包含 lastFlower
//      "最后一步是花"这个条件依赖它，漏掉的话答案会翻倍。
//
//   ★ 剪枝必须在【查表之前】
//      money > M-c 时 money 可能超出数组维度，先 return 0 才不会越界。
//
//   ★ dfs 从"改全局 ret"改成"返回方案数"
//      只有返回值才能"存表再复用"。
//
//   ★ 剪枝的经济性：money > M - c（剩下的花不够喝完当前酒）能砍掉绝大多数分支，
//      是这题从"完全跑不动"到"只差一个记忆化"的关键。
//
// 复杂度：状态数 = N × M × (M+1) × 2（N=M=100 时约 2e6），每个状态 O(1)。
// ============================================================

#include <iostream>
using namespace std;
using ll = long long;

ll N, M;                                    // N = 遇店次数，M = 遇花次数
ll memo[105][105][105][2];
bool vis[105][105][105][2];

// s: 已遇店次数  c: 已遇花次数  money: 当前酒量  last: 上一步是否是花
ll dfs(int s, int c, int money, int last) {
    if (money < 0 || money > M - c) return 0;        // ★ 剪枝（先做，不碰 memo）
    if (s == N && c == M)
        return (money == 0 && last) ? 1 : 0;         // 终点：喝完且最后一步是花
    if (vis[s][c][money][last])                      // ★ 查表
        return memo[s][c][money][last];

    vis[s][c][money][last] = true;
    ll res = 0;
    if (s < N)              res += dfs(s + 1, c, money * 2, 0);   // 遇店：翻倍
    if (c < M && money > 0) res += dfs(s, c + 1, money - 1, 1);   // 遇花：喝 1 斗

    return memo[s][c][money][last] = res % 1000000007;   // ★ 存表
}

int main() {
    cin >> N >> M;
    cout << dfs(0, 0, 2, 1);                     // 初始 2 斗酒
    return 0;
}
