// ------------------------------------------------------------
// 考点：自定义进制（X 进制，每位进制不同）+ 贪心
// 日期：2026-10-16（用户从"看不懂"到独立写对，当晚完成）
// ------------------------------------------------------------
// 题意：
//   X 进制：每一位"逢几进一"可以不同。例如最低位 2 进制、第二数位 10 进制、
//   第三数位 8 进制时，X 进制数 321 = 65：
//      3×(2×10) + 2×2 + 1×1 = 60 + 4 + 1 = 65
//   现在给两个 X 进制整数 A、B，但【每一数位的进制不确定】，只知道：
//       ① 每位进制范围 [2, N]
//       ② 每位数字必须 < 该位进制（否则不合法）
//   求 A − B 的最小可能值（十进制，mod 1e9+7）。
//   样例：11 / 3 / 10 4 0 / 3 / 1 2 0  ->  94
// ------------------------------------------------------------
// 两个核心（看懂这两点，题就通了）：
//
//   ★ 权重规则：第 i 位的权重 = 所有【更低位的进制】的乘积。
//       最低位权重 1；第二数位权重 = 最低位进制；第三数位权重 = 最低位进制×第二数位进制…
//       所以十进制值 = Σ digit[i] × 权重[i]
//
//   ★ 贪心结论：要让差最小，【每一位的进制都取最小合法值】：
//       base[i] = max(A[i], B[i]) + 1   （且至少 2）
//       因为进制越大 → 权重越大 → A、B 都被放大 → 差也被放大。
//
// 实现：
//   ① 把 A、B 反转成"低位在前"，对齐到 max(Ma,Mb)（短的补 0）
//   ② 从低位往高位累加：ans += (A[i]-B[i]) * w；然后 w *= base[i]
//   ③ 数据范围 Ma,Mb ≤ 1e5 → 权重爆炸大 → 每一步都 mod 1e9+7，用 long long
// ------------------------------------------------------------
// 易错点（首版踩了 3 个）：
//   ① 【括号】`(A[i] - B[i] * w)` —— 算的是 A[i]-B[i]*w；
//      正确是 `(A[i] - B[i]) * w`（先减差，再乘权重）→ 首版样例输出 0（应 94）
//   ② 【循环上界】`i < Mb` —— A 比 B 多的高位全丢；应循环到 max(Ma,Mb)，短的补 0
//   ③ 【负数取模】`(A[i]-B[i])*w` 可能为负，C++ 里 `%Mod` 仍为负；
//      应 `(ans + x % Mod + Mod) % Mod`
// ------------------------------------------------------------
// 实测：样例 94；手工用例 A=[1]B=[0]->1、A=[1,0]B=[0]->2、A=[3,2,1]B=[1,2,0]->13 全对
// ============================================================

#include <bits/stdc++.h>
using namespace std;
using ll = long long;
constexpr ll Mod = 1000000007;

int main() {
    ll N;
    cin >> N;
    int Ma, Mb;
    cin >> Ma;
    vector<ll> A(Ma);
    for (int i = 0; i < Ma; i++) cin >> A[i];
    cin >> Mb;
    vector<ll> B(Mb);
    for (int i = 0; i < Mb; i++) cin >> B[i];

    reverse(A.begin(), A.end());
    reverse(B.begin(), B.end());

    ll w = 1;          // 权重（最低位 = 1）
    ll ans = 0;
    int len = max(Ma, Mb);
    for (int i = 0; i < len; i++) {
        ll a = (i < Ma) ? A[i] : 0;      // 短的补 0
        ll b = (i < Mb) ? B[i] : 0;
        ll base = max(a, b) + 1;         // 最小合法进制
        if (base < 2) base = 2;
        ans = (ans + (a - b) * w % Mod + Mod) % Mod;   // (差) × 权重，处理负数
        w = (w * base) % Mod;            // 下一位的权重 = 前面进制乘积
    }
    cout << ans;
    return 0;
}
