// ============================================================
// LeetCode 1109. 航班预订统计
// 考点：一维差分（区间加 + 一次前缀和还原）
// 复杂度：时间 O(n + m)，空间 O(n)
// 日期：2026-09-11
// ============================================================
//
// 【题意】
// 有 n 个航班（编号 1..n）。bookings[i] = [first, last, seats]
// 表示从 first 到 last（两端都含）每个航班都预订了 seats 个座位。
// 返回长度为 n 的数组，第 i 个元素是航班 i+1 的总预订数。
//
// 【为什么用差分】
// 暴力逐格加是 O(区间长度)，2 万条记录 × 2 万航班 = 4×10^8，会超时。
// 差分把「区间加」压缩成两次单点修改，最后统一还原一次。
//
// 【关键理解】
// d[i] = a[i] - a[i-1]（差值）。给 [l,r] 加 x 之后：
//   d[l]   增加 x   —— 差值从 l 开始变大
//   d[r+1] 减少 x   —— 差值在 r+1 处恢复
//   l+1..r 之间的差值不变（前后都加了 x，差抵消）
//
// 【易错】
// 数组至少开 n+2：r+1 最大可以等于 n+1。
// ============================================================

class Solution {
public:
    vector<int> corpFlightBookings(vector<vector<int>>& bookings, int n) {
        vector<int> diff(n + 2, 0);            // 1-based；多开两位接住 r+1

        for (auto& b : bookings) {
            int l = b[0], r = b[1], x = b[2];
            diff[l]     += x;                  // 从 l 开始生效
            diff[r + 1] -= x;                  // 到 r+1 抵消（航班编号含 r 本身）
        }

        vector<int> ret(n, 0);
        int cur = 0;
        for (int i = 1; i <= n; i++) {
            cur += diff[i];                    // 累加出差分代表的实际值
            ret[i - 1] = cur;
        }
        return ret;
    }
};
