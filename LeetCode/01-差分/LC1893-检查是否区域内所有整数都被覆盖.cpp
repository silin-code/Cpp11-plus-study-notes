// ============================================================
// LeetCode 1893. 检查是否区域内所有整数都被覆盖
// 考点：差分 + 判零（覆盖次数为 0 就是断层）
// 复杂度：时间 O(m + 1000)，空间 O(52)
// 日期：2026-09-12
// ============================================================
//
// 【题意】
// 给若干区间 ranges 和查询区间 [left, right]，
// 判断 left..right 中每个整数是否都至少被一个区间覆盖。
//
// 【为什么用差分】
// 信号词：「某段范围内每个位置是否都被覆盖」= 区间加 + 单点查询。
// 每个区间贡献 1 次覆盖，所以把「区间加 x」写成「区间加 1」，
// 前缀和得到的就是「该位置被几个区间覆盖」，等于 0 即为断层。
//
// 【关键理解】
// cur == 0 表示没有任何区间覆盖这个位置；被覆盖至少 1 次的位置必然 >= 1。
// 所以只需要判零。
//
// 【易错】
// 前缀和必须从 i = 1 开始（模拟从数轴起点累积），
// 不能从 left 直接开始 —— 那样会丢掉 left 之前所有区间的贡献。
// ============================================================

class Solution {
public:
    bool isCovered(vector<vector<int>>& ranges, int left, int right) {
        vector<int> diff(52, 0);               // 值域 1..50；e[1]+1 最大为 51

        for (auto& e : ranges) {
            diff[e[0]]     += 1;               // 区间起点：从这开始被覆盖
            diff[e[1] + 1] -= 1;               // 终点后一位：覆盖结束
        }

        int cur = 0;
        for (int i = 1; i <= right; i++) {
            cur += diff[i];                    // 位置 i 的覆盖次数
            if (i >= left && cur == 0) return false;   // 在查询范围内且无人覆盖
        }
        return true;
    }
};
