// ============================================================
// LeetCode 1094. 拼车
// 考点：差分 + 右端点是否包含（本题到 dst 就下车，不含）
// 复杂度：时间 O(n + 1000)，空间 O(1002)
// 日期：2026-09-11
// ============================================================
//
// 【题意】
// trips[i] = [numPassengers, from, to]：从 from 站上车，到 to 站下车。
// 判断能否载完所有乘客且任意时刻载客数都不超过 capacity。
//
// 【和 LC 1109 的关键区别 —— 右端点】
// 乘客在 to 站**已经下车**，所以 to 站不算载客，实际占据区间 [from, to-1]。
//   区间两端都算（如 1109）→ 减在 d[r + 1]
//   右端不算（如本题）    → 减在 d[r]
//
// 【为什么前缀和要检查每一个站点】
// 只要有一个站点超载就要返回 false，所以要扫过全部站点。
//
// 【易错】
// 1. 站点编号从 0 开始，数组至少开 1001 才能索引到 1000。
// 2. 前缀和循环必须从 i = 0 开始，否则站点 0 永远不会被检查。
// 3. memset 参数顺序是 (指针, 值, 字节数)，写反了等于没初始化；
//    直接写 int num[1002] = {0}; 最安全。
// ============================================================

class Solution {
public:
    bool carPooling(vector<vector<int>>& trips, int capacity) {
        int num[1002] = {0};                   // 站点 0..1000

        for (auto& t : trips) {
            int n = t[0], src = t[1], dst = t[2];
            num[src] += n;                     // from 站上车
            num[dst] -= n;                     // to 站已经下车，减在 to 上
        }

        int cur = 0;
        for (int i = 0; i <= 1000; i++) {
            cur += num[i];                     // 站点 i 的实时载客数
            if (cur > capacity) return false;
        }
        return true;
    }
};
