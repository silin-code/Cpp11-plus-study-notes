// ============================================================
// LeetCode 304. 二维区域和检索 - 矩阵不可变
// 考点：二维前缀和 + 哨兵（消除所有边界 if）
// 复杂度：构造 O(n*m)，查询 O(1)，空间 O(n*m)
// 日期：2026-09-11
// ============================================================
//
// 【题意】
// 给定矩阵，多次查询 (r1,c1) 到 (r2,c2) 矩形内元素之和。
//
// 【递推式：上面 + 左边 − 左上 + 自己】
//   pre[i][j] = pre[i-1][j] + pre[i][j-1] - pre[i-1][j-1] + matrix[i-1][j-1]
//                                          ↑ 左上被重复算了，减掉
//                                                        ↑ 最后这项最常漏
//
// 【查询：容斥】
//   pre[r2+1][c2+1]   整体
//   - pre[r1][c2+1]   减去上方条带
//   - pre[r2+1][c1]   减去左侧条带
//   + pre[r1][c1]     左上角被减了两次，加回来
//
// 【为什么要开 (n+1) × (m+1) 的哨兵】
// 多出的一行一列全是 0，让所有"越界"的查询自动命中 0，
// 于是上面四个公式项里没有任何一项需要 if。
//
// 判断标准：如果前缀和代码里出现了边界 if，说明哨兵没开。
//
// 【易错】
// 用 long long：相减的中间值可能远超最终答案，int 会静默溢出。
// ============================================================

class NumMatrix {
public:
    NumMatrix(vector<vector<int>>& matrix) {
        int n = matrix.size(), m = matrix[0].size();
        pre.assign(n + 1, vector<long long>(m + 1, 0));   // 多的一行一列全 0

        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= m; j++) {
                pre[i][j] = pre[i - 1][j] + pre[i][j - 1]
                          - pre[i - 1][j - 1]
                          + matrix[i - 1][j - 1];            // 别忘了当前元素
            }
        }
    }

    int sumRegion(int r1, int c1, int r2, int c2) {
        return pre[r2 + 1][c2 + 1] - pre[r1][c2 + 1]
             - pre[r2 + 1][c1]     + pre[r1][c1];
    }

private:
    vector<vector<long long>> pre;
};
