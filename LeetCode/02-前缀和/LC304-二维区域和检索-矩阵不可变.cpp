// ============================================================
// LeetCode 304. 二维区域和检索 - 矩阵不可变
// 考点：二维前缀和 + 哨兵（消除所有边界 if）
// 复杂度：构造 O(n*m)，查询 O(1)，空间 O(n*m)
// 日期：2026-09-11 初版 / 2026-09-17 不看代码重写，7'11" 一次通过
// ============================================================
//
// 【题意】
// 给定矩阵，多次查询 (r1,c1) 到 (r2,c2) 矩形内元素之和。
//
// 【递推式：上面 + 左边 − 左上 + 自己】
//   dp[i][j] = dp[i-1][j] + dp[i][j-1] - dp[i-1][j-1] + matrix[i-1][j-1]
//                                          ↑ 左上被重复算了，减掉
//                                                        ↑ 最后这项最常漏
//
// 【查询：容斥】
//   dp[r2+1][c2+1]   整体
//   - dp[r1][c2+1]   减去上方条带
//   - dp[r2+1][c1]   减去左侧条带
//   + dp[r1][c1]     左上角被减了两次，加回来
//
// 【为什么要开 (n+1) × (m+1) 的哨兵】
// 多出的一行一列全是 0，让所有"越界"的查询自动命中 0，
// 于是上面四个公式项里没有任何一项需要 if。
// 判断标准：如果前缀和代码里出现了边界 if，说明哨兵没开。
//
// 【为什么这题 int 够用 —— 别背结论，要会算】
//   约束：m, n ≤ 200，|matrix[i][j]| ≤ 10^4
//   最大绝对和 = 200 × 200 × 10^4 = 4×10^8
//   int 上限   = 2.147×10^9        → 余量 5.37 倍，安全
//   ⚠️ 但这只是"恰好安全"：若行列上限变成 1000，4×10^9 立刻爆 int。
//   通用纪律仍是「前缀和 / 累加和默认 long long」，
//   敢用 int 的前提是上面这道算式算过。
//
// 【易错（09-11 初版两个坑，重写已全部修掉）】
// 1. 递推漏加 matrix[i-1][j-1]（初版栽在这）。
// 2. 查询写成 4 个边界 if —— 说明哨兵没开（初版也栽在这）。
// 3. 相减的中间值可能远超最终答案，默认应该用 long long。
// ============================================================

class NumMatrix {
public:
    NumMatrix(vector<vector<int>>& matrix) {
        int n = matrix.size(), m = matrix[0].size();
        dp.resize(n + 1, vector<int>(m + 1, 0));      // 多的一行一列全 0

        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= m; j++) {
                dp[i][j] = dp[i - 1][j] + dp[i][j - 1]
                         - dp[i - 1][j - 1]
                         + matrix[i - 1][j - 1];      // 别忘了当前元素
            }
        }
    }

    int sumRegion(int r1, int c1, int r2, int c2) {
        return dp[r2 + 1][c2 + 1] - dp[r1][c2 + 1]
             - dp[r2 + 1][c1]     + dp[r1][c1];       // 零 if
    }

private:
    vector<vector<int>> dp;
};
