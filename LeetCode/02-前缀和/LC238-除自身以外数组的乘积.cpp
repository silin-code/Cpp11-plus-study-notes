// ============================================================
// LeetCode 238. 除自身以外数组的乘积
// 考点：前后缀积（不用除法，O(1) 额外空间）
// 复杂度：时间 O(n)，空间 O(1)（不含返回数组）
// 日期：2026-09-12
// ============================================================
//
// 【题意】
// 返回数组 ret，其中 ret[i] = nums 中除 nums[i] 外所有元素的乘积。
// 要求不能用除法，且进阶要求 O(1) 额外空间。
//
// 【思路：两遍扫描，原地复用返回数组】
// 第一遍从左到右：ret[i] 先存"含自身的前缀积" nums[0..i]
// 第二遍从右到左：用 suffix 变量滚动"不含自身的后缀积"，
//                 同时把 ret[i] 覆盖成最终答案。
//
// 【哨兵】
// 乘积类问题的哨兵是 1（乘法的单位元），加法类问题才是 0。
//
// 【易错 / 可读性提醒】
// 这个写法里 ret[i] 的语义在两个阶段会变（含自身 → 不含自身），
// 需要靠注释维持可读性。如果不追求 O(1)，用 left/right 两个数组更直白。
// 考场原则：写对优先于写巧。
// ============================================================

class Solution {
public:
    vector<int> productExceptSelf(vector<int>& nums) {
        int n = nums.size();
        vector<int> ret(n, 0);

        // 第一遍：ret[i] = nums[0] * nums[1] * ... * nums[i]（含自身）
        ret[0] = nums[0];
        for (int i = 1; i < n; i++) {
            ret[i] = ret[i - 1] * nums[i];
        }

        // 第二遍：从右往左，suffix 滚出"不含自身的后缀积"
        int suffix = 1;
        for (int i = n - 1; i > 0; i--) {
            ret[i] = ret[i - 1] * suffix;      // ret[i-1] 是"不含 nums[i] 的前缀积"
            suffix *= nums[i];                 // 后缀往前滚一格
        }
        ret[0] = suffix;                       // 下标 0 单独处理（它没有左边的前缀积）

        return ret;
    }
};

