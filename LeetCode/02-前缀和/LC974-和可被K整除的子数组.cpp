// ============================================================
// LeetCode 974. 和可被 K 整除的子数组
// 考点：前缀和 + 同余
// 复杂度：时间 O(n)，空间 O(min(n, k))
// 日期：2026-09-12
// ============================================================
//
// 【题意】
// 统计和能被 k 整除的连续子数组个数。
//
// 【推导：从"和为 k"升级到"能被 k 整除"】
// 子数组 nums[j..i-1] 的和 = s[i] - s[j]，要求 (s[i] - s[j]) % k == 0，
// 等价于 s[i] % k == s[j] % k（同余）。
// 所以哈希表里存的不再是前缀和本身，而是**前缀和对 k 取余的结果**。
//
// 【易错：C++ 负数取余是负的】
//   -97 % 5 在 C++ 里等于 -2，而数学上应该等于 3。
//   只加一次 k 不够（x 一大就失效），标准写法是**取两次余**：
//       int r = ((sum % k) + k) % k;
//
// 【易错：忘写 hash[0] = 1】
// 与 LC 560 同理，空前缀（余数为 0，出现 1 次）必须预先置入，
// 否则所有从下标 0 开始的合法子数组都会被漏掉。
// ============================================================

class Solution {
public:
    int subarraysDivByK(vector<int>& nums, int k) {
        unordered_map<int, int> hash;
        hash[0] = 1;                           // 空前缀：和为 0，余 0，出现 1 次

        int ret = 0;
        int sum = 0;
        for (int e : nums) {
            sum += e;
            int r = ((sum % k) + k) % k;       // 保证余数落在 [0, k-1]
            ret += hash[r];                    // 之前出现过几次同样的余数，就新增几个合法子数组
            hash[r]++;
        }
        return ret;
    }
};
