// ============================================================
// LeetCode 525. 连续数组
// 考点：前缀和 + 同余思想的变种（**把 0 看成 -1，找最长的和为 0 的子数组**）
// 复杂度：时间 O(n)，空间 O(n)
// 日期：2026-09-21
// ============================================================
//
// 【题意】
// 只含 0 和 1，找**最长的**连续子数组，使得其中 0 的数量 == 1 的数量。
//
// ============================================================
// 【核心转换：0 看成 -1】
// ============================================================
// 把每个元素：0 → -1，1 → +1。
// 一段"0 和 1 数量相等" ⟺ "这一段的和 = 0"。
// 于是问题变成：在转换后的数组里，找**最长的、和为 0 的连续子数组**。
//
// 而"某段子数组和为 0" ⟺ "**两个位置的前缀和相等**"：
//     pre[i] == pre[j]  ⟹  nums[j+1..i] 的和 = pre[i] - pre[j] = 0
//
// 所以：只要同一个前缀和出现两次，中间那段就合法，长度 = i - j。
//
// ============================================================
// 【哈希表存什么：前缀和 → 第一次出现的下标】
// ============================================================
// 和 LC 523 是**同一条线**（都是"同余/同值配对"），
// 区别只在问法：
//   LC 523（连续子数组和为 k 倍数）：问【是否存在】+ 长度≥2 → 存余数→下标
//   LC 525（本题）               ：问【最长】              → 存前缀和→下标
//   只是本题没有"长度≥2"的硬门槛，但有"要最长"的目标。
//
// 只记第一次出现的下标：j 越小，i - j 越大，算出的长度越长。
//
// ============================================================
// 【hash[0] = -1：给"空前缀"占位（和 LC 523 / 560 同一个坑）】
// ============================================================
// 代表"和为 0 的前缀，出现在数组开始之前"，位置记 -1。
// 作用：处理"子数组从第一个元素就开始"的情况。
// 例：[0, 1]（转换后 [-1, 1]）
//   i=0: sum=-1 → hash[-1]=0
//   i=1: sum= 0 → hash 里有 0（预置 -1）→ ret = 1 - (-1) = 2 ✓ [0,1] 各一个
//   若没预置 hash[0]：i=1 时 sum=0，hash 里没有 0 → 漏掉整段
//
// ============================================================
// 【和 LC 523 的余数取模不同：本题不需要 %k】
// ============================================================
// LC 523 关心"模 k 的余数"，所以要 ((cur%k)+k)%k 处理负余数。
// 本题没有 k，直接配对的【就是前缀和的真实值】，不用取模。
// 但 sum 的符号仍会正负摆动，unordered_map 直接存原始值即可。
//
// 【408 标注】哈希 408 考的是散列构造 + 冲突处理 + ASL 计算，不是这样解题。
// ============================================================

class Solution {
public:
int findMaxLength(vector<int>& nums) {
int sum=0;
int ret=0;
int n=nums.size();
unordered_map<int,int> hash;//存前缀和的值+第一次出现的下标
//两个前缀和相等->当前相减为0->两个长度之和为0->都
hash[0]=-1;
for(int i=0;i<n;i++)
{
sum+=nums[i]==0?-1:1;
if(hash.count(sum)) ret=max(ret,i-hash[sum]);
else hash[sum]=i;
}
return ret;
}
};
