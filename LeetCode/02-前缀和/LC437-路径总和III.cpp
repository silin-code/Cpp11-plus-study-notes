// ============================================================
// LeetCode 437. 路径总和 III
// 考点：树上前缀和 + 哈希（回溯撤销）—— 前缀和从数组搬到树上
// 复杂度：哈希版 时间 O(n) / 空间 O(n)；暴力版 时间 O(n^2) / 空间 O(h)
// 日期：2026-09-20（经五版打磨，最终哈希版通过）
// ============================================================
//
// 【题意】
// 二叉树中，路径和等于 targetSum 的路径条数。路径不必从根开始、不必到叶子结束，
// 但必须【一路向下】（祖先 → 后代）。
//
// 【「一路向下」允许拐弯】
// 从起点出发，每到一层都可以选左或选右 —— 不是"一直往左"或"一直往右"。
// 例：
//       1
//      /
//     2
//      \
//       5
// 路径 1→2→5 是「先左后右」，合法。
//
// ============================================================
// 【解法一：暴力 O(n^2)】
// ============================================================
// 外层枚举每个节点当起点；内层从起点往下递归，左右都试，累计和传下去。
// n ≤ 5000 时约 2.5×10^7，能勉强 AC。
// 关键：累计和要【传下去】，不能重置。
//
// ============================================================
// 【解法二：树上前缀和 + 哈希 O(n)】
// ============================================================
// 与 LC 560 完全同源，只是把"数组上的前缀和"换成"树上一条路径的前缀和"。
//
// curSum = 从根到当前节点的和。
// 若路径上存在某祖先的前缀和 == curSum - target，
// 则「该祖先之后到当前节点」这一段的和 == target。
//
//     ret += hash[curSum - target];
//     hash[curSum]++;
//     ... 递归左右 ...
//     hash[curSum]--;          // ← 关键：离开节点时撤销
//
// 【为什么要撤销 —— 本题的命门】
// 哈希表里存的是「从根到【当前节点】这条路径上」的前缀和集合。
// 离开节点时它就不在路径上了 —— 不删的话，父节点的另一个分支处理时，
// 会拿"已不在路径上"的前缀和来配对，算出一条"拐上去又拐下来"的路径；
// 而题目要求路径必须一路向下，那条路径根本不存在。
//
// 反例（实测）：树 10(左 3, 右 7)，target = 4，正确答案 0。
//   不删除：处理 3 时留下 hash[13]；处理 7 时查 hash[17-4] = hash[13] 命中
//          → 误算出一条"3 到 7"的路径（3、7 是兄弟，不连通）→ 返回 1 ✗
//   删除：返回 0 ✓
//   随机对拍 400 组：不删除错 5 组，删除错 0 组。
//
// 【为什么必须 hash[0] = 1】
// 当 curSum == target 时，curSum - target = 0，要查的就是 hash[0]。
// hash[0] 代表「起点之前」的位置（空前缀）—— 它存在，
// 才说明"从路径开头（根节点）一路加到当前"这条路径有效。
// 不预置 → 所有从根开始的路径全部漏掉。
// 实测：单节点 root=5, target=5 时不加得 0（应 1）；
//       而官方示例恰好三条路径都不从根开始，所以【不会暴露这个 bug】。
// 这与 LC 560 的 hash[0]=1 是同一个道理。
//
// 【这行撤销其实就是回溯】
// 「进入时 hash[curSum]++、离开时 hash[curSum]--」，
// 与 LC 46/47/51 里的 path.pop_back()、visit[i]=false 是同一个动作，
// 只是撤销对象从 visit 数组换成了哈希表。
//   数组上的前缀和：一路往后累积、从不回头 → 不用撤
//   树上的前缀和：沿一条路径累积、会回溯     → 必须撤
//
// ============================================================
// 【五版演进 —— 每一版的错因（均为实测）】
// ============================================================
// 第 1 版：
//   a) 「一路向下」理解成"一直往左 / 一直往右"两条直链 → 拐弯路径全漏
//      （用例 1→左2→右5 得 0，应 1）
//   b) 「一直右」那条链从 sum = 0 起算，忘了加回 root->val
//      → 官方示例得 2（应 3）
//   c) 空树未判空 → 段错误（题目允许 0 个节点）
//   d) ret / t 成员变量未复位
// 第 2 版：
//   结构改对（递归 + 左右都试）→ 拐弯、sum=0 两个问题解决
//   但 _dfs 里起点值传错：dfs(root->left, root->val) 应为 root->left->val
//   → 起点值专测用例得 0（应 1）
// 第 3 版（暴力版通过）：
//   修掉起点值 + 加空树保护 → 随机对拍 300 组零不一致；仅剩 ret / t 成员变量
// 第 4 版（哈希版首版）：
//   撤销那一行写对了（hash[sum]--），但漏了 hash[0] = 1
//   → 从根开始的路径全漏（单节点 root=5,t=5 得 0；随机对拍 36 组错）
// 第 5 版（最终）：
//   补 hash[0]++ → 全部用例通过，随机对拍 500 组零不一致
//   ⚠️ 遗留：ret / t / hash 仍是成员变量（第 ⑥ 类第 6 次）——
//      力扣每用例新建对象不触发，本地多测 / 调试连调会累积（实测 3 → 6）
//
// 【408 标注】树的遍历 408 要求会写非递归版；哈希 408 考的是散列构造 + ASL 计算，
// 不是这样拿来解题。
// ============================================================

class Solution {
    int ret = 0;
    int t = 0;
    unordered_map<long long, long long> hash;
public:
    int pathSum(TreeNode* root, int targetSum) {
        hash[0]++;                           // 空前缀：和为 0，出现 1 次
        if (root == nullptr) return 0;       // 空树保护（题目允许 0 个节点）
        t = targetSum;
        dfs(root, root->val);
        return ret;
    }

    void dfs(TreeNode* root, long long sum) {
        ret += hash[sum - t];                // 之前有几个前缀和 == sum - target
        hash[sum]++;                         // 进入节点：加上自己

        if (root->left != nullptr)
            dfs(root->left, sum + (long long)root->left->val);    // 往左走
        if (root->right != nullptr)
            dfs(root->right, sum + (long long)root->right->val);  // 往右走

        hash[sum]--;                         // 回溯：离开节点，删掉自己
    }
};

