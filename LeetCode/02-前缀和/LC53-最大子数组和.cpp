// ============================================================
// LeetCode 53. 最大子数组和
// 考点：DP（状态设计）+ 前缀和最值 —— 同一问题的两个视角
// 复杂度：时间 O(n)；DP 版空间 O(n)，前缀和版空间 O(1)
// 日期：2026-09-19
// ============================================================
//
// 【题意】
// 求连续子数组的最大和（数组可含负数）。
//
// ============================================================
// 【视角一：DP】
// ============================================================
// 状态定义：dp[i] = 以第 i 个元素结尾的连续子数组的最大和
//
// 「以 i 结尾」= 子数组必须包含 nums[i-1]（dp 是 1-based，数组是 0-based）。
//
// 既然必须包含 nums[i-1]，dp[i] 的来路就只有两条：
//   ① 接上前面：dp[i-1] + nums[i-1]
//   ② 从 i 重新开始：nums[i-1]         ← 前面拖后腿，全扔掉
//
//     dp[i] = max(dp[i-1] + nums[i-1], nums[i-1])
//
// 【为什么 max 里没有 dp[i-1] 单独一项】
// dp[i-1] 是"以 i-1 结尾的最优值"，它对应的子数组**不含 nums[i-1]**，
// 不满足"以 i 结尾"的定义 —— 没资格当候选。
// 把它塞进去 = 允许 dp[i] 表示一个不含 i 的子数组，与定义打架。
//
// 【等价写法】max(dp[i-1]+x, x) = x + max(dp[i-1], 0)
//   前面那段和为负 → 不带它；否则带上。
//
// ============================================================
// 【视角二：前缀和最值】
// ============================================================
// pre = 当前前缀和，minpre = 到目前为止出现过的最小前缀和。
//
// 子数组 nums[j..i-1] 的和 = pre[i] - pre[j]
// 固定 i 时 pre[i] 是常数 → 要让差最大，只需让 pre[j] 最小
//   → 不必枚举 j，只维护 minpre（O(1) 更新）→ 整体 O(n)
//
// 【顺序不能反】
//   先 ret = max(ret, pre - minpre);    // 用当前 pre 算答案
//   再 minpre = min(minpre, pre);       // 再更新 minpre
// 写反会拿 pre[i] 减它自己，得到长度为 0 的子数组。
//
// ============================================================
// 【两个视角是同一件事】
// ============================================================
//     dp[i] = pre[i] - min(pre[0..i-1])
//
// "以 i 结尾的最大和" = "当前前缀和 − 前面出现过的最小前缀和"
//
// DP 说"前面是负的就不带它"；前缀和说"只减掉最小的那个前缀和"。
// "前面那段和为负" ⟺ "之前存在比我更小的前缀和"。
// **实测：3000 组随机数据上两版结果零不一致。**
//
// ============================================================
// 【为什么不能用滑动窗口（双指针）】
// ============================================================
// 滑动窗口的前提是"窗口和随窗口扩大单调变化"。
// 本题有负数 → 加负数变小、再加正数又变大 → 无法判断该缩还是该扩 → 失效。
// 对比 LC 209（长度最小的子数组）全是正数 → 滑动窗口成立。
// 通用判据：**先看有没有负数 / 有没有单调性，再决定能不能上双指针。**
//
// ============================================================
// 【易错（首版三个 bug，均为实测）】
// ============================================================
// 1. 转移第一个候选写成 dp[i-1]（应为 nums[i-1]）：
//      dp[i] = max(dp[i-1], dp[i-1]+nums[i-1]) = dp[i-1] + max(0, nums[i-1])
//    → 等价于"遇正数就累加"，实际在求"所有正数之和"。
//    实测官方示例返回 12（应 6）；3000 组对拍错 1129 组。
// 2. 下标越界：循环 1..n 却写 nums[i]，应 nums[i-1]（第 ① 类错）。
// 3. ret 初值写成 0：全负数时会错。
//    实测 [-1] → 0（应 -1）；[-3,-1,-2] → 0（应 -1）。初值应取 nums[0]。
//
// 【408 标注】DP 在 408 里基本不考，本题属蓝桥杯专属。
// ============================================================

class Solution {
public:
    // ---- 视角一：DP ----
    int maxSubArray(vector<int>& nums) {
        int n = nums.size();
        // dp[i] 表示以 i 元素为结尾的连续子数组的最大和
        vector<int> dp(n + 1, 0);
        int ret = nums[0];                   // 不能用 0（全负数时会错）

        for (int i = 1; i <= n; i++) {
            dp[i] = max(nums[i - 1], dp[i - 1] + nums[i - 1]);   // 两路取大
            ret = max(ret, dp[i]);
        }
        return ret;
    }
};

