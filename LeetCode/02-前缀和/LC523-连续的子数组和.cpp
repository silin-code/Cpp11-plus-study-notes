// ============================================================
// LeetCode 523. 连续的子数组和
// 考点：前缀和 + 同余 + 哈希（**存下标**，不是存次数）
// 复杂度：时间 O(n)，空间 O(n)
// 日期：2026-09-21
// ============================================================
//
// 【题意】
// 判断是否存在连续子数组，满足 ① 长度 ≥ 2  ② 元素和是 k 的倍数。
//
// ============================================================
// 【核心推导：同余】
// ============================================================
// 设 cur 为前缀和。子数组 nums[j+1..i] 的和 = dp[i] - dp[j]。
// 要求它被 k 整除：
//       (dp[i] - dp[j]) % k == 0
//   ⟺   dp[i] % k == dp[j] % k        ← 两个前缀和【除以 k 的余数相同】
//
// 所以：找到"两个余数相同的前缀和"，它们中间那段就是答案。
// 前缀和的具体数值一点都不重要，重要的是它对 k 的【余数】。
//
// ============================================================
// 【和 LC 974 的关键区别：存"下标"，不存"次数"】
// ============================================================
//   LC 974（和可被 K 整除的子数组）：问【有多少个】→ 哈希表存「余数 → 出现次数」
//   LC 523（本题）                ：问【是否存在】+【长度 ≥ 2】
//                                   → 必须存「余数 → 第一次出现的下标」
//
// 因为"长度 ≥ 2"要靠**下标差**算出来：
//   子数组 nums[j+1..i] 的长度 = i - j
//   要求 i - j >= 2
//
// 存次数的话根本算不出长度 —— 这是本题唯一的难点。
//
// 【为什么只留第一次出现的下标】
// 下标 j 越小，i - j 越大，越容易满足 >= 2。所以同一个余数只记第一次。
//
// ============================================================
// 【hash[0] = -1：给"空前缀"占位】
// ============================================================
// 它代表「和为 0 的前缀，出现在数组开始之前」，位置记 -1。
//
// 作用：处理"子数组从第一个元素开始"的情况。
// 例：[2,4]，k=6（应 true）
//   没有 hash[0] 时：i=1 时 cur=6, r=0，但 hash 里没有 0 → 漏掉
//   有 hash[0]=-1 ：i=1 时 cur=6, r=0，i - (-1) = 2 >= 2 ✓ → true
//
// 为什么是 -1 而不是 0：长度必须算准。
//   写 hash[0] = 0 时，i - 0 = 1 < 2，会把 [2,4] 这种漏掉。
//
// 与 LC 560 的 hash[0] = 1 是同一个东西（都让"空前缀"能被配对），
// 区别只是那道题记次数、本题记下标。
//
// ============================================================
// 【余数的符号】
// ============================================================
// C++ 里负数取模得负数（-7 % 6 == -1）。
// 用 ((cur % k) + k) % k 保证结果落在 [0, k-1]。
// 注意只写 (cur%k)+k 是不够的：整除时会得到 k，越出范围。
//
// ============================================================
// 【首版错在哪（实测记录）】
// ============================================================
//   ① hash[cur]++ 存的是"次数" → 无法判断"长度 ≥ 2"（本题命门）
//   ② 检查写在 cur += nums[i] 之前 → 查的是上一轮的余数，与"记"对不上
//   ③ 没预置 hash[0]
//   ④ (cur-k)%k+k 在整除时得 k，不在 [0, k-1] 内
//   实测：8 个用例错 5 个，随机对拍 2000 组错 905 组。
//
// 【大坑：写了 (cur-k) 而不是 cur 也算余数相同】
//   (cur-k) % k == cur % k（因为 k ≡ 0 mod k），所以那个写法"思路"没错，
//   出问题的是它没做 +k 之后的取模。
//
// 【408 标注】哈希 408 考的是散列构造 + 冲突处理 + ASL 计算，不是这样解题。
// ============================================================

class Solution {
public:
    bool checkSubarraySum(vector<int>& nums, int k) {
        int n = nums.size();
        if (n < 2) return false;

        unordered_map<long long, int> hash;   // 余数 → 第一次出现的下标
        long long cur = 0;
        hash[0] = -1;                         // 空前缀，位置记 -1

        for (int i = 0; i < n; i++) {
            cur += nums[i];
            long long r = ((cur % k) + k) % k;      // 保证落在 [0, k-1]
            if (hash.count(r) && i - hash[r] >= 2)  // 长度 = i - j >= 2
                return true;
            if (!hash.count(r)) hash[r] = i;        // 只记第一次
        }
        return false;
    }
};
