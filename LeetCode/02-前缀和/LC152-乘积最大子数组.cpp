// ============================================================
// LeetCode 152. 乘积最大子数组
// 考点：双状态 DP（因为负数会翻转大小关系）
// 复杂度：时间 O(n)，空间 O(n)（可滚动成 O(1)）
// 日期：2026-09-20（经三版修正后通过）
// ============================================================
//
// 【题意】
// 求连续子数组的最大乘积。（与 LC 53 最大子数组和几乎同题，只差"乘积"二字）
//
// 【核心：为什么一个状态不够】
// LC 53 只需要记「以 i 结尾的最大和」；
// 本题若只记「以 i 结尾的最大乘积」，会丢掉关键信息：
//
//     一个【最负】的乘积，乘上一个负数，会翻成【最大】的正数。
//
// 例：nums = [2, -3, -2]
//   走到 -3 时，以它结尾的乘积有 2*(-3) = -6 和 -3，最大是 -3；
//   但后面来了个 -2，(-6) * (-2) = 12 才是全局最大 —— 而那个 -6 早被扔了。
//
// 【两个状态】
//   f[i] = 以 i 结尾的最大乘积
//   g[i] = 以 i 结尾的最小乘积（最负的那个）
//
// 【转移：三个候选取最大 / 最小】（x = nums[i]）
//   f[i] = max(f[i-1]*x, g[i-1]*x, x)
//   g[i] = min(f[i-1]*x, g[i-1]*x, x)
//
// 三个候选的含义：
//   ① f[i-1]*x —— 接在"之前最大"后面
//   ② g[i-1]*x —— 接在"之前最小"后面（负负得正的关键）
//   ③ x        —— 从自己重新开始（前面拖后腿就扔掉，同 LC 53）
//
// 用 max / min 就不用 if 分 nums[i] 的正负 —— 三个候选一起丢进去，
// 谁大谁当最大、谁小谁当最小，符号问题自动解决。
//
// ============================================================
// 【三版演进 —— 每一版的错因（均为实测）】
// ============================================================
// 第 1 版：
//   a) 循环从 i = 0 开始，却用了 g[i-1] / f[i-1] → i=0 时访问 g[-1] 越界
//   b) 判断条件写成 if (f[i] < 0)：vector<int> f(n) 会把元素初始化为 0，
//      f[i] < 0 恒为 false；此处本想判断的是 nums[i] 的符号
//      → 三个 if 叠加后结果恒为 0（如 [2,3,-2,4] 得 0，应 6）
//   c) 缺"从当前元素重新开始"(x) 这个候选
//   d) f[i]=g[i]==0; 是语法陷阱 —— 实际含义是 f[i] = (g[i] == 0)，
//      把 bool 赋给 int；且此时 g[i] 还没赋值（[-2,0,-1] 得 1，应 0）
//   e) ret = 0 初值，全负数时会错
// 第 2 版：
//   结构改对（两个状态 + 三候取极值），但
//   a) 候选里混进了 0：f[i] = max(x, max(g[i-1]*x, 0))
//      → 【0 未必对应任何以 i 结尾的子数组】。例 [1,2]：
//         以索引 1 结尾的子数组只有 [2]=2 和 [1,2]=2，没有 0
//         但他的 g[1] = min(2, min(2, 0)) = 0 ← 凭空捏造
//      → g 被污染成 0 后，往后乘负数时 g[i-1]*x 给出 0 而非真正的最小值，
//        "负负得正"的机会全丢。
//        实测 [0,-3,1,-2] 得 1（应 6）；随机对拍 1000 组错 501 组
//   b) 漏了 f[i-1]*x 这个候选（只写了 g 和 x 两条来路）
//   c) ret 初值仍是哨兵值，n=1 时循环不执行 → 返回 -4144959（应 -2）
// 第 3 版（通过）：
//   ret = nums[0]；三候选齐全且不含 0
//   → 10 个用例全过，随机对拍 2000 组零不一致；
//   **且全程未用成员变量，复用测试 6/6 通过（第 ⑥ 类首次零违规）**
//
// 【408 标注】DP 在 408 里基本不考，本题属蓝桥杯专属。
// ============================================================

class Solution {
public:
    int maxProduct(vector<int>& nums) {
        int n = nums.size();
        vector<int> f(n, -0x3f3f3f);   // 以 i 结尾的最大乘积
        vector<int> g(n,  0x3f3f3f);   // 以 i 结尾的最小乘积
        int ret = nums[0];             // 不能用哨兵值（n=1 时循环不执行）
        f[0] = g[0] = nums[0];

        for (int i = 1; i < n; i++) {
            // 三个候选：接在最大后 / 接在最小后 / 从自己重新开始
            f[i] = max(nums[i], max(g[i - 1] * nums[i], f[i - 1] * nums[i]));
            g[i] = min(nums[i], min(f[i - 1] * nums[i], g[i - 1] * nums[i]));
            ret = max(ret, f[i]);
        }
        return ret;
    }
};
