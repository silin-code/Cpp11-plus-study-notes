#pragma once
#include <vector>
#include <queue>
#include <utility>
using namespace std;

// ============================================================
// Dijkstra：单源最短路（所有边权 >= 0）
// ------------------------------------------------------------
// 【这个函数在干什么】
//   从 src 出发，算出 src 到【每一个点】的最短距离，一次性全部返回。
//   不是"求两点最短路"—— 那只是返回值里的一个格子。
//
// 【为什么不能直接用 BFS】
//   BFS 的前提是"每走一步代价都是 1"，所以"先到的一定最短"。
//   边权不同时这个前提就没了：
//       1 --10--> 2 --1--> 4
//       1 --3-->  3 --1--> 4
//   BFS 会先到 2（10 步），但从 1→3→4 只要 4。
//   Dijkstra 换成"每次取当前距离最小的点"来扩展。
//
// 【算法的核心一句话】
//   每一轮，从"还没确定的点"里挑出【当前 dist 最小】的那个 u，
//   用 u 去更新它的邻居；被取出的 u，它的 dist 就是最终答案了。
//
// 【为什么"取出时就是最终值"（这句是算法的全部，必须能自己证）】
//   反证：假设取出的 u 满足 dist[u] = d，但真实最短距离更小，
//        走的是 u' → u 这条路（最后一条边权 w）。
//        那么 dist[u'] <= d - w < d  （因为 w >= 0）
//        -> u' 的距离比 u 小 -> u' 应该【先于 u】被取出
//        -> 它会先松弛 u，把 dist[u] 改小
//        -> 与"取出 u 时是 d"矛盾。
//   ★ 关键那一步用了 w >= 0。这就是为什么 Dijkstra 不支持负权边。
//
// 【复杂度】O((n + m) log n)
//   n 个点、m 条边。每次松弛成功压一次堆，堆操作 log(m)。
//
// ============================================================
// 【四个必须记住的细节（都是实际踩过的）】
// ============================================================
//   1. 堆元素是 pair<距离, 节点>，【距离必须在前】
//      pair 默认按 first 比较，距离在前才会"按距离排序"。
//      写成 pair<节点, 距离> -> 变成按编号排序 -> 全错。
//
//   2. 出堆后必须判过期：if (d > dist[u]) continue;
//      同一个点会入堆多次（每次被改进都压一条）。
//      取出的旧记录里 d 比当前 dist[u] 大 -> 这条记录作废。
//      不写这行 -> 同一个点被反复扩展，复杂度退化，可能 TLE。
//
//   3. 只有"更新成功"才 push
//      错法：每个邻居都 push -> 堆里全是没用的记录 -> 又慢又占内存。
//
//   4. INF 不能用 LLONG_MAX
//      松弛要算 dist[u] + w，LLONG_MAX + w 会溢出成负数，
//      那个 "< dist[v]" 就永远成立 -> 答案直接错。
//
// ============================================================
// 【参数】
//   n    : 节点个数，编号 0 .. n-1
//   g    : 邻接表，g[u] = { {v, w}, ... } 表示 u -> v 代价 w
//   src  : 源点
//
// 【返回】
//   dist[0..n-1]，src 到各点的最短距离；不可达为 INF
//
// 【用法】
//   int n = 5;
//   vector<vector<pair<int,int>>> g(n);
//   addEdge(g, 1, 2, 1);            // 有向边 1 -> 2，代价 1
//   addEdge(g, 1, 3, 4, true);      // 无向边 1 <-> 3，代价 4
//   vector<long long> d = dijkstra(n, g, 1);
//   if (d[4] == INF) { /* 不可达 */ }
// ============================================================

// INF 取 0x3f3f3f3f3f3f3f3f ≈ 4.5e18
// 为什么要这个值：比任何合法答案都大（能表示"不可达"），
// 但加一个正常边权（1e9 量级）不会溢出。
// 别用 LLONG_MAX（9.2e18）——它 + w 直接绕回负数。
const long long INF = 0x3f3f3f3f3f3f3f3fLL;

vector<long long> dijkstra(int n, const vector<vector<pair<int, int>>>& g, int src) {
    // dist[v] = src 到 v 的【当前已知】最短距离。
    // "当前已知"四个字很重要：过程中它会不断变小，不是一开始就定死的。
    vector<long long> dist(n, INF);
    dist[src] = 0;                                 // 自己到自己，距离 0

    // ------------------------------------------------------------------
    // 小根堆
    //   priority_queue<元素类型, 底层容器, 比较器>
    //   不写比较器 = 大根堆（堆顶最大）；写 greater<...> 才是小根堆。
    //
    // 元素 pair<long long, int>：
    //   first  = 距离（放前面，pair 按 first 排序）
    //   second = 节点编号
    // ------------------------------------------------------------------
    priority_queue<pair<long long, int>,
                   vector<pair<long long, int>>,
                   greater<pair<long long, int>>> pq;
    pq.push({0, src});                             // 起点入堆：距离 0

    while (!pq.empty()) {
        // ---- 第 1 步：取出"当前距离最小"的点 ----
        long long d = pq.top().first;              // 这条记录声称的距离
        int u = pq.top().second;                   // 是哪个点
        pq.pop();

        // ---- 第 2 步：过期判断 ----
        // 同一个点会被压多条记录（每次 dist 变小就压一条）。
        // 现在这条记录里的 d 比 dist[u] 大 -> 说明它是"改进之前的老记录"
        // -> 丢掉，别拿它去松弛（否则会用旧距离算出更差的答案）。
        if (d > dist[u]) continue;

        // ---- 第 3 步：用 u 松弛所有出边 ----
        // "松弛"：看看"经过 u 再到 v"会不会比"现在到 v 的最短路"更短。
        // 这里用下标循环而不是 range-for，是为了兼容老编译器/写起来更明确。
        for (size_t i = 0; i < g[u].size(); i++) {
            int v = g[u][i].first;                 // 边指向的点
            int w = g[u][i].second;                // 这条边的代价

            if (dist[u] + w < dist[v]) {           // 经过 u 更优
                dist[v] = dist[u] + w;             // 更新 v 的最短距离
                pq.push({dist[v], v});             // ③ 只压"变好了"的点
            }
        }
    }

    return dist;
}

// ============================================================
// 加边小工具：无向图要加两次，很容易漏
// ------------------------------------------------------------
// 为什么单独写一个函数：
//   无向图要 push_back 两次（u->v 和 v->u）。
//   手写时漏一次，表现是"某些点到达不了"，很难联想到"建图漏边"。
//   封装一下，靠 undirected 开关就不会忘。
//
// 参数：
//   undirected = false（默认）-> 有向边 u -> v
//   undirected = true         -> 无向边 u <-> v
// ============================================================
void addEdge(vector<vector<pair<int, int>>>& g, int u, int v, int w, bool undirected = false) {
    g[u].push_back({v, w});                        // 正向边
    if (undirected) g[v].push_back({u, w});        // 反向边（无向图才有）
}

// ============================================================
// 【常见变体：dist 里存的不是"距离和"】
// ------------------------------------------------------------
// 框架完全不用改，只改 `dist[v] = ?` 那一行：
//
//   题目问的              更新写法
//   --------------------  --------------------------
//   路径总长度（标准）     dist[v] = dist[u] + w
//   路径上的【最大边权】   dist[v] = max(dist[u], w)    （LC 1631）
//   路径上的【最小边权】   dist[v] = min(dist[u], w)    （LC 1102）
//   换乘 / 中转次数        状态加一维                   （LC 787）
//
// 判据：只要"最优值能从父节点递推出来"，且递推对父节点的值单调，
//      就能套这个框架。
//
// ============================================================
// 【和 408 的联系】
// ------------------------------------------------------------
// 408 的 Dijkstra 用"邻接矩阵 + 已确定/未确定两个集合"，
// 每轮线性扫描未确定集合找最小值 -> O(V^2)。
// 本文件是"邻接表 + 优先队列" -> O((V+E) log V)。
// 同一个算法，"找最小值"的手段不同：
//   408：线性扫描（稠密图、V 小）
//   本文件：堆（稀疏图）
// 408 喜欢手算"每一轮确定了哪个点、dist 数组什么样子"，那是同一套逻辑。
// ============================================================
