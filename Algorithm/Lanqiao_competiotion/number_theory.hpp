// ------------------------------------------------------------
// gcd(a, b)：最大公约数（欧几里得 / 辗转相除）
// ------------------------------------------------------------
// 【一句话原理】
//   gcd(a, b) = gcd(b, a % b)
//   一直换到 b == 0，此时 gcd(a, 0) = a。
//
// 【为什么成立（两个方向都要走一遍）】
//   设 a = q*b + r，其中 r = a % b。
//   要证「a,b 的公约数集合」=「b,r 的公约数集合」：
//     方向一：若 d|a 且 d|b，则 d|(a - q*b)，即 d|r
//             -> d 也是 b,r 的公约数
//     方向二：若 d|b 且 d|r，则 d|(q*b + r)，即 d|a
//             -> d 也是 a,b 的公约数
//   两个集合完全相等 -> 最大元必然相等 -> gcd 不变。
//
// 【为什么快】O(log min(a,b))
//   设 a > b，分两种情况看 a % b 有多大：
//     b <= a/2  ->  a%b < b <= a/2
//     b >  a/2  ->  a%b = a-b < a/2
//   两种都推出 a%b < a/2 —— 「被取模的那个数」每轮至少减半。
//   所以 1e18 也只要 60 轮左右，比线性快到不可比。
//
// 【三个必须注意的点】
//   1. 循环条件必须是 while (b)，不能先取模再判断
//      b == 0 时算 a % b 是除零（UB，可能直接崩，也可能给出垃圾值）。
//      正确顺序：先看 b，再决定要不要取模。
//
//   2. 赋值顺序（这行最容易写错）
//      想同时更新 a 和 b 时，不能先改 a：
//          a = b;
//          b = a % b;     // ✗ 这时 a 已经是 b 了，算出来恒为 0
//      必须先用临时变量接住 a % b，再统一赋值。
//
//   3. 负数
//      C++ 的 % 是截断除法（-7 % 3 == -1），负数直接进去会得到负的 gcd。
//      蓝桥杯偶尔给负数，所以模板里第一步统一取绝对值。
//
// 【参数】a, b：任意整数（内部先取绝对值）
// 【返回】最大公约数，恒 >= 0；gcd(0, 0) 返回 0
// ------------------------------------------------------------
inline long long gcd(long long a, long long b) {
    // TODO 1: 把 a、b 都变成非负（llabs(a)、llabs(b)）
    a = llabs(a);
    b = llabs(b);
    // TODO 2: 迭代欧几里得
    //         只要 b 不为 0，就把这一对 (a, b) 换成 (b, a % b)
    //         —— 用一个临时变量 t 接住 a % b，再 a = b; b = t;
    
    while (b)
    {
        long long t = a % b;
        a = b;
        b = t;
    }
    // TODO 3: 循环结束时 b 一定为 0，此时的 a 就是答案

    return a;   // 循环结束时 b == 0，a 就是最大公约数
}

inline long long lcm(long long a,long long b)
{
    if (a == 0 || b == 0) return 0;   // 0 和任何数的 lcm 都是 0；也避免 (0,0) 时 a/gcd 除零崩掉
    return a / gcd(a, b) * b;
}

// ------------------------------------------------------------
// sieve(n)：埃氏筛，返回 isPrime[0..n]
// ------------------------------------------------------------
// 【用法】
//   vector<bool> isPrime = sieve(1000);
//   isPrime[7] == true, isPrime[8] == false
//   要「个数」就自己数：int cnt = 0; for (int i = 2; i <= n; i++) if (isPrime[i]) cnt++;
//   （要方便的话后面再加一个 countPrimes(n)，它只是层封装）
//
// 【为什么必须用 vector<bool>，不能用 vector<char> 或 int 数组】
//   vector<bool> 是标准库的特化版本：【按位存】，1 个 bit / 个数。
//       n = 1e8  ->  12.5 MB
//   vector<char> 是 1 字节 / 个数：
//       n = 1e8  ->  100 MB（很多题目内存限制就是 128 MB，加上别的直接 MLE）
//   int 数组：
//       n = 1e8  ->  400 MB，必挂。
//   ★ 蓝桥杯报 MLE 的筛法题，十有八九是数组元素类型开大了。
//
// 【为什么外层到 sqrt(n)、为什么内层从 p*p 起】
//   见今天讲的第五节，两句话：
//     - p*p 之前的那些倍数（2p, 3p, ..., (p-1)p），早被更小的质因子划过了
//     - p > sqrt(n) 时 p*p > n，内层一次都不会执行，白写
//
// 【复杂度】时间 O(n log log n)，空间 O(n/8)
// ------------------------------------------------------------
inline vector<bool> sieve(int n) {
    // ① 开表：n+1 个格子，全部先当成"质数"
    //    为什么是 n+1：下标要能从 0 走到 n，一共 n+1 个数
    vector<bool> isPrime(n + 1, true);

    // ② 0 和 1 本来就不算质数，手动划掉
    //    （加 if 是因为 n = 0 时表里只有下标 0，写 isPrime[1] 就越界了）
    if (n >= 0) isPrime[0] = false;
    if (n >= 1) isPrime[1] = false;

    // ③ 主循环：p 只用试到 sqrt(n)
    //    p*p > n 时，p 的最小倍数 p*p 已经在表外，内层一次都不会跑
    for (int i = 2; i * i <= n; i++)
    {
        // ④ i 还没被划掉 -> i 是质数 -> 值得划它的倍数
        //    如果 i 已经被划掉（合数），它的倍数早被更小的质数处理完了
        if (isPrime[i]) {
            // ⑤ 从 i*i 开始划，步长 i：i*i, i*i+i, i*i+2i, ...
            //    i*i 之前那些倍数（2i, 3i, ..., (i-1)i）已经有人划过了
            for (int m = i * i; m <= n; m += i) {
                isPrime[m] = false;
            }
        }
    }
    return isPrime;
}

//求(a^b % mod)
inline long long qpow(long long a, long long b, long long mod)
{
    long long ret = 1 % mod;
    a %= mod;
    while (b)
    {
        if (b & 1) ret = ret * a % mod;
        a = a * a % mod;
        b >>= 1;
    }
    return ret;
}