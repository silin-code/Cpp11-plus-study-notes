// ============================================================
// Kruskal：最小生成树（MST）
// ------------------------------------------------------------
// 【解决什么问题】
//   n 个点 + 一堆带权边，从中挑出 n-1 条边把所有点连成一整块（无环），
//   使总权值最小。
//
//   "n-1 条边 + 全连通" = 一棵树。
//   为什么恰好 n-1 条：
//       一开始 n 个点各自独立 = n 个连通块
//       每加 1 条【连接不同块】的边，块数 -1
//       从 n 块降到 1 块，需要 n-1 条边
//       第 n 条边必然两端已连通 -> 成环 -> 违反树的定义
//
// ------------------------------------------------------------
// 【算法三步】
// ------------------------------------------------------------
//   ① 所有边按权值【从小到大】排序
//   ② 依次看每条边：
//         两端【还没连通】 -> 选它，合并这两块
//         两端【已经连通】 -> 跳过（选了就成环，而且连通性没改善）
//   ③ 选够 n-1 条边就停
//
//   第 ② 步的"跳过"是算法核心：
//       两端已连通 = 它们之间已经有一条路径
//       再加这条边 = 路径 + 这条边 = 一个环
//       树不能有环，而且这块本来就连通了，加它纯属浪费钱
//
// ------------------------------------------------------------
// 【为什么贪心是对的（Cut Property 切分性质）】
// ------------------------------------------------------------
//   结论：全局最小的那条边，一定存在某棵 MST 包含它。
//
//   证明思路：
//       假设最小边 e 不在最优解 T 里。
//       把 e 加进 T -> 形成一个环。
//       环里除了 e 之外，一定还有别的边，它们的权值都 >= e（e 全局最小）。
//       从环里删掉任意一条别的边 -> 又变回树，总权值不会变大。
//       -> 所以"包含 e"的方案不比 T 差，矛盾。
//
//   每一步都这样论证 -> Kruskal 的每次选择都是安全的。
//   （蓝桥杯不考证明，记住结论即可）
//
// ------------------------------------------------------------
// 【复杂度】
// ------------------------------------------------------------
//   排序           O(E log E)
//   并查集部分      O(E * α(n))   ≈ O(E)
//   合计           O(E log E)      主要开销在排序
//
//   对比 Prim（朴素 O(n²)、堆优化 O(E log V)）：
//       Kruskal 适合【稀疏图】（E 小）
//       Prim    适合【稠密图】（E 接近 n²，如完全图）
//       ★ 但完全图的 E = n²/2，n=1000 时 50 万条边，Kruskal 也能过
//         （50 万条边排序约 1000 万次比较）
//
// ------------------------------------------------------------
// 【参数与返回】
// ------------------------------------------------------------
//   n     : 点数，编号 0 .. n-1
//   edges : 边表（会被排序，传引用因为要改）
//           有向/无向不影响 —— MST 只关心"连接"，按无向处理
//   返回   : 最小生成树的总权值
//            图不连通（无法生成树）时返回 -1
//
// ------------------------------------------------------------
// 【必须注意的四个点】
// ------------------------------------------------------------
//   ① 边权累加用 long long
//      n=1000、坐标 1e6 时，单边最大 2e6，999 条边合计约 2e9，
//      逼近 int 上限（2.147e9），很危险。
//
//   ② Edge 的字段顺序无所谓，但 operator< 必须只按 w 比较
//      （如果写成按 (u,v,w) 字典序，会变成按起点排序，算法就错了）
//
//   ③ 并查集节点编号 0..n-1 -> UnionFind uf(n)，不要 +1
//      （除非题目编号是 1..n，那时才传 n+1）
//
//   ④ 不连通的处理：cnt 最终 != n-1 -> 返回 -1
//      不要直接返回 total（那会返回"最小生成森林"的权值，不是答案）
//
// ------------------------------------------------------------
// 【用法示例 1：题目直接给边表】
// ------------------------------------------------------------
//   int n = 4;
//   vector<Edge> es = {
//       {0,1,1}, {1,2,2}, {0,2,3}, {2,3,4}, {1,3,5}
//   };
//   long long ans = kruskal(n, es);      // 7
//
// ------------------------------------------------------------
// 【用法示例 2：只给坐标，要自己造完全图的边（LC 1584）】
// ------------------------------------------------------------
//   int n = points.size();
//   vector<Edge> es;
//   es.reserve(n * (n - 1) / 2);          // 预分配，避免反复扩容
//   for (int i = 0; i < n; i++)
//       for (int j = i + 1; j < n; j++) {
//           int w = abs(points[i][0] - points[j][0])
//                 + abs(points[i][1] - points[j][1]);
//           es.push_back({i, j, w});
//       }
//   long long ans = kruskal(n, es);
//
// ------------------------------------------------------------
// 【408 视角】
// ------------------------------------------------------------
//   408 常考 Prim 和 Kruskal 的对比：
//       Prim    ：从一个点出发，每次把"离当前树最近的点"加进来
//                  朴素 O(n²)（邻接矩阵），适合稠密图
//       Kruskal ：按边权从小到大挑，用并查集判环
//                  O(E log E)，适合稀疏图
//   两者都基于贪心，都能得到 MST（权值唯一，形态可能不唯一）
// ============================================================

// 边：{起点, 终点, 权值}
// 字段顺序可以调整，但 operator< 只按 w 比较
struct Edge {
    int u, v, w;

    // 排序依据：只按权值升序
    bool operator<(const Edge& o) const {
        return w < o.w;
    }
};

// 返回最小生成树总权值；不连通返回 -1
long long kruskal(int n, vector<Edge>& edges) {
    // ① 按权值从小到大排序
    sort(edges.begin(), edges.end());

    UnionFind uf(n);          // 并查集：负责"两点是否已连通"
    long long total = 0;      // 累计权值（用 long long，见注释 ①）
    int cnt = 0;              // 已选边数，够 n-1 就停

    // ② 依次尝试每条边
    for (const Edge& e : edges) {
        // 两端已连通 -> 选了会成环 -> 跳过
        if (uf.issame(e.u, e.v)) continue;

        // 两端不连通 -> 选它，合并这两块
        uf.unoin(e.u, e.v);
        total += e.w;
        cnt++;

        // ③ 选够 n-1 条，已经是一棵完整的树，提前结束
        if (cnt == n - 1) break;
    }

    // 不连通：选不满 n-1 条边
    return (cnt == n - 1) ? total : -1;
}

