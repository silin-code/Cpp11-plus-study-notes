#pragma once
#include <vector>
#include <algorithm>
#include "UF.hpp"         
using namespace std;

// ============================================================
// Kruskal：最小生成树（MST）
// ------------------------------------------------------------
// 【解决什么问题】
//   n 个点 + 一堆带权边，挑出 n-1 条边把所有点连成一整块（无环），
//   使总权值最小。
//
//   "n-1 条边 + 全连通" = 一棵树。
//   为什么恰好 n-1 条：
//       一开始 n 个点各自独立 = n 个连通块
//       每加 1 条【连接不同块】的边，块数 -1
//       从 n 块降到 1 块，需要 n-1 条边
//
// ------------------------------------------------------------
// 【算法三步】
// ------------------------------------------------------------
//   ① 所有边按权值【从小到大】排序
//   ② 依次看每条边：
//         两端【还没连通】 -> 选它，合并这两块
//         两端【已经连通】 -> 跳过（选了就成环）
//   ③ 选够 n-1 条边就停
//
//   为什么"跳过"：两端已连通 = 它们之间已有路径，
//   再加这条边就会形成一个环，而树不允许有环。
//
// ------------------------------------------------------------
// 【为什么贪心是对的（Cut Property）】
// ------------------------------------------------------------
//   全局最小的边，一定存在某棵 MST 含它。
//   反证：若不含，加进去会成环；环里其它边都 >= 它；
//         删掉其中任意一条，总权值不会变大 -> 矛盾。
//
// ------------------------------------------------------------
// 【复杂度】O(E log E)，开销在排序；并查集部分近似 O(E)
//
// ------------------------------------------------------------
// 【参数与返回】
// ------------------------------------------------------------
//   n     : 点数，编号 0 .. n-1
//   edges : 边表（会被排序，所以传引用）
//   返回   : MST 总权值；图不连通时返回 -1
//
// ------------------------------------------------------------
// 【四个要注意的点】
// ------------------------------------------------------------
//   ① 累计权值用 long long（单边可达 2e6，999 条边接近 2e9）
//   ② operator< 只按 w 比较（写成字典序会变成按起点排，算法就错了）
//   ③ 并查集传 uf(n)，编号 0..n-1，不要 +1
//   ④ 不连通时返回 -1，不要直接返回 total
// ============================================================


// ------------------------------------------------------------
// 边：起点 u、终点 v、权值 w
// ------------------------------------------------------------
struct Edge {
    int u, v, w;
};

bool cmp(const Edge& e1,const Edge& e2)
{
    return e1.w < e2.w;
}
// ------------------------------------------------------------
// 返回最小生成树总权值；不连通返回 -1
// ------------------------------------------------------------
long long kruskal(int n, vector<Edge>& edges) {

    sort(edges.begin(), edges.end(),cmp);

    UnionFind uf(n);

    long long total = 0;      // 累计权值
    int cnt = 0;              // 已选边数

    for (auto& e : edges)
    {
        int u = e.u, v = e.v, w = e.w;
        if (uf.issame(u,v))
        {
            continue;
        }
        uf.unoin(u, v);
        cnt++;
        total += w;
    }

    if (cnt != n - 1) return -1;
    return total;
}
